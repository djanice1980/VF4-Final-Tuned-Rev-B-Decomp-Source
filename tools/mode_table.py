#!/usr/bin/env python3
"""Generate types and symbols from mode_data, the game's state machine.

mode_data (0x0C162B00, mode.c) is MODE_MAIN_MAX = 8 entries of 0xCC bytes:
a main_func followed by sub_func[16], each a 12-byte
{ int mode_asg; char *name; void (*func)(void); } (field names from the
asserts in mode.c; layout from mode_update() at 0x0C0247C0, which checks
mode_asg, prints name as "%s.%s" and mode_exec() calls func).

Writes:
  ghidra/types/gen_mode.h          e_mode_main + one sub-mode enum per main mode
  ghidra/symbols/gen_mode.tsv      a row per handler function

Handler names are the mode's own debug name in lower case (GAME_STAGE_INIT
-> game_stage_init; main modes -> mode_<name>). Sega's sub-mode names
mostly carry their mode already (SEGA_INIT, SEL_CHARA_SELECT); a one-word
name (WARNING's INIT, DISP) or one used by two modes gets the main mode's
name in front (WARNING_INIT). Main-mode enum members are MODE_MAIN_<name>,
after the MODE_MAIN_MAX in the assert.

usage: mode_table.py <main.bin> <repo root>
"""
import os
import re
import struct
import sys

BASE = 0x0C020000
MODE_DATA = 0x0C162B00
MAIN_MAX = 8          # assert mode.c:451 (req < MODE_MAIN_MAX), bound checked as > 7
SUB_MAX = 16          # (0xCC - 12) / 12
STRIDE = 0xCC


def main():
    data = open(sys.argv[1], "rb").read()
    root = sys.argv[2]

    def u32(a):
        return struct.unpack_from("<I", data, a - BASE)[0]

    def cstr(a):
        off = a - BASE
        end = data.find(b"\0", off, off + 64)
        return data[off:end].decode("ascii")

    def ident(s):
        return re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").upper()

    # first pass: raw sub-mode names, to find ones used by more than one mode
    raw = []
    for m in range(MAIN_MAX):
        a = MODE_DATA + m * STRIDE
        for k in range(SUB_MAX):
            p = u32(a + 12 + k * 12 + 4)
            if not p:
                break
            raw.append(ident(cstr(p)))
    dup = {n for n in raw if raw.count(n) > 1}

    header = ["/* Generated by tools/mode_table.py from mode_data (0x0C162B00). */", ""]
    rows = []
    mains = []
    for m in range(MAIN_MAX):
        a = MODE_DATA + m * STRIDE
        asg, name_p, fn = u32(a), u32(a + 4), u32(a + 8)
        assert asg == m, f"main {m}: mode_asg {asg}"
        name = cstr(name_p)
        short = ident(re.sub(r"\s+MODE$", "", name))
        mains.append(short)
        rows.append((fn, f"mode_{short.lower()}", "void {}(void)",
                     f'main-mode handler for "{name}" (mode_data[{m}].main_func.func)'))
        subs = []
        for k in range(SUB_MAX):
            e = a + 12 + k * 12
            sasg, sname_p, sfn = u32(e), u32(e + 4), u32(e + 8)
            if not sname_p:
                break
            assert sasg == k, f"main {m} sub {k}: mode_asg {sasg}"
            sname = cstr(sname_p)
            sid = ident(sname)
            if "_" not in sid or sid in dup:
                sid = f"{short}_{sid}"
            subs.append(sid)
            rows.append((sfn, sid.lower(), "void {}(void)",
                         f'sub-mode handler for "{sname}" (mode_data[{m}].sub_func[{k}].func, in "{name}")'))
        header.append(f"/* sub-modes of \"{name}\" (mode_data[{m}].sub_func[]) */")
        header.append(f"typedef enum e_mode_{short.lower()} {{")
        header += [f"    {s} = {i}," for i, s in enumerate(subs)]
        header.append(f"}} e_mode_{short.lower()};")
        header.append("")

    main_enum = ["/* main modes: mode_data[] index, main_mode_no. MODE_MAIN_NONE (inferred) is",
                 " * the \"no request\" value mode_update() resets main_mode_req to. */",
                 "typedef enum e_mode_main {", "    MODE_MAIN_NONE = -1,"]
    main_enum += [f"    MODE_MAIN_{s} = {i}," for i, s in enumerate(mains)]
    main_enum += [f"    MODE_MAIN_MAX = {MAIN_MAX},", "} e_mode_main;", ""]
    header = header[:2] + main_enum + header[2:]

    os.makedirs(os.path.join(root, "ghidra", "types"), exist_ok=True)
    os.makedirs(os.path.join(root, "ghidra", "symbols"), exist_ok=True)
    with open(os.path.join(root, "ghidra", "types", "gen_mode.h"), "w") as f:
        f.write("\n".join(header))
    seen = set()
    with open(os.path.join(root, "ghidra", "symbols", "gen_mode.tsv"), "w") as f:
        f.write("address\tkind\tdeclaration\tconfidence\tevidence\n")
        for fn, name, proto, ev in rows:
            if fn in seen:      # one handler used by two modes keeps its first name
                continue
            seen.add(fn)
            f.write(f"{fn:08x}\tfunction\t{proto.format(name)}\tnamed\t{ev}\n")
    print(f"{len(mains)} main modes, {len(rows) - len(mains)} sub-modes, {len(seen)} handler functions")


if __name__ == "__main__":
    main()
