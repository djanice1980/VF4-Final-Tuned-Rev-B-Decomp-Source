"""Which hand-written assembly routines in source/asm/ read like source.

    python3 -I tools/match/asm_readable.py [FILE.s ...] [-q]

A routine the game's authors wrote in assembly has no C to recover; its
source is the assembly. tools/match/to_asm.py writes that from the game's
bytes as a bare listing. A file counts as readable once a person can
follow it without the binary:

  1. every entry (.global) is introduced by a comment block, directly
     above its .global line, that says what the routine does and has an
     "! In:" line (what each input register or global holds) and an
     "! Out:" line (what it returns or leaves behind; "nothing" is an
     answer);
  2. the code is explained: no stretch of 8 or more instructions between
     two labels goes without a comment, and the file has at least one
     comment for every 10 instructions;
  3. no word is left raw without saying what it is: a .word / .long /
     .short / .byte line that is not a named pool word (.long _symbol or
     .long _symbol+N) has a comment on its line, or its run of such lines
     starts under a comment line (a label ends a run: a labelled raw word
     needs its own comment);
  4. no placeholder names: no _DAT_<address> or _FUN_<address> symbol.

A comment counts only if it says something: at least three words. The
generated header lines do not count. The description must have text of
its own besides its In:, Out:, Uses: and Notes: lines. The checker counts
comments and cannot judge them; that they are true is the writer's job.

Comments do not change the bytes; tools/match/match.py still checks the
file against the game. With no FILE it checks every file in source/asm/
and prints the totals; the exit status is 0 only when all pass.

tools/progress.py counts a hand-written routine as reading like source
when its file passes (readable_names()).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GENERATED = ("! Generated by tools/match/to_asm.py", "! assembly (not the game's compiler's output)")
LABEL = re.compile(r"^([.\w$]+):")
GLOBAL = re.compile(r"^\s*\.global\s+(\S+)")
RAW = re.compile(r"^\s*\.(word|long|short|byte)\b\s*(.*?)\s*(!.*)?$")
DIRECTIVE = re.compile(r"^\s*\.\w+")
PLACEHOLDER = re.compile(r"\b_(?:DAT|FUN)_[0-9a-f]{8}\b")


HEADER1 = re.compile(r"^! 0x[0-9a-f]{8}  size 0x")
FIELD = ("In:", "Out:", "Uses:", "Notes:")


def says_something(text):
    """A comment's text has at least three words."""
    return len(re.findall(r"[A-Za-z0-9_]{2,}", text)) >= 3


def is_comment(line):
    t = line.lstrip()
    return t.startswith("!") and not line.startswith(GENERATED) and not HEADER1.match(line) \
        and not t.startswith("! Annotated by hand") and says_something(t[1:])


def trailing_comment(line):
    i = line.find("!")
    return i > 0 and says_something(line[i + 1:])


def check(path):
    """(entry names, list of problems) for one .s file."""
    lines = open(path, encoding="utf-8", errors="replace").read().split("\n")
    problems, entries = [], []
    code = 0
    comments = 0
    since = 0          # instructions since the last label or comment
    since_at = 0
    run_ok = False     # inside a run of raw words that started under a comment
    prev_raw = False
    prev_comment = False
    for i, line in enumerate(lines):
        s = line.strip()
        if not s:
            prev_raw = False
            continue
        if line.lstrip().startswith("!"):
            if is_comment(line):
                comments += 1
                since = 0
                prev_comment = True
            prev_raw = False
            continue
        g = GLOBAL.match(line)
        if g:
            name = g.group(1)
            entries.append(name[1:] if name.startswith("_") else name)
            block = []
            j = i - 1
            while j >= 0 and lines[j].lstrip().startswith("!"):
                if is_comment(lines[j]):
                    block.append(lines[j].lstrip()[1:].strip())
                j -= 1
            text = [b for b in block if b]
            own = " ".join(b for b in text if not b.startswith(FIELD) and b != name.lstrip("_"))
            # continuation lines of a field are indented further; they are
            # still field text, so ask for real prose: 8 words of description
            if not any(b.startswith("In:") for b in text) or not any(b.startswith("Out:") for b in text) \
                    or len(re.findall(r"[A-Za-z0-9_]{2,}", own)) < 8:
                problems.append(f"{i + 1}: {name} has no description block with In: and Out: above its .global")
            prev_comment = prev_raw = False
            continue
        if LABEL.match(line):
            since = 0
            prev_raw = False
            prev_comment = False
            continue
        trailing = trailing_comment(line)
        r = RAW.match(line)
        if trailing and (r or not DIRECTIVE.match(line)):
            comments += 1
        if r:
            named = r.group(1) == "long" and re.fullmatch(r"_[A-Za-z_]\w*(?:[+-]\w+)?", r.group(2) or "") \
                and not PLACEHOLDER.search(r.group(2))
            if not prev_raw:
                run_ok = prev_comment
            if not (named or trailing or run_ok):
                problems.append(f"{i + 1}: raw {s.split()[0]} with no comment saying what it is")
            prev_raw = True
            prev_comment = False
            if trailing:
                since = 0
            continue
        prev_raw = False
        prev_comment = False
        if DIRECTIVE.match(line):
            continue
        code += 1
        if trailing:
            since = 0
        else:
            if since == 0:
                since_at = i + 1
            since += 1
            if since == 8:
                problems.append(f"{since_at}: 8 instructions in a row with no comment")
    for m in sorted(set(PLACEHOLDER.findall("\n".join(lines)))):
        problems.append(f"placeholder name {m}")
    if code and comments * 10 < code:
        problems.append(f"{comments} comments for {code} instructions (at least one per 10)")
    return entries, problems


def files():
    d = os.path.join(ROOT, "source", "asm")
    return sorted(os.path.join(d, f) for f in os.listdir(d) if f.endswith(".s")) if os.path.isdir(d) else []


def readable_names():
    """Names of the entries in source/asm/ files that pass."""
    out = set()
    for p in files():
        entries, problems = check(p)
        if not problems:
            out.update(entries)
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("-")]
    quiet = "-q" in sys.argv
    paths = args or files()
    good = fns = good_fns = 0
    for p in paths:
        entries, problems = check(p)
        fns += len(entries)
        if not problems:
            good += 1
            good_fns += len(entries)
        elif not quiet or args:
            print(f"{os.path.relpath(p, ROOT)}: {len(problems)} problem(s)")
            for x in problems[:12 if args else 3]:
                print(f"    {x}")
            if len(problems) > (12 if args else 3):
                print(f"    ... {len(problems) - (12 if args else 3)} more")
    print(f"{good} of {len(paths)} files read like source ({good_fns} of {fns} routines)")
    sys.exit(0 if good == len(paths) else 1)


if __name__ == "__main__":
    main()
