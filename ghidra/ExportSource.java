	private static String sourceTag(Function f) {
		for (FunctionTag t : f.getTags()) {
			String n = t.getName();
			if (n.startsWith("src:") || n.startsWith("src?:") || n.startsWith("srcp:") || n.startsWith("srcc:") || n.startsWith("srcs:")) {
				return n;
			}
		}
		return null;
	}

	private static String confidence(Function f) {
		SourceType s = f.getSymbol().getSource();
		if (s == SourceType.DEFAULT) {
			return "placeholder";
		}
		String c = f.getComment();
		if (c != null && c.contains("name: named")) {
			return "named";
		}
		// the name is from analysis and a logged run of the game confirmed
		// what the description says (tools/observe_apply.py)
		if (c != null && c.contains("name: observed")) {
			return "observed";
		}
		// the game never runs it; called in the harness with chosen inputs it
		// did what the description says (tools/observe_apply.py)
		return (c != null && c.contains("name: exercised")) ? "exercised" : "inferred";
	}

	// C spelling of a Ghidra type (Ghidra prints a bare default pointer as "pointer")
	private static String cName(ghidra.program.model.data.DataType dt) {
		if (dt instanceof ghidra.program.model.data.Pointer) {
			ghidra.program.model.data.DataType to = ((ghidra.program.model.data.Pointer) dt).getDataType();
			// a pointer with no target type: the decompiler treats it as
			// pointing at bytes (indexes and adds in bytes), so undefined *
			return (to == null ? "undefined" : cName(to)) + " *";
		}
		if (dt instanceof ghidra.program.model.data.Array) {
			ghidra.program.model.data.Array a = (ghidra.program.model.data.Array) dt;
			String of = cName(a.getDataType());
			String n = "[" + a.getNumElements() + "]";
			// an array of arrays: this count is the outer one, so it goes first
			// (char x[31][256] is 31 of char[256])
			return a.getDataType() instanceof ghidra.program.model.data.Array
				? of.replaceFirst("\\[", java.util.regex.Matcher.quoteReplacement(n) + "[")
				: of + n;
		}
		if (dt instanceof ghidra.program.model.data.Enum
			&& dt.getCategoryPath().getPath().equals("/vf4ft/enums")) {
			return "enum " + dt.getName();
		}
		return dt.getDisplayName();
	}

	private static final String GEN = " * Generated by ghidra/ExportSource.java from the Ghidra project.\n";

	// Ghidra's DataTypeWriter starts every file with its own copies of the basic
	// types (typedef unsigned char byte; ...); C before C11 rejects a typedef
	// given twice, and the game's compiler is GCC 3.2, so they live once, in
	// vf4ft_base.h, and these copies are dropped (bool too: Ghidra's is one
	// byte, vf4ft_base.h's an int, which is what a signature printing bool
	// has always meant here; a committed signature brings Ghidra's in)
	private static final java.util.regex.Pattern BASIC = java.util.regex.Pattern.compile(
		"^typedef\\s+(unsigned\\s+|signed\\s+)?(char|short|int|long|long\\s+long)\\s+(undefined\\d?|byte|uchar|uint|ulong|ushort|word|dword|qword|ulonglong|longlong|sbyte|schar|sdword|sqword|sword|bool)\\s*;\\s*$");

	private void writeTypes(PrintWriter w, java.util.List<ghidra.program.model.data.DataType> list) throws Exception {
		java.io.StringWriter sw = new java.io.StringWriter();
		new DataTypeWriter(currentProgram.getDataTypeManager(), sw).write(list, monitor);
		// a struct Ghidra knows only by name (zlib's internal_state: deflate.c
		// and inflate.c each define their own) is written empty, which GCC
		// sizes 0, so the decompiler's z->state + 0x14 (bytes, to it) came out
		// as + 0; one placeholder byte makes C count in bytes as it does
		String typesText = sw.toString().replaceAll("(?m)^(struct \\w+ \\{)\\n\\};",
			"$1\n    undefined _; /* known by name only: offsets from it are in bytes */\n};");
		sw = new java.io.StringWriter();
		sw.write(typesText);
		// enums from /vf4ft/enums are written once, in vf4ft_enums.h; the writer
		// repeats one a structure member uses (a debug-menu member: AssignAggregates)
		Category enums = currentProgram.getDataTypeManager().getCategory(new CategoryPath("/vf4ft/enums"));
		java.util.Set<String> enumNames = new java.util.HashSet<>();
		boolean writingEnums = list.stream().anyMatch(t -> t.getCategoryPath().getPath().startsWith("/vf4ft/enums"));
		if (enums != null && !writingEnums) {
			java.util.Deque<Category> cats = new java.util.ArrayDeque<>();
			cats.push(enums);
			while (!cats.isEmpty()) { // the sized variants (e_off_on_8) live in subcategories
				Category c = cats.pop();
				for (ghidra.program.model.data.DataType t : c.getDataTypes()) {
					enumNames.add(t.getName());
				}
				for (Category sub : c.getCategories()) {
					cats.push(sub);
				}
			}
		}
		boolean skipping = false;
		for (String line : sw.toString().split("\n", -1)) {
			java.util.regex.Matcher em = java.util.regex.Pattern.compile("^typedef enum (\\w+) \\{").matcher(line);
			if (!skipping && em.find() && enumNames.contains(em.group(1))) {
				skipping = true;
			}
			if (skipping) {
				if (line.matches("^\\}\\s*\\w+;\\s*$")) {
					skipping = false;
				}
				continue;
			}
			// the writer names an undefined filler byte fieldN_0xOFF, the decompiler
			// field_0xOFF; one member per offset, so the decompiler's name is safe
			line = line.replaceAll("\\bfield\\d+_(0x[0-9a-f]+)\\b", "field_$1");
			// every enum in vf4ft_enums.h has a typedef name (a sized one is only a
			// typedef of unsigned char/short), so a member uses that, not "enum X"
			java.util.regex.Matcher tm = java.util.regex.Pattern.compile("\\benum (\\w+)\\b(?! \\{)").matcher(line);
			StringBuffer tb = new StringBuffer();
			while (tm.find()) {
				tm.appendReplacement(tb, enumNames.contains(tm.group(1)) ? tm.group(1) : tm.group(0));
			}
			tm.appendTail(tb);
			line = tb.toString();
			// size_t and va_list come from <stddef.h> and <stdarg.h> in
			// vf4ft_base.h (ghidra/types/libc.h)
			if (!BASIC.matcher(line).matches() && !line.matches("^typedef\\s.*\\b(size_t|va_list)\\s*;\\s*$")) {
				w.println(line);
			}
		}
	}

	private static String guard(String name) {
		String g = name.toUpperCase().replaceAll("[^A-Z0-9]", "_");
		return "#ifndef " + g + "\n#define " + g + "\n";
	}

	private void writeHeaders(File inc) throws Exception {
		inc.mkdirs();
		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft_base.h"))) {
			w.print("/*\n * Ghidra's sized placeholder types, defined once for every header.\n" + GEN + " */\n"
				+ guard("vf4ft_base.h") + "#include <stdarg.h>\n#include <stddef.h>\n#include <stdint.h>\n\n"
				+ "typedef unsigned char undefined, undefined1, byte, uchar;\n"
				+ "typedef unsigned short undefined2, ushort, word;\n"
				+ "typedef unsigned int undefined4, uint, dword;\n"
				+ "typedef unsigned long ulong;\n"
				+ "typedef unsigned long long undefined8, ulonglong, qword;\n"
				+ "typedef long long longlong;\n"
				+ "typedef int code(); /* Ghidra's code: a function (any arguments), so (*(code *)p)(...) compiles */\n"
				+ "typedef void *pointer; /* how Ghidra writes an untyped pointer member */\n"
				+ "#ifndef __cplusplus\ntypedef int bool;\n#define true 1\n#define false 0\n#endif\n\n"
				+ "#endif\n");
		}
		Category enums = currentProgram.getDataTypeManager()
			.getCategory(new CategoryPath("/vf4ft/enums"));
		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft_enums.h"))) {
			w.print("/*\n * Enums recovered from debug name tables (tools/name_tables.py,\n"
				+ " * ghidra/ApplyEnums.java). Each value is the index into its table.\n"
				+ " * Member names are unique per enum only, not across enums.\n" + GEN + " */\n"
				+ guard("vf4ft_enums.h") + "#include \"vf4ft_base.h\"\n\n");
			if (enums != null) {
				java.util.List<ghidra.program.model.data.DataType> top =
					java.util.Arrays.asList(enums.getDataTypes());
				writeTypes(w, top);
				// narrower copies (ApplyEnums SIZED): same values, so a typedef
				Category sized = enums.getCategory("sized");
				if (sized != null) {
					w.println("\n/* Narrower variants: same values as the enum named in the comment. */");
					for (ghidra.program.model.data.DataType d : sized.getDataTypes()) {
						String base = d.getName().replaceAll("_(8|16)$", "");
						w.printf("typedef %s %s; /* enum %s */%n",
							d.getLength() == 1 ? "unsigned char" : "unsigned short", d.getName(), base);
					}
				}
			}
			w.println("\n#endif");
		}

		Category types = currentProgram.getDataTypeManager()
			.getCategory(new CategoryPath("/vf4ft/types"));
		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft_types.h"))) {
			w.print("/*\n * Recovered structs and enums (the headers in ghidra/types/, applied by\n"
				+ " * ghidra/ApplyTypes.java); the field comments live in those headers.\n" + GEN + " */\n"
				+ guard("vf4ft_types.h") + "#include \"vf4ft_enums.h\"\n\n");
			if (types != null) {
				writeTypes(w, java.util.Arrays.asList(types.getDataTypes()));
			}
			// object layouts from base + offset addressing (ghidra/AssignAggregates.java)
			Category aggs = currentProgram.getDataTypeManager().getCategory(new CategoryPath("/vf4ft/aggregates"));
			if (aggs != null) {
				w.println("\n/* object layouts from how the code addresses them (ghidra/AssignAggregates.java) */");
				writeTypes(w, java.util.Arrays.asList(aggs.getDataTypes()));
			}
			w.println("\n#endif");
		}

		int n = 0;
		// every unnamed global (DAT_ / PTR_) as Ghidra types it: what decompiler
		// output assumes. Not included by vf4ft.h: source/ files declare the
		// globals they use with better types (int, not undefined4), and
		// signedness changes the code GCC makes.
		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft_data.h"))) {
			w.print("/*\n * The unnamed globals (DAT_..., PTR_...) src/ uses, as Ghidra types them, for compiling\n"
				+ " * decompiler output (tools/match/auto_match.py). Not part of vf4ft.h.\n" + GEN
				+ " */\n" + guard("vf4ft_data.h") + "#include \"vf4ft_enums.h\"\n#include \"vf4ft_types.h\"\n\n");
			int nd = 0;
			java.util.Set<String> declared = new java.util.HashSet<>();
			SymbolIterator si = currentProgram.getSymbolTable().getAllSymbols(true);
			while (si.hasNext()) {
				Symbol sym = si.next();
				long off = sym.getAddress().getOffset();
				String nm = sym.getName();
				// unnamed: a default label, or an analysis label that keeps the
				// address name (AssignSigns.java types the data under it)
				boolean unnamed = sym.getSource() == SourceType.DEFAULT
					|| (sym.getSource() == SourceType.ANALYSIS && nm.startsWith("DAT_"));
				// every global with a type is declared, used by src/ or not: matched
				// code (by hand, by agents) may reach one the decompiler does not
				Data typed = getDataAt(sym.getAddress());
				boolean hasType = nm.startsWith("agg_") || (typed != null && typed.isDefined()
					&& !(typed.getDataType() instanceof ghidra.program.model.data.Undefined));
				if (sym.getSymbolType() != SymbolType.LABEL || !unnamed
					|| !(used.contains(nm) || hasType) || !(nm.startsWith("DAT_") || nm.startsWith("PTR_") || nm.startsWith("agg_")
						|| nm.startsWith("LAB_") || nm.startsWith("SUB_"))
					|| !nm.matches("[A-Za-z_]\\w*") // a pointer named after its string (PTR_s_%d_...)
					|| !sym.getAddress().isMemoryAddress() // any address the code uses, not only main RAM
					|| getFunctionAt(sym.getAddress()) != null) {
					continue;
				}
				Data d = getDataAt(sym.getAddress());
				String type = d == null ? "undefined" : cName(d.getDataType());
				String decl = type.endsWith("]")
					? type.replaceFirst("\\[", " " + nm + "[")
					: type + " " + nm;
				w.printf("extern %s; /* 0x%08x */%n", decl, off);
				declared.add(nm);
				nd++;
			}
			// a name the code uses (src/ or source/) for an address that is now
			// inside an object (AssignAggregates) or its start: still declared on
			// its own, typed as the member there, so code written with the name
			// compiles as it did (a pool word holding that address); match.py
			// reads a DAT_ name's address from its spelling
			int nm2 = 0;
			for (String nm : new java.util.TreeSet<>(used)) {
				java.util.regex.Matcher am = java.util.regex.Pattern.compile("_(0c[0-9a-f]{6})$").matcher(nm);
				if (declared.contains(nm) || !am.find() || !(nm.startsWith("DAT_") || nm.startsWith("PTR_"))) {
					continue;
				}
				ghidra.program.model.address.Address at = toAddr(Long.parseLong(am.group(1), 16));
				Data obj = currentProgram.getListing().getDataContaining(at);
				if (obj != null && obj.getAddress().equals(at) && !(obj.getDataType() instanceof ghidra.program.model.data.Structure)) {
					// data Ghidra names otherwise (PTR_LAB_..., a typed default
					// label) that source/ spells by its address (pin_globals)
					String type = cName(obj.getDataType());
					String decl = type.endsWith("]") ? type.replaceFirst("\\[", " " + nm + "[") : type + " " + nm;
					Symbol own = currentProgram.getSymbolTable().getPrimarySymbol(at);
					w.printf("extern %s; /* 0x%s, Ghidra's %s */%n", decl, at, own == null ? "data" : own.getName());
					declared.add(nm);
					nm2++;
					continue;
				}
				if (obj == null || !(obj.getDataType() instanceof ghidra.program.model.data.Structure)) {
					continue;
				}
				Data member = obj.getComponentContaining((int) at.subtract(obj.getAddress()));
				String type = member != null && member.getAddress().equals(at) && member.getDataType() != ghidra.program.model.data.DataType.DEFAULT
					? cName(member.getDataType()) : "undefined";
				String decl = type.endsWith("]") ? type.replaceFirst("\\[", " " + nm + "[") : type + " " + nm;
				w.printf("extern %s; /* 0x%s, in %s */%n", decl, at, obj.getDataType().getName());
				declared.add(nm);
				nm2++;
			}
			// _DAT_ names: volatile outside main RAM (hardware registers: a
			// polling loop must load every time)
			for (Map.Entry<String, String> e : partialGlobals.entrySet()) {
				String nm = e.getKey(), addr = nm.substring(5);
				boolean ram = addr.startsWith("0c") || addr.startsWith("8c");
				String type = e.getValue();
				String decl = type.endsWith("]") ? type.replaceFirst("\\[", " " + nm + "[") : type + " " + nm;
				w.printf("extern %s%s; /* 0x%s, accessed as %s */%n", ram ? "" : "volatile ", decl, addr, type);
				nm2++;
			}
			w.println("\n#endif");
			println(String.format("headers: %d unnamed globals, %d more for addresses inside objects or accessed as another type -> vf4ft_data.h", nd, nm2));
		}
		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft_globals.h"))) {
			w.print("/*\n * Named globals. Names come from Sega's debug-menu labels unless a\n"
				+ " * note says otherwise; the plate notes are listed above each one.\n" + GEN
				+ " */\n" + guard("vf4ft_globals.h") + "#include \"vf4ft_enums.h\"\n#include \"vf4ft_types.h\"\n\n");
			java.util.Set<String> vol = volatileGlobals();
			SymbolIterator si = currentProgram.getSymbolTable().getAllSymbols(true);
			while (si.hasNext()) {
				Symbol sym = si.next();
				long off = sym.getAddress().getOffset();
				if (sym.getSymbolType() != SymbolType.LABEL || sym.getSource() != SourceType.USER_DEFINED
					|| !sym.isPrimary()
					|| !sym.getAddress().isMemoryAddress() // RAM and named hardware registers alike
					|| getFunctionAt(sym.getAddress()) != null) {
					continue;
				}
				Data d = getDataAt(sym.getAddress());
				String type = d == null ? memberType(sym.getAddress()) : cName(d.getDataType());
				String note = currentProgram.getListing().getComment(
					ghidra.program.model.listing.CodeUnit.PLATE_COMMENT, sym.getAddress());
				if (note != null) {
					for (String line : note.split("\n")) {
						w.println("/* " + line + " */");
					}
				}
				String decl = type.endsWith("]")
					? type.replaceFirst("\\[", " " + sym.getName() + "[")
					: type + " " + sym.getName();
				w.printf("extern %s%s; /* 0x%08x */%n%n", vol.contains(sym.getName()) ? "volatile " : "", decl, off);
				n++;
			}
			w.println("#endif");
		}

		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft.h"))) {
			w.print("/*\n * Common header for the reconstructed source: Ghidra's sized\n"
				+ " * placeholder types, plus the recovered enums, globals and functions.\n" + GEN + " */\n"
				+ guard("vf4ft.h") + "#include \"vf4ft_base.h\"\n"
				+ "#include \"vf4ft_enums.h\"\n#include \"vf4ft_types.h\"\n#include \"vf4ft_globals.h\"\n"
				+ "#include \"vf4ft_functions.h\"\n\n#endif\n");
		}
		try (PrintWriter w = new PrintWriter(new File(inc, "vf4ft_functions.h"))) {
			w.print("/*\n * Every function: as its row in ghidra/symbols/ declares it, else as the\n"
				+ " * decompiler prints its signature (the definitions in src/ show the same).\n"
				+ " * Variadic ones are declared with their named arguments and \"...\";\n"
				+ " * Ghidra itself keeps them unprototyped.\n"
				+ GEN + " */\n" + guard("vf4ft_functions.h")
				+ "#include \"vf4ft_enums.h\"\n#include \"vf4ft_types.h\"\n\n"
				+ "/* The original files did not all declare a function the same way. One the\n"
				+ " * game calls both through r0 and through r1 (ghidra/returns.tsv: \"mixed\")\n"
				+ " * was undeclared in some: GCC calls an undeclared function as returning int,\n"
				+ " * through r0. One with a char or short parameter was declared old-style in\n"
				+ " * some (void f();): the return type known, the arguments passed as ints,\n"
				+ " * not converted (sound_request's callers). A file that defines\n"
				+ " * NOPROTO_<name> before including this gets no declaration of it, one that\n"
				+ " * defines KRPROTO_<name> the old-style one; the others the prototype. */\n\n");
			java.util.Set<String> mixed = mixedCallees();
			java.util.regex.Pattern fname = java.util.regex.Pattern.compile("\\b([A-Za-z_]\\w*)\\s*\\(");
			java.util.regex.Pattern narrow = java.util.regex.Pattern.compile(
				"\\((?:[^()]*[,(]\\s*)?(?:char|short|byte|uchar|ushort|bool|undefined1|undefined2|schar)\\s+\\w+\\s*[,)]");
			int guarded = 0;
			for (String line : decls.toString().split("\n")) {
				java.util.regex.Matcher fm = fname.matcher(line);
				String head = line.replaceFirst("/\\*.*$", "");
				boolean nar = narrow.matcher(head).find() && !head.contains("...");
				if (fm.find() && (mixed.contains(fm.group(1)) || nar)) {
					String nm = fm.group(1);
					w.println("#if defined(NOPROTO_" + nm + ")");
					w.println("#elif defined(KRPROTO_" + nm + ")");
					w.println(head.substring(0, fm.end()) + ");");
					w.println("#else");
					w.println(line);
					w.println("#endif");
					guarded++;
				} else if (!line.isEmpty()) {
					w.println(line);
				}
			}
			println("headers: " + guarded + " functions declared three ways (NOPROTO_ / KRPROTO_ / prototype)");
			w.println("\n#endif");
		}
		println(String.format("headers: %d named globals -> %s", n, inc));
	}

	/** The type of the member starting at a, when a is inside an object
	 *  (a debug-menu name for one member: AssignAggregates; a name-only alias
	 *  row), looking through nested records (user_back_data.challenge.
	 *  chlg_map_hiscores); else undefined. */
	private String memberType(ghidra.program.model.address.Address a) {
		Data obj = currentProgram.getListing().getDataContaining(a);
		while (obj != null && obj.getDataType() instanceof ghidra.program.model.data.Structure) {
			Data m = obj.getComponentContaining((int) a.subtract(obj.getAddress()));
			if (m == null) {
				break;
			}
			if (m.getAddress().equals(a) && m.getDataType() != ghidra.program.model.data.DataType.DEFAULT) {
				return cName(m.getDataType());
			}
			obj = m; // a must start inside this member: look into it
		}
		return "undefined";
	}

	private final StringBuilder decls = new StringBuilder();

	/** Globals ghidra/volatile_globals.tsv declares volatile (name, evidence):
	 *  objects the original declared so, which a Ghidra data type cannot say. */
	private java.util.Set<String> volatileGlobals() throws Exception {
		java.util.Set<String> out = new java.util.HashSet<>();
		File t = new File(getSourceFile().getParentFile().getAbsolutePath(), "volatile_globals.tsv");
		if (t.exists()) {
			for (String line : java.nio.file.Files.readAllLines(t.toPath())) {
				String[] f = line.split("\t");
				if (f.length > 0 && !f[0].isEmpty()) {
					out.add(f[0]);
				}
			}
		}
		return out;
	}

	/** Callees AssignReturns found called through both r0 and r1. */
	private java.util.Set<String> mixedCallees() throws Exception {
		java.util.Set<String> out = new java.util.HashSet<>();
		File t = new File(getSourceFile().getParentFile().getAbsolutePath(), "returns.tsv");
		if (!currentProgram.getName().equals("main.bin") || !t.exists()) {
			return out;
		}
		for (String line : java.nio.file.Files.readAllLines(t.toPath())) {
			String[] f = line.split("\t");
			if (f.length > 5 && f[5].startsWith("mixed")) {
				out.add(f[1]);
			}
			// the same callee on the pass that first types it: AssignReturns
			// makes it void there ("set void" with calls through r0 is only
			// its few-through-r0-among-many-through-r1 rule) and reports
			// "mixed: left alone" on every later pass; the header must not
			// depend on which pass this is
			if (f.length > 5 && f[5].equals("set void") && !f[2].equals("0")) {
				out.add(f[1]);
			}
		}
		// and every function a matched file declares its own way (#define
		// NOPROTO_f / KRPROTO_f in source/): without the guard its define does
		// nothing, and the file stops compiling as the original did
		java.util.regex.Pattern def = java.util.regex.Pattern.compile("^#define (?:NO|KR)PROTO_(\\w+)", java.util.regex.Pattern.MULTILINE);
		java.nio.file.Path src = new File(getSourceFile().getParentFile().getParentFile().getAbsolutePath(), "source").toPath();
		if (java.nio.file.Files.isDirectory(src)) {
			try (java.util.stream.Stream<java.nio.file.Path> s = java.nio.file.Files.walk(src)) {
				for (java.nio.file.Path p : (Iterable<java.nio.file.Path>) s.filter(x -> x.toString().endsWith(".c"))::iterator) {
					java.util.regex.Matcher m = def.matcher(java.nio.file.Files.readString(p));
					while (m.find()) {
						out.add(m.group(1));
					}
				}
			}
		}
		return out;
	}

	private static final java.util.regex.Pattern HW_DEREF = java.util.regex.Pattern.compile(
		// not a code pointer: a call through the uncached mirror (FUN | 0xa0000000)
		// is no register, and GCC takes a call through a volatile function as noreturn
		"\\*\\((?!volatile |code )([A-Za-z_]\\w*(?: \\w+)? \\*)\\)\\((?=(?:[^()]|\\([^()]*\\))*?\\+ -0x[0-9a-f]{7,8}\\b)");

	/** *(T *)(x + -0x5fa08000): an address 0xa05f8000 + x, a hardware register
	 *  (an offset that large is no struct's): volatile, as the original must
	 *  have had it (GCC adds and then loads at @(0,rN) for one, FUN_0c14a280) */
	static String volatileHardware(String c) {
		java.util.regex.Matcher m = HW_DEREF.matcher(c);
		StringBuffer b = new StringBuffer();
		while (m.find()) {
			m.appendReplacement(b, java.util.regex.Matcher.quoteReplacement("*(volatile " + m.group(1) + ")("));
		}
		m.appendTail(b);
		return b.toString();
	}

	/** libgcc's division helpers are what GCC calls for "/" on ints: the C
	 *  said a / b (a call to the helper compiles as an ordinary call). */
	static String division(String c, String helper, String type) {
		StringBuilder out = new StringBuilder();
		int from = 0;
		while (true) {
			int at = c.indexOf(helper + "(", from);
			if (at < 0) {
				break;
			}
			int open = at + helper.length(), depth = 0, comma = -1, close = -1;
			for (int i = open; i < c.length(); i++) {
				char ch = c.charAt(i);
				if (ch == '(') {
					depth++;
				} else if (ch == ')') {
					if (--depth == 0) {
						close = i;
						break;
					}
				} else if (ch == ',' && depth == 1) {
					comma = i;
				}
			}
			// the helper's own definition or declaration (a type before it on
			// its line) stays: only calls become "/"
			int bol = c.lastIndexOf('\n', at) + 1;
			boolean signature = c.substring(bol, at).matches("\\s*[A-Za-z_][\\w \\*]*\\s+\\**");
			if (close < 0 || comma < 0 || signature || (at > 0 && Character.isJavaIdentifierPart(c.charAt(at - 1)))) {
				out.append(c, from, open);
				from = open;
				continue;
			}
			String a = c.substring(open + 1, comma).strip(), b = c.substring(comma + 1, close).strip();
			out.append(c, from, at).append("((" + type + ")(" + a + ") / (" + type + ")(" + b + "))");
			from = close + 1;
		}
		out.append(c.substring(from));
		return out.toString();
	}

	// _DAT_<address>: a global the decompiler accesses as another type than
	// the data there (hardware registers at a05f..., e0..., mostly); its type
	// as the decompiler has it, from its global symbol map
	private final Map<String, String> partialGlobals = new java.util.TreeMap<>();

	private static final java.util.regex.Pattern PARTIAL_GLOBAL = java.util.regex.Pattern.compile("(?<![\\w])_DAT_([0-9a-f]{8})\\b");

	/** The decompiler prints _DAT_x for its global symbol DAT_x when the
	 *  access has another type than the data there; the type is the symbol's. */
	private void notePartialGlobals(String c, ghidra.program.model.pcode.HighFunction hf) {
		if (hf == null) {
			return;
		}
		// the access: a varnode at that address, of the access's size, whose
		// high variable has the type the decompiler gives it
		java.util.Map<Long, String> types = new java.util.HashMap<>();
		java.util.Iterator<ghidra.program.model.pcode.PcodeOpAST> ops = hf.getPcodeOps();
		while (ops.hasNext()) {
			ghidra.program.model.pcode.PcodeOpAST op = ops.next();
			java.util.List<ghidra.program.model.pcode.Varnode> vns = new java.util.ArrayList<>(java.util.Arrays.asList(op.getInputs()));
			if (op.getOutput() != null) {
				vns.add(op.getOutput());
			}
			for (ghidra.program.model.pcode.Varnode vn : vns) {
				if (vn == null || !vn.isAddress() || !vn.getAddress().isMemoryAddress()) {
					continue;
				}
				ghidra.program.model.data.DataType t = vn.getHigh() == null ? null : vn.getHigh().getDataType();
				String name = t != null && t.getLength() == vn.getSize() ? cName(t) : "undefined" + vn.getSize();
				types.putIfAbsent(vn.getAddress().getOffset(), name);
			}
		}
		java.util.regex.Matcher m = PARTIAL_GLOBAL.matcher(c);
		while (m.find()) {
			String t = types.get(Long.parseLong(m.group(1), 16));
			partialGlobals.putIfAbsent("_DAT_" + m.group(1), t == null ? "undefined4" : t);
		}
	}

	private static final java.util.regex.Pattern PARTIAL = java.util.regex.Pattern.compile(
		"\\b([A-Za-z_]\\w*(?:\\.[A-Za-z_]\\w*)*)\\._(\\d+)_([1248])_\\b");

	/** The decompiler's X._56_4_ (4 bytes at offset 56 of an object with no
	 *  field there) is not C: written as an access at that offset. */
	static String partialAccess(String c) {
		// &UNK_ffffa880: a constant (here -0x5780) the decompiler took for an
		// address outside memory; written as the number
		c = c.replaceAll("&UNK_([0-9a-f]{8})\\b", "((undefined *)0x$1)");
		// the decompiler's TrapAlways(n) is the trapa #n instruction (a
		// deliberate trap, always #0x50 here): inline assembly in C
		c = c.replaceAll("\\bTrapAlways\\((0x[0-9a-f]+|\\d+)\\)", "__asm__ volatile (\"trapa #$1\")");
		c = volatileHardware(c);
		c = division(c, "__sdivsi3_i4", "int");
		c = division(c, "__udivsi3_i4", "uint");
		// (uint) of a float: GCC converts that with a call to __fixunssfsi;
		// the game converts with ftrc (to int) and keeps the bits (127 near
		// misses called the helper where the game does not)
		c = c.replaceAll("\\(uint\\)(?=\\s*\\(*\\s*(?:fVar\\d+|\\*\\(float \\*\\)|\\(float\\)|\\d+\\.\\d))", "(int)");
		java.util.regex.Matcher m = PARTIAL.matcher(c);
		StringBuffer b = new StringBuffer();
		while (m.find()) {
			m.appendReplacement(b, java.util.regex.Matcher.quoteReplacement(
				"(*(undefined" + m.group(3) + " *)((char *)&" + m.group(1) + " + " + m.group(2) + "))"));
		}
		m.appendTail(b);
		return b.toString();
	}

	// the DAT_ / PTR_ names the exported code uses (vf4ft_data.h declares these)
	private final java.util.Set<String> used = new java.util.HashSet<>();
	// LAB_ / SUB_: code addresses the code takes as values (a callback, a
	// call through the uncached mirror)
	// (a goto's LAB_ is a label, not one of these)
	private static final java.util.regex.Pattern UNNAMED = java.util.regex.Pattern.compile(
		"\\b(?:(?:DAT|PTR)_[A-Za-z0-9_]+|agg_[0-9a-f]{8}_[0-9a-f]{8})\\b|(?<!goto )\\b(?:LAB|SUB)_[0-9a-f]{8}\\b(?!:)");

	// source/: top-level definitions (signature on one line, braces at column 0).
	// The return type may be left out (an implicit int definition), and the
	// signature line may end in a comment
	private static final java.util.regex.Pattern DEFINITION = java.util.regex.Pattern.compile(
		"^((?:[A-Za-z_][^\\n;]*?\\b)?([A-Za-z_]\\w*)\\([^\\n;]*?\\)(?: [^\\n{]*;)?)(?: /\\*[^\\n]*\\*/)?\\n\\{.*?\\n\\}\\n",
		java.util.regex.Pattern.MULTILINE | java.util.regex.Pattern.DOTALL);
	private final Map<String, String[]> matched = new java.util.HashMap<>(); // name -> path, signature, text
	// a .s file's functions: its global labels (signature and text null)
	private static final java.util.regex.Pattern ASM_GLOBAL = java.util.regex.Pattern.compile(
		"^\\t\\.global\\t_(\\w+)$", java.util.regex.Pattern.MULTILINE);

	/** A declaration for a definition's signature: an old-style (K&R) one,
	 *  "void f(a, b) char a; int b;", becomes the prototype "void f(char a, int b)"
	 *  (the original declared some functions so: callers pass ints, the
	 *  function narrows its char / short parameters itself). */
	static String prototypeOf(String sig) {
		java.util.regex.Matcher m = java.util.regex.Pattern.compile("^(.*?\\b\\w+)\\(([^()]*)\\) (.+;)$").matcher(sig.strip());
		if (!m.matches()) {
			return sig;
		}
		Map<String, String> types = new java.util.HashMap<>();
		for (String d : m.group(3).split(";")) {
			java.util.regex.Matcher dm = java.util.regex.Pattern.compile("^\\s*(.*?)\\s*\\b(\\w+)\\s*$").matcher(d);
			if (dm.matches()) {
				types.put(dm.group(2), dm.group(1));
			}
		}
		java.util.List<String> ps = new java.util.ArrayList<>();
		for (String n : m.group(2).split(",")) {
			n = n.strip();
			if (!n.isEmpty()) {
				ps.add(types.getOrDefault(n, "int") + " " + n);
			}
		}
		return m.group(1) + "(" + (ps.isEmpty() ? "void" : String.join(", ", ps)) + ")";
	}

	private void readMatched(File dir, String rel) throws Exception {
		readMatched(dir, rel, "source/");
	}

	private void readMatched(File dir, String rel, String tree) throws Exception {
		File[] list = dir.listFiles();
		if (list == null) {
			return;
		}
		java.util.Arrays.sort(list);
		for (File f : list) {
			String r = rel.isEmpty() ? f.getName() : rel + "/" + f.getName();
			if (f.isDirectory()) {
				readMatched(f, r, tree);
			} else if (f.getName().endsWith(".c")) {
				java.util.regex.Matcher m = DEFINITION.matcher(new String(java.nio.file.Files.readAllBytes(f.toPath())));
				while (m.find()) {
					// a static helper the game's compiler inlined (GCC 3.2 inlines only
					// a function defined above its use) has no function in the program
					if (m.group(0).stripLeading().startsWith("static ")) {
						continue;
					}
					matched.put(m.group(2), new String[] { tree + r, m.group(1), m.group(0).strip() });
				}
			} else if (f.getName().endsWith(".s")) {
				String asm = new String(java.nio.file.Files.readAllBytes(f.toPath()));
				java.util.regex.Matcher m = ASM_GLOBAL.matcher(asm);
				while (m.find()) {
					// data an assembly file keeps in .text (a table, a constant:
					// ".type _name,@object") is a global, not a function
					if (asm.contains("\t.type\t_" + m.group(1) + ",@object\n")) {
						continue;
					}
					matched.put(m.group(1), new String[] { tree + r, null, null });
				}
			}
		}
	}
	private static final java.util.regex.Pattern VARIADIC =
		java.util.regex.Pattern.compile("(?m)^variadic: (\\d+) named int, (\\d+) named float");

	// declarations from ghidra/symbols/*.tsv function rows, by address: what
	// Ghidra cannot hold (const, "...") is kept there
	private final Map<String, String> rowDecls = new java.util.HashMap<>();
	private final Map<String, String> rowByName = new java.util.HashMap<>();

	private void readRows(File symbols) throws Exception {
		for (File t : symbols.listFiles((d, n) -> n.endsWith(".tsv"))) {
			for (String line : java.nio.file.Files.readAllLines(t.toPath())) {
				String[] f = line.split("\t", -1);
				if (f.length > 2 && f[1].equals("function") && f[2].contains("(")) {
					rowDecls.put(f[0], f[2].strip());
					java.util.regex.Matcher nm = java.util.regex.Pattern.compile("([A-Za-z_]\\w*)\\s*\\(").matcher(f[2]);
					if (nm.find()) {
						rowByName.put(nm.group(1), f[2].strip()); // for test.bin, whose addresses differ
					}
				}
			}
		}
	}

	/** A function's declaration: its symbol row's when it has one; otherwise
	 *  the decompiler's signature, and for a variadic function its named
	 *  arguments (the first ones the decompiler shows, padded with int) and "...". */
	private String declaration(Function f, String sig) {
		String row = currentProgram.getName().equals("main.bin") ? rowDecls.get(f.getEntryPoint().toString())
			: rowByName.get(f.getName());
		if (row != null) {
			return row + ";";
		}
		sig = sig.strip().replaceAll("\\s+", " ").replaceFirst(";$", "");
		java.util.regex.Matcher m = f.getComment() == null ? null : VARIADIC.matcher(f.getComment());
		if (m == null || !m.find()) {
			return sig + ";";
		}
		int named = Integer.parseInt(m.group(1)) + Integer.parseInt(m.group(2));
		int open = sig.indexOf('('), close = sig.lastIndexOf(')');
		java.util.List<String> params = new java.util.ArrayList<>();
		int depth = 0, from = open + 1;
		for (int i = open + 1; i <= close; i++) {
			char c = sig.charAt(i);
			if (c == '(') {
				depth++;
			} else if (c == ')' && depth > 0) {
				depth--;
			} else if ((c == ',' && depth == 0) || i == close) {
				String p = sig.substring(from, i).strip();
				if (!p.isEmpty() && !p.equals("void") && !p.equals("...")) {
					params.add(p);
				}
				from = i + 1;
			}
		}
		StringBuilder b = new StringBuilder(sig.substring(0, open + 1));
		for (int i = 0; i < named; i++) {
			b.append(i < params.size() ? params.get(i) : "int param_" + (i + 1)).append(", ");
		}
		return b.append("...);").toString();
	}

	@Override
	protected void run() throws Exception {
		// main.bin -> src/; test.bin -> src_test/ (symbol rows matched by address in
		// main.bin, by name in test.bin, whose names came over from main.bin)
		boolean isMain = currentProgram.getName().equals("main.bin");
		File root = new File(getSourceFile().getParentFile().getParentFile().getAbsolutePath(), isMain ? "src" : "src_test");
		readRows(new File(getSourceFile().getParentFile().getAbsolutePath(), "symbols"));
		readMatched(new File(root.getParentFile(), "source"), "");
		if (!isMain) { // test.bin's own matched C (tools/match with VF4FT_PROGRAM=test); it wins
			readMatched(new File(root.getParentFile(), "source_test"), "", "source_test/");
		}
		int nMatched = 0;

		DecompInterface ifc = new DecompInterface();
		DecompileOptions opts = new DecompileOptions();
		opts.setHeadCommentIncluded(false); // the header above already carries it
		opts.setConventionPrint(false);
		ifc.setOptions(opts);
		ifc.openProgram(currentProgram);

		Map<String, StringBuilder> files = new LinkedHashMap<>();
		String chunk = null;
		int done = 0, failed = 0;

		FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
		while (it.hasNext() && !monitor.isCancelled()) {
			Function f = it.next();
			String tag = sourceTag(f);
			String path, evidence;
			if (tag != null) {
				boolean guess = tag.startsWith("src?:"), matched = tag.startsWith("srcp:"), callers = tag.startsWith("srcc:"),
					strings = tag.startsWith("srcs:");
				path = tag.substring(guess || matched || callers || strings ? 5 : 4);
				evidence = matched ? "file by match with source" : callers ? "file by callers" : strings ? "file by strings"
					: guess ? "file by link order" : "file by assert string";
				chunk = null;
			} else {
				if (chunk == null) {
					chunk = "_unmapped/" + f.getEntryPoint() + ".c";
				}
				path = chunk;
				evidence = "file unknown";
			}

			StringBuilder sb = files.computeIfAbsent(path, k -> new StringBuilder());
			sb.append(String.format("/* 0x%s  size 0x%x  %s\n * confidence: %s\n",
				f.getEntryPoint(), f.getBody().getNumAddresses(), evidence, confidence(f)));
			// size counts the body's code; a body with gaps (a pool or a jump
			// table placed mid-function, alignment) spans more: the tools
			// that compare with the game need the span
			long extent = f.getBody().getMaxAddress().subtract(f.getEntryPoint()) + 1;
			if (extent != f.getBody().getNumAddresses() && extent < f.getBody().getNumAddresses() + 0x1000) {
				sb.append(String.format(" * extent: 0x%x\n", extent));
			}
			if (f.getComment() != null) {
				for (String line : f.getComment().split("\n")) {
					if (line.startsWith("name: ")) {
						continue; // shown as "confidence:" above
					}
					sb.append(" * ").append(line).append('\n');
				}
			}
			String cc = f.getCallingConventionName();
			if (cc != null && cc.startsWith("__keeps")) {
				sb.append(" * convention: ").append(cc).append(" (AssignCallEffects)\n");
			}
			// in test.bin a placeholder name (FUN_<address>) is a different function
			// from main.bin's of the same name (both load at 0x0C020000)
			String[] mine = matched.get(f.getName());
			if (mine != null && !isMain && f.getSymbol().getSource() == SourceType.DEFAULT && !mine[0].startsWith("source_test/")) {
				mine = null; // main.bin's placeholder of the same name, not this function
			}
			if (mine != null && mine[1] == null) { // hand-written assembly: no C body
				sb.append(" * matched: ").append(mine[0]).append(" (hand-written assembly, tools/match/match.py)\n */\n");
				DecompileResults r = ifc.decompileFunction(f, 60, monitor);
				String d;
				if (r.decompileCompleted() && r.getDecompiledFunction() != null) {
					// the body's globals stay declared as before
					String c = partialAccess(r.getDecompiledFunction().getC().strip());
					notePartialGlobals(c, r.getHighFunction());
					java.util.regex.Matcher um = UNNAMED.matcher(c);
					while (um.find()) {
						used.add(um.group());
					}
					d = declaration(f, r.getDecompiledFunction().getSignature());
				} else {
					d = declaration(f, f.getSignature().getPrototypeString());
				}
				sb.append(d).append("\n\n");
				decls.append(String.format("%s /* 0x%s */\n", d, f.getEntryPoint()));
				nMatched++;
				done++;
				continue;
			}
			if (mine != null) {
				sb.append(" * matched: ").append(mine[0]).append(" (tools/match/match.py)\n */\n");
				sb.append(mine[2]).append("\n\n");
				java.util.regex.Matcher um = UNNAMED.matcher(mine[2]);
				while (um.find()) {
					used.add(um.group());
				}
				if (mine[1].matches("^[A-Za-z_]\\w*\\(.*")) {
					// defined without a return type: an implicit int
					decls.append(String.format("int %s; /* 0x%s */\n", prototypeOf(mine[1]), f.getEntryPoint()));
				} else {
					decls.append(String.format("%s; /* 0x%s */\n", prototypeOf(mine[1]), f.getEntryPoint()));
				}
				nMatched++;
				done++;
				continue;
			}
			sb.append(" */\n");

			DecompileResults r = ifc.decompileFunction(f, 60, monitor);
			if (r.decompileCompleted() && r.getDecompiledFunction() != null) {
				String c = partialAccess(r.getDecompiledFunction().getC().strip());
				notePartialGlobals(c, r.getHighFunction());
				sb.append(c).append("\n\n");
				java.util.regex.Matcher um = UNNAMED.matcher(c);
				while (um.find()) {
					used.add(um.group());
				}
				decls.append(String.format("%s /* 0x%s */\n",
					declaration(f, r.getDecompiledFunction().getSignature()), f.getEntryPoint()));
				done++;
			} else {
				sb.append("/* decompile failed: ").append(r.getErrorMessage()).append(" */\n\n");
				failed++;
			}
		}
		ifc.dispose();

		for (Map.Entry<String, StringBuilder> e : files.entrySet()) {
			File out = new File(root, e.getKey());
			out.getParentFile().mkdirs();
			try (PrintWriter w = new PrintWriter(out)) {
				w.println("/*");
				w.println(" * " + e.getKey());
				w.println(" * Reconstructed from Virtua Fighter 4 Final Tuned (Ver. B) " + currentProgram.getName() + ".");
				w.println(" * Generated by ghidra/ExportSource.java: decompiler output plus");
				w.println(" * annotations. This is not Sega's original text.");
				w.println(" */");
				w.println("#include \"vf4ft.h\"");
				w.println();
				w.print(e.getValue());
			}
		}
		writeHeaders(new File(root, "include"));
		println(String.format("exported %d functions (%d failed, %d from source/) into %d files under %s",
			done, failed, nMatched, files.size(), root));
		if (isMain && nMatched != matched.size()) { // test.bin has only some of them
			java.util.Set<String> missing = new java.util.TreeSet<>(matched.keySet());
			for (Function f : currentProgram.getFunctionManager().getFunctions(true)) {
				missing.remove(f.getName());
			}
			throw new IllegalStateException("source/ defines functions the program has no function named: " + missing);
		}
	}
