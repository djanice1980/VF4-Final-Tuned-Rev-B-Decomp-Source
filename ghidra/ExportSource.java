// Write annotated decompiler output into src/, one file per original
// source file (from MapSourceFiles tags). Functions with no source file
// go to src/_unmapped/<first address>.c, split at each mapped file, so
// link order is kept and each chunk is one stretch of unknown objects.
//
// Every function gets a header: address, size, confidence, evidence.
// Also writes src/include/: vf4ft_base.h (Ghidra's placeholder types, once),
// vf4ft_enums.h (types in /vf4ft/enums, via
// Ghidra's DataTypeWriter), vf4ft_types.h (/vf4ft/types: structs from
// ghidra/types/), vf4ft_globals.h (every user-named global, RAM or register, primary
// name only, with its address and notes), vf4ft_functions.h (a declaration
// of every function: its ghidra/symbols/ row's, else the decompiler's
// signature; a variadic one gets its named arguments and "...", from
// AssignPrototypes' count) and vf4ft.h, which includes them.
// Calling conventions are not printed (Ghidra's names are not C); a
// function with a measured one says so in a "convention:" line.
// src/ is regenerated by this script and never hand-edited: names,
// types and comments are made in Ghidra, then exported again. Hand-written
// C lives in source/ (every function there matches the game, as
// tools/match/match.py checks); a function defined there is exported as
// that definition instead of the decompiler's, with a "matched:" line, and
// declared in vf4ft_functions.h as it is defined. A function defined in a
// .s there (hand-written assembly, tools/match/to_asm.py) gets the
// "matched:" line and its declaration only, declared as the decompiler has it.
// @category VF4FT
