!
! Takes a point back through the current matrix: from the space the
! matrix transforms into, to the space it transforms from. With m the
! 16 floats of XMTRX (the back bank of FPU registers, xf0-xf15):
!     d      = in - (m[12], m[13], m[14])        the position removed
!     out[i] = d.x * m[4*i] + d.y * m[4*i + 1] + d.z * m[4*i + 2]
! for i = 0, 1, 2: the dot product of d with each of the matrix's three
! axes. That is the exact inverse of the transform only when the three
! axes are unit length and at right angles (a rotation and a move, no
! scale).
!
! The matrix registers are used where they are: the difference is
! written over the matrix's last four floats (xf12-xf15), the banks
! are swapped with frchg so that the matrix is in fr0-fr15 and fipr can
! take the dot products, and afterwards xf12-xf15 are put back.
!
! In:    r4 = in, three floats x, y, z
!        r5 = out, three floats
!        XMTRX = the current matrix
! Out:   nothing in r0. The three floats at out.
! Uses:  r4 is left 12 bytes on; r5 comes back as it was. fr0-fr3 =
!        m[12..15] and fr4-fr6 = d on return; fr7 and fr8-fr15 are
!        kept. XMTRX is the same on return as on entry. No integer
!        register besides r4 changes; no stack is used.
! Notes: entered with FPSCR.SZ = 0, PR = 0 and FR = 0. Between a pair
!        of fschg an fmov moves two floats, and the listing keeps the
!        single-float names: fr13 and fr15 are then the back-bank pairs
!        xd12 (xf12, xf13) and xd14 (xf14, xf15), an even name the
!        front pair. Between the two frchg the names fr0-fr15 mean the
!        matrix.
