! transforms the position, lights the vertex as the specular loop of
! float_colour_strip_send does, and tests it against the near plane.
! Nothing is sent or kept here.
!
! In:    r4 = vertex record (the vertex itself, 32 bytes, or an 8-byte
!        reference; see float_colour_strip_send).
!        r8 = the row of obj_spec_power_table (less 309 entries).
!        r12 = near limit as raw bits (minus the near distance; bit 0 is
!        a flag of the caller's).
!        fr12, fr13, fr14 = light direction y, z, x; XMTRX = the matrix
!        with the half vector as its fourth row.
!        float_colour_ambient, float_colour_group_base,
!        float_colour_group_offset, single_light_color,
!        second_light_color.
!        FPSCR: single moves.
! Out:   T = the vertex is outside: r12 is above the raw bits of minus
!        the depth, compared unsigned. The one test covers both ways of
!        being outside. Minus the depth is a negative float when the
!        vertex is ahead of the viewer, and negative floats order
!        backwards as unsigned words, so r12 is above it when the depth
!        is below the near distance; behind the viewer it is a positive
!        float, which as a word is below every negative one.
!        r4 = past the record.
!        fr4 = minus the depth; fr5, fr6 = screen x, y, still times the
!        depth; fr7 = 1 / depth.
!        r1, r2 = u, v as raw bits.
!        fr8-fr11 = base alpha, red, green, blue.
!        fr1, fr2, fr3 = offset red, green, blue (0 without a highlight).
!        fr0 = what the callers store as the offset's first word: the
!        row entry (highlight), N.L (lit, no highlight) or 0 (facing
!        away from the light).
! Uses:  r0, r14 and fr15 are changed as well. float_colour_base_stash
!        is written on the highlight path. r3, r5, r6, r7 are kept.
! Notes: fschg is switched to 64-bit moves and back before each return.
!        The offset's first word differs from float_colour_strip_send,
!        which writes the group's offset alpha there (0 when there is no
!        highlight).
	.global	_float_colour_vtx_load_spec
	.type	_float_colour_vtx_load_spec,@function
_float_colour_vtx_load_spec:
.Lvtx_load:	! 0c109888
	mov.l	@r4,r0			! r0 = first word of the record
	tst	#1,r0			! bit 0 marks a vertex
	mov	r4,r14			! r14 = the record, if it is the vertex itself
	bf.s	.Lload_fetch		! the vertex itself
	add	#32,r4			! (delay slot) r4 = past a 32-byte record
	mov.l	@(4,r14),r14		! a reference: r14 = its byte offset,
	add	#-24,r4			! r4 = past the 8-byte record,
	add	r4,r14			! r14 = the vertex it points at
.Lload_fetch:	! 0c109898
	fldi0	fr10
	fschg				! 64-bit moves from here to the return
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14+,fr6		! fr6, fr7 = z, normal x
	fadd	fr7,fr10		! fr10 = normal x
	fldi1	fr7			! the position is a point: w = 1
	fmov	@r14+,fr8		! fr8, fr9 = normal y, z
	mov.l	.Llight,r2
	fldi0	fr15
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = screen x, y times depth
	mov.l	.Lambient,r0		! r0 = float_colour_ambient
	fmov	@r2+,fr0		! has no use: fr0, fr1 are loaded again two lines on
	fipr	fv8,fv12		! fr15 = N.L (fv8 = normal y, z, x; fr15 was 0)
	fmov	@r0+,fr0		! fr1 = ambient red
	ftrv	xmtrx,fv8		! fr11 = N.H (the other three results are not used)
	fmov	@r0,fr2			! fr2, fr3 = ambient green, blue
	fldi0	fr0
	add	#32,r4
	mov.l	.Lgroup_base,r2		! r2 = float_colour_group_base
	fcmp/gt	fr15,fr0		! T = N.L is negative
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth
	bt.s	.Lload_facing_away	! facing away from the light: ambient only
	pref	@r4			! (delay slot) prefetch the source 32 bytes on
	fadd	fr15,fr0		! fr0 = N.L
	mov.l	.Llight,r0
	add	#-32,r4
	fmov	@r0+,fr8		! fr9 = light red
	ftrc	fr11,fpul		! fpul = N.H as an integer, the row index
	fmov	@r0,fr10		! fr10, fr11 = light green, blue
	fmac	fr0,fr10,fr2		! green = ambient + N.L x light
	sts	fpul,r0			! r0 = the row index
	fmac	fr0,fr11,fr3		! blue likewise
	fmov	@r2+,fr10		! fr10, fr11 = group base green, blue
	fmac	fr0,fr9,fr1		! red likewise
	fmov	@r2+,fr8		! fr8, fr9 = group base alpha, red
	fmul	fr2,fr10		! base green
	mov.w	.Lload_index_309,r1	! r1 = 309
	fmul	fr3,fr11		! base blue
	cmp/gt	r1,r0			! T = the index is above 309: a highlight
	fmul	fr1,fr9			! base red
	bf	.Lload_no_highlight	! no highlight: offset 0
! The highlight: offset = second_light_color x row entry x group offset.
! The base color is put aside in float_colour_base_stash meanwhile, since
! fr8-fr11 are needed for the group offset.
	mov.l	.Lsecond_light,r2	! r2 = second_light_color, the color of the highlight
	shll2	r0
	fmov	@r2+,fr0		! fr1 = its red
	fschg				! one single move:
	fmov	@(r0,r8),fr0		! fr0 = row[index], the specular power
	mov.l	.Lbase_stash_end,r0	! r0 = the end of float_colour_base_stash
	fschg
	fmov	@r2+,fr2		! fr2, fr3 = second_light_color green, blue
	fmov	fr10,@-r0		! stash +8, +12 = base green, blue
	fmov	fr8,@-r0		! stash +0, +4 = base alpha, red
	mov.l	.Lgroup_offset,r2	! r2 = float_colour_group_offset
	fmul	fr0,fr1
	fmov	@r2+,fr10		! fr10, fr11 = group offset green, blue
	fmul	fr0,fr2
	fmov	@r2+,fr8		! fr8, fr9 = group offset alpha, red
	fmul	fr0,fr3
	fmul	fr9,fr1			! fr1 = offset red
	mov.l	@r14+,r1		! r1 = u as raw bits
	fmul	fr10,fr2		! fr2 = offset green
	mov.l	@r14+,r2		! r2 = v as raw bits
	fmul	fr11,fr3		! fr3 = offset blue
	fneg	fr4			! fr4 = minus the depth
	flds	fr4,fpul
	mov.l	.Lbase_stash,r0		! r0 = float_colour_base_stash
	fmov	@r0+,fr8		! fr8, fr9 = base alpha, red again
	fmov	@r0+,fr10		! fr10, fr11 = base green, blue again
	sts	fpul,r0			! r0 = minus the depth as raw bits
	cmp/hi	r0,r12			! T = outside: r12 above it, unsigned
	fsts	fpul,fr4		! fr4 as it was (minus the depth)
	rts
	fschg				! (delay slot) single moves again
.Lload_index_309:
	.word	0x0135			! the value 309: N.H indexes at or below it have no highlight
.Llight:
	.long	_single_light_color
.Lambient:
	.long	_float_colour_ambient
.Lgroup_base:
	.long	_float_colour_group_base
.Lsecond_light:
	.long	_second_light_color
.Lbase_stash_end:
	.long	_float_colour_base_stash+16
.Lgroup_offset:
	.long	_float_colour_group_offset
.Lbase_stash:
	.long	_float_colour_base_stash
! Lit, but no highlight: offset red, green, blue = 0. fr0 is left as N.L.
.Lload_no_highlight:	! 0c109948
	fneg	fr4			! fr4 = minus the depth
	flds	fr4,fpul
	sts	fpul,r0			! r0 = minus the depth as raw bits
	mov.l	@r14+,r1		! r1, r2 = u, v as raw bits
	mov.l	@r14+,r2
	fldi0	fr1			! offset red, green, blue = 0
	fldi0	fr2
	cmp/hi	r0,r12			! T = outside: r12 above it, unsigned
	fldi0	fr3
	fsts	fpul,fr4		! fr4 as it was (minus the depth)
	rts
	fschg				! (delay slot) single moves again
! N.L negative: base = ambient x group base, offset 0. r2 =
! float_colour_group_base, fr1-fr3 = ambient red, green, blue, fr0 = 0.
.Lload_facing_away:	! 0c109960
	fneg	fr4			! fr4 = minus the depth
	add	#-32,r4
	fmov	@r2+,fr10		! fr10, fr11 = group base green, blue
	flds	fr4,fpul
	fmul	fr2,fr10		! base green = ambient x group base
	fmov	@r2+,fr8		! fr8, fr9 = group base alpha, red
	fmul	fr3,fr11		! base blue likewise
	sts	fpul,r0			! r0 = minus the depth as raw bits
	fmul	fr1,fr9			! base red likewise
	mov.l	@r14+,r1		! r1, r2 = u, v as raw bits
	mov.l	@r14+,r2
	fldi0	fr1			! offset red, green, blue = 0
	fldi0	fr2
	cmp/hi	r0,r12			! T = outside: r12 above it, unsigned
	fldi0	fr3
	rts
	fschg				! (delay slot) single moves again

! float_colour_vtx_emit_spec
!
! Sends the vertex float_colour_vtx_load_spec left in the registers as a
! 64-byte vertex (the layout is in float_colour_strip_send) and counts it
! off the strip.
!
! In:    r3 = vertices left in the strip, this one included.
!        r5 = the list's write pointer; r6 = the same place as a
!        store-queue address.
!        fr5, fr6 = screen x, y times depth; fr7 = 1 / depth.
!        r1, r2 = u, v as raw bits.
!        fr8-fr11 = base alpha, red, green, blue; fr0-fr3 = the offset
!        color's four words.
!        FPSCR: single moves.
! Out:   T = that was the strip's last vertex (r3 has reached 0); the
!        vertex then carries the control word that ends a strip.
!        r3 one less; r5 and r6 moved on 64 bytes.
! Uses:  r0 is changed; fr4 = the control word's bits, fr5, fr6 = X, Y
!        (divided by the depth now). r1, r2, r4, r7, fr0-fr3 and
!        fr7-fr11 are kept.
	.global	_float_colour_vtx_emit_spec
	.type	_float_colour_vtx_emit_spec,@function
_float_colour_vtx_emit_spec:
.Lvtx_emit:	! 0c109982
	dt	r3			! count the vertex off; T = the strip's last
	lds	r6,fpul			! fpul = control word: r6 itself
	bf	.Lemit_write		! not the last one
	mov	r6,r0
	shar	r0			! the last: r6 >> 1, the control word that ends a strip
	lds	r0,fpul
	sett				! T set again (the shift cleared it)
.Lemit_write:	! 0c109990
	fschg				! 64-bit moves
	add	#24,r6			! r6 = vertex +24
	fsts	fpul,fr4		! fr4 = the control word, to go out beside X
	fmul	fr7,fr6			! fr6 = Y = y / depth
	mov.l	r2,@-r6			! vertex +20 = v
	fmul	fr7,fr5			! fr5 = X = x / depth
	mov.l	r1,@-r6			! vertex +16 = u
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	fmov	fr4,@-r6		! vertex +0, +4 = control word, X
	pref	@r6			! the first half goes to the list
	add	#64,r6			! r6 = vertex +64
	fmov	fr2,@-r6		! vertex +56, +60 = offset green, blue
	fmov	fr0,@-r6		! vertex +48, +52 = offset first word, red
	fmov	fr10,@-r6		! vertex +40, +44 = base green, blue
	add	#64,r5			! the list takes the vertex: 64 bytes
	fmov	fr8,@-r6		! vertex +32, +36 = base alpha, red
	fschg				! single moves again
	pref	@r6			! the second half goes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the place after the vertex

! float_colour_vtx_keep_spec
!
! Stores the vertex float_colour_vtx_load_spec left in the registers in
! a slot of float_colour_clip_ring, which has four slots of 64 bytes:
!   +0   minus the depth
!   +4   x and +8 y, still times the depth
!   +12  1 / depth
!   +16  u, +20 v
!   +24  and +28 not written
!   +32  base alpha, red, green, blue
!   +48  the offset color's four words (fr0, then red, green, blue)
!
! In:    r11 = the vertex's index; its low two bits are the slot.
!        fr4-fr7, r1, r2, fr8-fr11 and fr0-fr3 as
!        float_colour_vtx_load_spec returns them.
!        FPSCR: single moves.
! Out:   nothing in registers; the slot is filled.
! Uses:  r0 and r10 are changed (r10 is not saved here; the walks save
!        it on entry). Everything else is kept.
	.global	_float_colour_vtx_keep_spec
	.type	_float_colour_vtx_keep_spec,@function
_float_colour_vtx_keep_spec:
.Lvtx_keep:	! 0c1099b8
	mov	#6,r10			! r10 = 6, the shift for 64 bytes a slot
	mov	r11,r0
	and	#3,r0			! r0 = the slot, 0-3
	fschg				! 64-bit moves
	shld	r10,r0			! r0 = slot x 64
	mov.l	.Lring_slot_end,r10	! r10 = the end of slot 0
	add	r0,r10			! r10 = the end of this slot
	fmov	fr2,@-r10		! slot +56, +60 = offset green, blue
	fmov	fr0,@-r10		! slot +48, +52 = offset first word, red
	fmov	fr10,@-r10		! slot +40, +44 = base green, blue
	fmov	fr8,@-r10		! slot +32, +36 = base alpha, red
	add	#-8,r10			! step over +24 and +28
	mov.l	r2,@-r10		! slot +20 = v
	mov.l	r1,@-r10		! slot +16 = u
	fmov	fr6,@-r10		! slot +8, +12 = y, 1 / depth
	fmov	fr4,@-r10		! slot +0, +4 = minus the depth, x
	rts
	fschg				! (delay slot) single moves again
.Lring_slot_end:
	.long	_float_colour_clip_ring+64

! float_colour_flat_copy_spec
!
! For a flat-shaded run: copies the base and offset colors (the 32 bytes
! from +32) of the newest vertex's ring slot into the two slots before
! it, so that all three corners of the newest triangle, and any cuts made
! between them, carry the color of its last vertex.
!
! In:    r11 = index of the newest vertex. Its slot is r11 & 3; the
!        copies go to slots (r11 - 1) & 3 and (r11 - 2) & 3.
!        FPSCR: single moves.
! Out:   nothing in registers; the two slots' colors are overwritten.
! Uses:  r0, r1 and r10 are changed. fr12-fr15 and fr0-fr3 are left
!        holding the copied colors: fr12-fr15 = base alpha, red, green,
!        blue.
! Notes: fr12, fr13 and fr14 are where float_colour_send_alpha keeps the
!        light direction for the whole object, and neither this file nor
!        float_colour_send_alpha loads it again. After this routine has
!        run, N.L is taken against the color values instead, here and in
!        every sender until the object ends. Whether a flat-shaded lit
!        run ever goes through the near plane in the game is not
!        established.
	.global	_float_colour_flat_copy_spec
	.type	_float_colour_flat_copy_spec,@function
_float_colour_flat_copy_spec:
.Lflat_copy:	! 0c1099e0
	mov	#6,r1			! r1 = 6, the shift for 64 bytes a slot
	mov	r11,r0
	and	#3,r0			! r0 = the newest vertex's slot, 0-3
	mov.l	.Lring_colors,r10	! r10 = the color half of slot 0 (ring +32)
	shld	r1,r0			! r0 = slot x 64
	fschg				! 64-bit moves
	mov	r10,r1
	add	r0,r1			! r1 = the newest slot's colors
	fmov	@r1+,fr12		! fr12, fr13 = base alpha, red
	add	#-64,r0			! r0 = the slot before, x 64 ...
	fmov	@r1+,fr14		! fr14, fr15 = base green, blue
	and	#255,r0			! ... wrapped from -64 round to 192
	fmov	@r1+,fr0		! fr0, fr1 = offset first word, red
	fmov	@r1+,fr2		! fr2, fr3 = offset green, blue
	add	#32,r10			! r10 = the end of slot 0
	mov	r10,r1
	add	r0,r1			! r1 = the end of the slot before
	fmov	fr2,@-r1		! its eight color words, written from the end down
	fmov	fr0,@-r1
	fmov	fr14,@-r1
	add	#-64,r0			! r0 = the slot two before, x 64 ...
	fmov	fr12,@-r1
	and	#255,r0			! ... wrapped the same way
	mov	r10,r1
	add	r0,r1			! r1 = the end of the slot two before
	fmov	fr2,@-r1		! its eight color words likewise
	fmov	fr0,@-r1
	fmov	fr14,@-r1
	fmov	fr12,@-r1
	rts
	fschg				! (delay slot) single moves again
	nop				! padding before the pool
.Lring_colors:
	.long	_float_colour_clip_ring+32

! float_colour_kept_vtx_emit_spec
!
! Sends a kept vertex: a slot of float_colour_clip_ring as a 64-byte
! vertex, with X and Y = the kept x and y times the kept 1 / depth.
!
! In:    r0 = the slot; only its low two bits are used, so the callers
!        pass r11, r11 - 1 or r11 - 2 as it is.
!        T = this vertex ends the strip.
!        r5 = the list's write pointer; r6 = the same place as a
!        store-queue address.
!        FPSCR: single moves.
! Out:   T as it came in. r5 and r6 moved on 64 bytes.
! Uses:  r0, r1, r2, r10 and fr0-fr7 are changed (fr7, the 1 / depth of
!        the last vertex loaded, among them). r3, r4, r7 and fr8-fr11
!        are kept.
! Notes: Vertex +24 and +28 get the slot's two words that nothing
!        writes.
	.global	_float_colour_kept_vtx_emit_spec
	.type	_float_colour_kept_vtx_emit_spec,@function
_float_colour_kept_vtx_emit_spec:
.Lkept_emit:	! 0c109a24
	mov	#6,r1			! r1 = 6, the shift for 64 bytes a slot
	mov.l	.Lring,r10
	and	#3,r0			! r0 = the slot, 0-3
	fschg				! 64-bit moves
	shld	r1,r0
	add	r0,r10			! r10 = the slot
	fmov	@r10+,fr0		! fr0, fr1 = minus the depth, x
	fmov	@r10+,fr2		! fr2, fr3 = y, 1 / depth
	add	#32,r6			! r6 = vertex +32
	fmov	@r10+,fr4		! fr4, fr5 = u, v
	fmul	fr3,fr2			! fr2 = Y = y x 1 / depth
	fmov	@r10+,fr6		! fr6, fr7 = the slot's two unwritten words
	fmul	fr3,fr1			! fr1 = X = x x 1 / depth
	fmov	fr6,@-r6		! vertex +24, +28 = those two words
	fmov	fr4,@-r6		! vertex +16, +20 = u, v
	mov	r6,r2			! r2 = control word: r6 as it is now
	fmov	fr2,@-r6		! vertex +8, +12 = Y, 1 / depth
	bf.s	.Lkept_write		! T clear: not the end of the strip
	fmov	fr0,@-r6		! (delay slot) vertex +4 = X (and +0, written over next)
	shar	r2			! T set: r6 >> 1, the control word that ends a strip
	sett				! T set again (the shift cleared it)
.Lkept_write:	! 0c109a4e
	mov.l	r2,@r6			! vertex +0 = control word
	pref	@r6			! the first half goes to the list
	add	#64,r6			! r6 = vertex +64
	fmov	@r10+,fr0		! fr0, fr1 = base alpha, red
	fmov	@r10+,fr2		! fr2, fr3 = base green, blue
	fmov	@r10+,fr4		! fr4, fr5 = offset first word, red
	fmov	@r10+,fr6		! fr6, fr7 = offset green, blue
	fmov	fr6,@-r6		! vertex +56, +60 = offset green, blue
	fmov	fr4,@-r6		! vertex +48, +52 = offset first word, red
	add	#64,r5			! the list takes the vertex: 64 bytes
	fmov	fr2,@-r6		! vertex +40, +44 = base green, blue
	fmov	fr0,@-r6		! vertex +32, +36 = base alpha, red
	fschg				! single moves again
	pref	@r6			! the second half goes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the place after the vertex
	nop				! padding before the pool
.Lring:
	.long	_float_colour_clip_ring

! float_colour_near_cut_emit_spec
!
! Sends the point where the edge between two kept vertices meets the
! near plane, as a 64-byte vertex. With a = ring slot r0 & 3 and
! b = ring slot r11 & 3:
!   t = (near - a's minus depth) / (b's minus depth - a's minus depth),
!       where near is r12 read as a float (minus the near distance; the
!       flag in its bit 0 is far too small to matter);
!   x, y, u, v and the eight color words = a + t x (b - a);
!   X = x x n, Y = y x n and the vertex's 1 / depth = n, where n is r7
!       read as a float (header +0x20, 1 / near): the point is on the
!       near plane, so its depth is the near distance.
!
! In:    r0 = slot of a, r11 = slot of b (low two bits of each).
!        T = this vertex ends the strip.
!        r7 = header +0x20 as raw bits; r12 = near limit as raw bits.
!        r5 = the list's write pointer; r6 = the same place as a
!        store-queue address.
!        FPSCR: single moves.
! Out:   T as it came in. r5 and r6 moved on 64 bytes.
! Uses:  r0, r1, r2, r10 and fr0-fr7 are changed. r3, r4, r7 and
!        fr8-fr11 are kept.
! Notes: Vertex +24 and +28 are not written.
	.global	_float_colour_near_cut_emit_spec
	.type	_float_colour_near_cut_emit_spec,@function
_float_colour_near_cut_emit_spec:
.Lnear_cut:	! 0c109a74
	mov	#6,r1			! r1 = 6, the shift for 64 bytes a slot
	mov.l	.Lring_2,r10
	and	#3,r0			! r0 = a's slot, 0-3
	mov	r10,r2
	shld	r1,r0			! r0 = slot x 64
	lds	r12,fpul
	add	r0,r10			! r10 = slot a
	fsts	fpul,fr0		! fr0 = near, r12 as a float
	mov	r11,r0
	fmov	@r10,fr2		! fr2 = a's minus depth
	and	#3,r0			! r0 = b's slot, 0-3
	shld	r1,r0
	fsub	fr2,fr0			! fr0 = near - a
	add	r0,r2			! r2 = slot b
	fmov	@r2,fr1			! fr1 = b's minus depth
	fschg				! 64-bit moves
	add	#16,r2			! r2 = b's u and v (slot +16)
	fsub	fr2,fr1			! fr1 = b - a
	add	#16,r10			! r10 = a's u and v (slot +16)
	lds	r7,fpul
	fdiv	fr1,fr0			! fr0 = t = (near - a) / (b - a)
	fmov	@r2,fr4			! fr4, fr5 = b's u, v
	add	#-8,r2			! r2 = b's y (slot +8)
	fmov	@r10,fr2		! fr2, fr3 = a's u, v
	fsub	fr2,fr4			! fr4, fr5 = the differences
	add	#-8,r10			! r10 = a's y (slot +8)
	fsub	fr3,fr5
	fsts	fpul,fr1		! fr1 = n, r7 as a float
	fmac	fr0,fr4,fr2		! u = a + t x (b - a)
	add	#24,r6			! r6 = vertex +24
	fmac	fr0,fr5,fr3		! v likewise
	fmov	fr2,@-r6		! vertex +16, +20 = u, v
	fschg				! single moves
	fmov	fr1,@-r6		! vertex +12 = 1 / depth = n
	fmov	@r2,fr5			! fr5 = b's y
	add	#-4,r2
	fmov	@r10,fr3		! fr3 = a's y
	add	#-4,r10
	fmov	@r2,fr4			! fr4 = b's x
	fmov	@r10,fr2		! fr2 = a's x
	fsub	fr3,fr5			! fr5, fr4 = the differences
	fsub	fr2,fr4
	fmac	fr0,fr5,fr3		! y = a + t x (b - a)
	add	#52,r10			! r10 = a's offset green, blue (slot +56)
	fmac	fr0,fr4,fr2		! x likewise
	mov	r6,r0			! r0 = control word: r6 as it is now
	fmul	fr1,fr3			! Y = y x n
	add	#64,r5			! the list takes the vertex: 64 bytes
	fmul	fr1,fr2			! X = x x n
	fmov	fr3,@-r6		! vertex +8 = Y
	bf.s	.Lcut_write		! T clear: not the end of the strip
	fmov	fr2,@-r6		! (delay slot) vertex +4 = X
	shar	r0			! T set: r6 >> 1, the control word that ends a strip
	sett				! T set again (the shift cleared it)
.Lcut_write:	! 0c109ae0
	mov.l	r0,@-r6			! vertex +0 = control word
	add	#52,r2			! r2 = b's offset green, blue (slot +56)
	pref	@r6			! the first half goes to the list
	add	#64,r6			! r6 = vertex +64
	fschg				! 64-bit moves
! The eight color words, a pair at a time from the end down: offset
! green and blue, offset first word and red, base green and blue, base
! alpha and red. Each is a + t x (b - a).
	fmov	@r2,fr4			! fr4, fr5 = b's offset green, blue
	add	#-8,r2
	fmov	@r10,fr2		! fr2, fr3 = a's offset green, blue
	add	#-8,r10
	fsub	fr2,fr4			! the differences
	fsub	fr3,fr5
	fmov	@r2,fr6			! fr6, fr7 = b's offset first word, red
	fmac	fr0,fr4,fr2		! offset green
	add	#-8,r2
	fmac	fr0,fr5,fr3		! offset blue
	fmov	@r10,fr4		! fr4, fr5 = a's offset first word, red
	fmov	fr2,@-r6		! vertex +56, +60 = offset green, blue
	fsub	fr4,fr6			! the differences
	add	#-8,r10
	fsub	fr5,fr7
	fmac	fr0,fr6,fr4		! offset first word and red
	fmac	fr0,fr7,fr5
	fmov	fr4,@-r6		! vertex +48, +52 = offset first word, red
	fmov	@r2,fr4			! fr4, fr5 = b's base green, blue
	add	#-8,r2
	fmov	@r10,fr2		! fr2, fr3 = a's base green, blue
	add	#-8,r10
	fsub	fr2,fr4			! the differences
	fsub	fr3,fr5
	fmov	@r2,fr6			! fr6, fr7 = b's base alpha, red
	fmac	fr0,fr4,fr2		! base green and blue
	fmac	fr0,fr5,fr3
	fmov	@r10,fr4		! fr4, fr5 = a's base alpha, red
	fmov	fr2,@-r6		! vertex +40, +44 = base green, blue
	fsub	fr4,fr6			! the differences
	fsub	fr5,fr7
	fmac	fr0,fr6,fr4		! base alpha and red
	fmac	fr0,fr7,fr5
	fmov	fr4,@-r6		! vertex +32, +36 = base alpha, red
	fschg				! single moves again
	pref	@r6			! the second half goes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the place after the vertex
	nop				! padding before the pool
