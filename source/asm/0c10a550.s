! with bit 7 set: another strip follows under the same header; its count
! and first record are read and the loop goes on, this vertex getting the
! end-of-strip control word either way.
.Ls_spec_last:
	mov	r6,r7
	shar	r7			! r7 = the control word shifted: end of strip
	cmp/pl	r0			! T = the word is positive
	bf.s	.Ls_spec_end		! not positive: finish with this vertex
	fipr	fv12,fv0		! (delay slot) fr3 = N.L
	tst	#128,r0
	fldi1	fr7
	bt	.Ls_spec_end		! bit 7 clear: finish with this vertex
	mov.l	@r4+,r3			! r3 = the new strip's count
	mov.l	@r4+,r0			! r0 = its first record's first word
	mov.l	@r4+,r14		! r14 = that record's second word
	tst	#1,r0
	fdiv	fr4,fr7			! fr7 = 1 / depth
	bf	.Ls_spec_next_inline2		! the first record is inline
	bra	.Ls_spec_next_ref		! it is a reference
	pref	@r4			! (delay slot) prefetch ahead
	nop				! padding, never run
	nop

! intensity_strip_near_clip
!
! Sends a triangle strip of a group whose bounding sphere crosses the
! near plane, cutting it at the plane. Each vertex is tested by
! intensity_vtx_load (T = it is nearer than the near plane: "behind"
! below; "in front" is the side that is drawn) and the tests are
! shifted into r9, newest in bit 0. The walk has three states:
!
!   plain (0c10acb2): the vertices so far are in front; each is loaded
!     and sent at once (intensity_vtx_emit). When one falls behind, it
!     and the two before it are put in the ring (the two before are
!     read again from the data) and the walk changes to "ring".
!   skipping (0c10acce): two vertices in a row were behind; the
!     following ones are only transformed, not lit, until one is in
!     front again. That one and the two before it are then loaded into
!     the ring.
!   ring (0c10ae04): every vertex is loaded and kept in
!     intensity_clip_ring, slot (r11 & 3), r11 counting the strip's
!     vertices. The last three tests, oldest first, pick what is sent
!     for the triangle (A, B, C) they end, C being the newest vertex;
!     cut(P, Q) is the point where edge P-Q meets the near plane
!     (intensity_near_cut_emit) and a plain letter is a kept vertex
!     (intensity_kept_vtx_emit):
!       001  cut(A,C), B, cut(B,C)
!       010  C, cut(B,C), C
!       011  cut(A,C) as the end of a strip; then "skipping"
!       100  cut(A,C), B, C; then "plain"
!       101  cut(B,C)
!       110  cut(A,C), cut(B,C), C when r11 is even;
!            cut(B,C), cut(A,C), cut(B,C), C when it is odd
!     000 and 111 never get here (100 and 011 leave the state first);
!     their two table entries are empty.
! The first two vertices are handled apart (0c10ac98 on): one in front
! and one behind start the ring with their cut. When r12 bit 0 is set
! (flat shading) intensity_flat_copy gives the triangle's first two
! vertices the newest one's intensities before anything is cut.
! The last thing sent for the strip's last vertex carries the
! end-of-strip control word. After the count runs out, a positive word
! with bit 7 set starts another strip under the same header, as in
! intensity_strip_send.
!
! In:    r4 = the run's count word (the vertex records follow it).
!        r5, r6 = list write address and store-queue pointer.
!        r7 = 1/w of the near plane (header +0x20).
!        r12 = the near value's bits, bit 0 = flat shading.
!        r8, fr15, fr12-fr14, fr8-fr10, XMTRX as intensity_vtx_load
!        needs them.
! Out:   r4 = the word after the last strip (the next run word).
!        r5 and r6 advanced by 32 for each vertex sent.
!        r12 bit 0 = 1 (the caller's "crosses the near plane" flag).
! Uses:  r10, r11 and pr are saved on the stack and restored. r0-r3,
!        r9 and r14 are changed without being saved (compiled code
!        would keep r9 and r14), and fr0-fr7 and fr11.
! Notes: FPSCR SZ = 0 on entry and return. Stepping back over records
!        (to read a vertex again) looks at the last word of the record
!        before: bit 0 set means a 32-byte inline record, clear an
!        8-byte reference. So the data must have bit 0 set in an inline
!        record's last word (v) as well as its first. T on entry is
!        not used. Called only by intensity_send_alpha (bsr).
	.global	_intensity_strip_near_clip
	.type	_intensity_strip_near_clip,@function
_intensity_strip_near_clip:
.Lstrip_near_clip:
	mov.l	r10,@-r15		! r10 is the helpers' scratch, r11 the ring index
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3			! r3 = the strip's vertex count
! 0c10ac98: a strip starts. r3 = its count, r4 = its first record.
.Lc_new_strip:
	mov	#0,r11			! r11 = 0: the first vertex
	bsr	.Lvtx_load		! load vertex 0; T = it is behind the near plane
	mov	#0,r9			! (delay slot) r9 = 0: no tests yet
	bt.s	.Lc_first_behind		! vertex 0 is behind
	rotcl	r9			! (delay slot) shift the test into r9
	bsr	.Lvtx_emit		! vertex 0 is in front: send it
	add	#1,r11			! (delay slot) r11 = 1
	bsr	.Lvtx_load		! load vertex 1
	nop
	bt.s	.Lc_second_behind		! vertex 1 is behind: start the ring with a cut
	rotcl	r9			! (delay slot) shift the test into r9
	bsr	.Lvtx_emit		! vertex 1 is in front too: send it
	add	#1,r11			! (delay slot) r11 = 2
! 0c10acb2: the plain state: load a vertex and send it while they stay in
! front.
.Lc_front_loop:
	bsr	.Lvtx_load		! load the next vertex
	nop
	bt.s	.Lc_went_behind		! it is behind: go over to the ring
	rotcl	r9			! (delay slot) shift the test into r9
	bsr	.Lvtx_emit		! send it; T = that was the strip's last vertex
	add	#1,r11			! (delay slot) r11 = the next vertex's number
	bf	.Lc_front_loop		! more vertices
	bt	.Lc_strip_done		! the strip is finished
! 0c10acc2: vertex 0 is behind the near plane. Nothing is sent for it; it
! is counted here because it never passes through intensity_vtx_emit.
.Lc_first_behind:
	dt	r3			! count vertex 0
	add	#1,r11			! r11 = 1
	bsr	.Lvtx_load		! load vertex 1
	dt	r3			! (delay slot) count vertex 1
	bf.s	.Lc_second_front		! vertex 1 is in front: start with a cut
	rotcl	r9			! (delay slot) shift the test into r9
! 0c10acce: the skipping state: the last two vertices were behind the near
! plane. r4 = the next record, R. Only its position is transformed.
! Fetch R as at 0c10a94e (4-byte fmov here).
.Lc_behind_loop:
	mov.l	@r4,r0			! r0 = R's first word
	mov	r4,r14
	tst	#1,r0
	add	#32,r4			! r4 = past an inline record
	bf.s	.Lc_behind_first		! inline: r14 = R itself
	fldi1	fr7			! (delay slot) w = 1
	add	#-24,r4			! reference: r4 = past its 8 bytes
	mov.l	@(4,r14),r14
	add	r4,r14			! r14 = the record referred to
! 0c10ace0: r14 = R's position, r4 = the record after R.
.Lc_behind_first:
	fmov	@r14+,fr4		! fr4 = x
	fmov	@r14+,fr5		! fr5 = y
! 0c10ace4: r14 = R's z, r4 = N, the record after R. While R is
! transformed N is looked at ahead: r14 = where its position is, r1 = its
! size.
.Lc_behind_test:
	fmov	@r14+,fr6		! fr6 = z
	mov	#32,r1			! r1 = 32, the size of N if it is inline
	mov.l	@r4,r0			! r0 = N's first word
	add	#32,r4
	pref	@r4			! prefetch 32 bytes past N
	ftrv	xmtrx,fv4		! fr7 = minus R's depth
	tst	#1,r0			! T = N is a reference
	add	#-32,r4
	bf.s	.Lc_behind_peeked		! N is inline
	mov	r4,r14			! (delay slot) r14 = N itself
	mov	#8,r1			! r1 = 8, the size of a reference
	mov.l	@(4,r14),r14
	add	#8,r14
	add	r4,r14			! r14 = the record N refers to
! 0c10ad00: the near test, as intensity_vtx_load makes it: the bits of
! minus the depth against r12 as unsigned numbers.
.Lc_behind_peeked:
	flds	fr7,fpul
	sts	fpul,r0			! r0 = the bits of minus R's depth
	cmp/hi	r0,r12			! T = R is behind the near plane
	add	#1,r11			! r11 = R's number
	bf.s	.Lc_came_front		! R is in front: the strip comes back into view
	rotcl	r9			! (delay slot) shift the test into r9
	dt	r3			! count R; T = it was the strip's last vertex
	fldi1	fr7			! w = 1 for the next one
	bt	.Lc_strip_done		! the strip ended behind the plane
	add	r1,r4			! r4 = the record after N
	fmov	@r14+,fr4		! fr4 = N's x
	bra	.Lc_behind_test		! test N
	fmov	@r14+,fr5		! (delay slot) fr5 = N's y
! 0c10ad1a: a strip's count has run out. r4 = the word after it: positive
! with bit 7 set starts another strip under the same header.
.Lc_strip_done:
	mov.l	@r4+,r0			! r0 = the word after the strip
	cmp/pl	r0
	bf.s	.Lc_return		! not positive: return
	tst	#128,r0			! (delay slot) bit 7
	bf.s	.Lc_new_strip		! set: the next strip
	mov.l	@r4+,r3			! (delay slot) r3 = its count
	add	#-4,r4			! not a strip to carry on with: un-read the count
! 0c10ad28: restore and return with r4 on the next run word.
.Lc_return:
	lds.l	@r15+,pr
	mov	#1,r0			! r0 = 1, for the delay slot below
	mov.l	@r15+,r11
	add	#-4,r4			! r4 = the word after the strip
	mov.l	@r15+,r10
	rts
	or	r0,r12			! (delay slot) r12 bit 0 = 1 again for the caller
! 0c10ad36: vertex 0 was in front (and sent), vertex 1 is behind. Keep
! vertex 1 in slot 1, read vertex 0 again into slot 0 and send their cut.
.Lc_second_behind:
	bsr	.Lvtx_keep		! keep vertex 1 (r11 = 1)
	dt	r3			! (delay slot) count vertex 1
! Step r4 back two records. The word just before r4 is the last word
! of the record before: bit 0 clear = a reference (8 bytes), set = an
! inline record (32 bytes).
	add	#-8,r4
	mov.l	@(4,r4),r0		! r0 = the last word of the record before
	tst	#1,r0
	bt	.Lc_sb_back1		! a reference: 8 bytes back is enough
	add	#-24,r4			! inline: 32 bytes back in all
! 0c10ad44: and once more, to vertex 0.
.Lc_sb_back1:
	add	#-8,r4
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sb_back2
	add	#-24,r4
! 0c10ad4e: r4 = vertex 0's record.
.Lc_sb_back2:
	bsr	.Lvtx_load		! load vertex 0 again
	nop
	bsr	.Lvtx_keep		! keep it in slot 0
	mov	#0,r11			! (delay slot) r11 = 0
	mov	#1,r11			! r11 = 1: the cut runs to vertex 1
	clrt				! T = 0: not the end of the strip
	bsr	.Lnear_cut_emit		! send cut(vertex 0, vertex 1)
	mov	#0,r0			! (delay slot) r0 = 0, the cut's first slot
! Step r4 forward over vertex 1 again (8 or 32 bytes by bit 0 of its
! first word).
	mov.l	@r4,r0
	tst	#1,r0
	add	#8,r4
	bt	.Lc_sb_step
	add	#24,r4
! 0c10ad68: on in the ring state.
.Lc_sb_step:
	bra	.Lc_ring_step
	nop				! (delay slot)
! 0c10ad6c: vertex 0 was behind, vertex 1 is in front. Keep vertex 1 in
! slot 1, read vertex 0 again into slot 0, send their cut and then vertex
! 1.
.Lc_second_front:
	bsr	.Lvtx_keep		! keep vertex 1
	mov	#1,r11			! (delay slot) r11 = 1
! Step r4 back two records, as at 0c10ad3a.
	add	#-8,r4
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sf_back1
	add	#-24,r4
! 0c10ad7a: the second step back.
.Lc_sf_back1:
	add	#-8,r4
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sf_back2
	add	#-24,r4
! 0c10ad84: r4 = vertex 0's record.
.Lc_sf_back2:
	bsr	.Lvtx_load		! load vertex 0 again
	nop
	bsr	.Lvtx_keep		! keep it in slot 0
	mov	#0,r11			! (delay slot) r11 = 0
	mov	#1,r11			! r11 = 1: the cut runs to vertex 1
	clrt				! T = 0: not the end of the strip
	bsr	.Lnear_cut_emit		! send cut(vertex 0, vertex 1)
	mov	#0,r0			! (delay slot) r0 = 0, the cut's first slot
	clrt
	bsr	.Lkept_vtx_emit		! send vertex 1 from its slot
	mov	#1,r0			! (delay slot) r0 = 1, the slot to send
! Step r4 forward over vertex 1 again.
	mov.l	@r4,r0
	tst	#1,r0
	add	#8,r4
	bt	.Lc_sf_step
	add	#24,r4
! 0c10ada4: on in the ring state.
.Lc_sf_step:
	bra	.Lc_ring_step
	nop				! (delay slot)
! 0c10ada8: from the skipping state: R (number r11) is in front after two
! or more behind. r4 = the record after R. Step back one record and load R
! properly, then go on as below.
.Lc_came_front:
	add	#-8,r4
	mov.l	@(4,r4),r0		! r0 = the last word of R
	tst	#1,r0
	bt	.Lc_cf_back		! R is a reference
	add	#-24,r4			! R is inline: 32 bytes back in all
! 0c10adb2: r4 = R.
.Lc_cf_back:
	bsr	.Lvtx_load		! load R in full
	nop				! (delay slot)
! 0c10adb6: (from the plain state too: R, just loaded, is the first vertex
! behind after two or more in front.) Keep R, then read the two vertices
! before it again into their slots: back three records, load two, and step
! forward over R.
.Lc_went_behind:
	bsr	.Lvtx_keep		! keep R in slot r11
	nop				! (delay slot)
! Three steps back, each as at 0c10ad3a.
	add	#-8,r4
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_wb_back2
	add	#-24,r4
! 0c10adc4: the second step back.
.Lc_wb_back2:
	add	#-8,r4
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_wb_back3
	add	#-24,r4
! 0c10adce: the third step back.
.Lc_wb_back3:
	add	#-8,r4
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_wb_reload
	add	#-24,r4
! 0c10add8: r4 = the record two before R.
.Lc_wb_reload:
	bsr	.Lvtx_load		! load it
	nop
	bsr	.Lvtx_keep		! keep it in the slot two before R's
	add	#-2,r11			! (delay slot) r11 = R's number - 2
	bsr	.Lvtx_load		! load the vertex before R
	nop
	bsr	.Lvtx_keep		! keep it in the slot before R's
	add	#1,r11			! (delay slot) r11 = R's number - 1
! Step r4 forward over R (8 or 32 bytes by bit 0 of its first word).
	mov.l	@r4,r0
	tst	#1,r0
	add	#8,r4
	bt	.Lc_wb_step
	add	#24,r4
! 0c10adf2: r4 = the record after R; the ring holds R and the two before
! it.
.Lc_wb_step:
	add	#1,r11			! r11 = R's number again
	mov	r12,r0
	tst	#1,r0			! r12 bit 0: flat shading
	bt.s	.Lc_dispatch		! Gouraud: straight to the cases
	mov	r9,r0			! (delay slot) r0 = the tests
	bsr	.Lflat_copy		! flat: R's intensities for all three
	nop
	bra	.Lc_dispatch		! to the cases
	mov	r9,r0			! (delay slot) r0 = the tests
! 0c10ae04: the ring state: load the next vertex, keep it, and act on the
! last three tests.
.Lc_ring_step:
	bsr	.Lvtx_load		! load the next vertex
	add	#1,r11			! (delay slot) r11 = its number
	bsr	.Lvtx_keep		! keep it in slot r11 & 3
	rotcl	r9			! (delay slot) shift its test into r9
	mov	r12,r0
	tst	#1,r0			! r12 bit 0: flat shading
	bt.s	.Lc_dispatch		! Gouraud: straight to the cases
	mov	r9,r0			! (delay slot) r0 = the tests
	bsr	.Lflat_copy		! flat: the newest vertex's intensities for all three
	nop
	mov	r9,r0			! r0 = the tests
! 0c10ae1a: r0 = the tests; bits 2, 1, 0 = A, B, C behind the near plane.
! Jump into the table of eight 4-byte entries that follows the braf.
.Lc_dispatch:
	and	#7,r0
	shll2	r0			! r0 = the case number x 4
	braf	r0			! to 0c10ae22 + case x 4
	nop				! (delay slot)
! Case 000 (never taken): empty, runs into the next entry.
	nop
	nop
! Case 001: A and B in front, C behind.
	bra	.Lc_case_001
	nop
! Case 010: only B behind.
	bra	.Lc_case_010
	nop
! Case 011: only A in front.
	bra	.Lc_case_011
	nop
! Case 100: only A behind.
	bra	.Lc_case_100
	nop
! Case 101: only B in front.
	bra	.Lc_case_101
	nop
! Case 110: only C in front.
	bra	.Lc_case_110
	nop
! Case 111 (never taken): empty, runs into the code below.
	nop
	nop
! 0c10ae42: 001: C has gone behind. Send cut(A,C), B, cut(B,C).
.Lc_case_001:
	mov	r11,r0
	clrt				! T = 0: not the end of the strip
	bsr	.Lnear_cut_emit		! cut(A,C): slots r11 - 2 and r11
	add	#-2,r0			! (delay slot) r0 = A's slot
	mov	r11,r0
	clrt
	bsr	.Lkept_vtx_emit		! B from its slot
	add	#-1,r0			! (delay slot) r0 = B's slot
	mov	r11,r0
	dt	r3			! count C; T = it was the strip's last vertex
	bsr	.Lnear_cut_emit		! cut(B,C), ending the strip when T is set
	add	#-1,r0			! (delay slot) r0 = B's slot
	bf	.Lc_ring_step		! more vertices: the next ring step
	bra	.Lc_strip_done		! the strip is finished
	nop				! (delay slot)
! 0c10ae60: 010: C is back in front after B alone was behind. Send C,
! cut(B,C) and C again.
.Lc_case_010:
	clrt				! T = 0: not the end of the strip
	bsr	.Lkept_vtx_emit		! C from its slot
	mov	r11,r0			! (delay slot) r0 = C's slot
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut(B,C)
	add	#-1,r0			! (delay slot) r0 = B's slot
	dt	r3			! count C; T = it was the strip's last vertex
	bsr	.Lkept_vtx_emit		! C again, ending the strip when T is set
	mov	r11,r0			! (delay slot) r0 = C's slot
	bf	.Lc_ring_step		! more vertices: the next ring step
	bra	.Lc_strip_done		! the strip is finished
	nop				! (delay slot)
! 0c10ae7a: 011: B and C are both behind. Send cut(A,C) as the end of a
! strip and skip ahead until a vertex is in front again.
.Lc_case_011:
	mov	r11,r0
	sett				! T = 1: the end of the strip
	bsr	.Lnear_cut_emit		! cut(A,C)
	add	#-2,r0			! (delay slot) r0 = A's slot
	dt	r3			! count C; T = it was the strip's last vertex
	bt	.Lc_to_done		! finished
	bra	.Lc_behind_loop		! to the skipping state
	nop				! (delay slot)
! 0c10ae8a: 100: B and C are in front again. Send cut(A,C), B and C, and
! go back to the plain state.
.Lc_case_100:
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut(A,C)
	add	#-2,r0			! (delay slot) r0 = A's slot
	mov	r11,r0
	clrt
	bsr	.Lkept_vtx_emit		! B from its slot
	add	#-1,r0			! (delay slot) r0 = B's slot
	dt	r3			! count C; T = it was the strip's last vertex
	bsr	.Lkept_vtx_emit		! C, ending the strip when T is set
	mov	r11,r0			! (delay slot) r0 = C's slot
	bt	.Lc_to_done		! finished
	bra	.Lc_front_loop		! to the plain state
	add	#1,r11			! (delay slot) r11 = the next vertex's number
! 0c10aea6: a step for the branches above that cannot reach 0c10ad1a.
.Lc_to_done:
	bra	.Lc_strip_done
	nop				! (delay slot)
! 0c10aeaa: 101: C has gone behind with A behind already. Send cut(B,C).
.Lc_case_101:
	mov	r11,r0
	dt	r3			! count C; T = it was the strip's last vertex
	bsr	.Lnear_cut_emit		! cut(B,C), ending the strip when T is set
	add	#-1,r0			! (delay slot) r0 = B's slot
	bf	.Lc_ring_step		! more vertices: the next ring step
	bra	.Lc_strip_done		! the strip is finished
	nop				! (delay slot)
! 0c10aeb8: 110: C is in front after A and B behind. The two cuts go out
! in the order that suits C's number (odd or even), then C.
.Lc_case_110:
	mov	r11,r0
	tst	#1,r0			! T = C's number is even
	bt	.Lc_110_even		! even
! Odd: cut(B,C), cut(A,C), cut(B,C).
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut(B,C)
	add	#-1,r0			! (delay slot) r0 = B's slot
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut(A,C)
	add	#-2,r0			! (delay slot) r0 = A's slot
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut(B,C) again
	add	#-1,r0			! (delay slot) r0 = B's slot
	bra	.Lc_110_last		! on to C
	nop				! (delay slot)
! 0c10aeda: even: cut(A,C), cut(B,C).
