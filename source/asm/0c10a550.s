! intensity_near_cut_emit
!
! Sends the point where the edge between two kept vertices meets the
! near plane. With a and b the two slots' minus-depth words,
!   t = (near - a) / (b - a)
! and every other value v is taken as va + t x (vb - va): x and y
! (times depth), u, v and the two intensities. The point lies on the
! near plane, so its 1/w is the plane's (r7) and X, Y are x, y times
! that.
!
! In:    r0 = the number of the vertex the edge starts from (slot
!        r0 & 3), r11 = the one it runs to (slot r11 & 3).
!        r12 = the near value's bits; r7 = 1/w of the near plane.
!        T = 1 to send the point as the last vertex of a strip.
!        r5 = list write address, r6 = store-queue pointer.
! Out:   r5 and r6 advanced by 32. T as it came in.
! Uses:  r0, r2, r10 and fr0-fr5 are changed; fr6, fr7 are kept. No
!        stack.
! Notes: FPSCR SZ = 0 on entry and return. r12 is used as a float with
!        its flag bit 0 in place, so "near" can be one unit in the last
!        place off. The end-of-strip control word here is the constant
!        0xf0000000, not the shifted pointer. Called (bsr) by
!        intensity_strip_near_clip and intensity_tri_near_clip.
	.global	_intensity_near_cut_emit
	.type	_intensity_near_cut_emit,@function
_intensity_near_cut_emit:
.Lnear_cut_emit:
	and	#3,r0			! r0 = the first slot's number (T is not touched)
	shll2	r0
	mov.l	.Lclip_ring,r10		! r10 = intensity_clip_ring
	shll2	r0
	add	r0,r0			! r0 = the slot number x 32
	mov	r10,r2			! r2 = intensity_clip_ring too
	add	r0,r10			! r10 = slot A, the edge's start
	mov	r11,r0
	and	#3,r0			! r0 = the second slot's number
	fmov	@r10,fr2		! fr2 = a, A's minus depth
	shll2	r0
	shll2	r0
	add	r0,r0			! r0 = the slot number x 32
	add	r0,r2			! r2 = slot B, the edge's end
	fmov	@r2,fr1			! fr1 = b, B's minus depth
	lds	r12,fpul
	fsts	fpul,fr0		! fr0 = the near value
	fsub	fr2,fr0			! fr0 = near - a
	add	#24,r10			! r10 = A's intensity pair (+24)
	fsub	fr2,fr1			! fr1 = b - a
	add	#24,r2			! r2 = B's intensity pair
	fdiv	fr1,fr0			! fr0 = t
	lds	r7,fpul
	fsts	fpul,fr1		! fr1 = 1/w of the near plane
	fschg				! 8-byte fmov
! The intensities, then u and v, a pair at a time: the difference
! B - A, then A + t x difference with fmac.
	fmov	@r2,fr4			! fr4, fr5 = B's base, offset
	add	#-8,r2
	fmov	@r10,fr2		! fr2, fr3 = A's base, offset
	add	#-8,r10
	fsub	fr2,fr4			! fr4, fr5 = B - A
	fsub	fr3,fr5
	add	#32,r6			! r6 = the end of the vertex's 32 bytes
	fmac	fr0,fr4,fr2		! fr2 = base at the cut
	fmac	fr0,fr5,fr3		! fr3 = offset at the cut
	fmov	fr2,@-r6		! words 6-7: base, offset
	fmov	@r2,fr4			! fr4, fr5 = B's u, v
	add	#-8,r2
	fmov	@r10,fr2		! fr2, fr3 = A's u, v
	add	#-8,r10
	fsub	fr2,fr4
	fsub	fr3,fr5
	fmac	fr0,fr4,fr2		! fr2 = u at the cut
	fmac	fr0,fr5,fr3		! fr3 = v at the cut
	fmov	fr2,@-r6		! words 4-5: the texture u, v
	fschg				! back to 4-byte fmov
	fmov	fr1,@-r6		! word 3: 1/w of the near plane
! x and y the same way, one word at a time.
	fmov	@r2,fr5			! fr5 = B's y times depth
	add	#-4,r2
	fmov	@r10,fr3		! fr3 = A's y times depth
	add	#-4,r10
	fmov	@r2,fr4			! fr4 = B's x times depth
	fmov	@r10,fr2		! fr2 = A's x times depth
	fsub	fr3,fr5
	fsub	fr2,fr4
	mov	#-16,r2			! r2 = -16, to become the end-of-strip word
	fmac	fr0,fr5,fr3		! fr3 = y at the cut
	shll16	r2
	fmac	fr0,fr4,fr2		! fr2 = x at the cut
	shll8	r2			! r2 = 0xf0000000
	fmul	fr1,fr3			! Y = y x 1/w
	add	#32,r5			! the list takes 32 bytes
	fmul	fr1,fr2			! X = x x 1/w
	fmov	fr3,@-r6		! word 2: Y
	fmov	fr2,@-r6		! word 1: X
	bt	.Ln_control		! T set: keep the end-of-strip word
	mov	r6,r2			! else the control word is the pointer itself
! 0c10b104: r2 = the control word.
.Ln_control:
	mov.l	r2,@-r6			! word 0: the control word
	pref	@r6			! send the 32 bytes
	rts
	add	#32,r6			! (delay slot) r6 = the next free 32 bytes
