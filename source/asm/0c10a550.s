! intensity_vtx_load
!
! Fetches one vertex record for the near-plane clippers, transforms it,
! lights it and tests it against the near plane. Nothing is written:
! the caller sends the vertex (intensity_vtx_emit), keeps it
! (intensity_vtx_keep) or drops it.
!
! The lighting is the same as intensity_strip_send's three bodies, done
! with tests instead of separate code: base = fr15, plus N.L when that
! is above 0; offset = 0, or for a specular r8 the row entry
! [int(N.H)] when N.L is above 0 and the index is above 309. For an
! odd r8 (unlit) the base is 1.0 (fr15 is 1.0 for those groups).
!
! In:    r4 = the vertex record (inline or reference).
!        r8 = lighting selector, fr15 = base intensity, fr12-fr14 =
!        light direction (y, z, x), fr8-fr10 = half vector (y, z, x).
!        r12 = the near value's bits (bit 0 = the flat flag).
!        XMTRX = the matrix: ftrv gives (depth, x times depth, y times
!        depth, minus depth).
! Out:   r4 = the next record.
!        fr4 = minus depth, fr5, fr6 = x, y times depth, fr7 = 1/depth.
!        fr2 = base intensity, fr3 = offset intensity.
!        r2 = pointer to the record's u, v.
!        T = the vertex is nearer than the near plane (r12 above the
!        bits of minus depth, as unsigned numbers; true as well for a
!        vertex behind the eye, whose minus depth is positive).
! Uses:  r0 and r1 are changed, fr0, fr1 (the normal's y, z) and fr11
!        (N.H); r3, r5-r7, fr8-fr10 are kept. No stack.
! Notes: FPSCR SZ = 0 (4-byte fmov). Called (bsr) by
!        intensity_strip_near_clip and intensity_tri_near_clip.
	.global	_intensity_vtx_load
	.type	_intensity_vtx_load,@function
_intensity_vtx_load:
.Lvtx_load:
	mov.l	@r4,r0			! r0 = the record's first word
	tst	#1,r0			! T = it is a reference (bit 0 clear)
	bf.s	.Ll_inline		! inline
	fmov	@r4+,fr4		! (delay slot) fr4 = x if inline; r4 past the first word
! A reference: its second word is the offset from its end to the record.
	mov.l	@r4+,r0			! r0 = the offset; r4 = the end of the reference
	add	r4,r0			! r0 = the record referred to
	fmov	@r0+,fr4		! fr4, fr5, fr6 = x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	fldi1	fr7			! w = 1
	fmov	@r0+,fr2		! fr2 = normal x
	fmov	@r0+,fr0		! fr0 = normal y
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = x, y times depth, fr7 = -depth
	fmov	@r0+,fr1		! fr1 = normal z
	fldi0	fr3			! fr3 = 0, the fourth term of N.L
	add	#32,r4			! r4 = 32 past the reference, for the prefetch below
	bra	.Ll_light
	mov	r0,r2			! (delay slot) r2 = &record.u
! 0c10af24: an inline record: the same loads straight from r4.
.Ll_inline:
	fmov	@r4+,fr5		! fr5 = y
	fmov	@r4+,fr6		! fr6 = z
	fldi1	fr7
	fmov	@r4+,fr2		! fr2 = normal x
	fmov	@r4+,fr0		! fr0 = normal y
	ftrv	xmtrx,fv4		! transform, as at 0c10af18
	fmov	@r4+,fr1		! fr1 = normal z
	fldi0	fr3
	mov	r4,r2			! r2 = &record.u
	add	#40,r4			! r4 = 32 past the record, for the prefetch below
! 0c10af38: both kinds: position in fr4-fr7, normal in fr0-fr2, fr3 = 0.
.Ll_light:
	fldi0	fr11			! fr11 = 0, for the compare and N.H's fourth term
	fipr	fv12,fv0		! fr3 = N.L
	pref	@r4			! prefetch 32 bytes past the next record
	add	#-32,r4			! r4 = the next record
	flds	fr7,fpul		! fpul = minus depth
	sts	fpul,r0			! r0 = its bits, for the near test
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth
	fsts	fpul,fr4		! fr4 = minus depth (the divide has taken the depth)
	fcmp/gt	fr11,fr3		! T = N.L is above 0
	fipr	fv0,fv8			! fr11 = N.H
	fmov	fr15,fr2		! fr2 = the base intensity
	bf	.Ll_no_offset		! facing away: base alone, offset 0
	fadd	fr3,fr2			! base = fr15 + N.L
	tst	r8,r8			! T = r8 is 0 (diffuse only)
	fldi0	fr3
	bt.s	.Ll_offset_zero		! diffuse: offset 0
	mov	#1,r1			! (delay slot)
	tst	r1,r8			! T = r8 is even
	bf.s	.Ll_unlit		! odd: unlit
	ftrc	fr11,fpul		! (delay slot) fpul = int(N.H)
! Specular: the offset is the row's entry when the index is above 309.
	mov	#127,r1
	add	#127,r1
	sts	fpul,r0			! r0 = the index
	add	#55,r1			! r1 = 127 + 127 + 55 = 309
	cmp/gt	r1,r0			! T = the index is above 309
	shll2	r0			! r0 = the index x 4
	bf	.Ll_no_offset		! not above: offset 0
	mov.l	@(r0,r8),r0		! r0 = the row's entry (r8 is the biased row pointer)
	lds	r0,fpul
	fsts	fpul,fr3		! fr3 = the offset intensity
	flds	fr4,fpul
	sts	fpul,r0			! r0 = the bits of minus depth again
	rts
	cmp/hi	r0,r12			! (delay slot) T = nearer than the near plane
! 0c10af7e: unlit: base 1.0, offset 0 (fr3 is 0 already).
.Ll_unlit:
	fldi1	fr2
	flds	fr4,fpul
	sts	fpul,r0			! r0 = the bits of minus depth
	rts
	cmp/hi	r0,r12			! (delay slot) T = nearer than the near plane
! 0c10af88: no highlight: r0 was used for the index, so take the bits
! again.
.Ll_no_offset:
	flds	fr4,fpul
	sts	fpul,r0			! r0 = the bits of minus depth
! 0c10af8c: offset intensity 0.
.Ll_offset_zero:
	fldi0	fr3
	rts
	cmp/hi	r0,r12			! (delay slot) T = nearer than the near plane
! Padding to the next routine's 16-byte boundary.
	nop
	nop
	nop
	nop
	nop
	nop
	nop

! intensity_vtx_emit
!
! Writes the vertex intensity_vtx_load has just left in the registers
! to the store queue as a 32-byte intensity vertex (the layout given at
! intensity_strip_send) and counts it off r3. When that makes r3 zero
! the vertex gets the end-of-strip control word.
!
! In:    fr4-fr7 = minus depth, x and y times depth, 1/depth; fr2, fr3
!        = base and offset intensity; r2 = pointer to u, v.
!        r3 = vertices left in the strip, this one included.
!        r5 = list write address, r6 = store-queue pointer.
! Out:   r3 one less; T = it reached 0 (this was the last vertex).
!        r5 and r6 advanced by 32.
! Uses:  r2, fr0, fr1 (u, v) and fr5, fr6 (now X, Y) are changed. No
!        stack.
! Notes: FPSCR SZ = 0 on entry and return, SZ = 1 for the stores.
!        Called (bsr) by intensity_strip_near_clip and
!        intensity_tri_near_clip.
	.global	_intensity_vtx_emit
	.type	_intensity_vtx_emit,@function
_intensity_vtx_emit:
.Lvtx_emit:
	fschg				! 8-byte fmov
	add	#32,r6			! r6 = the end of the vertex's 32 bytes
	fmov	@r2,fr0			! fr0, fr1 = u, v
	fmul	fr7,fr6			! Y on screen = y / depth
	fmov	fr2,@-r6		! words 6-7: base, offset
	fmul	fr7,fr5			! X on screen = x / depth
	fmov	fr0,@-r6		! words 4-5: the texture u, v
	mov	r6,r2			! r2 = the pointer, for the end-of-strip word
	fmov	fr6,@-r6		! words 2-3: Y and 1 / depth
	dt	r3			! count the vertex; T = the strip's last
	fmov	fr4,@-r6		! words 0-1: (minus depth, replaced below), X
	bt.s	.Le_last		! the last vertex
	fschg				! (delay slot) back to 4-byte fmov
	mov.l	r6,@r6			! word 0: the control word, the pointer itself
	add	#32,r5			! the list took 32 bytes
	pref	@r6			! send them
	rts
	add	#32,r6			! (delay slot) r6 = the next free 32 bytes
! 0c10afc4: the strip's last vertex: the control word shifted right, and T
! set for the caller.
.Le_last:
	shar	r2			! r2 = the end-of-strip control word
	mov.l	r2,@r6
	add	#32,r5
	sett				! T = 1: the strip is finished
	pref	@r6			! send the 32 bytes
	rts
	add	#32,r6			! (delay slot) r6 = the next free 32 bytes
! Padding to the next routine's 16-byte boundary.
	nop
