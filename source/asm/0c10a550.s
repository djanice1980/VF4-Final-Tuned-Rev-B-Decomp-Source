! intensity_strip_send
!
! Sends one triangle strip that needs no clipping: each vertex record is
! fetched, put through the matrix, divided by its depth and written to
! the store queue as a 32-byte intensity vertex
!   word 0  control word      word 1  X = x / depth
!   word 2  Y = y / depth     word 3  1 / depth
!   words 4-5  u, v           words 6-7  base and offset intensity
! The control word is the store-queue pointer itself (0xe0......: the
! top three bits are what the vertex needs); for the last vertex of a
! strip it is that value shifted right one place arithmetically
! (0xf0......), which also sets the end-of-strip bit 28.
!
! Three bodies, chosen by r8:
!   odd (unlit)    0c10a940: base 1.0 and offset 0 are written once into
!                  words 6-7 of both store queues and left there; each
!                  vertex then writes only its first 24 bytes.
!   0 (diffuse)    0c10aa62: base = fr15 + max(0, N.L), offset = 0.
!   else (specular) 0c10abb6: base as diffuse; offset = the entry
!                  [int(N.H)] of the row r8 points at when N.L is above
!                  0 and the index is above 309, else 0.
! The unlit and diffuse bodies are unrolled over two vertices (one in
! fr4-fr7, the next in fr8-fr11) so that one vertex's transform runs
! while the other's divide finishes; the specular body does one vertex
! a pass.
!
! When the strip's count runs out the word after its last record is
! looked at: positive with bit 7 set means another strip follows under
! the same polygon header (that word, a count, then records), and the
! loop carries on with it. Anything else ends the routine.
!
! In:    r4 = the run's count word (the vertex records follow it).
!        r5 = the list write address, r6 = the store-queue pointer (the
!        next free 32 bytes).
!        r8 = lighting selector, fr15 = base intensity, fr12-fr14 =
!        light direction (y, z, x), fr8-fr10 = half vector (y, z, x),
!        as intensity_send_alpha sets them; XMTRX = its matrix.
! Out:   r4 = the word after the last strip (the next run word).
!        r5 and r6 advanced by 32 for each vertex sent.
! Uses:  r0-r3 and r14 are changed without being saved (compiled code
!        would keep r14), and fr0-fr11; the specular body also changes
!        r7, r9 is not touched. No stack is used.
! Notes: FPSCR SZ = 0 on entry and on return; SZ = 1 (fschg) inside, so
!        every fmov here moves a pair of registers (8 bytes). The
!        diffuse body uses fr11 as the next vertex's w and its 1/depth,
!        and the specular body uses it for N.H, so the half vector's
!        fourth element is whatever those leave. Called only by
!        intensity_send_alpha (bsr).
	.global	_intensity_strip_send
	.type	_intensity_strip_send,@function
_intensity_strip_send:
.Lstrip_send:
	tst	r8,r8			! T = r8 is 0
	mov	r8,r0
	bf	.Ls_not_diffuse		! not 0: unlit or specular
	bra	.Ls_diffuse		! 0: the diffuse body
! 0c10a938: (also the delay slot of the bra above) odd r8 = unlit.
.Ls_not_diffuse:
	tst	#1,r0			! T = r8 is even
	bf	.Ls_unlit		! odd: the unlit body, just below
	bra	.Ls_specular		! even and not 0: the specular body
	nop				! (delay slot)
! 0c10a940: the unlit body. r6 = V, the start of the next free 32 bytes.
! The store queue is two 32-byte buffers taken in turn (bit 5 of the
! address picks one), so words 6-7 are written once at V-8 (the other
! buffer) and once at V+24 (this one); r6 stays at V+24 and each vertex is
! stored downward from there.
.Ls_unlit:
	mov.l	@r4+,r3			! r3 = the strip's vertex count
	fldi1	fr2
	fschg				! 8-byte fmov until the return
	fldi0	fr3			! (fr2, fr3) = base 1.0, offset 0.0
	fmov	fr2,@-r6		! words 6-7 of the other buffer
	add	#32,r6			! r6 = V+24
	fmov	fr2,@r6			! words 6-7 of this buffer
! Fetch the first record. Bit 0 of its first word says which kind: set
! = inline (the 32 bytes at r4); clear = a reference, whose second word
! is the offset from its end to the record.
	mov.l	@r4,r0			! r0 = the record's first word
	mov	r4,r14
	tst	#1,r0
	add	#32,r4			! r4 = past an inline record
	bf	.Ls_unlit_first		! inline: r14 = the record itself
	mov.l	@(4,r14),r14		! reference: r14 = the offset
	add	#-24,r4			! r4 = past the 8-byte reference
	add	r4,r14			! r14 = the record it refers to
! 0c10a95e: r14 = the first vertex. With 8-byte moves the normal's x rides
! along in fr7 and is thrown away.
.Ls_unlit_first:
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14,fr6		! fr6 = z
	add	#16,r14			! r14 = &record.u (+0x18)
	fldi1	fr7			! w = 1
	fmov	@r14,fr0		! fr0, fr1 = u, v
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = x, y times depth
! 0c10a96a: first half. Vertex A is in fr4-fr6 with u, v in fr0, fr1.
! Start its divide and fetch vertex B into fr8-fr11 meanwhile.
.Ls_unlit_a:
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth of A
	dt	r3			! count A; T = A is the strip's last vertex
	mov.l	@r4+,r0			! r0 = the next record's first word
	bt.s	.Ls_unlit_a_last		! A is the last: see what follows the strip
	mov.l	@r4+,r14		! (delay slot) r14 = the next record's second word
	tst	#1,r0			! T = it is a reference
	mov	r6,r2			! r2 = A's control word
	bt.s	.Ls_unlit_a_next		! reference
	add	r4,r14			! (delay slot) r14 = the record referred to
! Inline: r14 = the record (the two words just read), r4 = its end.
	mov	r4,r14
	add	#24,r4
	add	#-8,r14
! 0c10a984: r14 = vertex B's record. Load and transform B while A is
! written.
.Ls_unlit_a_next:
	fmov	@r14+,fr8		! fr8, fr9 = B's x, y
	add	#32,r4
	pref	@r4			! prefetch 32 bytes past the next record
	fmov	@r14,fr10		! fr10 = B's z
	add	#16,r14			! r14 = &B.u
	fldi1	fr11			! B's w = 1
	fmul	fr7,fr6			! A: Y on screen = y / depth
	fmov	fr0,@-r6		! A words 4-5: the texture u, v
	fmul	fr7,fr5			! A: X on screen = x / depth
	fmov	fr6,@-r6		! A words 2-3: Y and 1 / depth
	ftrv	xmtrx,fv8		! fr8 = B's depth, fr9, fr10 = its x, y times depth
	fmov	fr4,@-r6		! A words 0-1: (the depth, replaced below), X
	add	#-32,r4
	mov.l	r2,@r6			! A word 0: the control word
	fmov	@r14,fr0		! fr0, fr1 = B's u, v
	dt	r3			! count B; T = B is the strip's last vertex
	pref	@r6			! send A's 32 bytes
	add	#56,r6			! r6 = 24 bytes into the next vertex
! Second half: the same with the two register sets changed over.
	mov	r6,r2			! r2 = B's control word
	fldi1	fr11
	fdiv	fr8,fr11		! fr11 = 1 / depth of B
	mov.l	@r4+,r0			! r0 = the next record's first word
	bt.s	.Ls_unlit_b_last		! B is the last: see what follows the strip
	mov.l	@r4+,r14		! (delay slot) r14 = its second word
	tst	#1,r0
	bt.s	.Ls_unlit_b_next		! reference: r14 = the record referred to
	add	r4,r14
