! intensity_tri_near_clip
!
! Sends the independent triangles of a group whose bounding sphere
! crosses the near plane, cutting them at the plane. For each triangle
! intensity_tri_classify first tests its three vertices (bit 2 = the
! first is nearer than the near plane, "behind"; bit 1 the second;
! bit 0 the third):
!   000  all in front: the three are loaded and sent as they are.
!   111  all behind: the three records are stepped over.
!   else the three are loaded into slots 0, 1, 2 of intensity_clip_ring
!        (with intensity_flat_copy when r12 bit 0 says flat shading)
!        and the visible part goes out as one strip, v0-v2 being kept
!        vertices and cut(a,b) the point where edge a-b meets the
!        near plane; the last one ends the strip:
!          001  v0, v1, cut(0,2), cut(1,2)
!          010  v0, cut(0,1), v2, cut(1,2)
!          011  v0, cut(0,1), cut(0,2)
!          100  cut(0,1), v1, cut(0,2), v2
!          101  cut(0,1), v1, cut(1,2)
!          110  cut(0,2), cut(1,2), v2
!
! In:    r4 = the run's count word (the number of triangles; three
!        vertex records each follow).
!        r5, r6 = list write address and store-queue pointer.
!        r7 = 1/w of the near plane (header +0x20).
!        r12 = the near value's bits, bit 0 = flat shading.
!        r8, fr15, fr12-fr14, fr8-fr10, XMTRX as intensity_vtx_load
!        needs them.
! Out:   r4 = the word after the last triangle (the next run word).
!        r5 and r6 advanced by 32 for each vertex sent.
!        r12 bit 0 = 1 (the caller's "crosses the near plane" flag).
! Uses:  r10, r11 and pr are saved on the stack and restored. r0-r3 and
!        r9 are changed without being saved (compiled code would keep
!        r9), and fr0-fr7 and fr11.
! Notes: FPSCR SZ = 0 on entry and return. T on entry is not used.
!        The jump table has entries for 000 and 111, which are dealt
!        with before it and never reach it. Called only by
!        intensity_send_alpha (bsr), for a run word without bit 4.
	.global	_intensity_tri_near_clip
	.type	_intensity_tri_near_clip,@function
_intensity_tri_near_clip:
.Ltri_near_clip:
	mov.l	r10,@-r15		! r10 is the helpers' scratch, r11 the slot number
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3			! r3 = the number of triangles
! 0c10b128: per triangle. r4 = its first vertex record.
.Lt_tri_loop:
	bsr	.Ltri_classify		! r9 = the three near tests
	mov	#0,r9			! (delay slot) r9 = 0 for the tests to shift into
	mov	r9,r0
	cmp/eq	#0,r0			! T = all three are in front
	bt	.Lt_all_front		! send them unclipped
	cmp/eq	#7,r0			! T = all three are behind
	bt	.Lt_all_behind		! skip the triangle
! The triangle crosses the plane: load and keep its three vertices.
	bsr	.Lvtx_load		! load the first vertex
	mov	#0,r11			! (delay slot) r11 = 0
	bsr	.Lvtx_keep		! keep it in slot 0
	nop
	bsr	.Lvtx_load		! load the second
	mov	#1,r11			! (delay slot) r11 = 1
	bsr	.Lvtx_keep		! keep it in slot 1
	nop
	bsr	.Lvtx_load		! load the third
	mov	#2,r11			! (delay slot) r11 = 2
	bsr	.Lvtx_keep		! keep it in slot 2
	nop
	mov	r12,r0
	tst	#1,r0			! r12 bit 0: flat shading
	bt.s	.Lt_dispatch		! Gouraud: straight to the cases
	shll2	r9			! (delay slot) r9 = the case number x 4
	bsr	.Lflat_copy		! flat: the third vertex's intensities for all three
	nop
! 0c10b15a: jump into the table of eight 4-byte entries that follows the
! braf.
.Lt_dispatch:
	braf	r9			! to 0c10b15e + case x 4
	nop				! (delay slot)
! Case 000 (never taken): empty, runs into the next entry.
	nop
	nop
! Case 001: only the third vertex behind.
	bra	.Lt_case_001
	nop
! Case 010: only the second behind.
	bra	.Lt_case_010
	nop
! Case 011: only the first in front.
	bra	.Lt_case_011
	nop
! Case 100: only the first behind.
	bra	.Lt_case_100
	nop
! Case 101: only the second in front.
	bra	.Lt_case_101
	nop
! Case 110: only the third in front.
	bra	.Lt_case_110
	nop
! Case 111 (never taken): empty, runs into the code below.
	nop
	nop
! 0c10b17e: the triangle is done.
.Lt_next_tri:
	dt	r3			! count it; T = that was the last
	bf	.Lt_tri_loop		! more triangles
! Restore and return; r4 is already on the word after the last record.
	mov	#1,r0			! r0 = 1, for the or below
	lds.l	@r15+,pr
	or	r0,r12			! r12 bit 0 = 1 again for the caller
	mov.l	@r15+,r11
	rts
	mov.l	@r15+,r10		! (delay slot)
! 0c10b18e: all three vertices in front: load and send each. r3 is lent to
! intensity_vtx_emit as a count of 3, so that the third vertex gets the
! end-of-strip control word; the triangle count waits in r9.
.Lt_all_front:
	mov	r3,r9			! r9 = the triangle count
	bsr	.Lvtx_load		! load the first vertex
	mov	#3,r3			! (delay slot) r3 = 3
	bsr	.Lvtx_emit		! send it
	nop
	bsr	.Lvtx_load		! load the second
	nop
	bsr	.Lvtx_emit		! send it
	nop
	bsr	.Lvtx_load		! load the third
	nop
	bsr	.Lvtx_emit		! send it, ending the strip
	nop
	bra	.Lt_next_tri		! on to the next triangle
	mov	r9,r3			! (delay slot) r3 = the triangle count again
! 0c10b1ac: all three behind: step r4 over the three records, each 8 bytes
! (a reference, bit 0 of its first word clear) or 32 (inline).
.Lt_all_behind:
	mov.l	@r4,r0			! r0 = the first record's first word
	tst	#1,r0
	add	#8,r4			! a reference's 8 bytes
	bt	.Lt_skip2		! it is a reference
	add	#24,r4			! inline: 32 bytes in all
! 0c10b1b6: the second record.
.Lt_skip2:
	mov.l	@r4,r0
	tst	#1,r0
	add	#8,r4
	bt	.Lt_skip3
	add	#24,r4
! 0c10b1c0: the third record.
.Lt_skip3:
	mov.l	@r4,r0
	tst	#1,r0
	add	#8,r4
	bt	.Lt_skipped
	add	#24,r4
! 0c10b1ca: r4 = the next triangle.
.Lt_skipped:
	bra	.Lt_next_tri
	nop				! (delay slot)
! 0c10b1ce: 001: the third vertex is behind. Send v0, v1, cut(0,2),
! cut(1,2).
.Lt_case_001:
	clrt				! T = 0: not the end of the strip
	bsr	.Lkept_vtx_emit		! v0 from slot 0
	mov	#0,r0			! (delay slot) r0 = 0
	clrt
	bsr	.Lkept_vtx_emit		! v1 from slot 1
	mov	#1,r0			! (delay slot) r0 = 1
	clrt
	mov	#2,r11			! r11 = 2: the cuts run to slot 2
	bsr	.Lnear_cut_emit		! cut(0,2)
	mov	#0,r0			! (delay slot) r0 = 0
	sett				! T = 1: the end of the strip
	bsr	.Lnear_cut_emit		! cut(1,2)
	mov	#1,r0			! (delay slot) r0 = 1
	bra	.Lt_next_tri		! on to the next triangle
	nop				! (delay slot)
! 0c10b1ec: 010: the second vertex is behind. Send v0, cut(0,1), v2,
! cut(1,2).
.Lt_case_010:
	clrt				! T = 0: not the end of the strip
	bsr	.Lkept_vtx_emit		! v0 from slot 0
	mov	#0,r0
	clrt
	mov	#1,r11			! r11 = 1: the cut runs to slot 1
	bsr	.Lnear_cut_emit		! cut(0,1)
	mov	#0,r0			! (delay slot) r0 = 0
	clrt
	mov	#2,r11			! r11 = 2 for the last cut
	bsr	.Lkept_vtx_emit		! v2 from slot 2
	mov	#2,r0			! (delay slot) r0 = 2
	sett				! T = 1: the end of the strip
	bsr	.Lnear_cut_emit		! cut(1,2)
	mov	#1,r0			! (delay slot) r0 = 1
	bra	.Lt_next_tri		! on to the next triangle
	nop				! (delay slot)
! 0c10b20c: 011: only the first vertex is in front. Send v0, cut(0,1),
! cut(0,2).
.Lt_case_011:
	clrt				! T = 0: not the end of the strip
	bsr	.Lkept_vtx_emit		! v0 from slot 0
	mov	#0,r0
	clrt
	mov	#1,r11			! r11 = 1: the cut runs to slot 1
	bsr	.Lnear_cut_emit		! cut(0,1)
	mov	#0,r0			! (delay slot) r0 = 0
	sett				! T = 1: the end of the strip
	mov	#2,r11			! r11 = 2: the cut runs to slot 2
	bsr	.Lnear_cut_emit		! cut(0,2)
	mov	#0,r0			! (delay slot) r0 = 0
	bra	.Lt_next_tri		! on to the next triangle
	nop				! (delay slot)
! 0c10b226: 100: the first vertex is behind. Send cut(0,1), v1, cut(0,2),
! v2.
.Lt_case_100:
	clrt				! T = 0: not the end of the strip
	mov	#1,r11			! r11 = 1: the cut runs to slot 1
	bsr	.Lnear_cut_emit		! cut(0,1)
	mov	#0,r0			! (delay slot) r0 = 0
	clrt
	bsr	.Lkept_vtx_emit		! v1 from slot 1
	mov	#1,r0			! (delay slot) r0 = 1
	clrt
	mov	#2,r11			! r11 = 2: the cut runs to slot 2
	bsr	.Lnear_cut_emit		! cut(0,2)
	mov	#0,r0			! (delay slot) r0 = 0
	sett				! T = 1: the end of the strip
	bsr	.Lkept_vtx_emit		! v2 from slot 2
	mov	#2,r0			! (delay slot) r0 = 2
	bra	.Lt_next_tri		! on to the next triangle
	nop				! (delay slot)
! 0c10b246: 101: only the second vertex is in front. Send cut(0,1), v1,
! cut(1,2).
.Lt_case_101:
	clrt				! T = 0: not the end of the strip
	mov	#1,r11			! r11 = 1: the cut runs to slot 1
	bsr	.Lnear_cut_emit		! cut(0,1)
	mov	#0,r0			! (delay slot) r0 = 0
	clrt
	bsr	.Lkept_vtx_emit		! v1 from slot 1
	mov	#1,r0			! (delay slot) r0 = 1
	sett				! T = 1: the end of the strip
	mov	#2,r11			! r11 = 2: the cut runs to slot 2
	bsr	.Lnear_cut_emit		! cut(1,2)
	mov	#1,r0			! (delay slot) r0 = 1
	bra	.Lt_next_tri		! on to the next triangle
	nop				! (delay slot)
! 0c10b260: 110: only the third vertex is in front. Send cut(0,2),
! cut(1,2), v2.
.Lt_case_110:
	clrt				! T = 0: not the end of the strip
	mov	#2,r11			! r11 = 2: both cuts run to slot 2
	bsr	.Lnear_cut_emit		! cut(0,2)
	mov	#0,r0			! (delay slot) r0 = 0
	clrt
	bsr	.Lnear_cut_emit		! cut(1,2)
	mov	#1,r0			! (delay slot) r0 = 1
	sett				! T = 1: the end of the strip
	bsr	.Lkept_vtx_emit		! v2 from slot 2
	mov	#2,r0			! (delay slot) r0 = 2
	bra	.Lt_next_tri		! on to the next triangle
	nop				! (delay slot)
! Padding to the next routine's 16-byte boundary.
	nop
	nop
	nop
	nop

! intensity_tri_classify
!
! Tests the three vertices of the triangle at r4 against the near
! plane without lighting or sending anything: only the positions are
! read and put through the matrix. The three results are shifted into
! r9, first vertex first, so that with r9 = 0 on entry it comes back
! as a number from 0 (all in front) to 7 (all nearer than the near
! plane), the first vertex in bit 2.
!
! In:    r4 = the triangle's first vertex record (three follow one
!        another, each inline or a reference).
!        r9 = 0 (the caller clears it in the bsr's delay slot).
!        r12 = the near value's bits; XMTRX = the matrix.
! Out:   r9 = r9 shifted left three places with the three tests in
!        bits 2, 1, 0. r4 unchanged.
! Uses:  r0, r1 and fr0-fr7 are changed; r2, r3, r5-r7 and fr8-fr11
!        are kept. No stack.
! Notes: FPSCR SZ = 0 (4-byte fmov). The test is intensity_vtx_load's:
!        r12 above the bits of minus depth (the transform's fourth
!        output) as unsigned numbers. Called (bsr) only by
!        intensity_tri_near_clip.
	.global	_intensity_tri_classify
	.type	_intensity_tri_classify,@function
_intensity_tri_classify:
.Ltri_classify:
	mov	r4,r1			! r1 = r4, put back at the end
! The first vertex into fr4-fr7, fetched as in intensity_vtx_load but
! for the position only.
	mov.l	@r4,r0			! r0 = the record's first word
	tst	#1,r0
	bf.s	.Lq_v0_inline		! inline
	fmov	@r4+,fr4		! (delay slot) fr4 = x if inline; r4 past the first word
	mov.l	@r4+,r0			! reference: r0 = the offset
	add	r4,r0			! r0 = the record referred to
	fmov	@r0+,fr4		! fr4, fr5, fr6 = x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Lq_v0_loaded		! transform it
	fldi1	fr7			! (delay slot) w = 1
! 0c10b298: inline: y and z follow at r4.
.Lq_v0_inline:
	fmov	@r4+,fr5		! fr5 = y
	fmov	@r4,fr6			! fr6 = z
	fldi1	fr7
	add	#24,r4			! r4 = the second record
! 0c10b2a0: r4 = the second record. Prefetch it and the 32 bytes after.
.Lq_v0_loaded:
	pref	@r4
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv4		! fr7 = minus the first vertex's depth
! The second vertex the same way, into fr0-fr3.
	mov.l	@r4,r0			! r0 = the record's first word
	tst	#1,r0
	bf.s	.Lq_v1_inline		! inline
	fmov	@r4+,fr0		! (delay slot) fr0 = x if inline
	mov.l	@r4+,r0
	add	r4,r0			! reference: r0 = the record referred to
	fmov	@r0+,fr0		! fr0, fr1, fr2 = x, y, z
	fmov	@r0+,fr1
	fmov	@r0+,fr2
	bra	.Lq_v1_loaded		! transform it
	fldi1	fr3			! (delay slot) w = 1
! 0c10b2c0: inline: y and z follow at r4.
.Lq_v1_inline:
	fmov	@r4+,fr1
	fmov	@r4,fr2
	fldi1	fr3
	add	#24,r4			! r4 = the third record
! 0c10b2c8: r4 = the third record.
.Lq_v1_loaded:
	add	#32,r4
	pref	@r4			! prefetch 32 bytes past it
	add	#-32,r4
	ftrv	xmtrx,fv0		! fr3 = minus the second vertex's depth
! The third vertex into fr4-fr7 again; the first one's minus depth is
! moved out to fpul before it is overwritten.
	mov.l	@r4,r0			! r0 = the record's first word
	tst	#1,r0
	flds	fr7,fpul		! fpul = minus the first vertex's depth
	bf.s	.Lq_v2_inline		! inline
	fmov	@r4+,fr4		! (delay slot) fr4 = x if inline
	mov.l	@r4+,r0
	add	r4,r0			! reference: r0 = the record referred to
	fmov	@r0+,fr4		! fr4, fr5, fr6 = x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Lq_v2_loaded
	fldi1	fr7			! (delay slot) w = 1
! 0c10b2e8: inline: y and z follow at r4.
.Lq_v2_inline:
	fmov	@r4+,fr5
	fmov	@r4,fr6
	fldi1	fr7
! 0c10b2ee: the three tests, shifted into r9 one after another.
.Lq_v2_loaded:
	mov	r1,r4			! r4 = the first record again
	sts	fpul,r0			! r0 = the bits of the first vertex's minus depth
	ftrv	xmtrx,fv4		! fr7 = minus the third vertex's depth
	cmp/hi	r0,r12			! T = the first vertex is nearer than the near plane
	flds	fr3,fpul
	rotcl	r9			! into r9
	sts	fpul,r0			! r0 = the bits of the second vertex's minus depth
	cmp/hi	r0,r12			! T = the second vertex is nearer than the near plane
	flds	fr7,fpul
	rotcl	r9			! into r9
	sts	fpul,r0			! r0 = the bits of the third vertex's minus depth
	cmp/hi	r0,r12			! T = the third vertex is nearer than the near plane
	rts
	rotcl	r9			! (delay slot) into r9
	nop				! padding, never run
	nop
	nop

! intensity_tri_send
!
! Sends a run of independent triangles that needs no clipping. It is
! intensity_strip_send with a different count: r9 counts the triangles
! and r3 the three vertices of each, and every third vertex gets the
! end-of-strip control word, so each triangle is a strip of its own
! under the run's polygon header. The vertex layout, the control word
! and the three lighting bodies chosen by r8 are the same:
!   odd (unlit)     0c10b320
!   0 (diffuse)     0c10b426
!   else (specular) 0c10b56a, named intensity_tri_send_plain in src/
! and the unlit and diffuse bodies are unrolled over two vertices in
! the same way (A in fr4-fr7, B in fr8-fr11). The steps are explained
! where they first appear, in intensity_strip_send; the comments here
! give the addresses.
!
! In:    r4 = the run's count word (the number of triangles; three
!        vertex records each follow).
!        r5 = the list write address, r6 = the store-queue pointer.
!        r8 = lighting selector, fr15 = base intensity, fr12-fr14 =
!        light direction (y, z, x), fr8-fr10 = half vector (y, z, x);
!        XMTRX = the matrix.
! Out:   r4 = the word after the last triangle (the next run word).
!        r5 and r6 advanced by 32 for each vertex sent.
! Uses:  r0-r3, r9 and r14 are changed without being saved (compiled
!        code would keep r9 and r14), and fr0-fr11. No stack.
! Notes: FPSCR SZ = 0 on entry and return, SZ = 1 inside. The specular
!        body (0c10b56a to 0c10b639, intensity_tri_send_plain in src/)
!        is part of this routine but lies past the end of this file,
!        which stops at 0c10b56a; the branch to it is written as a raw
!        word because the assembler cannot reach a symbol outside the
!        file with bra. It is the specular body of intensity_strip_send
!        (0c10abb6) with the same triangle counting, and like it uses
!        r7 for the control word. Unlike a strip, the last triangle is
!        not followed by a test for a further run. Called only by
!        intensity_send_alpha (bsr), for a run word with bit 3.
	.global	_intensity_tri_send
	.type	_intensity_tri_send,@function
_intensity_tri_send:
.Ltri_send:
	tst	r8,r8			! T = r8 is 0
	mov	r8,r0
	bf	.Lts_not_diffuse		! not 0: unlit or specular
	bra	.Lts_diffuse		! 0: the diffuse body
! 0c10b318: (also the delay slot of the bra above) odd r8 = unlit.
.Lts_not_diffuse:
	tst	#1,r0			! T = r8 is even
	bf	.Lts_unlit		! odd: the unlit body, two instructions down
	.word	0xa125			! bra intensity_tri_send_plain (0c10b56a): specular
	nop				! (delay slot)
! 0c10b320: the unlit body, as at 0c10a940: words 6-7 (base 1.0, offset 0)
! are written once into both store-queue buffers, then 24 bytes a vertex.
.Lts_unlit:
	mov.l	@r4+,r9			! r9 = the number of triangles
	fldi1	fr2
	fschg				! 8-byte fmov until the return
	fldi0	fr3			! (fr2, fr3) = base 1.0, offset 0.0
	mov	#3,r3			! r3 = 3: the vertices left in this triangle
	fmov	fr2,@-r6		! words 6-7 of the other buffer
	add	#32,r6			! r6 = 24 bytes into the first vertex
	fmov	fr2,@r6			! words 6-7 of this buffer
! Fetch the first record, as at 0c10a94e.
	mov.l	@r4,r0
	mov	r4,r14
	tst	#1,r0
	add	#32,r4
	bf	.Lts_unlit_first		! inline: r14 = the record itself
	mov.l	@(4,r14),r14
	add	#-24,r4
	add	r4,r14			! reference: r14 = the record referred to
! 0c10b340: r14 = the first vertex.
.Lts_unlit_first:
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14,fr6		! fr6 = z
	add	#16,r14
	fldi1	fr7			! w = 1
	fmov	@r14,fr0		! fr0, fr1 = u, v
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = x, y times depth
! 0c10b34c: first half, as at 0c10a96a: start A's divide and fetch B.
.Lts_unlit_a:
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth of A
	dt	r3			! count A; T = A is its triangle's third vertex
	mov.l	@r4+,r0			! r0 = the next record's first word
	bt.s	.Lts_unlit_a_third		! the third: see whether triangles are left
	mov.l	@r4+,r14		! (delay slot) r14 = the next record's second word
	tst	#1,r0
	mov	r6,r2			! r2 = A's control word
	bt.s	.Lts_unlit_a_next		! reference: r14 = the record referred to
	add	r4,r14
! Inline: r14 = the record, r4 = its end.
	mov	r4,r14
	add	#24,r4
	add	#-8,r14
! 0c10b366: r14 = vertex B's record: load and transform B while A is
! written.
.Lts_unlit_a_next:
	fmov	@r14+,fr8		! fr8, fr9 = B's x, y
	add	#32,r4
	pref	@r4			! prefetch 32 bytes past the next record
	fmov	@r14,fr10		! fr10 = B's z
	add	#16,r14
	fldi1	fr11			! B's w = 1
	fmul	fr7,fr6			! A: Y on screen = y / depth
	fmov	fr0,@-r6		! A words 4-5: the texture u, v
	fmul	fr7,fr5			! A: X on screen = x / depth
	fmov	fr6,@-r6		! A words 2-3: Y and 1 / depth
	ftrv	xmtrx,fv8		! put B through the matrix
	fmov	fr4,@-r6		! A words 0-1
	add	#-32,r4
	mov.l	r2,@r6			! A word 0: the control word
	fmov	@r14,fr0		! fr0, fr1 = B's u, v
	dt	r3			! count B; T = B is its triangle's third vertex
	pref	@r6			! send A's 32 bytes
	add	#56,r6			! r6 = 24 bytes into the next vertex
! Second half: the same with the register sets changed over.
	mov	r6,r2			! r2 = B's control word
	fldi1	fr11
	fdiv	fr8,fr11		! fr11 = 1 / depth of B
	mov.l	@r4+,r0
	bt.s	.Lts_unlit_b_third		! the third: see whether triangles are left
	mov.l	@r4+,r14		! (delay slot) r14 = the next record's second word
	tst	#1,r0
	bt.s	.Lts_unlit_b_next		! reference: r14 = the record referred to
