	bf.s	.Lskip_group		! off the top: skip the group
	fsub	fr1,fr0			! (delay slot) fr0 = the right-hand limit
	fcmp/gt	fr0,fr5			! T = beyond the right edge
	fmov	@r3+,fr5		! fr5 = light color red (sp+24)
	fmul	fr4,fr7
	bt.s	.Lskip_group		! off the right: skip the group
	fmov	fr2,@-r9		! (delay slot) header word 1 = the ISP word
	fsub	fr3,fr7			! fr7 = the bottom limit
	mov.l	r8,@-r9			! header word 0 = the control word
	mov	#8,r1			! r1 = 8; no reader of this value was found
	fcmp/gt	fr7,fr6			! T = beyond the bottom edge
	fmov	@r3+,fr6		! fr6 = light color green (sp+28)
	bt	.Lskip_group		! off the bottom: skip the group
! The group is drawn. Read its material byte and group float, and step
! r4 to the run words.
	mov	r8,r0
	tst	#16,r0			! control bit 4: are the face colors needed?
	mov.b	@(4,r2),r0		! r0 = the material byte (+0x24), sign-extended
	add	#8,r2			! r2 = &group.float (+0x28)
	fmov	@r3+,fr7		! fr7 = light color blue (sp+32); r3 = sp+36
	mov	r0,r8			! r8 = the material byte
	fmov	@r2+,fr15		! fr15 = the group float; r2 = &group.base_color
	bf.s	.Lby_material		! bit 4 set: no face colors with this header
	add	#48,r4			! (delay slot) r4 = &group.runs (+0x50)
! Face colors, for the second half of a 64-byte header. The base color
! (alpha, red, green, blue) is multiplied by the object's alpha and the
! light color; the offset color's red, green and blue by
! obj_light_colour2, its alpha left as it is. fr11 is borrowed for the
! colour2 words, which is why the alpha is reloaded at 0c10a604.
! bump_group_send reads the base color from fr0-fr3 as left here.
	fmov	@r2+,fr0		! fr0-fr3 = the face base color
	fmov	@r2+,fr1
	fmov	@r2+,fr2
	fmov	@r2+,fr3
	fmul	fr11,fr0		! base alpha x the object's alpha
	mov.l	.Llight_colour2,r0
	fmov	@r0+,fr11
	fmul	fr5,fr1			! base red x light red
	fmov	@r2+,fr4		! fr4 = offset alpha
	fmov	@r2+,fr5
	fmul	fr11,fr5		! offset red x colour2[0]
	fmov	@r0+,fr11
	fmul	fr6,fr2			! base green x light green
	fmov	@r2+,fr6
	fmul	fr11,fr6		! offset green x colour2[1]
	fmov	@r0+,fr11
	fmul	fr7,fr3			! base blue x light blue
	fmov	@r2+,fr7
	add	#64,r6			! r6 = the end of the 64-byte header
	fmul	fr11,fr7		! offset blue x colour2[2]
	fschg				! 8-byte fmov: two words a store
	fmov	fr6,@-r6		! words 14-15: offset green, blue
	fmov	fr4,@-r6		! words 12-13: offset alpha, red
	fmov	fr2,@-r6		! words 10-11: base green, blue
	fmov	fr0,@-r6		! words 8-9: base alpha, red
	fschg
	add	#-32,r6			! r6 = the start of the header again; nothing sent yet
! 0c10a7a8: choose the lighting by the material byte in r8.
.Lby_material:
	cmp/pz	r8
	bt	.Llit		! 0 or above: diffuse or specular
	mov	r8,r0
	cmp/eq	#-1,r0
	bt.s	.Lunlit		! -1: unlit
	cmp/eq	#-2,r0
	bf	.Lnot_bump		! neither -1 nor -2
! -2: a bump-mapped group. bump_group_send walks all its runs as the
! run loop below does and comes back with T set at the end of the
! object, else with r8 = the next group's control word and r4 at that
! group's word 1.
	mov.l	.Lbump_group_send,r0
	jsr	@r0
	mov.l	@(60,r15),r7		! (delay slot) r7 = 1/w of the near plane
	bt	.Ldone		! T: that was the last group
	fmov	@r4+,fr2
	mov.l	@r4+,r1
	bra	.Lnext_group		! on to the next group
	fmov	@r4+,fr3
	nop				! padding, never run
! 0c10a7c8: -3: colors in the vertices, vertex_colour_group_send, called
! with fr15 = group float x light scalar and returning as bump_group_send
! does. Any other negative byte is treated as unlit.
.Lnot_bump:
	mov.l	@(60,r15),r7
	cmp/eq	#-3,r0
	mov	#36,r0
	mov.l	.Lvertex_colour_group_send,r1
	bf	.Lunlit		! not -3: unlit
	fmov	@(r0,r15),fr1		! fr1 = the light scalar (sp+36)
	jsr	@r1
	fmul	fr1,fr15		! (delay slot) fr15 = group float x light scalar
	bt	.Ldone		! T: that was the last group
	fmov	@r4+,fr2
	mov.l	@r4+,r1
	bra	.Lnext_group		! on to the next group
	fmov	@r4+,fr3
	nop				! padding, never run
! 0c10a7e4: unlit: r8 stays the (odd) material byte, which the senders
! take as "no lighting", and the base intensity is 1.0.
.Lunlit:
	bra	.Lfirst_run
	fldi1	fr15			! (delay slot) fr15 = 1.0
! 0c10a7e8: material 0 or above. For a specular material (above 0) put the
! half vector back in fr8-fr10 (the unlit and diffuse senders use those
! registers for a vertex) and make r8 the row pointer:
! obj_spec_power_table row [material], biased by -309 entries because the
! index the senders use starts at 310.
.Llit:
	cmp/pl	r8
	mov	#56,r0
	bf	.Lbase_intensity		! 0: diffuse only, r8 stays 0
	fmov	@(r0,r15),fr10		! fr10 = half vector x
	mov	#48,r0
	fmov	@(r0,r15),fr8		! fr8 = half vector y
	mov	#52,r0
	fmov	@(r0,r15),fr9		! fr9 = half vector z
	mov	#9,r0
	shld	r0,r8			! r8 = material x 512, the size of a row
	mov.l	.Lspec_row_base,r0
	add	r0,r8			! r8 = the biased row pointer (always even, never 0)
! 0c10a800: diffuse and specular: the base intensity every vertex starts
! from.
.Lbase_intensity:
	mov	#36,r0
	fmov	@(r0,r15),fr1
	fmul	fr1,fr15		! fr15 = group float x light scalar (sp+36)
! 0c10a806: r4 = the group's first run word.
.Lfirst_run:
	mov.l	@r4+,r0			! r0 = the run word
! 0c10a808: the run loop. r0 = the word at the head of the next run.
.Lrun_loop:
	cmp/pl	r0
	mov.l	.Lheader_words,r9		! r9 = elan_group_header_words
	bt.s	.Lsend_header		! positive: a run to send
	cmp/pz	r0			! (delay slot) T = the word is 0, when not positive
! Zero or negative: the group is finished. Store the list's write
! pointer back; r8 = the word, the next group's control word unless 0.
	mov	r0,r8
	mov	r11,r0
	mov.l	r5,@(r0,r10)		! list_write_ptrs record [list] = r5
	bt	.Ldone		! 0: the end of the object
	fmov	@r4+,fr2
	mov.l	@r4+,r1
	bra	.Lnext_group		! negative: it starts the next group
	fmov	@r4+,fr3
! 0c10a820: a run. Build its polygon header from elan_group_header_words:
! control word with bit 1 (Gouraud) from run bit 6, ISP word with
! bits 27-28 (culling) from run bits 0-1. r1 keeps the run word.
.Lsend_header:
	mov	r0,r1
	mov	#-5,r2
	mov.l	@r9+,r3			! r3 = header word 0, the control word
	and	#64,r0
	shld	r2,r0			! r0 = run bit 6 moved down to bit 1
	mov	#-3,r2
	and	r2,r3			! clear the control word's bit 1
	or	r3,r0			! r0 = this run's control word
	tst	#16,r0			! bit 4 clear: the face colors go with this header
	add	#32,r4			! r4 = 32 bytes into the run, for the prefetch below
	bf.s	.Lcull_bits		! bit 4 set: a plain 32-byte header
	lds	r0,fpul			! (delay slot) fpul = this run's control word
! First header of a group with face colors: set bit 4 in the stored
! copy, so that the group's later runs go out with plain 32-byte
! headers (for intensity mode 1 that makes them mode 2).
	or	#16,r0
	mov	r9,r2
	mov.l	r0,@-r2			! elan_group_header_words[0] with bit 4 set
! 0c10a83e: r3 = 1 when this header carries the face colors (64 bytes).
! The two culling bits come from the run word; bit 0 is flipped when
! poly_header_or_words.control_or is negative (bit 31 set).
.Lcull_bits:
	mov.l	@(40,r15),r2
	movt	r3			! r3 = T = the colors go with this header
	mov	r1,r0
	cmp/pz	r2			! T = control_or is not negative
	mov	#27,r2
	bt.s	.Lheader_out
	and	#3,r0			! (delay slot) r0 = run bits 0-1
	xor	#1,r0			! negative: flip the culling direction
! 0c10a84e: write the 32 bytes: control word, ISP word with the culling
! bits, then the TSP and texture words as one 8-byte store.
.Lheader_out:
	shld	r2,r0			! r0 = the culling bits at 27-28
	cmp/pl	r3			! T = a 64-byte header
	mov	#3,r3
	fschg				! 8-byte fmov
	shld	r2,r3
	pref	@r4			! prefetch the run's vertex records
	not	r3,r3			! r3 = all but bits 27-28
	mov.l	@r9+,r2			! r2 = header word 1, the ISP word
	and	r3,r2
	fsts	fpul,fr0		! fr0 = the control word
	or	r0,r2			! r2 = the ISP word with this run's culling
	lds	r2,fpul
	add	#-32,r4			! r4 = &run.count again
	fsts	fpul,fr1		! fr1 = the ISP word
	add	#16,r6
	fmov	@r9+,fr2		! fr2, fr3 = TSP word, texture word
	fmov	fr2,@-r6		! words 2-3 of the header
	add	#32,r5			! the list takes 32 bytes
	fmov	fr0,@-r6		! words 0-1 of the header
	fschg				! back to 4-byte fmov
	pref	@r6			! send the 32 bytes
	bf.s	.Lpick_sender		! no colors: the header is complete
	add	#32,r6			! (delay slot) r6 = the next 32 bytes
! The face colors stored at 0c10a79c make the second 32 bytes.
	pref	@r6			! send the color half
	add	#32,r6
	add	#32,r5			! 64 bytes in all
! 0c10a882: pick the sender. r12 bit 0 (the group crosses the near plane)
! is rotated out into T and the bit left clear; r0 = the run word.
.Lpick_sender:
	rotcr	r12			! T = crosses the near plane
	mov	r1,r0
	bt.s	.Lnear_clip		! crossing: the clipping senders
	shll	r12			! (delay slot) r12 back in place, bit 0 = 0
	tst	#8,r0			! run bit 3: independent triangles
	bf	.Lsend_tris		! set: intensity_tri_send
	bsr	.Lstrip_send		! a strip, wholly in front of the near plane
	nop
	bra	.Lrun_loop		! back for the next run word
	mov.l	@r4+,r0			! (delay slot) r0 = the next run word
! Six halfwords no path reaches: padding, and a second copy of the two
! instructions above.
	nop
	nop
	bra	.Lrun_loop		! never run: as 0c10a892
	mov.l	@r4+,r0			! never run: its delay slot
	nop				! padding, never run
! 0c10a8a0: independent triangles, wholly in front of the near plane.
.Lsend_tris:
	bsr	.Ltri_send		! intensity_tri_send
	nop
	bra	.Lrun_loop		! back for the next run word
	mov.l	@r4+,r0			! (delay slot) r0 = the next run word
! 0c10a8a8: the end of the object: drop the frame and restore.
.Ldone:
	add	#64,r15			! drop the 64-byte frame
	lds.l	@r15+,pr
	mov.l	@r15+,r8
	mov.l	@r15+,r9
	mov.l	@r15+,r10
	mov.l	@r15+,r11
! r12-r14 and the four float registers pushed first come off last.
	mov.l	@r15+,r12
	mov.l	@r15+,r13
	mov.l	@r15+,r14
	fmov	@r15+,fr12
	fmov	@r15+,fr13
	fmov	@r15+,fr14
	fmov	@r15+,fr15
	rts				! back to the caller, nothing in r0
	nop
	nop				! padding, never run
! 0c10a8c8: the group crosses the near plane. r12 bit 0 now becomes
! "flat": set when run bit 6 (Gouraud) is clear, for intensity_flat_copy.
! The clipping senders return with bit 0 set again, which restores the
! crossing flag for the group's next run. r7 = 1/w of the near plane.
.Lnear_clip:
