	tst	#64,r0			! T = run bit 6 clear: flat shading
	addc	r1,r12			! r12 bit 0 = flat
	mov.l	@(60,r15),r7		! r7 = header +0x20 (sp+60)
	tst	#16,r0			! run bit 4: a strip
	bt.s	.Lnear_clip_tris		! clear: independent triangles
	tst	#8,r0			! (delay slot) the T this sets is not used
	bsr	.Lstrip_near_clip		! clip a strip
	tst	#32,r0			! (delay slot) T = run bit 5 clear; not used
	bra	.Lrun_loop		! back for the next run word
	mov.l	@r4+,r0			! (delay slot) r0 = the next run word
	nop				! padding, never run
! 0c10a8e0: independent triangles that cross the near plane.
.Lnear_clip_tris:
	bsr	.Ltri_near_clip		! clip the triangles
	tst	#32,r0			! (delay slot) T = run bit 5 clear; not used
	bra	.Lrun_loop		! back for the next run word
	mov.l	@r4+,r0			! (delay slot) r0 = the next run word
