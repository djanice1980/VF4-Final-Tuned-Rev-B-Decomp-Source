	bf	.Lambient_set		! 0: diffuse only, r8 stays 0
	mov	#9,r0
	shld	r0,r8			! r8 = byte x 512
	mov.l	.Lspec_rows,r0
	add	r0,r8			! r8 = the row, less 309 entries
.Lambient_set:	! 0c108d48
