	bra	.Lrun_body
	add	#32,r6			! (delay slot) r6 = the next 32 bytes
! An unlit group that does not cross the near plane is sent as intensity
! vertices (32 bytes each, by the senders' unlit paths). Its first run
! gets a 64-byte header with color type 2 and the face color in the
! second half; after that r8 = -3 and elan_group_header_words holds color
! type 3, so later runs of the group send the plain header and use the
! face color already sent.
.Lheader_unlit:	! 0c108df0
	cmp/eq	r0,r8			! T = the face color has gone out already (r8 = -3)
	fmov	fr2,@-r6		! header +8, +12 = TSP word, texture word
	bt	.Lheader_out		! yes: the plain 32-byte header, color type 3
	add	#64,r5			! the list takes 64 bytes
	flds	fr0,fpul
	sts	fpul,r0			! r0 = control word
	or	#48,r0
	fschg
	xor	#16,r0			! color type bits 4-5 = 10
	fmov	fr1,@-r6		! header +4 = ISP word
	add	#-16,r9
	mov.l	r0,@-r6			! header +0 = control word
	or	#48,r0			! color type bits 4-5 = 11
	pref	@r6			! the first 32 bytes go to the list
	fschg
	mov.l	r0,@r9			! ... kept as the header control word for later runs
	add	#64,r6			! r6 = header +64
	mov.l	.Lgroup_offset,r0
	fldi0	fr4
	add	#-16,r0			! r0 = float_colour_group_base
	fldi0	fr5
	fmov	@r0+,fr2		! fr2, fr3 = face base green, blue
	fmov	@r0+,fr0		! fr0, fr1 = face base alpha, red
	fmov	fr4,@-r6		! header +56, +60 = 0 (face offset green, blue)
	fmov	fr4,@-r6		! header +48, +52 = 0 (face offset alpha, red)
	mov.l	.Lambient_3,r0
	fmov	@r0+,fr4		! fr5 = ambient red (1.0 here)
	fmul	fr5,fr1
	fmov	@r0+,fr4		! fr4, fr5 = ambient green, blue
	fmul	fr4,fr2
	fmul	fr5,fr3			! face red, green, blue x the ambient
	fmov	fr2,@-r6		! header +40, +44 = green, blue
	fmov	fr0,@-r6		! header +32, +36 = alpha, red
	fschg
	pref	@r6			! the second 32 bytes go to the list
	mov	#-3,r8			! r8 = -3: unlit, face color sent
	add	#32,r6			! r6 = the place after the header
