! float_colour_strip_send
!
! Sends the vertices of one strip, and of any strips that continue it,
! for float_colour_send_alpha, with no clipping. The run's polygon
! header has gone out already.
!
! The run data at r4 is a vertex count and then that many vertex
! records. A record is either
!   the vertex itself, 32 bytes: x, y, z, normal x, y, z, u, v, with
!   bit 0 of the x word set to mark it (the clippers, which walk
!   backwards, find the same mark in bit 0 of the v word), or
!   a reference, 8 bytes: a word with bit 0 clear, then a byte offset
!   from the end of the reference to a vertex kept elsewhere.
! After the last record, a positive word with bit 7 set means another
! strip follows under the same header: that word, a count, its records.
!
! There are three loops, chosen by r8:
!   specular (r8 even and not 0, 0c108ec0) and diffuse only (r8 = 0,
!   0c10905a) write 64-byte vertices:
!     +0 control word, +4 X, +8 Y, +12 1/depth, +16 u, +20 v,
!     +24 and +28 not written, +32 base alpha, red, green, blue,
!     +48 offset alpha, red, green, blue.
!   unlit (r8 odd, 0c109162) writes 32-byte vertices: the same first
!     24 bytes, then base and offset intensity, both 1.0.
! A vertex is written from its end down through r6, a store-queue
! address; a pref after each 32 bytes sends them to the list. The
! control word is r6 itself: only its top bits count, and they are 111
! (a vertex). For the last vertex of a strip it is r6 shifted right one
! place, arithmetically, which sets bit 28 as well: end of strip.
!
! Lighting, for each color channel, with N the vertex normal, L the
! light direction in fv12 and H the half vector in XMTRX's fourth row:
!   base   = (float_colour_ambient + max(0, N.L) x single_light_color)
!            x float_colour_group_base; alpha = the group base alpha.
!   offset = second_light_color x row[ftrc(N.H)]
!            x float_colour_group_offset, with the group offset alpha,
!            where row is the obj_spec_power_table row in r8. It is all
!            0 when N.L is negative or the index is not above 309, and
!            always in the diffuse loop.
!
! In:    r4 = the run's vertex count word.
!        r5 = the list's write pointer; r6 = the same place as a
!        store-queue address.
!        r8 = lighting choice (see above).
!        fr12, fr13, fr14 = light direction y, z, x.
!        XMTRX = the matrix, its fourth row the half vector.
!        float_colour_ambient, float_colour_group_base,
!        float_colour_group_offset as float_colour_send_alpha set them;
!        single_light_color and second_light_color (each: a word not
!        read, then red, green, blue).
!        FPSCR: single moves.
! Out:   r4 = the word after the strip (the next run word, or the word
!        that ends the group's runs). r5 and r6 moved on past the
!        vertices written.
! Uses:  r0-r3, r14, fr0-fr11 and fr15 are changed; r14 is not saved
!        (float_colour_send_alpha has saved it). r7-r13 and fr12-fr14
!        are kept.
! Notes: fschg is switched to 64-bit moves for the loop and back before
!        the return.
	.global	_float_colour_strip_send
	.type	_float_colour_strip_send,@function
_float_colour_strip_send:
.Lstrip_send:	! 0c108eb0
	tst	r8,r8			! r8 = 0: diffuse only
	mov	r8,r0
	bf	.Lstrip_not_diffuse
	bra	.Lsd_start		! ... at 0c10905a (its delay slot is the tst below)
.Lstrip_not_diffuse:	! 0c108eb8
	tst	#1,r0			! T = r8 even
	bt	.Lss_start		! even: specular
	bra	.Lsu_start		! odd: unlit, at 0c109162
	nop
! Specular loop. r3 = vertices left, r14 = the vertex being read, r6 =
! the vertex being written (+48 between vertices).
.Lss_start:	! 0c108ec0
	mov.l	@r4+,r3			! r3 = vertex count
	fldi0	fr0
	add	#48,r6			! r6 = vertex +48, the end of the base color
	fldi0	fr1
	mov.l	@r4,r0			! r0 = first word of the record
	mov	r4,r14			! r14 = the record, if it is the vertex itself
	tst	#1,r0			! bit 0 marks a vertex
	bf.s	.Lss_first		! the vertex itself
