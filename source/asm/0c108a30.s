! floats (512 bytes) a row. The pool address is the table less 1236
! bytes, so that the row for byte b is at r8 = that + b x 512 and the
! senders can index it with ftrc(N.H) as it is: the entry for index 309
! is the row's first (1236 = 309 x 4), and they use the row only for an
! index above 309.
.Llit_group:	! 0c108d3c
