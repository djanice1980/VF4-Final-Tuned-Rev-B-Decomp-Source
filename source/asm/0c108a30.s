! The polygon header for this run: the group's header words with Gouraud
! (control word bit 1) from run bit 6 and the culling bits 27-28 of the
! ISP word from run bits 0-1; bit 0 of the culling pair is flipped when
! header OR word 0 is negative. The words travel through fpul into fr0
! and fr1 so that they can be stored as a pair.
.Lsend_run:	! 0c108d94
