! float_colour_tri_send
!
! float_colour_strip_send for a run of independent triangles (run bit 3
! set). The run data at r4 is a triangle count and then three vertex
! records for each triangle, in the same two forms. Every third vertex
! gets the control word that ends a strip, so each triangle goes out as
! a strip of three. The three loops (specular 0c1092a0, diffuse only
! 0c10941c, unlit 0c10950c), the vertex formats and the lighting are
! those of float_colour_strip_send, instruction for instruction; only
! the counting differs: r9 = triangles left, r3 = vertices left in the
! triangle. There is no continuation word to look for after the last
! triangle.
!
! In:    r4 = the run's triangle count word.
!        r5, r6, r8, fr12-fr14, XMTRX and the float_colour_ globals as
!        float_colour_strip_send.
!        FPSCR: single moves.
! Out:   r4 = the word after the last triangle's records (the next run
!        word, or the word that ends the group's runs). r5 and r6 moved
!        on past the vertices written.
! Uses:  r0-r3, r9, r14, fr0-fr11 and fr15 are changed; r9 and r14 are
!        not saved (float_colour_send_alpha has saved them). r7, r8,
!        r10-r13 and fr12-fr14 are kept.
! Notes: fschg is switched to 64-bit moves inside a triangle and back
!        after its third vertex (specular and diffuse loops), or once
!        for the whole run (unlit loop).
	.global	_float_colour_tri_send
	.type	_float_colour_tri_send,@function
_float_colour_tri_send:
.Ltri_send:	! 0c109290
	tst	r8,r8			! r8 = 0: diffuse only
	mov	r8,r0
	bf	.Ltri_not_diffuse
	bra	.Ltd_start		! ... at 0c10941c (its delay slot is the tst below)
.Ltri_not_diffuse:	! 0c109298
	tst	#1,r0			! T = r8 even
	bt	.Lts_start		! even: specular
	bra	.Ltu_start		! odd: unlit, at 0c10950c
	nop
! Specular loop, as at 0c108ec0. r9 = triangles left, r3 = vertices left
! in this triangle.
.Lts_start:	! 0c1092a0
	mov.l	@r4+,r9			! r9 = triangle count
	mov	#3,r3			! three vertices a triangle
	fldi0	fr0
	add	#48,r6			! r6 = vertex +48, the end of the base color
	fldi0	fr1
.Lts_triangle:	! 0c1092aa
	mov.l	@r4,r0			! r0 = first word of the record
	mov	r4,r14			! r14 = the record, if it is the vertex itself
	tst	#1,r0			! bit 0 marks a vertex
	bf.s	.Lts_first		! the vertex itself
	add	#32,r4			! (delay slot) r4 = past a 32-byte record
	mov.l	@(4,r14),r14		! a reference: r14 = its byte offset,
	add	#-24,r4			! r4 = past the 8-byte record,
	add	r4,r14			! r14 = the vertex it points at
.Lts_first:	! 0c1092ba
	fldi0	fr10
	fschg				! 64-bit moves until the triangle's third vertex
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14+,fr6		! fr6, fr7 = z, normal x
	fadd	fr7,fr10		! fr10 = normal x
	fldi1	fr7			! the position is a point: w = 1
	fmov	@r14+,fr8		! fr8, fr9 = normal y, z
	mov.l	.Llight_5,r2
	fldi0	fr15
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = screen x, y times depth
	mov.l	.Lambient_8,r0		! r0 = float_colour_ambient
	bra	.Lts_light
	fmov	@r2+,fr0		! (delay slot) has no use here: fr0, fr1 are loaded again at 0c1092fa
.Llight_5:
	.long	_single_light_color
.Lambient_8:
	.long	_float_colour_ambient
.Lts_next_vertex:	! 0c1092dc
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	add	#32,r4			! r4 = past the record
	fmov	@r14+,fr6		! fr6, fr7 = z, normal x
	fldi0	fr10
.Lts_next:	! 0c1092e4
	fadd	fr7,fr10		! fr10 = normal x
	fldi1	fr7
	fmov	@r14+,fr8		! fr8, fr9 = normal y, z
	add	#64,r5			! the list takes the vertex before: 64 bytes
	add	#32,r6			! r6 = second half of the vertex before
	fldi0	fr15
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = screen x, y times depth
	mov.l	.Lambient_9,r0
	pref	@r6			! the second half goes to the list
	add	#80,r6			! r6 = this vertex +48
.Lts_light:	! 0c1092f8
	fipr	fv8,fv12		! fr15 = N.L
	fmov	@r0+,fr0		! fr1 = ambient red
	ftrv	xmtrx,fv8		! fr11 = N.H (the other three results are not used)
	fmov	@r0,fr2			! fr2, fr3 = ambient green, blue
	fldi0	fr0
	add	#32,r4
	mov.l	.Lgroup_base_3,r2	! r2 = float_colour_group_base
	fcmp/gt	fr15,fr0		! T = N.L is negative
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth
	bt.s	.Lts_facing_away	! facing away from the light: ambient only
	pref	@r4			! (delay slot) prefetch the source 32 bytes on
	fadd	fr15,fr0		! fr0 = N.L
	mov.l	.Llight_6,r0
	add	#-32,r4
	fmov	@r0+,fr8		! fr9 = light red
	ftrc	fr11,fpul		! fpul = N.H as an integer, the row index
	fmov	@r0,fr10		! fr10, fr11 = light green, blue
	fmac	fr0,fr10,fr2		! green = ambient + N.L x light
	sts	fpul,r0			! r0 = the row index
	fmac	fr0,fr11,fr3		! blue likewise
	fmov	@r2+,fr10		! fr10, fr11 = group base green, blue
	fmac	fr0,fr9,fr1		! red likewise
	fmov	@r2+,fr8		! fr8, fr9 = group base alpha, red
	fmul	fr2,fr10		! base green
	mov.w	.Lindex_309_2,r1	! r1 = 309
	fmul	fr3,fr11		! base blue
	cmp/gt	r1,r0			! T = the index is above 309: a highlight
	fmul	fr1,fr9			! base red
	fmov	fr10,@-r6		! vertex +40, +44 = base green, blue
	fmul	fr7,fr6			! fr6 = Y = y / depth
	fmov	fr8,@-r6		! vertex +32, +36 = base alpha, red
	bf.s	.Lts_no_highlight	! no highlight: offset 0
	fmul	fr7,fr5			! (delay slot) fr5 = X = x / depth
	mov.l	.Lsecond_light_2,r2	! r2 = second_light_color, the color of the highlight
	shll2	r0
	fmov	@r2+,fr0		! fr1 = its red
	fmov	@r2+,fr2		! fr2, fr3 = its green, blue
	fschg				! one single move:
	fmov	@(r0,r8),fr0		! fr0 = row[index], the specular power
	fschg
	mov.l	.Lgroup_offset_3,r2	! r2 = float_colour_group_offset
	fmul	fr0,fr1
	fmov	@r2+,fr10		! fr10, fr11 = group offset green, blue
	fmul	fr0,fr2
	fmov	@r2+,fr8		! fr8, fr9 = group offset alpha, red
	fmul	fr0,fr3
	mov.l	@r4,r0			! r0 = first word of the next record
	fmul	fr1,fr9			! offset red
	add	#32,r6			! r6 = vertex +64
	fmul	fr2,fr10		! offset green
	fmov	@r14+,fr0		! fr0, fr1 = u, v
	fmul	fr3,fr11		! offset blue
	dt	r3			! T = this is the triangle's third vertex
	fmov	fr10,@-r6		! vertex +56, +60 = offset green, blue
	fmov	fr8,@-r6		! vertex +48, +52 = offset alpha, red
.Lts_write_front:	! 0c109368
	add	#-24,r6			! r6 = vertex +24
	fmov	fr0,@-r6		! vertex +16, +20 = u, v
	mov	r4,r14			! r14 = the next record
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	bt.s	.Lts_third		! the third vertex: end the triangle
	fmov	fr4,@-r6		! (delay slot) vertex +4 = X (and +0, written over next)
	tst	#1,r0			! T = the next record is a reference
	mov.l	r6,@r6			! vertex +0 = control word: r6 itself
	bf.s	.Lts_next_vertex	! the vertex itself is next
	pref	@r6			! (delay slot) the first half goes to the list
	mov.l	@(4,r14),r14		! a reference: r14 = its byte offset,
	add	#8,r4			! r4 = past the 8-byte record,
	fldi0	fr10
	add	r4,r14			! r14 = the vertex it points at
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	bra	.Lts_next
	fmov	@r14+,fr6		! (delay slot) fr6, fr7 = z, normal x
.Lindex_309_2:
	.word	0x0135			! the value 309: N.H indexes at or below it have no highlight
.Lambient_9:
	.long	_float_colour_ambient
.Lgroup_base_3:
	.long	_float_colour_group_base
.Llight_6:
	.long	_single_light_color
.Lsecond_light_2:
	.long	_second_light_color
.Lgroup_offset_3:
	.long	_float_colour_group_offset
.Lts_no_highlight:	! 0c1093a0
	fldi0	fr3
	fsub	fr2,fr2			! fr2, fr3 = 0, 0
	fmov	@r14+,fr0		! fr0, fr1 = u, v
	add	#32,r6			! r6 = vertex +64
	mov.l	@r4,r0			! r0 = first word of the next record
	dt	r3			! T = this is the triangle's third vertex
	fmov	fr2,@-r6		! vertex +56, +60 = 0
	bra	.Lts_write_front
	fmov	fr2,@-r6		! (delay slot) vertex +48, +52 = 0
	nop				! padding
.Lts_facing_away:	! 0c1093b4
	fldi0	fr8
	add	#16,r6			! r6 = vertex +64
	fldi0	fr9
	fmov	fr8,@-r6		! vertex +56, +60 = 0
	add	#-32,r4
	fmov	@r2+,fr10		! fr10, fr11 = group base green, blue
	dt	r3			! T = this is the triangle's third vertex
	fmov	fr8,@-r6		! vertex +48, +52 = 0
	fmul	fr2,fr10		! base green
	fmov	@r2+,fr8		! fr8, fr9 = group base alpha, red
	fmul	fr3,fr11		! base blue
	mov.l	@r4,r0			! r0 = first word of the next record
	fmul	fr1,fr9			! base red
	fmov	@r14+,fr2		! fr2, fr3 = u, v
	fmul	fr7,fr6			! fr6 = Y = y / depth
	fmov	fr10,@-r6		! vertex +40, +44 = base green, blue
	fmul	fr7,fr5			! fr5 = X = x / depth
	fmov	fr8,@-r6		! vertex +32, +36 = base alpha, red
	add	#-8,r6
	fmov	fr2,@-r6		! vertex +16, +20 = u, v
	mov	r4,r14			! r14 = the next record
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	bt.s	.Lts_third		! the third vertex: end the triangle
	fmov	fr4,@-r6		! (delay slot) vertex +4 = X
	tst	#1,r0			! T = the next record is a reference
	mov.l	r6,@r6			! vertex +0 = control word: r6 itself
	bt	.Lts_away_reference	! a reference
	bra	.Lts_next_vertex	! the vertex itself (delay slot: the pref below)
.Lts_away_reference:	! 0c1093ec
	pref	@r6			! the first half goes to the list
	mov.l	@(4,r14),r14		! r14 = the reference's byte offset,
	add	#8,r4			! r4 = past the 8-byte record,
	fldi0	fr10
	add	r4,r14			! r14 = the vertex it points at
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	bra	.Lts_next
	fmov	@r14+,fr6		! (delay slot) fr6, fr7 = z, normal x
! The triangle's third vertex is written but for its control word.
.Lts_third:	! 0c1093fc
	mov	r6,r1
	shar	r1			! r1 = r6 >> 1: the control word that ends a strip
	mov.l	r1,@r6			! vertex +0 = control word: the triangle ends here
	dt	r9			! T = that was the last triangle
	pref	@r6			! the first half goes to the list
	add	#32,r6			! r6 = the vertex's second half
	fschg				! single moves again
	add	#64,r5			! the list takes the vertex: 64 bytes
	bt	.Lts_done		! no triangles left
	mov	#3,r3			! three vertices for the next triangle
	pref	@r6			! the second half goes to the list
	bra	.Lts_triangle
	add	#80,r6			! (delay slot) r6 = the next vertex +48
.Lts_done:	! 0c109416
	pref	@r6			! the last vertex's second half goes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the place after the vertex
! Diffuse-only loop, as at 0c10905a: the offset color is written as 0
! once and stays in the store queue.
.Ltd_start:	! 0c10941c
	mov.l	@r4+,r9			! r9 = triangle count
	mov	#3,r3			! three vertices a triangle
	fldi0	fr0
	add	#64,r6			! r6 = vertex +64
	fldi0	fr1
	fschg				! 64-bit moves
	fmov	fr0,@-r6		! vertex +56, +60 = 0
	fmov	fr0,@-r6		! vertex +48, +52 = 0; r6 = vertex +48
	fschg				! single moves
.Ltd_triangle:	! 0c10942e
	mov.l	@r4,r0			! r0 = first word of the record
	mov	r4,r14
	tst	#1,r0			! bit 0 marks a vertex
	bf.s	.Ltd_first		! the vertex itself
	add	#32,r4			! (delay slot) r4 = past a 32-byte record
	mov.l	@(4,r14),r14		! a reference: r14 = its byte offset,
	add	#-24,r4
	add	r4,r14			! r14 = the vertex it points at
.Ltd_first:	! 0c10943e
	fldi0	fr10
	fschg				! 64-bit moves until the triangle's third vertex
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14+,fr6		! fr6, fr7 = z, normal x
	fadd	fr7,fr10		! fr10 = normal x
	fldi1	fr7
	fmov	@r14+,fr8		! fr8, fr9 = normal y, z
	mov.l	.Llight_7,r2		! r2 = single_light_color
	fldi0	fr15
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = screen x, y times depth
	mov.l	.Lambient_10,r0		! r0 = float_colour_ambient
	bra	.Ltd_light
	fmov	@r2+,fr0		! (delay slot) fr1 = light red
.Llight_7:
	.long	_single_light_color
.Lambient_10:
	.long	_float_colour_ambient
.Ltd_next_vertex:	! 0c109460
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	add	#32,r4			! r4 = past the record
	fmov	@r14+,fr6		! fr6, fr7 = z, normal x
	fldi0	fr10
.Ltd_next:	! 0c109468
	fadd	fr7,fr10		! fr10 = normal x
	fldi1	fr7
	fmov	@r14+,fr8		! fr8, fr9 = normal y, z
	add	#64,r5			! the list takes the vertex before: 64 bytes
	mov.l	.Llight_8,r2
	add	#32,r6			! r6 = second half of the vertex before
	fldi0	fr15
	ftrv	xmtrx,fv4		! fr4 = depth, fr5, fr6 = screen x, y times depth
	mov.l	.Lambient_11,r0
	fmov	@r2+,fr0		! fr1 = light red
	pref	@r6			! the second half goes to the list (offset still 0)
