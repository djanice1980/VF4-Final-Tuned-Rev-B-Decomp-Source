	add	#16,r14
	fldi1	fr11			! w = 1
	fmul	fr7,fr6			! fr6 = Y of A: y / depth
	fmov	fr0,@-r6		! A +16, +20 = u, v
	fmul	fr7,fr5			! fr5 = X of A: x / depth
	fmov	fr6,@-r6		! A +8, +12 = Y, 1 / depth
	ftrv	xmtrx,fv8		! B: fr8 = depth, fr9, fr10 = screen x, y times depth
	fmov	fr4,@-r6		! A +4 = X
	add	#-32,r4
	mov.l	r2,@r6			! A +0 = control word
	fmov	@r14,fr0		! fr0, fr1 = u, v of B
	dt	r3			! T = B is the strip's last vertex
	pref	@r6			! A goes to the list
	add	#56,r6			! r6 = B +24
	mov	r6,r2			! r2 = control word for B
	fldi1	fr11
	fdiv	fr8,fr11		! fr11 = 1 / depth of B
	mov.l	@r4+,r0			! r0 = first word of the next record
	bt.s	.Lsu_b_last		! B is the last
	mov.l	@r4+,r14		! (delay slot) r14 = its second word; r4 = record +8
	tst	#1,r0
	bt.s	.Lsu_load_a		! a reference:
	add	r4,r14			! (delay slot) r14 = the vertex it points at
	mov	r4,r14			! the vertex itself: r14 = record +8,
	add	#24,r4			! r4 = past the 32-byte record,
	add	#-8,r14			! r14 = the record
! Read the next A into fv4 and transform it while B is written.
.Lsu_load_a:	! 0c1091e2
	add	#32,r4
	fmov	@r14+,fr4		! fr4, fr5 = x, y of the next A
	pref	@r4			! prefetch the source 32 bytes on
	fmov	@r14,fr6		! fr6 = z
	add	#16,r14
	fldi1	fr7			! w = 1
	fmul	fr11,fr10		! fr10 = Y of B: y / depth
	add	#-32,r4
	fmul	fr11,fr9		! fr9 = X of B: x / depth
	fmov	fr0,@-r6		! B +16, +20 = u, v
	fmov	fr10,@-r6		! B +8, +12 = Y, 1 / depth
	ftrv	xmtrx,fv4		! A: fr4 = depth, fr5, fr6 = screen x, y times depth
	fmov	fr8,@-r6		! B +4 = X
	add	#64,r5			! the list takes A and B: 64 bytes
	mov.l	r2,@r6			! B +0 = control word
	fmov	@r14,fr0		! fr0, fr1 = u, v of A
	pref	@r6			! B goes to the list
	bra	.Lsu_a_ready
	add	#56,r6			! (delay slot) r6 = A +24
! B is the strip's last vertex and is not written yet. r0 = the word
! after the records, r14 = the word after that; r4 is past both.
.Lsu_b_last:	! 0c109208
	cmp/pl	r0			! T = the word after is positive
	mov.l	@r4+,r2			! r2 = the third word; r4 = past it
	bf	.Lsu_b_end		! not positive: the runs are over
	tst	#128,r0
	mov	r14,r3			! r3 = vertex count, if another strip follows
	bt	.Lsu_b_end		! bit 7 clear: a new run; leave it to the caller
	mov	r2,r0			! another strip: r0 = first word of its first record
	mov	r6,r2
	shar	r2			! r2 = r6 >> 1: B's control word ends the strip
	mov.l	@r4+,r14		! r14 = the record's second word; r4 = record +8
	tst	#1,r0
	bt.s	.Lsu_load_a		! a reference:
	add	r4,r14			! (delay slot) r14 = the vertex it points at
	mov	r4,r14			! the vertex itself: r14 = record +8,
	add	#24,r4			! r4 = past the 32-byte record
	bra	.Lsu_load_a		! the new strip's first vertex is the next A
	add	#-8,r14			! (delay slot) r14 = the record
	nop				! padding
.Lsu_b_end:	! 0c10922c
	add	#44,r4			! prefetch further on in the source
	pref	@r4
	add	#-48,r4			! r4 = the word after, +8
	fmov	fr8,fr4			! B moves into A's registers: fr4, fr5 = depth, x
	add	#32,r5			! the list takes A's 32 bytes
	bra	.Lsu_write_last
	fmov	fr10,fr6		! (delay slot) fr6, fr7 = y, 1 / depth
	nop				! padding
! A is the strip's last vertex and is not written yet. The same test of
! the words after the records as at 0c109208.
.Lsu_a_last:	! 0c10923c
	cmp/pl	r0			! T = the word after is positive
	mov.l	@r4+,r2			! r2 = the third word; r4 = past it
	bf	.Lsu_a_end		! not positive: the runs are over
	tst	#128,r0
	mov	r14,r3			! r3 = vertex count, if another strip follows
	bt	.Lsu_a_end		! bit 7 clear: a new run; leave it to the caller
	mov	r2,r0			! another strip: r0 = first word of its first record
	mov	r6,r2
	shar	r2			! r2 = r6 >> 1: A's control word ends the strip
	mov.l	@r4+,r14		! r14 = the record's second word; r4 = record +8
	tst	#1,r0
	bt.s	.Lsu_load_b		! a reference:
	add	r4,r14			! (delay slot) r14 = the vertex it points at
	mov	r4,r14			! the vertex itself: r14 = record +8,
	add	#24,r4			! r4 = past the 32-byte record
	bra	.Lsu_load_b		! the new strip's first vertex is the next B
	add	#-8,r14			! (delay slot) r14 = the record
	nop				! padding
.Lsu_a_end:	! 0c109260
	add	#44,r4			! prefetch further on in the source
	pref	@r4
	add	#-48,r4			! r4 = the word after, +8
! Write the strip's last vertex from fv4, fr7 and fr0, fr1, and return.
.Lsu_write_last:	! 0c109266
	fmul	fr7,fr6			! Y = y / depth
	mov	r6,r2
	shar	r2			! r2 = r6 >> 1: the control word that ends a strip
	fmul	fr7,fr5			! X = x / depth
	fmov	fr0,@-r6		! vertex +16, +20 = u, v
	add	#-8,r4			! r4 = back on the word after the strip
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	add	#32,r5			! the list takes its 32 bytes
	fmov	fr4,@-r6		! vertex +4 = X
	mov.l	r2,@r6			! vertex +0 = control word
	fschg				! single moves again
	pref	@r6			! the vertex goes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the place after the vertex
	nop				! padding to the next routine
