	fschg				! 64-bit moves
	lds	r0,fpul
	mov.l	@(40,r15),r2		! r2 = header OR word 0 (frame +40)
	mov	r1,r0
	cmp/pz	r2
	mov	#27,r2
	bt.s	.Lcull_set		! OR word 0 is not negative
	and	#3,r0			! (delay slot) r0 = run bits 0-1
	xor	#1,r0			! negative: the other facing
.Lcull_set:	! 0c108dba
