! modvol_clip_vertex_load
!
! Helper of modvol_strips_send's clipping paths (its registers and
! terms: P, Q, N, kept, cut off, slots A, B, C, the anchor). Loads the
! next vertex into N = fr12-fr15 as (minus w, x, y, 1/w), counts it in
! r3, moves the read position on to the record after it (unless it was
! the last), and tests it against the near plane.
!
! In:    r14 = the vertex's data (x, y, z). r4 = the record after it.
!        r3 = the count left. fr1 = near_limit. fpul = the integer 1.
!        XMTRX = the w-first transform.
! Out:   N loaded. T = the vertex is kept (near_limit above its minus
!        w). r3 one less. r14 = the next vertex's data and r4 past its
!        record, when r3 has not reached 0. fpul = 1.
! Uses:  r0 is changed. No stack use.
! Notes: 64-bit fmov (FPSCR SZ = 1) on entry and exit. Called 12 times
!        by modvol_strips_send (bsr).
	.global	_modvol_clip_vertex_load
	.type	_modvol_clip_vertex_load,@function
_modvol_clip_vertex_load:
.Lload_n:
	fmov	@r14+,fr12	! fr12, fr13 = x, y
	dt	r3		! count the vertex; T = it is the last
	fmov	@r14+,fr14	! fr14, fr15 = z and the word after it
	float	fpul,fr15	! fr15 = 1.0
	mov	r4,r14		! r14 = the record after
	bt.s	.L0c10885c	! the last one: no record to look at
	ftrv	xmtrx,fv12	! (delay slot) fv12 = (w, x, y, minus w)
	mov.l	@r4,r0		! first word of the record after
	add	#32,r4		! r4 = past an inline record
	tst	#1,r0		! T = it is a reference
	bf	.L0c10885c	! inline: r14 is its vertex
	mov.l	@(4,r14),r14	! a reference: its offset word
	add	#-24,r4		! r4 = past the 8-byte reference
	add	r4,r14		! r14 = the vertex it refers to
.L0c10885c:
	pref	@r14		! fetch the next vertex
	fcmp/gt	fr15,fr1	! T = near_limit above minus w: the vertex is kept
	flds	fr15,fpul	! fpul = the bits of minus w
	mov	#1,r0
	fldi1	fr15		! fr15 = 1.0, then
	fdiv	fr12,fr15	! fr15 = 1 / w
	fsts	fpul,fr12	! fr12 = minus w: N = (minus w, x, y, 1/w)
	rts
