! modvol_cut_pq_to_side
!
! Helper of modvol_strips_send's clipping paths. Works out cut(P,Q),
! the point where the edge from Q to P meets the near plane, and writes
! it as (X, Y, 1/w) into a side slot of the triangle being built: slot A
! when r9 is even, slot C when it is odd. With p and q the minus-w words
! of P and Q, t = (near_limit - q) / (p - q); x and y are Q's plus t
! times (P's - Q's); 1/w is near_inv and X, Y are x, y times it.
!
! In:    P = fr4-fr7, Q = fr8-fr11 (one kept, one cut off). fr1 =
!        near_limit. r7 = the near_inv bits. r9 bit 0 = the slot.
!        r6 = the triangle (store-queue address).
! Out:   the slot written. fr13, fr14, fr15 = X, Y, 1/w of the point.
!        fpul = the integer 1.
! Uses:  r0, fr0, fr2, fr3 and fr12 are changed. No stack use.
! Notes: 32-bit fmov (SZ = 0). Called 8 times by modvol_strips_send;
!        each caller has "fmov fr5,fr13" in the delay slot, which this
!        routine overwrites.
	.global	_modvol_cut_pq_to_side
	.type	_modvol_cut_pq_to_side,@function
_modvol_cut_pq_to_side:
.Lcut_pq_to_side:
	fmov	fr4,fr12
	fsub	fr8,fr12	! fr12 = p - q, the difference of the minus-w words
	fmov	fr1,fr0
	fsub	fr8,fr0		! fr0 = near_limit minus q
	fmov	fr6,fr3
	fsub	fr10,fr3	! fr3 = the y of P minus the y of Q
	fmov	fr5,fr2
	fsub	fr9,fr2		! fr2 = the x of P minus the x of Q
	fmov	fr10,fr14	! fr14 = the y of Q
	fdiv	fr12,fr0	! fr0 = t, how far along the edge
	fmov	fr9,fr13	! fr13 = the x of Q
	lds	r7,fpul		! fpul = the near_inv bits
	fsts	fpul,fr15	! fr15 = near_inv, the 1/w of a point on the plane
	mov	#1,r0
	lds	r0,fpul		! fpul = 1 again
	mov	r9,r0
	tst	#1,r0		! T = r9 is even
	mov	#12,r0		! even: slot A (its 1/w is at +12)
	bt	.L0c108898
	mov	#36,r0		! odd: slot C (its 1/w is at +36)
.L0c108898:
	fmac	fr0,fr3,fr14	! fr14 = y at the crossing
	fmac	fr0,fr2,fr13	! fr13 = x at the crossing
	fmul	fr15,fr14	! fr14 = Y
	fmul	fr15,fr13	! fr13 = X
	fmov	fr15,@(r0,r6)	! the slot's 1/w
	add	#-4,r0
	fmov	fr14,@(r0,r6)	! the slot's Y
	add	#-4,r0
	rts
	fmov	fr13,@(r0,r6)	! (delay slot) the slot's X

! modvol_n_to_newest
!
! Helper of modvol_strips_send's clipping paths. Writes N, the vertex
! just loaded, into slot B as (X, Y, 1/w), sends the triangle (both
! halves) and copies N into P.
!
! In:    N = fr12-fr15. r6 = the triangle + 32 (the caller adds 32 in
!        the delay slot). r5 = the list's write pointer.
