! mtx_premul_two
!
! Multiplies the current matrix by two 4x4 matrices in one go:
! current = b x a x current. A vector later put through the current
! matrix with ftrv therefore goes through the old current matrix first,
! then a, then b.
!
! The current matrix lives in the back bank of FPU registers (XMTRX),
! which is the left-hand side of every ftrv; ftrv multiplies XMTRX by
! one group of four front registers (fv0, fv4, fv8, fv12). The routine
! gets its products by swapping the banks (frchg) so that each matrix in
! turn sits in the back bank while the running product sits in the
! front one:
!   1. a is loaded into the front bank and the banks are swapped: the
!      old current matrix is now in front, a behind. Four ftrv make the
!      front bank a x current.
!   2. the banks are swapped back (the product goes behind), b is loaded
!      into the front bank, and they are swapped again: the product is
!      in front, b behind. Four ftrv make the front bank b x a x current.
!   3. a last swap puts that product in the back bank as the new
!      current matrix.
!
! In:    r4 = a, 16 floats: the matrix applied right after the old
!        current one. Read with 64-bit moves, two floats at a time.
!        r5 = b, 16 floats: the matrix applied last. Read one float at
!        a time; its two 32-byte halves are prefetched while the first
!        products are worked out.
!        XMTRX = the current matrix.
! Out:   nothing in the integer registers. XMTRX = b x a x current.
! Uses:  r4 (left at b + 32) and r5 (left at b + 64) are changed.
!        fr0-fr11 are changed: they are left holding the first twelve
!        floats of b. fr12-fr15, which compiled code expects to be
!        kept, are saved on the stack and restored (16 bytes of stack).
! Notes: expects single precision and 32-bit fmov on entry (FPSCR
!        PR = 0, SZ = 0). SZ is switched to 1 (fschg) only around the
!        eight paired loads of a; the register bank bit FR is flipped
!        four times and so ends as it began. Only mtx_premul_rect_proj
!        calls this, with a = the projection stack's top and b =
!        rect_from_clip_matrix.
