!        fr4 = minus the depth, fr5 = x, fr6 = y (neither divided yet),
!        fr7 = 1 / depth; fr8-fr11 = base alpha, red, green, blue;
!        r1, r2 = the bits of u, v. r4 = past the record.
! Uses:  r0, r14, fr0-fr3 and fr15 are changed (a compiled routine
!        would keep r14). No stack use.
! Notes: called with 32-bit fmov (SZ = 0); fschg makes the moves 64-bit
!        (register pairs) for the body and the delay slot of rts puts
!        SZ back. Callers: float_colour_strip_near_clip_plain and
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_vtx_load_plain
	.type	_float_colour_vtx_load_plain,@function
_float_colour_vtx_load_plain:
.Lvtx_load:
	mov.l	@r4,r0		! first word of the record
	fschg			! 64-bit fmov from here: each move is a register pair
	tst	#1,r0		! T = the record is a reference
	mov	r4,r14
	bf.s	.Lvl_vertex	! inline: the vertex is the record itself
	add	#32,r4		! (delay slot) r4 = past an inline record
	mov.l	@(4,r14),r14	! the reference's offset word
	add	#-24,r4		! r4 = past the 8-byte reference
	add	r4,r14		! r14 = the vertex it refers to
! 0c109daa: r14 = the 32-byte vertex.
.Lvl_vertex:
	mov	r8,r0
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	tst	#1,r0		! T = r8 is even (lit)
	fmov	@r14+,fr6	! fr6, fr7 = z, normal x
	bf	.Lvl_unlit	! r8 odd: unlit
! Lit: fv8 = (normal y, normal z, normal x, .) against fv12 = the light
! direction in the same order; fr15 = 0 keeps the fourth term out.
	fldi0	fr10
	fadd	fr7,fr10	! fr10 = normal x (0 + fr7)
	fldi1	fr7		! w = 1 for the transform
	fmov	@r14+,fr8	! fr8, fr9 = normal y, z
	fldi0	fr15
	ftrv	xmtrx,fv4	! fv4 = (depth, x, y, .)
	mov.l	.Lambient,r0
	mov.l	.Llight_color,r2
	fipr	fv8,fv12	! fr15 = N.L
	fmov	@r0+,fr0	! fr0, fr1 = ambient (unused word, red)
	fmov	@r0+,fr2	! fr2, fr3 = ambient green, blue
	fldi0	fr0
	fcmp/gt	fr15,fr0	! T = N.L is below 0
	fmov	@r2+,fr8	! fr8, fr9 = single_light_color +0, +4 (red in fr9)
	fmov	@r2+,fr10	! fr10, fr11 = its green, blue
	flds	fr15,fpul
	bt	.Lvl_project	! facing away: ambient only
	fsts	fpul,fr0	! fr0 = N.L (through fpul)
	fmac	fr0,fr9,fr1	! red = ambient + N.L x light red
	fmac	fr0,fr10,fr2	! green likewise
	fmac	fr0,fr11,fr3	! blue likewise
! 0c109dde: fr1-fr3 = the light on the vertex (1, 1, 1 when unlit).
! Divide for the projection, make the near test and apply the group's
! color.
.Lvl_project:
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1 / depth
	fneg	fr4		! fr4 = minus the depth
	add	#32,r4
	flds	fr4,fpul
	pref	@r4		! fetch the cache line after the next record
	mov.l	.Lgroup_base,r2
	add	#-32,r4
	sts	fpul,r0		! r0 = the bits of minus the depth
	fmov	@r2+,fr10	! fr10, fr11 = group base green, blue
	fmov	@r2+,fr8	! fr8, fr9 = group base alpha, red
	cmp/hi	r0,r12		! T = r12 above r0 unsigned: the vertex is cut off
	fmul	fr1,fr9		! red = group red x light
	mov.l	@r14+,r1	! r1 = the bits of u
	fmul	fr2,fr10	! green = group green x light
	mov.l	@r14+,r2	! r2 = the bits of v
	fmul	fr3,fr11	! blue = group blue x light
	rts
	fschg			! (delay slot) back to 32-bit fmov
.Lambient:
	.long	_float_colour_ambient
.Llight_color:
	.long	_single_light_color
.Lgroup_base:
	.long	_float_colour_group_base
! 0c109e10: unlit (r8 odd). Skip the rest of the normal; light = 1.
.Lvl_unlit:
	fldi1	fr7		! w = 1 (fr7 held normal x)
	add	#8,r14		! r14 = the vertex's u, v
	ftrv	xmtrx,fv4	! fv4 = (depth, x, y, .)
	fldi1	fr1
	fldi1	fr2
	bra	.Lvl_project
	fldi1	fr3		! (delay slot) fr1-fr3 = 1.0

! float_colour_vtx_emit_plain
!
! Writes the vertex .Lvtx_load left in the registers to the list as a
! 64-byte textured vertex with floating colors, and counts it against
! the strip. The words: control, X, Y, 1/w, u, v, two words not
! written, base alpha, red, green, blue, offset alpha, red, green, blue
! (the offset color is zero here). The control word is r6 itself, a
! store-queue address whose top three bits make it a vertex word; for
! the strip's last vertex it is r6 shifted right one (arithmetic), which
! adds the end-of-strip bit.
!
! In:    r3 = vertices left in the strip, this one included.
!        r6 = where to write (store-queue address); r5 = the list's
!        write pointer. fr5, fr6 = x, y; fr7 = 1 / depth; r1, r2 = u, v;
!        fr8-fr11 = the base color (as .Lvtx_load leaves them).
! Out:   r3 one less; T = this was the strip's last vertex.
!        r5 and r6 advanced by 64.
! Uses:  r0 and fr0, fr1, fr4-fr6 are changed. No stack use.
! Notes: called with SZ = 0; 64-bit fmov inside. Each half of the
!        vertex goes out with a pref on its store-queue line. Callers:
!        float_colour_strip_near_clip_plain and
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_vtx_emit_plain
	.type	_float_colour_vtx_emit_plain,@function
_float_colour_vtx_emit_plain:
.Lvtx_emit:
	dt	r3		! count the vertex; T = it is the strip's last
	lds	r6,fpul		! fpul = r6, the control word of a vertex in mid-strip
	bf	.Lve_write	! not the last
	mov	r6,r0
	shar	r0		! r0 = r6 >> 1: the end-of-strip control word
	lds	r0,fpul
	sett			! T = 1 again (shar changed it): the answer for the caller
! 0c109e2c: the first 32 bytes, written downward from +24.
.Lve_write:
	fschg			! 64-bit fmov
	add	#24,r6
	fsts	fpul,fr4	! fr4 = the control word (fr4, fr5 = control, x)
	fmul	fr7,fr6		! fr6 = Y = y / depth
	mov.l	r2,@-r6		! +20: v
	fmul	fr7,fr5		! fr5 = X = x / depth
	mov.l	r1,@-r6		! +16: u
	fmov	fr6,@-r6	! +8, +12: Y and 1 / depth
	fmov	fr4,@-r6	! +0, +4: the control word and X
	pref	@r6		! send the first half
	add	#64,r6		! r6 = the end of the vertex
	fldi0	fr0
	fldi0	fr1
	fmov	fr0,@-r6	! +56, +60: offset green, blue = 0
	fmov	fr0,@-r6	! +48, +52: offset alpha, red = 0
	fmov	fr10,@-r6	! +40, +44: base green, blue
	add	#64,r5		! the list pointer moves with it
	fmov	fr8,@-r6	! +32, +36: base alpha, red
	fschg
	pref	@r6		! send the second half
	rts
	add	#32,r6		! (delay slot) r6 = the next vertex

! float_colour_vtx_keep_plain
!
! Stores the vertex .Lvtx_load left in the registers in one slot of
! float_colour_clip_ring. A slot is 64 bytes: +0 minus depth, +4 x,
! +8 y, +12 1 / depth, +16 u, +20 v, +24 and +28 not written, +32 base
! alpha, red, green, blue, +48 offset color (stored as zero here).
!
! In:    r11 = the vertex's index (slot = r11 & 3); fr4-fr7, r1, r2,
!        fr8-fr11 as .Lvtx_load leaves them.
! Out:   the slot filled. T is not changed.
! Uses:  r0, r10, fr0 and fr1 are changed (the callers save r10).
! Notes: called with SZ = 0; 64-bit fmov inside. Callers:
!        float_colour_strip_near_clip_plain and
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_vtx_keep_plain
	.type	_float_colour_vtx_keep_plain,@function
_float_colour_vtx_keep_plain:
.Lvtx_keep:
	mov	#6,r10		! r10 = 6, the shift for a slot's 64 bytes
	mov	r11,r0
	and	#3,r0		! r0 = the slot number
	fldi0	fr0
	shld	r10,r0		! r0 = the slot's offset in the ring
	fldi0	fr1
	fschg			! 64-bit fmov
	mov.l	.Lring_slot0_end,r10	! r10 = the end of slot 0
	add	r0,r10		! r10 = the end of this slot
	fmov	fr0,@-r10	! +56: offset green, blue = 0
	fmov	fr0,@-r10	! +48: offset alpha, red = 0
	fmov	fr10,@-r10	! +40: base green, blue
	fmov	fr8,@-r10	! +32: base alpha, red
	add	#-8,r10		! +24, +28 are left as they are
	mov.l	r2,@-r10	! +20: v
	mov.l	r1,@-r10	! +16: u
	fmov	fr6,@-r10	! +8: y and 1 / depth
	fmov	fr4,@-r10	! +0: minus depth and x
	rts
	fschg			! (delay slot) back to 32-bit fmov
.Lring_slot0_end:
! The end of ring slot 0: the slot is filled downward from here.
	.long	_float_colour_clip_ring+64

! float_colour_flat_copy_plain
!
! For flat shading across a cut: copies the base color of the newest
! ring slot over the base color of the two slots before it (wrapping
! within the four), so all three corners carry the newest vertex's
! color.
!
! In:    r11 = the newest vertex's index (slot = r11 & 3).
! Out:   base color (+32..+47) of slots r11 - 1 and r11 - 2 replaced.
!        fr8-fr11 = that color. T is not changed.
! Uses:  r0, r1 and r10 are changed (the callers save r10).
! Notes: called with SZ = 0; 64-bit fmov inside. Called when r12 bit 0
!        is set, by float_colour_strip_near_clip_plain and
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_flat_copy_plain
	.type	_float_colour_flat_copy_plain,@function
_float_colour_flat_copy_plain:
.Lflat_copy:
	mov	#6,r1		! r1 = 6, the shift for a slot's 64 bytes
	mov	r11,r0
	and	#3,r0		! r0 = the newest slot's number
	mov.l	.Lring_base_color,r10	! r10 = the base color of slot 0 (ring + 32)
	shld	r1,r0		! r0 = the slot's offset in the ring
	fschg			! 64-bit fmov
	mov	r10,r1
	add	r0,r1		! r1 = the newest slot's base color
	fmov	@r1+,fr8	! fr8, fr9 = alpha, red
	add	#-64,r0		! r0 = the offset of the slot before
	fmov	@r1+,fr10	! fr10, fr11 = green, blue
	and	#255,r0		! wrap the offset within the four slots (256 bytes)
	add	#16,r10		! r10 = the end of slot 0's base color (ring + 48)
	mov	r10,r1
	add	r0,r1		! r1 = the end of the base color one slot back
	fmov	fr10,@-r1	! its green, blue
	add	#-64,r0		! r0 = the offset two slots back
	fmov	fr8,@-r1	! its alpha, red
	and	#255,r0		! wrap again
	mov	r10,r1
	add	r0,r1		! r1 = the end of the base color two slots back
	fmov	fr10,@-r1	! its green, blue
	fmov	fr8,@-r1	! its alpha, red
	rts
	fschg			! (delay slot) back to 32-bit fmov
	nop			! padding before the pool word
.Lring_base_color:
	.long	_float_colour_clip_ring+32

! float_colour_kept_vtx_emit_plain
!
! Sends one vertex kept in float_colour_clip_ring as a 64-byte vertex
! (layout as float_colour_vtx_emit_plain; offset color zero): X and Y
! are the slot's x and y times its 1 / depth.
!
! In:    r0 = the vertex's index (slot = r0 & 3).
!        T = 1 to end the strip with this vertex, 0 otherwise.
!        r6 = where to write; r5 = the list's write pointer.
! Out:   r5 and r6 advanced by 64. T is not changed, so a caller's
!        "dt r3" before the call still shows after it.
! Uses:  r0-r2, r10 and fr0-fr7 are changed (the callers save r10).
! Notes: called with SZ = 0; 64-bit fmov inside. The control word is r6
!        as it stands when written (the address of the vertex), or the
!        constant 0xf0000000 for the end of a strip. Callers:
!        float_colour_strip_near_clip_plain and
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_kept_vtx_emit_plain
	.type	_float_colour_kept_vtx_emit_plain,@function
_float_colour_kept_vtx_emit_plain:
.Lkept_emit:
	mov	#6,r1		! r1 = 6, the shift for a slot's 64 bytes
	mov.l	.Lring_base_color2,r10	! r10 = the base color of slot 0 (ring + 32)
	and	#3,r0		! r0 = the slot number
	fschg			! 64-bit fmov
	shld	r1,r0		! r0 = the slot's offset
	fldi0	fr6
	add	r0,r10		! r10 = this slot's base color
	fldi0	fr7		! fr6, fr7 = 0 for the offset color
	mov	#-16,r2		! r2 = -16, shifted below into 0xf0000000
	fmov	@r10+,fr0	! fr0, fr1 = base alpha, red
	add	#64,r6		! r6 = the end of the vertex
	fmov	@r10+,fr2	! fr2, fr3 = base green, blue
	add	#-48,r10	! r10 = the start of the slot
	fmov	fr6,@-r6	! +56: offset green, blue = 0
	fmov	fr6,@-r6	! +48: offset alpha, red = 0
	fmov	fr2,@-r6	! +40: base green, blue
	fmov	fr0,@-r6	! +32: base alpha, red
	fmov	@r10+,fr0	! fr0, fr1 = minus depth, x
	shll16	r2
	fmov	@r10+,fr2	! fr2, fr3 = y, 1 / depth
	fmov	@r10+,fr4	! fr4, fr5 = u, v
	fmul	fr3,fr2		! fr2 = Y = y / depth
	fmov	@r10+,fr6	! fr6, fr7 = the slot's two unused words
	fmul	fr3,fr1		! fr1 = X = x / depth
	shll8	r2		! r2 = 0xf0000000: a vertex word with end of strip
	fmov	fr6,@-r6	! +24: the unused words, copied as they are
	add	#64,r5
	fmov	fr4,@-r6	! +16: u, v
	fmov	fr2,@-r6	! +8: Y, 1 / depth
	bt.s	.Lke_control	! T set by the caller: keep the end-of-strip word
	fmov	fr0,@-r6	! (delay slot) +0, +4: minus depth (replaced below) and X
	mov	r6,r2		! mid-strip: the control word is r6
! 0c109efc: r2 = the control word.
.Lke_control:
	mov.l	r2,@r6		! +0: the control word
	pref	@r6		! send the first half
	add	#32,r6
	pref	@r6		! send the second half
	fschg
	rts
	add	#32,r6		! (delay slot) r6 = the next vertex
	nop			! padding before the pool word
.Lring_base_color2:
	.long	_float_colour_clip_ring+32

! float_colour_near_cut_emit_plain
!
! Sends the point where an edge between two ring slots crosses the near
! plane. With a and b the minus-depth words of the two slots,
! t = (near_limit - a) / (b - a), and x, y, u, v and the base color are
! each taken as first + t x (second - first). The point lies on the
! plane, so 1 / depth is the header's near_inv (r7): X = x x near_inv,
! Y = y x near_inv, and near_inv is written as 1/w. The offset color is
! zero. Layout as float_colour_vtx_emit_plain.
!
! In:    r0 = the index of the first vertex (slot = r0 & 3); r11 = the
!        index of the second, the newest (slot = r11 & 3).
!        T = 1 to end the strip with this vertex, 0 otherwise.
!        r12 = the near_limit bits; r7 = the near_inv bits.
!        r6 = where to write; r5 = the list's write pointer.
! Out:   r5 and r6 advanced by 64. T as on entry.
! Uses:  r0-r2, r10 and fr0-fr7 are changed (the callers save r10).
! Notes: called with SZ = 0; 64-bit fmov for the pairs inside. r12 is
!        used with its flag bit 0 as it is, so the near value is off by
!        at most one unit in the last place. The control word is r6 at
!        the time (vertex + 12; the low bits do not matter to a vertex
!        word, by the evidence of its use here), shifted right one for
!        the end of a strip. Callers:
!        float_colour_strip_near_clip_plain and
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_near_cut_emit_plain
	.type	_float_colour_near_cut_emit_plain,@function
_float_colour_near_cut_emit_plain:
.Lcut_emit:
	mov	#6,r1		! r1 = 6, the shift for a slot's 64 bytes
	mov.l	.Lring,r10	! r10 = the ring
	and	#3,r0		! r0 = the first slot's number
	mov	r10,r2
	shld	r1,r0
	lds	r12,fpul	! fpul = the near_limit bits
	add	r0,r10		! r10 = the first slot
	fsts	fpul,fr0	! fr0 = near_limit as a float
	mov	r11,r0
	fmov	@r10,fr2	! fr2 = a, the first slot's minus depth
	and	#3,r0		! r0 = the second slot's number
	shld	r1,r0
	fsub	fr2,fr0		! fr0 = near_limit - a
	add	r0,r2		! r2 = the second slot
	fmov	@r2,fr1		! fr1 = b, the second slot's minus depth
	fschg			! 64-bit fmov
	add	#16,r2
	fsub	fr2,fr1		! fr1 = b - a
	add	#16,r10
	lds	r7,fpul		! fpul = the near_inv bits
	fdiv	fr1,fr0		! fr0 = t
	fmov	@r2,fr4		! fr4, fr5 = u, v of the second
	add	#-8,r2
	fmov	@r10,fr2	! fr2, fr3 = u, v of the first
	fsub	fr2,fr4
	add	#-8,r10
	fsub	fr3,fr5
	fsts	fpul,fr1	! fr1 = near_inv
	fmac	fr0,fr4,fr2	! fr2 = u at the crossing
	add	#24,r6		! r6 = vertex + 24
	fmac	fr0,fr5,fr3	! fr3 = v at the crossing
	fmov	fr2,@-r6	! +16, +20: u, v
	fschg			! 32-bit fmov for the single words
	fmov	fr1,@-r6	! +12: 1/w = near_inv
	fmov	@r2,fr5		! fr5 = y of the second
	add	#-4,r2
	fmov	@r10,fr3	! fr3 = y of the first
	add	#-4,r10
	fmov	@r2,fr4		! fr4 = x of the second
	fmov	@r10,fr2	! fr2 = x of the first
	fsub	fr3,fr5
	fsub	fr2,fr4
	fmac	fr0,fr5,fr3	! fr3 = y at the crossing
	add	#52,r10		! r10 = the first slot + 56
	fmac	fr0,fr4,fr2	! fr2 = x at the crossing
	mov	r6,r0		! r0 = r6, the control word of a vertex in mid-strip
	fmul	fr1,fr3		! fr3 = Y = y x near_inv
	add	#64,r5
	fmul	fr1,fr2		! fr2 = X = x x near_inv
	fmov	fr3,@-r6	! +8: Y
	bf.s	.Lce_control	! T clear: the strip goes on
	fmov	fr2,@-r6	! (delay slot) +4: X
	shar	r0		! end of strip: the control word shifted right one
	sett			! T = 1 again (shar changed it)
! 0c109f7c: r0 = the control word. Then the second half: the colors.
.Lce_control:
	mov.l	r0,@-r6		! +0: the control word
	add	#52,r2		! r2 = the second slot + 56
	pref	@r6		! send the first half
	add	#64,r6		! r6 = the end of the vertex
	fschg			! 64-bit fmov
	fldi0	fr2
	add	#-16,r2		! r2 = the second slot's base green (+40)
	fldi0	fr3
	add	#-16,r10	! r10 = the first slot's base green (+40)
	fmov	fr2,@-r6	! +56: offset green, blue = 0
	fmov	fr2,@-r6	! +48: offset alpha, red = 0
	fmov	@r2,fr4		! fr4, fr5 = green, blue of the second
	add	#-8,r2
	fmov	@r10,fr2	! fr2, fr3 = green, blue of the first
	add	#-8,r10
	fsub	fr2,fr4
	fsub	fr3,fr5
	fmov	@r2,fr6		! fr6, fr7 = alpha, red of the second
	fmac	fr0,fr4,fr2	! fr2 = green at the crossing
	fmac	fr0,fr5,fr3	! fr3 = blue at the crossing
	fmov	@r10,fr4	! fr4, fr5 = alpha, red of the first
	fmov	fr2,@-r6	! +40: base green, blue
	fsub	fr4,fr6
	fsub	fr5,fr7
	fmac	fr0,fr6,fr4	! fr4 = alpha at the crossing
	fmac	fr0,fr7,fr5	! fr5 = red at the crossing
	fmov	fr4,@-r6	! +32: base alpha, red
	fschg			! back to 32-bit fmov
	pref	@r6		! send the second half
	rts
	add	#32,r6		! (delay slot) r6 = the next vertex
	nop			! padding before the pool word
.Lring:
	.long	_float_colour_clip_ring
	.size	_float_colour_strip_near_clip_plain,0x258
	.size	_float_colour_vtx_load_plain,0x86
	.size	_float_colour_vtx_emit_plain,0x3a
	.size	_float_colour_vtx_keep_plain,0x2c
	.size	_float_colour_flat_copy_plain,0x38
	.size	_float_colour_kept_vtx_emit_plain,0x54
	.size	_float_colour_near_cut_emit_plain,0xb0
