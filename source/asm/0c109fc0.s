! float_colour_tri_classify_plain
!
! A second copy, byte for byte, of float_colour_tri_classify_spec:
! transforms the positions of the next triangle's three vertex records
! without moving r4 and shifts one bit a vertex into r9, 1 = cut off by
! the near plane.
!
! In:    r4 = the first of three vertex records. r9 = 0. r12 = the
!        near_limit bits. XMTRX = the transform giving (depth, x, y, .).
! Out:   r9 = the three bits: vertex 0 in bit 2, vertex 1 in bit 1,
!        vertex 2 in bit 0. r4 unchanged.
! Uses:  r0, r1 and fr0-fr7 are changed. No stack use.
! Notes: 32-bit fmov (FPSCR SZ = 0). Called by
!        float_colour_tri_near_clip_plain (bsr).
	.global	_float_colour_tri_classify_plain
	.type	_float_colour_tri_classify_plain,@function
_float_colour_tri_classify_plain:
.Lp_classify:
	mov	r4,r1		! r1 = r4, to put it back at the end
	mov.l	@r4,r0		! first word of record 0
	tst	#1,r0		! T = it is a reference
	bf.s	.Lp_v0_inline	! bit 0 set: an inline vertex
	fmov	@r4+,fr4	! (delay slot) fr4 = x of an inline vertex; r4 on the second word
	mov.l	@r4+,r0		! a reference: r0 = its offset word, r4 = past the reference
	add	r4,r0		! r0 = the vertex it refers to
	fmov	@r0+,fr4	! fr4, fr5, fr6 = its x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Lp_v0_through
	fldi1	fr7		! (delay slot) w = 1
! 0c10a338: an inline vertex; x is loaded already.
.Lp_v0_inline:
	fmov	@r4+,fr5	! fr5 = y
	fmov	@r4,fr6		! fr6 = z
	fldi1	fr7
	add	#24,r4		! r4 = past the 32-byte record
! 0c10a340: vertex 0 through the matrix, fetching the cache lines of
! the records that follow.
.Lp_v0_through:
	pref	@r4
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv4	! fv4 = (depth, x, y, .) of vertex 0
	mov.l	@r4,r0		! first word of record 1
	tst	#1,r0
	bf.s	.Lp_v1_inline	! bit 0 set: an inline vertex
	fmov	@r4+,fr0	! (delay slot) fr0 = x of an inline vertex
	mov.l	@r4+,r0		! a reference: its offset word
	add	r4,r0		! r0 = the vertex it refers to
	fmov	@r0+,fr0	! fr0, fr1, fr2 = its x, y, z
	fmov	@r0+,fr1
	fmov	@r0+,fr2
	bra	.Lp_v1_through
	fldi1	fr3		! (delay slot) w = 1
! 0c10a360: record 1 is an inline vertex.
.Lp_v1_inline:
	fmov	@r4+,fr1	! fr1 = y
	fmov	@r4,fr2		! fr2 = z
	fldi1	fr3
	add	#24,r4		! r4 = past the 32-byte record
! 0c10a368: vertex 1 through the matrix.
.Lp_v1_through:
	pref	@r4
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv0	! fv0 = (depth, x, y, .) of vertex 1
	mov.l	@r4,r0		! first word of record 2
	fneg	fr4		! fr4 = minus the depth of vertex 0
	tst	#1,r0
	flds	fr4,fpul	! its bits wait in fpul while fr4-fr7 take vertex 2
	bf.s	.Lp_v2_inline	! bit 0 set: an inline vertex
	fmov	@r4+,fr4	! (delay slot) fr4 = x of an inline vertex
	mov.l	@r4+,r0		! a reference: its offset word
	add	r4,r0		! r0 = the vertex it refers to
	fmov	@r0+,fr4	! fr4, fr5, fr6 = its x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Lp_v2_through
	fldi1	fr7		! (delay slot) w = 1
! 0c10a38c: record 2 is an inline vertex.
.Lp_v2_inline:
	fmov	@r4+,fr5	! fr5 = y
	fmov	@r4,fr6		! fr6 = z
	fldi1	fr7
! 0c10a392: the three near tests, vertex 0 first. T = r12 is above the
! bits of minus the depth (unsigned): the vertex is cut off. Each T is
! shifted into r9 from the right.
.Lp_v2_through:
	mov	r1,r4		! r4 back on record 0
	sts	fpul,r0		! r0 = the bits of minus the depth of vertex 0
	ftrv	xmtrx,fv4	! fv4 = (depth, x, y, .) of vertex 2
	cmp/hi	r0,r12		! T = vertex 0 is cut off
	fneg	fr0		! fr0 = minus the depth of vertex 1
	flds	fr0,fpul
	rotcl	r9		! vertex 0's bit into r9
	sts	fpul,r0
	cmp/hi	r0,r12		! T = vertex 1 is cut off
	fneg	fr4		! fr4 = minus the depth of vertex 2
	flds	fr4,fpul
	rotcl	r9		! vertex 1's bit into r9
	sts	fpul,r0
	cmp/hi	r0,r12		! T = vertex 2 is cut off
	rts
	rotcl	r9		! (delay slot) vertex 2's bit into r9
