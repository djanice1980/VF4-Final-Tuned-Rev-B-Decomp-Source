! 0c10a1fc: jump into the table on the three bits (vertex 0, 1, 2;
! 1 = cut off). braf lands at 0c10a200 + r9; each entry is a bra and
! its delay slot. Entries 000 and 111 are two nops each and are not
! reached (both values were dealt with above): 000 would run on into
! entry 001, and 111 into .Lp_tri_done.
! In the cases v0, v1, v2 are the triangle's vertices in ring slots 0,
! 1, 2 and cut(p,q) is the point where the edge from p to q crosses the
