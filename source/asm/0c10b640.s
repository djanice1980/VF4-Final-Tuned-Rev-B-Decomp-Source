	lds.l	@r15+,pr
	mov.l	@r15+,r8	! r8-r14 back
	mov.l	@r15+,r9
	mov.l	@r15+,r10
	mov.l	@r15+,r11
	mov.l	@r15+,r12
	mov.l	@r15+,r13
	mov.l	@r15+,r14
	fmov	@r15+,fr12	! fr12-fr15 back
	fmov	@r15+,fr13
	fmov	@r15+,fr14
	fmov	@r15+,fr15
