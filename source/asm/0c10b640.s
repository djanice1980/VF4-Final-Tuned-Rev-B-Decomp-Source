	tst	#8,r0		! T = run bit 3 clear: one strip (or more, bit 7)
	mov.l	.Lspill_params,r13	! r13 = &intensity_spill_params
	bf	.Lrun_tris	! bit 3 set: independent triangles
	bsr	.Lstrip_send	! intensity_spill_strip_send
	nop
	bra	.Lrun_loop	! on to the next run word
	mov.l	@r4+,r0		! (delay slot) r0 = the next run word
! 0c10b988: a run of independent triangles, not clipped.
.Lrun_tris:
