	bra	.Lfirst_run
	fldi1	fr15		! (delay slot) fr15 = 1.0
! 0c10b8d8: material 0 or above. Above 0 is specular: reload the
! half vector (the other paths use fr8-fr10 for vertices) and turn
! r8 into the row's address, biased so that the index ftrc(N.H) = 309
! lands on the row's first entry.
.Llit:
