! intensity_spill_strip_send
!
! Sends one run of strips that needs no clipping. r8 picks one of three
! loops, each written out in full:
!   odd (-1), at 0c10ba30: unlit. Base 1.0 and offset 0 are written once
!     into the last two words of both store queues; each vertex then
!     writes only its first 24 bytes. No spill.
!   0, at 0c10bb52: diffuse. base = ambient + max(0, N.L) and
!     offset = k0 * (base + k1), whatever its sign.
!   else, at 0c10bccc: specular, r8 = the biased row address. base as
!     above. When N.L is above 0 and the index ftrc(N.H) is above 309
!     (H = the half vector), offset = row[index], plus
!     k0 * (base + k1) only if base + k1 is above 0; in the other cases
!     offset = k0 * (base + k1), whatever its sign.
! The unlit and diffuse loops handle two vertices per turn, "A" in
! fr4-fr7 and "B" in fr8-fr11, so that each one's divide and transform
! overlap the other's stores. All three loops read the next record's two
! words before they know that the strip has ended; when it has, those
! are the words after the strip. If the first is positive with bit 7 set
! it starts a further strip of the same run: its count follows, the loop
! goes on, and the vertex in hand gets the end-of-strip control word. If
! not, the run is over and r4 is put back on that word.
!
! In:    r4 = the run's count word (vertices in the first strip),
!        r5 = list write pointer, r6 = its store-queue address,
!        r8 = lighting selector, r13 = &intensity_spill_params,
!        fr12-fr15 = light direction (y, z, x) and the ambient term,
!        fr8-fr10 = half vector (y, z, x) when r8 is a row address.
! Out:   r4 = the word after the run; r5 and r6 moved past the vertices
!        sent (32 bytes each).
! Uses:  r0-r3, r14 and fr0-fr11 are changed (r14 and fr8-fr11 without
!        being saved); r7 too on the specular path. No stack use.
! Notes: SZ is flipped to pair moves on entry and back before each rts.
	.global	_intensity_spill_strip_send
	.type	_intensity_spill_strip_send,@function
_intensity_spill_strip_send:
! 0c10ba20: the entry (bsr from the group loop). Pick the loop by r8.
.Lstrip_send:
	tst	r8,r8		! T = r8 is 0: diffuse
	mov	r8,r0
	bf	.Lstrip_not_diffuse	! not 0: unlit or specular
	bra	.Lstrip_diffuse	! 0: the diffuse loop (its delay slot is the tst below)
! 0c10ba28: also the delay slot of the bra above, where it does no harm.
.Lstrip_not_diffuse:
	tst	#1,r0		! T = r8 is even: a row address
	bf	.Lstrip_unlit	! odd: the unlit loop
	bra	.Lstrip_specular	! even: the specular loop
	nop			! (delay slot)
! 0c10ba30: the unlit loop. The intensities are the same for every
! vertex, so they are stored once: (1.0, 0) into words 6-7 of this slot
! and of the slot before it, which is the other store queue. From here
! r6 = slot + 24 and the stores go down from there.
.Lstrip_unlit:
	mov.l	@r4+,r3		! r3 = the strip's vertex count
	fldi1	fr2
	fschg			! pair moves
	fldi0	fr3		! fr2, fr3 = 1.0, 0: base and offset intensity
	fmov	fr2,@-r6	! words 6-7 of the other queue (slot - 8)
	add	#32,r6		! r6 = slot + 24
	fmov	fr2,@r6		! words 6-7 of this queue
! Fetch the first record: a vertex (bit 0 of its first word set), or a
! reference whose second word is the offset from its end to the vertex.
	mov.l	@r4,r0		! r0 = the record's first word
	mov	r4,r14		! r14 = the record
	tst	#1,r0
	add	#32,r4		! r4 = past a 32-byte vertex
	bf	.Lunlit_first	! bit 0 set: the record is the vertex
	mov.l	@(4,r14),r14	! a reference: r14 = its offset word
	add	#-24,r4		! r4 = the end of the 8-byte reference
	add	r4,r14		! r14 = the vertex it refers to
! 0c10ba4e: transform the first vertex as "A".
.Lunlit_first:
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	fmov	@r14,fr6	! fr6 = z (fr7 gets nx, not used on this path)
	add	#16,r14		! r14 = &u
	fldi1	fr7		! w = 1.0
	fmov	@r14,fr0	! fr0, fr1 = u, v
	ftrv	xmtrx,fv4	! fr4 = w, fr5, fr6 = X, Y times w
! 0c10ba5a: A is transformed (fr4-fr6) with its u, v in fr0, fr1. Start
! its divide and fetch the next record as "B".
.Lunlit_a:
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1 / w of A
	dt	r3		! count A
	mov.l	@r4+,r0		! r0 = the next record's first word
	bt.s	.Lunlit_a_last	! A was the last vertex of the strip
	mov.l	@r4+,r14	! (delay slot) r14 = the next record's second word
	tst	#1,r0
	mov	r6,r2		! r2 = A's control word (a store-queue address)
	bt.s	.Lunlit_b_load	! bit 0 clear: B is a reference
	add	r4,r14		! (delay slot) r14 = the vertex it refers to
	mov	r4,r14		! B is the record itself
	add	#24,r4		! r4 = past the 32-byte vertex
	add	#-8,r14		! r14 = its start
! 0c10ba74: load and transform B while A is finished and stored.
.Lunlit_b_load:
	fmov	@r14+,fr8	! fr8, fr9 = B's x, y
	add	#32,r4
	pref	@r4		! prefetch 32 bytes on in the records
	fmov	@r14,fr10	! fr10 = B's z
	add	#16,r14		! r14 = &B's u
	fldi1	fr11		! B's w = 1.0
	fmul	fr7,fr6		! A: Y = Y*w * 1/w
	fmov	fr0,@-r6	! A slot +16 and +20: u, v
	fmul	fr7,fr5		! A: X
	fmov	fr6,@-r6	! A slot +8 and +12: Y, 1/w
	ftrv	xmtrx,fv8	! B through the matrix
	fmov	fr4,@-r6	! A slot +0 and +4: (w), then X
	add	#-32,r4
	mov.l	r2,@r6		! A slot +0: the control word, over w
	fmov	@r14,fr0	! fr0, fr1 = B's u, v
	dt	r3		! count B
	pref	@r6		! send A
	add	#56,r6		! r6 = B's slot + 24
	mov	r6,r2		! r2 = B's control word
	fldi1	fr11
	fdiv	fr8,fr11	! fr11 = 1 / w of B
	mov.l	@r4+,r0		! r0 = the next record's first word
	bt.s	.Lunlit_b_last	! B was the last vertex of the strip
	mov.l	@r4+,r14	! (delay slot) r14 = the next record's second word
	tst	#1,r0
	bt.s	.Lunlit_a_load	! bit 0 clear: the next vertex is a reference
	add	r4,r14		! (delay slot) r14 = the vertex it refers to
	mov	r4,r14		! else the record is the vertex
	add	#24,r4
	add	#-8,r14		! r14 = its start
! 0c10bab0: the same with the roles exchanged: load the next vertex as A
! while B is finished and stored.
.Lunlit_a_load:
	add	#32,r4
	fmov	@r14+,fr4	! fr4, fr5 = A's x, y
	pref	@r4		! prefetch 32 bytes on in the records
	fmov	@r14,fr6	! fr6 = A's z
	add	#16,r14
	fldi1	fr7		! A's w = 1.0
	fmul	fr11,fr10	! B: Y
	add	#-32,r4
	fmul	fr11,fr9	! B: X
	fmov	fr0,@-r6	! B slot +16 and +20: u, v
	fmov	fr10,@-r6	! B slot +8 and +12: Y, 1/w
	ftrv	xmtrx,fv4	! A through the matrix
	fmov	fr8,@-r6	! B slot +0 and +4: (w), then X
	add	#64,r5		! the write pointer: 64 bytes on, for A and B
	mov.l	r2,@r6		! B slot +0: the control word
	fmov	@r14,fr0	! fr0, fr1 = A's u, v
	pref	@r6		! send B
	bra	.Lunlit_a	! round again
	add	#56,r6		! (delay slot) r6 = A's slot + 24
	nop			! padding (never run)
! 0c10bad8: the strip ended with B. r0 and r14 are the two words after
! it; a third is read here.
.Lunlit_b_last:
	cmp/pl	r0		! T = the word after the strip is positive
	mov.l	@r4+,r2		! r2 = the third word
	bf	.Lunlit_end_on_b	! not positive: the run is over
	tst	#128,r0		! T = bit 7 clear
	mov	r14,r3		! r3 = the second word: a further strip's count
	bt	.Lunlit_end_on_b	! bit 7 clear: the run is over
! A further strip of the run: B gets the end-of-strip control word and
! the new strip's first vertex is loaded as A.
	mov	r2,r0		! r0 = the third word: its first record's first word
	mov	r6,r2
	shar	r2		! r2 = B's control word, end of strip
	mov.l	@r4+,r14	! r14 = that record's second word
	tst	#1,r0
	bt.s	.Lunlit_a_load	! bit 0 clear: a reference
	add	r4,r14		! (delay slot) r14 = the vertex it refers to
	mov	r4,r14		! else the record is the vertex
	add	#24,r4
	bra	.Lunlit_a_load
	add	#-8,r14		! (delay slot) r14 = its start
	nop			! padding (never run)
! 0c10bafc: the run is over and B is the last vertex. Move B into
! fr4-fr7 (1/w included) and finish through the common tail.
.Lunlit_end_on_b:
	add	#44,r4		! prefetch ahead in the data
	pref	@r4
	add	#-48,r4		! r4 = 8 bytes past the word after the strip
	fmov	fr8,fr4		! fr4, fr5 = B's w, X*w
	add	#32,r5		! the write pointer: A's 32 bytes
	bra	.Lunlit_final
	fmov	fr10,fr6	! (delay slot) fr6, fr7 = B's Y*w, 1/w
	nop			! padding (never run)
! 0c10bb0c: the strip ended with A; as 0c10bad8 with the roles
! exchanged.
.Lunlit_a_last:
	cmp/pl	r0		! T = the word after the strip is positive
	mov.l	@r4+,r2		! r2 = the third word
	bf	.Lunlit_end_on_a	! not positive: the run is over
	tst	#128,r0
	mov	r14,r3		! r3 = a further strip's count
	bt	.Lunlit_end_on_a	! bit 7 clear: the run is over
	mov	r2,r0		! r0 = the new strip's first record word
	mov	r6,r2
	shar	r2		! r2 = A's control word, end of strip
	mov.l	@r4+,r14	! r14 = that record's second word
	tst	#1,r0
	bt.s	.Lunlit_b_load	! bit 0 clear: a reference
	add	r4,r14		! (delay slot) r14 = the vertex it refers to
	mov	r4,r14		! else the record is the vertex
	add	#24,r4
	bra	.Lunlit_b_load
	add	#-8,r14		! (delay slot) r14 = its start
	nop			! padding (never run)
! 0c10bb30: the run is over and A is the last vertex.
.Lunlit_end_on_a:
	add	#44,r4		! prefetch ahead in the data
	pref	@r4
	add	#-48,r4		! r4 = 8 bytes past the word after the strip
! 0c10bb36: store the run's last vertex (in fr4-fr7, u and v in fr0,
! fr1) with the end-of-strip control word, and return.
.Lunlit_final:
	fmul	fr7,fr6		! Y
	mov	r6,r2
	shar	r2		! r2 = the end-of-strip control word
	fmul	fr7,fr5		! X
	fmov	fr0,@-r6	! slot +16 and +20: u, v
	add	#-8,r4		! r4 = the word after the run
	fmov	fr6,@-r6	! slot +8 and +12: Y, 1/w
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	fr4,@-r6	! slot +0 and +4: (w), then X
	mov.l	r2,@r6		! slot +0: the control word
	fschg			! single moves again
	pref	@r6		! send the vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next slot
! 0c10bb52: the diffuse loop. The record fetches and the A/B turns are
! those of the unlit loop; what is new is the lighting. The normal is
! put in fr0-fr3 as (ny, nz, nx, 0), the order of the light direction in
! fr12-fr14, so that fipr leaves N.L in fr3. Stores go down from the end
! of the slot (r6 = slot + 32).
.Lstrip_diffuse:
	mov.l	@r4+,r3		! r3 = the strip's vertex count
	add	#32,r6		! r6 = the end of the first slot
	fschg			! pair moves
	mov.l	@r4,r0		! r0 = the first record's first word
	mov	r4,r14
	fldi0	fr2		! fr2 = 0, to receive nx
	tst	#1,r0
	add	#32,r4		! r4 = past a 32-byte vertex
	bf	.Ldiff_first	! bit 0 set: the record is the vertex
	mov.l	@(4,r14),r14	! a reference: its offset word
	add	#-24,r4		! r4 = the end of the reference
	add	r4,r14		! r14 = the vertex it refers to
! 0c10bb6a: the first vertex as A.
.Ldiff_first:
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	mov	r6,r2		! r2 = A's control word
	fmov	@r14+,fr6	! fr6, fr7 = z, nx
	fadd	fr7,fr2		! fr2 = nx
	fldi1	fr7		! w = 1.0
	fldi0	fr3		! fr3 = 0: the normal's fourth term
	fmov	@r14+,fr0	! fr0, fr1 = ny, nz; r14 = &u
	ftrv	xmtrx,fv4	! A through the matrix
! 0c10bb7a: A is transformed, its normal is in fr0-fr3 and r14 is on its
! u, v. Light it while the next record is fetched as B (into r1).
.Ldiff_a:
	mov.l	@r4+,r0		! r0 = the next record's first word
	flds	fr15,fpul	! fpul = the ambient term
	dt	r3		! count A
	mov.l	@r4+,r1		! r1 = the next record's second word
	fipr	fv12,fv0	! fr3 = N.L of A
	fldi1	fr7
	bt.s	.Ldiff_a_last	! A was the last vertex of the strip
	fdiv	fr4,fr7		! (delay slot) fr7 = 1 / w of A
	tst	#1,r0
	add	r4,r1		! r1 = the vertex a reference points at
	bt.s	.Ldiff_a_light	! bit 0 clear: B is that reference
	fsts	fpul,fr2	! (delay slot) fr2 = the ambient term
	mov	r4,r1		! else the record is the vertex
	add	#24,r4
	add	#-8,r1		! r1 = its start
! 0c10bb98: A's intensities. base (fr2) = ambient + N.L when N.L is
! above 0; offset (fr3) = k0 * (base + k1), the spill.
.Ldiff_a_light:
	fldi0	fr10		! fr10 = 0 for the compare (B's z is loaded later)
	fcmp/gt	fr10,fr3	! T = N.L is above 0
	fmov	@r1+,fr8	! fr8, fr9 = B's x, y
	add	#32,r4
	fmov	@r13,fr0	! fr0, fr1 = k0, k1 (intensity_spill_params)
	bf	.Ldiff_a_spill	! N.L not above 0: base = ambient
	fadd	fr3,fr2		! base = ambient + N.L
! 0c10bba6: the spill, into A's offset intensity.
.Ldiff_a_spill:
	pref	@r4		! prefetch 32 bytes on in the records
	cmp/pz	r8		! T = r8 is not negative: always, on this path
	fadd	fr2,fr1		! fr1 = base + k1
	fldi0	fr3		! fr3 = 0
	bf	.Ldiff_a_store	! (never taken here)
	fmac	fr0,fr1,fr3	! offset = k0 * (base + k1)
! 0c10bbb2: store A; load B's z, normal and transform.
.Ldiff_a_store:
	fmov	@r14,fr0	! fr0, fr1 = A's u, v
	fmov	@r1+,fr10	! fr10, fr11 = B's z, nx
	add	#-32,r4
	fmov	fr2,@-r6	! A slot +24 and +28: base, offset
	fsub	fr2,fr2		! fr2 = 0 ...
	fmov	fr0,@-r6	! A slot +16 and +20: u, v
	fmul	fr7,fr6		! A: Y
	fmov	@r1+,fr0	! fr0, fr1 = B's ny, nz; r1 = &B's u
	fadd	fr11,fr2	! ... fr2 = B's nx
	fldi1	fr11		! B's w = 1.0
	fmul	fr7,fr5		! A: X
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	fr6,@-r6	! A slot +8 and +12: Y, 1/w
	dt	r3		! count B
	fmov	fr4,@-r6	! A slot +0 and +4: (w), then X
	ftrv	xmtrx,fv8	! B through the matrix
	mov.l	r2,@r6		! A slot +0: the control word
	fsub	fr3,fr3		! fr3 = 0: B's normal is ready for fipr
	mov.l	@r4+,r0		! r0 = the next record's first word
	mov	r6,r2		! r2 = B's control word
	pref	@r6		! send A
	add	#64,r6		! r6 = the end of B's slot
	mov.l	@r4+,r14	! r14 = the next record's second word
	flds	fr15,fpul	! fpul = the ambient term
	fipr	fv12,fv0	! fr3 = N.L of B
	fldi1	fr11
	bt.s	.Ldiff_b_last	! B was the last vertex of the strip
	fdiv	fr8,fr11	! (delay slot) fr11 = 1 / w of B
	tst	#1,r0
	add	r4,r14		! r14 = the vertex a reference points at
	bt.s	.Ldiff_b_light	! bit 0 clear: the next vertex is that reference
	fsts	fpul,fr2	! (delay slot) fr2 = the ambient term
	mov	r4,r14		! else the record is the vertex
	add	#24,r4
	add	#-8,r14		! r14 = its start
! 0c10bbf8: B's intensities, as at 0c10bb98, while the next vertex is
! loaded as A.
.Ldiff_b_light:
	fldi0	fr0
	fcmp/gt	fr0,fr3		! T = N.L is above 0
	fmov	@r14+,fr4	! fr4, fr5 = the next A's x, y
	add	#32,r4
	fmov	@r13,fr0	! fr0, fr1 = k0, k1
	bf	.Ldiff_b_spill	! N.L not above 0: base = ambient
	fadd	fr3,fr2		! base = ambient + N.L
! 0c10bc06: the spill, into B's offset intensity.
.Ldiff_b_spill:
	pref	@r4
	cmp/pz	r8		! T = r8 is not negative: always, on this path
	fadd	fr2,fr1		! fr1 = base + k1
	fldi0	fr3
	bf	.Ldiff_b_store	! (never taken here)
	fmac	fr0,fr1,fr3	! offset = k0 * (base + k1)
! 0c10bc12: store B; load A's z, normal and transform.
.Ldiff_b_store:
	fmov	@r1,fr0		! fr0, fr1 = B's u, v
	fmov	@r14+,fr6	! fr6, fr7 = A's z, nx
	add	#-32,r4
	fmov	fr2,@-r6	! B slot +24 and +28: base, offset
	fsub	fr2,fr2
	fmov	fr0,@-r6	! B slot +16 and +20: u, v
	fmul	fr11,fr10	! B: Y
	fmov	@r14+,fr0	! fr0, fr1 = A's ny, nz; r14 = &A's u
	fadd	fr7,fr2		! fr2 = A's nx
	fldi1	fr7		! A's w = 1.0
	fmul	fr11,fr9	! B: X
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	fr10,@-r6	! B slot +8 and +12: Y, 1/w
	fsub	fr3,fr3		! fr3 = 0: A's normal is ready for fipr
	fmov	fr8,@-r6	! B slot +0 and +4: (w), then X
	ftrv	xmtrx,fv4	! A through the matrix
	mov.l	r2,@r6		! B slot +0: the control word
	mov	r6,r2		! r2 = A's control word
	pref	@r6		! send B
	bra	.Ldiff_a	! round again
	add	#64,r6		! (delay slot) r6 = the end of A's slot
! 0c10bc3c: the strip ended with B. r0 and r14 are the two words after
! it: a positive first word with bit 7 set starts a further strip.
.Ldiff_b_last:
	cmp/pl	r0		! T = the word after the strip is positive
	fsts	fpul,fr2	! fr2 = the ambient term, for B
	bf	.Ldiff_end_on_b	! not positive: the run is over
	tst	#128,r0
	mov	r14,r3		! r3 = a further strip's count
	bt	.Ldiff_end_on_b	! bit 7 clear: the run is over
	mov.l	@r4+,r0		! r0 = the new strip's first record word
	mov	r6,r2
	shar	r2		! r2 = B's control word, end of strip
	tst	#1,r0
	mov.l	@r4+,r14	! r14 = that record's second word
	bt.s	.Ldiff_b_light	! bit 0 clear: a reference
	add	r4,r14		! (delay slot) r14 = the vertex it refers to
	mov	r4,r14		! else the record is the vertex
	add	#24,r4
	bra	.Ldiff_b_light
	add	#-8,r14		! (delay slot) r14 = its start
	nop			! padding (never run)
! 0c10bc60: the run is over and B is the last vertex. Move it into
! fr4-fr7 for the common tail; r1 is already on its u, v.
.Ldiff_end_on_b:
	add	#48,r4		! prefetch ahead in the data
	pref	@r4
	add	#-48,r4		! r4 = 8 bytes past the word after the strip
	fmov	fr8,fr4		! fr4, fr5 = B's w, X*w
	bra	.Ldiff_final
	fmov	fr10,fr6	! (delay slot) fr6, fr7 = B's Y*w, 1/w
! 0c10bc6c: the strip ended with A; as 0c10bc3c with the roles
! exchanged (the words after the strip are in r0 and r1).
.Ldiff_a_last:
	cmp/pl	r0		! T = the word after the strip is positive
	fsts	fpul,fr2	! fr2 = the ambient term, for A
	bf	.Ldiff_end_on_a	! not positive: the run is over
	tst	#128,r0
	mov	r1,r3		! r3 = a further strip's count
	bt	.Ldiff_end_on_a	! bit 7 clear: the run is over
	mov.l	@r4+,r0		! r0 = the new strip's first record word
	mov	r6,r2
	shar	r2		! r2 = A's control word, end of strip
	tst	#1,r0
	mov.l	@r4+,r1		! r1 = that record's second word
	bt.s	.Ldiff_a_light	! bit 0 clear: a reference
	add	r4,r1		! (delay slot) r1 = the vertex it refers to
	mov	r4,r1		! else the record is the vertex
	add	#24,r4
	bra	.Ldiff_a_light
	add	#-8,r1		! (delay slot) r1 = its start
	nop			! padding (never run)
! 0c10bc90: the run is over and A is the last vertex.
.Ldiff_end_on_a:
	add	#48,r4
	mov	r14,r1		! r1 = &A's u, v
	pref	@r4		! prefetch ahead in the data
	add	#-48,r4		! r4 = 8 bytes past the word after the strip
! 0c10bc98: light and store the run's last vertex (fr4-fr7, normal dot
! in fr3, ambient in fr2, r1 on its u, v), end of strip, and return.
.Ldiff_final:
	fldi0	fr0
	fcmp/gt	fr0,fr3		! T = N.L is above 0
	fmov	@r13,fr0	! fr0, fr1 = k0, k1
	bf	.Ldiff_final_spill	! N.L not above 0: base = ambient
	fadd	fr3,fr2		! base = ambient + N.L
! 0c10bca2: the spill, into the last vertex's offset intensity.
.Ldiff_final_spill:
	cmp/pz	r8
	fmov	@r1,fr10	! fr10, fr11 = u, v
	fadd	fr2,fr1		! fr1 = base + k1
	fldi0	fr3
	bf	.Ldiff_final_store	! (never taken here: r8 is 0)
	fmac	fr0,fr1,fr3	! offset = k0 * (base + k1)
! 0c10bcae: store the last vertex with the end-of-strip control word.
.Ldiff_final_store:
	fmul	fr7,fr6		! Y
	fmov	fr2,@-r6	! slot +24 and +28: base, offset
	fmul	fr7,fr5		! X
	fmov	fr10,@-r6	! slot +16 and +20: u, v
	mov	r6,r2
	shar	r2		! r2 = the end-of-strip control word
	fmov	fr6,@-r6	! slot +8 and +12: Y, 1/w
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	fr4,@-r6	! slot +0 and +4: (w), then X
	add	#-8,r4		! r4 = the word after the run
	mov.l	r2,@r6		! slot +0: the control word
	fschg			! single moves again
	pref	@r6		! send the vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next slot
! 0c10bccc: the specular loop, one vertex per turn. r2 = 309, the
! highest index with no highlight; r7 = the vertex's control word;
! r1 = its u, v; r14 = the next vertex. fr8-fr11 hold (H.y, H.z, H.x, 0),
! H the half vector, so fipr leaves N.H in fr11.
.Lstrip_specular:
	mov	#127,r2		! r2 = 127 ...
	mov.l	@r4+,r3		! r3 = the strip's vertex count
	add	#-32,r6		! r6 = one slot back: each turn adds 64 before storing down
	mov.l	@r4,r0		! r0 = the first record's first word
	add	#127,r2		! ... 254 ...
	fschg			! pair moves
	add	#55,r2		! ... r2 = 309
	tst	#1,r0
	mov	r4,r14		! r14 = the record
	bf.s	.Lspec_first	! bit 0 set: the record is the vertex
	add	#32,r4		! (delay slot) r4 = past a 32-byte vertex
	mov.l	@(4,r14),r14	! a reference: its offset word
	add	#-24,r4		! r4 = the end of the reference
	add	r4,r14		! r14 = the vertex it refers to
! 0c10bce8: r14 is on the first vertex.
.Lspec_first:
	fmov	@r14+,fr4	! fr4, fr5 = x, y
! 0c10bcea: per vertex; fr4, fr5 = x, y are loaded and r14 is on z.
.Lspec_vertex:
	fmov	@r14+,fr6	! fr6, fr7 = z, nx
	mov	r6,r7		! r7 = the control word (the slot before, a store-queue address)
	fldi0	fr2
	fadd	fr7,fr2		! fr2 = nx
	fldi1	fr7		! w = 1.0
	add	#64,r6		! r6 = the end of this vertex's slot
	fldi0	fr3		! fr3 = 0: the normal's fourth term
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	@r14+,fr0	! fr0, fr1 = ny, nz; r14 = &u
	ftrv	xmtrx,fv4	! the vertex through the matrix
	fldi0	fr11		! fr11 = 0: the half vector's fourth term
	dt	r3		! count the vertex
	mov.l	@r4+,r0		! r0 = the next record's first word
	bt.s	.Lspec_last	! this was the last vertex of the strip
	mov	r14,r1		! (delay slot) r1 = &u, v of this vertex
	fipr	fv12,fv0	! fr3 = N.L
	tst	#1,r0
	mov.l	@r4+,r14	! r14 = the next record's second word
	bf.s	.Lspec_next_inline	! bit 0 set: the next record is a vertex
	fldi1	fr7		! (delay slot) fr7 = 1.0 for the divide
	fdiv	fr4,fr7		! fr7 = 1 / w
	pref	@r4		! prefetch at the record after
! 0c10bd16: the next record is a reference. Light this vertex.
.Lspec_next_ref:
	fcmp/gt	fr11,fr3	! T = N.L is above 0
	add	r4,r14		! r14 = the vertex the reference points at
	flds	fr15,fpul	! fpul = the ambient term
	fipr	fv0,fv8		! fr11 = N.H
	fmov	@r13,fr0	! fr0, fr1 = k0, k1
	pref	@r14		! prefetch the next vertex
	bf.s	.Lspec_dark	! N.L not above 0: no light on this vertex
	fsts	fpul,fr2	! (delay slot) fr2 = the ambient term
	fadd	fr3,fr2		! base = ambient + N.L
	fldi0	fr3
	bra	.Lspec_highlight	! on to the highlight
	ftrc	fr11,fpul	! (delay slot) fpul = ftrc(N.H), the row index
	nop			! padding (never run)
! 0c10bd30: the run is over (from 0c10bd90): r4 goes back onto the word
! after the strip through the +24 below, and r3 is 0, so the store at
! 0c10bd6e returns.
.Lspec_run_ends:
	add	#-28,r4		! r4 - 28 + 24 = the word after the strip
	fldi1	fr7
! 0c10bd34: the next record is a vertex; the divide is still to start.
.Lspec_next_inline:
	fdiv	fr4,fr7		! fr7 = 1 / w
! 0c10bd36: the next record is a vertex. The same lighting.
.Lspec_inline_lit:
	add	#24,r4		! r4 = past that 32-byte vertex
	fcmp/gt	fr11,fr3	! T = N.L is above 0
	flds	fr15,fpul	! fpul = the ambient term
	fipr	fv0,fv8		! fr11 = N.H
	mov	r4,r14		! r14 = ...
	fmov	@r13,fr0	! fr0, fr1 = k0, k1
	add	#-32,r14	! ... the start of the next vertex
	pref	@r4
	bf.s	.Lspec_dark	! N.L not above 0: no light on this vertex
	fsts	fpul,fr2	! (delay slot) fr2 = the ambient term
	fadd	fr3,fr2		! base = ambient + N.L
	ftrc	fr11,fpul	! fpul = ftrc(N.H), the row index
	fldi0	fr3		! fr3 = 0
! 0c10bd50: N.L is above 0. An index above 309 reads the highlight from
! the row; the spill is added to it only when base + k1 is above 0.
.Lspec_highlight:
	sts	fpul,r0		! r0 = the index
	fadd	fr2,fr1		! fr1 = base + k1
	cmp/gt	r2,r0		! T = the index is above 309
	shll2	r0		! r0 = the index as a byte offset
	bf	.Lspec_spill_only	! no highlight: the spill alone
	fcmp/gt	fr3,fr1		! T = base + k1 is above 0
	fschg			! a single move for the table read
	fmov	@(r0,r8),fr3	! fr3 = row[index]: the highlight
	bf.s	.Lspec_store	! base + k1 not above 0: the highlight alone
	fschg			! (delay slot) pair moves again
	bra	.Lspec_store
	fmac	fr0,fr1,fr3	! (delay slot) offset = highlight + k0 * (base + k1)
! 0c10bd68: N.L not above 0: base = ambient, offset = the spill alone.
.Lspec_dark:
	fadd	fr2,fr1		! fr1 = ambient + k1
	fldi0	fr3
! 0c10bd6c: no highlight: the offset is the spill alone.
.Lspec_spill_only:
	fmac	fr0,fr1,fr3	! offset = k0 * (base + k1), whatever its sign
! 0c10bd6e: store the vertex and go on, or return after the last one.
.Lspec_store:
	fmov	@r1,fr0		! fr0, fr1 = u, v
	fmul	fr7,fr6		! Y
	fmov	fr2,@-r6	! slot +24 and +28: base, offset
	fmul	fr7,fr5		! X
	fmov	fr0,@-r6	! slot +16 and +20: u, v
	tst	r3,r3		! T = no vertices left
	fmov	fr6,@-r6	! slot +8 and +12: Y, 1/w
	fmov	fr4,@-r6	! slot +0 and +4: (w), then X
	bt.s	.Lspec_send	! none left: send and return
	mov.l	r7,@r6		! (delay slot) slot +0: the control word
	fmov	@r14+,fr4	! fr4, fr5 = the next vertex's x, y
	bra	.Lspec_vertex	! round again; its delay slot is the pref below
! 0c10bd86: sends the vertex: as the delay slot of the bra above, and as
! the start of the way out.
.Lspec_send:
	pref	@r6		! send the vertex
	add	#32,r6		! r6 = the next slot
	rts
	fschg			! (delay slot) single moves again
	nop			! padding (never run)
! 0c10bd90: the strip's last vertex; r0 = the word after the strip.
.Lspec_last:
	mov	r6,r7
	shar	r7		! r7 = the end-of-strip control word
	cmp/pl	r0		! T = the word is positive
	bf.s	.Lspec_run_ends	! not positive: the run is over
	fipr	fv12,fv0	! (delay slot) fr3 = N.L
	tst	#128,r0		! T = bit 7 clear
	fldi1	fr7
	bt	.Lspec_run_ends	! bit 7 clear: the run is over
! A further strip of the run: its count and its first record.
	mov.l	@r4+,r3		! r3 = its vertex count
	mov.l	@r4+,r0		! r0 = its first record's first word
	mov.l	@r4+,r14	! r14 = that record's second word
	tst	#1,r0
	fdiv	fr4,fr7		! fr7 = 1 / w of the vertex in hand
	bf	.Lspec_inline_lit	! bit 0 set: the record is a vertex
	bra	.Lspec_next_ref	! else a reference
	pref	@r4		! (delay slot) prefetch at the record after

! intensity_spill_strip_near_clip
!
! Sends one run of strips of a group that crosses the near limit,
! cutting each strip at the limit. Every vertex is loaded and lit by
! intensity_spill_vtx_load, which also says whether it is cut away
! ("out", T set). r9 collects those answers, the newest in bit 0, and
! r11 counts the strip's vertices; r11 & 3 is a vertex's slot in
! intensity_spill_clip_ring.
!   While the last two vertices were in, vertices are sent as they come
!   and are not kept (0c10bdd2). While the last two were out, vertices
!   are only transformed and tested (0c10bdee). In between, each new
!   vertex C is kept in the ring after its predecessors A and B, and
!   the three answers pick a case through the branch table at 0c10bf42
!   ("cut PQ" = the point where the edge from P to Q meets the near
!   limit, sent by intensity_spill_near_cut_emit):
!     1  A in,  B in,  C out   cut AC, B, cut BC
!     2  A in,  B out, C in    C, cut BC, C
!     3  A in,  B out, C out   cut AC, ending the strip; then testing
!     4  A out, B in,  C in    cut AC, B, C; then plain sending
!     5  A out, B in,  C out   cut BC
!     6  A out, B out, C in    cut AC, cut BC, C; when r11 is odd a cut
!                              BC goes first, which keeps the facing
!   Cases 0 and 7 cannot arrive: after case 4 and after case 3 the walk
!   leaves the table. When the walk enters the table from plain sending
!   or from testing, r4 is stepped back over the last records and they
!   are loaded again, because those two states keep nothing.
!   In a flat shaded run (r12 bit 0) the newest vertex's intensities are
!   copied over the two before it (intensity_spill_flat_copy) before a
!   case sends anything.
! The vertex count in r3 runs down as vertices are consumed; the piece
! sent for the last one carries the end-of-strip control word. After a
! strip, a positive word with bit 7 set starts a further strip of the
! same run.
!
! In:    r4 = the run's count word, r5 = list write pointer, r6 = its
!        store-queue address, r7 = near_inv bits, r8 = lighting
!        selector, r12 = near_limit bits with bit 0 = flat shaded,
!        r13 = &intensity_spill_params, fr12-fr15 and fr8-fr10 as for
!        intensity_spill_strip_send.
! Out:   r4 = the word after the run; r5 and r6 moved past what was
!        sent; r12 bit 0 set (the group loop's crosses-near flag).
! Uses:  r10, r11 and pr are saved and restored (the helpers use r10 for
!        the ring; r11 is the group loop's list index). r0-r3, r9, r14,
!        fr0-fr7 and fr11 are changed, r9 and r14 without being saved.
! Notes: T on entry (run bit 5 clear) is not read.
	.global	_intensity_spill_strip_near_clip
	.type	_intensity_spill_strip_near_clip,@function
_intensity_spill_strip_near_clip:
! 0c10bdb0: the entry (bsr from the group loop).
.Lstrip_near_clip:
	mov.l	r10,@-r15	! save r10, r11 and pr
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3		! r3 = the strip's vertex count
! 0c10bdb8: the start of a strip: its first two vertices.
.Lclip_strip_start:
	mov	#0,r11		! r11 = 0: the first vertex
	bsr	.Lvtx_load	! load and light the first vertex; T = out
	mov	#0,r9		! (delay slot) r9 = 0: no answers yet
	bt.s	.Lclip_first_out	! out: see what the second one is
	rotcl	r9		! (delay slot) the answer into r9
	bsr	.Lvtx_emit	! in: send it (counts r3)
	add	#1,r11		! (delay slot) r11 = 1
	bsr	.Lvtx_load	! the second vertex
	nop
	bt.s	.Lclip_in_out	! in then out: the strip is cut on its first edge
	rotcl	r9		! (delay slot) the answer into r9
	bsr	.Lvtx_emit	! in, in: send it
	add	#1,r11		! (delay slot) r11 = 2
! 0c10bdd2: plain sending. The last two vertices were in and have been
! sent; go on like that until a vertex is out.
.Lclip_plain:
	bsr	.Lvtx_load	! the next vertex; T = out
	nop
	bt.s	.Lclip_refill	! out: case 1, after reloading the two before it
	rotcl	r9		! (delay slot) the answer into r9
	bsr	.Lvtx_emit	! in: send it; T = that was the strip's last vertex
	add	#1,r11		! (delay slot) count it in r11
	bf	.Lclip_plain	! more vertices
	bt	.Lclip_strip_done	! the strip is finished
! 0c10bde2: the first vertex is out.
.Lclip_first_out:
	dt	r3		! count the first vertex
	add	#1,r11		! r11 = 1
	bsr	.Lvtx_load	! the second vertex; T = out
	dt	r3		! (delay slot) count it
	bf.s	.Lclip_out_in	! out then in: the strip starts with a cut
	rotcl	r9		! (delay slot) the answer into r9
! 0c10bdee: testing. The last two vertices were out; nothing can be
! drawn until a vertex is in. Vertices are only transformed here, one
! per turn. From 0c10be04 on, the record after the vertex in hand is
! looked at ahead: r4 is on that record, r14 becomes its vertex and r1
! its size.
.Lclip_scan:
	mov.l	@r4,r0		! r0 = the record's first word
	mov	r4,r14		! r14 = the record
	tst	#1,r0
	add	#32,r4		! r4 = past a 32-byte vertex
	bf.s	.Lclip_scan_xy	! bit 0 set: the record is the vertex
	fldi1	fr7		! (delay slot) w = 1.0
	add	#-24,r4		! a reference: r4 = its end
	mov.l	@(4,r14),r14	! its offset word
	add	r4,r14		! r14 = the vertex it refers to
! 0c10be00: r14 is on the vertex to test.
.Lclip_scan_xy:
	fmov	@r14+,fr4	! fr4 = x
	fmov	@r14+,fr5	! fr5 = y
! 0c10be04: transform the vertex in hand and look at the record after.
.Lclip_scan_next:
	fmov	@r14+,fr6	! fr6 = z
	mov	#32,r1		! r1 = 32: the size of the record after, if it is a vertex
	mov.l	@r4,r0		! r0 = that record's first word
	add	#32,r4
	pref	@r4		! prefetch 32 bytes on
	ftrv	xmtrx,fv4	! the vertex through the matrix: fr7 = minus its depth
	tst	#1,r0
	add	#-32,r4		! r4 back on the record after
	bf.s	.Lclip_scan_test	! bit 0 set: that record is a vertex
	mov	r4,r14		! (delay slot) r14 = that record
	mov	#8,r1		! a reference: its size is 8
	mov.l	@(4,r14),r14	! its offset word
	add	#8,r14
	add	r4,r14		! r14 = the vertex it refers to (record + 8 + offset)
! 0c10be20: the near test of the vertex in hand.
.Lclip_scan_test:
	flds	fr7,fpul	! fpul, then r0 = the bits of minus the depth
	sts	fpul,r0
	cmp/hi	r0,r12		! T = out: near_limit's bits are the higher unsigned word
	add	#1,r11		! count the vertex in r11
	bf.s	.Lclip_scan_found	! in: draw again from here
	rotcl	r9		! (delay slot) the answer into r9
	dt	r3		! out: count it off the strip
	fldi1	fr7		! w = 1.0 for the next one
	bt	.Lclip_strip_done	! the strip is finished
	add	r1,r4		! step over the record after: it is the vertex in hand now
	fmov	@r14+,fr4	! fr4 = its x
	bra	.Lclip_scan_next	! round again
	fmov	@r14+,fr5	! (delay slot) fr5 = its y
! 0c10be3a: the strip is finished; r4 is on the word after it.
.Lclip_strip_done:
	mov.l	@r4+,r0		! r0 = the word after the strip
	cmp/pl	r0		! T = it is positive
	bf.s	.Lclip_return	! not positive: the run is over
	tst	#128,r0		! (delay slot) T = bit 7 clear
	bf.s	.Lclip_strip_start	! bit 7 set: a further strip of this run
	mov.l	@r4+,r3		! (delay slot) r3 = its vertex count
	add	#-4,r4		! not a further strip: undo that read
! 0c10be48: the run is over: restore and return.
.Lclip_return:
	lds.l	@r15+,pr	! restore pr
	mov	#1,r0
	mov.l	@r15+,r11	! restore r11
	add	#-4,r4		! r4 = the word after the run
	mov.l	@r15+,r10	! restore r10
	rts
	or	r0,r12		! (delay slot) r12 bit 0 = 1 for the group loop
! 0c10be56: the strip's first vertex A was in (and is sent), the second,
! B, is out. Keep B in slot 1, load A again into slot 0 and send the cut
! AB; then go on in the table.
.Lclip_in_out:
	bsr	.Lvtx_keep	! keep B (r11 = 1)
	dt	r3		! (delay slot) count B
! Step r4 back over B's record and A's. The word before r4 is the last
! word of the record before: bit 0 clear = an 8-byte reference, set = a
! 32-byte vertex.
	add	#-8,r4		! back 8 bytes
	mov.l	@(4,r4),r0	! the last word of the record
	tst	#1,r0
	bt	.Lin_out_back_a	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10be64: now back over A's record.
.Lin_out_back_a:
	add	#-8,r4		! the same for A's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lin_out_reload	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10be6e: r4 is on A's record.
.Lin_out_reload:
	bsr	.Lvtx_load	! load A again
	nop
	bsr	.Lvtx_keep	! keep it ...
	mov	#0,r11		! (delay slot) ... in slot 0
	mov	#1,r11		! r11 = 1: B's slot, the far end of the edge
	clrt			! T clear: the cut does not end the strip
	bsr	.Lnear_cut_emit	! send the cut AB
	mov	#0,r0		! (delay slot) r0 = 0: A's slot
! Step forward over B's record: r4 is on it after the reload of A.
	mov.l	@r4,r0		! its first word
	tst	#1,r0
	add	#8,r4		! 8 bytes for a reference
	bt	.Lin_out_go	! bit 0 clear: a reference
	add	#24,r4		! a vertex: 24 bytes more
! 0c10be88: r4 is on the third record.
.Lin_out_go:
	bra	.Lclip_next	! on with the third vertex, in the table
	nop
! 0c10be8c: the first vertex A is out, the second, B, is in. Keep B in
! slot 1, load A again into slot 0, send the cut AB and then B.
.Lclip_out_in:
	bsr	.Lvtx_keep	! keep B ...
	mov	#1,r11		! (delay slot) ... in slot 1
	add	#-8,r4		! step r4 back over B's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lout_in_back_a	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10be9a: now back over A's record.
.Lout_in_back_a:
	add	#-8,r4		! and over A's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lout_in_reload	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10bea4: r4 is on A's record.
.Lout_in_reload:
	bsr	.Lvtx_load	! load A again
	nop
	bsr	.Lvtx_keep	! keep it ...
	mov	#0,r11		! (delay slot) ... in slot 0
	mov	#1,r11		! r11 = 1: B's slot
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut AB
	mov	#0,r0		! (delay slot) r0 = 0: A's slot
	clrt			! T clear: not the end of the strip
	bsr	.Lkept_vtx_emit	! send B from the ring
	mov	#1,r0		! (delay slot) r0 = 1: B's slot
	mov.l	@r4,r0		! step forward over B's record
	tst	#1,r0
	add	#8,r4
	bt	.Lout_in_go	! bit 0 clear: a reference
	add	#24,r4		! a vertex: 24 bytes more
! 0c10bec4: r4 is on the third record.
.Lout_in_go:
	bra	.Lclip_next	! on with the third vertex, in the table
	nop
! 0c10bec8: testing found a vertex C that is in. Step r4 back onto its
! record and load it in full (it was only transformed).
.Lclip_scan_found:
	add	#-8,r4		! back over C's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lscan_found_load	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10bed2: r4 is on C's record.
.Lscan_found_load:
	bsr	.Lvtx_load	! load and light C
	nop
! 0c10bed6: C is loaded and its two predecessors A and B are not in the
! ring: either both were sent plainly and C is out (case 1), or both
! were out and C is in (case 6). Keep C, step back three records, load
! and keep A and B, and step forward over C again.
.Lclip_refill:
	bsr	.Lvtx_keep	! keep C in slot r11
	nop
	add	#-8,r4		! back over C's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lrefill_back_b	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10bee4: then back over B's record.
.Lrefill_back_b:
	add	#-8,r4		! back over B's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lrefill_back_a	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10beee: then back over A's record.
.Lrefill_back_a:
	add	#-8,r4		! back over A's record
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lrefill_reload	! a reference: done
	add	#-24,r4		! a vertex: 24 bytes more
! 0c10bef8: r4 is on A's record: load and keep A and B.
.Lrefill_reload:
	bsr	.Lvtx_load	! load A again
	nop
	bsr	.Lvtx_keep	! keep it ...
	add	#-2,r11		! (delay slot) ... two slots before C's
	bsr	.Lvtx_load	! load B again
	nop
	bsr	.Lvtx_keep	! keep it ...
	add	#1,r11		! (delay slot) ... one slot before C's
	mov.l	@r4,r0		! step forward over C's record
	tst	#1,r0
	add	#8,r4
	bt	.Lrefill_done	! bit 0 clear: a reference
	add	#24,r4		! a vertex: 24 bytes more
! 0c10bf12: A, B and C are in the ring and r4 is past C's record.
.Lrefill_done:
	add	#1,r11		! r11 back on C's slot
	mov	r12,r0
	tst	#1,r0		! T = r12 bit 0 clear: not flat shaded
	bt.s	.Lclip_dispatch	! not flat: to the table
	mov	r9,r0		! (delay slot) r0 = the answers
	bsr	.Lflat_copy	! flat: C's intensities over A's and B's
	nop
	bra	.Lclip_dispatch	! to the table
	mov	r9,r0		! (delay slot) r0 = the answers
! 0c10bf24: clipping. The last two vertices are in the ring and one of
! them was out. Load the next vertex C, keep it and take its case.
.Lclip_next:
	bsr	.Lvtx_load	! load and light C; T = out
	add	#1,r11		! (delay slot) r11 = C's index
	bsr	.Lvtx_keep	! keep C in slot r11
	rotcl	r9		! (delay slot) the answer into r9
	mov	r12,r0
	tst	#1,r0		! T = r12 bit 0 clear: not flat shaded
	bt.s	.Lclip_dispatch	! not flat: to the table
	mov	r9,r0		! (delay slot) r0 = the answers
	bsr	.Lflat_copy	! flat: C's intensities over A's and B's
	nop
	mov	r9,r0		! r0 = the answers
! 0c10bf3a: branch on the last three answers (A, B, C in bits 2, 1, 0)
! into the table of two-instruction entries at 0c10bf42.
.Lclip_dispatch:
	and	#7,r0		! the last three answers
	shll2	r0		! 4 bytes per entry
	braf	r0		! to 0c10bf42 + 4 * case
	nop			! (delay slot)
	nop			! case 0 (in, in, in): cannot arrive; would fall into case 1
	nop
	bra	.Lcase_in_in_out	! case 1: in, in, out
	nop
	bra	.Lcase_in_out_in	! case 2: in, out, in
	nop
	bra	.Lcase_in_out_out	! case 3: in, out, out
	nop
	bra	.Lcase_out_in_in	! case 4: out, in, in
	nop
	bra	.Lcase_out_in_out	! case 5: out, in, out
	nop
	bra	.Lcase_out_out_in	! case 6: out, out, in
	nop
	nop			! case 7 (out, out, out): cannot arrive; would fall into case 1
	nop
! 0c10bf62: case 1. A and B are already sent. Send cut AC, B again and
! cut BC: with A and B before them they cover the part that stays.
.Lcase_in_in_out:
	mov	r11,r0		! r0 = C's slot ...
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut AC
	add	#-2,r0		! (delay slot) ... r0 = A's slot (r11 - 2)
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lkept_vtx_emit	! send B from the ring
	add	#-1,r0		! (delay slot) r0 = B's slot (r11 - 1)
	mov	r11,r0
	dt	r3		! count C; T = it was the strip's last vertex
	bsr	.Lnear_cut_emit	! send the cut BC, ending the strip on T
	add	#-1,r0		! (delay slot) r0 = B's slot
	bf	.Lclip_next	! more vertices: the next one
	bra	.Lclip_strip_done	! the strip is finished
	nop			! (delay slot)
! 0c10bf80: case 2. The cut AB was sent last. Send C, the cut BC and C
! again.
.Lcase_in_out_in:
	clrt			! T clear: not the end of the strip
	bsr	.Lkept_vtx_emit	! send C from the ring
	mov	r11,r0		! (delay slot) r0 = C's slot
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut BC
	add	#-1,r0		! (delay slot) r0 = B's slot
	dt	r3		! count C; T = it was the strip's last vertex
	bsr	.Lkept_vtx_emit	! send C again, ending the strip on T
	mov	r11,r0		! (delay slot) r0 = C's slot
	bf	.Lclip_next	! more vertices: the next one
	bra	.Lclip_strip_done	! the strip is finished
	nop			! (delay slot)
! 0c10bf9a: case 3. Close the piece with the cut AC, ending the strip,
! and go back to testing: the last two vertices are out.
.Lcase_in_out_out:
	mov	r11,r0
	sett			! T set: end of strip
	bsr	.Lnear_cut_emit	! send the cut AC
	add	#-2,r0		! (delay slot) r0 = A's slot
	dt	r3		! count C
	bt	.Lcase_strip_done	! the strip is finished
	bra	.Lclip_scan	! testing, from the vertex after C
	nop			! (delay slot)
! 0c10bfaa: case 4. Send the cut AC, B and C, and go back to plain
! sending: the last two vertices are in and sent.
.Lcase_out_in_in:
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut AC
	add	#-2,r0		! (delay slot) r0 = A's slot
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lkept_vtx_emit	! send B from the ring
	add	#-1,r0		! (delay slot) r0 = B's slot
	dt	r3		! count C; T = it was the strip's last vertex
	bsr	.Lkept_vtx_emit	! send C from the ring, ending the strip on T
	mov	r11,r0		! (delay slot) r0 = C's slot
	bt	.Lcase_strip_done	! the strip is finished
	bra	.Lclip_plain	! plain sending
	add	#1,r11		! (delay slot) r11 = the next vertex's index
! 0c10bfc6: where cases 3 and 4 go when the strip is finished.
.Lcase_strip_done:
	bra	.Lclip_strip_done	! the strip is finished (a relay to 0c10be3a)
	nop			! (delay slot)
! 0c10bfca: case 5. B was sent last; close the piece with the cut BC.
.Lcase_out_in_out:
	mov	r11,r0
	dt	r3		! count C; T = it was the strip's last vertex
	bsr	.Lnear_cut_emit	! send the cut BC, ending the strip on T
	add	#-1,r0		! (delay slot) r0 = B's slot
	bf	.Lclip_next	! more vertices: the next one
	bra	.Lclip_strip_done	! the strip is finished
	nop			! (delay slot)
! 0c10bfd8: case 6. A new piece starts with the two cuts and C. For an
! odd r11 a cut BC goes first, so that the piece's first triangle has
! the facing the strip's triangle had.
.Lcase_out_out_in:
	mov	r11,r0
	tst	#1,r0		! T = r11 is even
	bt	.Lcase_out_out_in_even	! even: no extra vertex
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut BC
	add	#-1,r0		! (delay slot) r0 = B's slot
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut AC
	add	#-2,r0		! (delay slot) r0 = A's slot
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut BC again
	add	#-1,r0		! (delay slot) r0 = B's slot
	bra	.Lcase_out_out_in_send	! then C
	nop			! (delay slot)
! 0c10bffa: an even r11: the two cuts only.
.Lcase_out_out_in_even:
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut AC
	add	#-2,r0		! (delay slot) r0 = A's slot
	mov	r11,r0
	clrt			! T clear: not the end of the strip
	bsr	.Lnear_cut_emit	! send the cut BC
	add	#-1,r0		! (delay slot) r0 = B's slot
! 0c10c00a: then C itself, for both.
.Lcase_out_out_in_send:
	dt	r3		! count C; T = it was the strip's last vertex
	bsr	.Lkept_vtx_emit	! send C from the ring, ending the strip on T
	mov	r11,r0		! (delay slot) r0 = C's slot
	bf	.Lclip_next	! more vertices: the next one
	bra	.Lclip_strip_done	! the strip is finished
	nop			! (delay slot, then padding)
	nop
	nop
	nop
	nop
	nop

! intensity_spill_vtx_load
!
! Fetches the vertex of the record at r4 (the vertex itself or a
! reference to one), transforms it, takes 1/w and lights it by r8 with
! the rules of intensity_spill_strip_send:
!   base   = ambient (fr15) + N.L when N.L is above 0; 1.0 when unlit
!   offset = 0 when unlit; k0 * (base + k1) when diffuse, when N.L is
!            not above 0, or when the index ftrc(N.H) is not above 309;
!            else row[index], plus k0 * (base + k1) if base + k1 is
!            above 0.
! Unlit is r8 odd when N.L is above 0 and r8 negative when it is not.
! The clippers call it for every vertex they send or keep.
!
! In:    r4 = the record, r8 = lighting selector, r12 = near_limit bits
!        (bit 0 a flag), r13 = &intensity_spill_params, fr12-fr15 =
!        light direction (y, z, x) and ambient, fr8-fr10 = specular
!        vector (y, z, x).
! Out:   r4 = the next record; r2 = &u, v of the vertex;
!        fr4 = minus the depth, fr5 = X * w, fr6 = Y * w, fr7 = 1/w,
!        fr2 = base intensity, fr3 = offset intensity;
!        T = the vertex is cut away (near_limit's bits are above the
!        bits of minus the depth, as unsigned words).
! Uses:  r0, r1, fr0, fr1 and fr11 are changed; no stack use. Single
!        moves throughout.
	.global	_intensity_spill_vtx_load
	.type	_intensity_spill_vtx_load,@function
_intensity_spill_vtx_load:
! 0c10c020: the entry (bsr from the two clippers).
.Lvtx_load:
	mov.l	@r4,r0		! r0 = the record's first word
	tst	#1,r0
	bf.s	.Lload_inline	! bit 0 set: the record is the vertex
	fmov	@r4+,fr4	! (delay slot) fr4 = that word: x, if it is the vertex
! A reference: the vertex is at its end plus its second word.
	mov.l	@r4+,r0		! r0 = the offset
	add	r4,r0		! r0 = the vertex
	fmov	@r0+,fr4	! fr4, fr5, fr6 = x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	fldi1	fr7		! w = 1.0
	fmov	@r0+,fr2	! fr2 = nx
	fmov	@r0+,fr0	! fr0 = ny
	ftrv	xmtrx,fv4	! through the matrix: w, X*w, Y*w, minus depth
	fmov	@r0+,fr1	! fr1 = nz
	fldi0	fr3		! fr3 = 0: the normal's fourth term
	add	#32,r4		! r4 = 32 past the next record, for the prefetch
	bra	.Lload_light
	mov	r0,r2		! (delay slot) r2 = &u, v
! 0c10c044: the record is the vertex.
.Lload_inline:
	fmov	@r4+,fr5	! fr5, fr6 = y, z
	fmov	@r4+,fr6
	fldi1	fr7		! w = 1.0
	fmov	@r4+,fr2	! fr2 = nx
	fmov	@r4+,fr0	! fr0 = ny
	ftrv	xmtrx,fv4	! through the matrix, as above
	fmov	@r4+,fr1	! fr1 = nz
	fldi0	fr3		! fr3 = 0: the normal's fourth term
	mov	r4,r2		! r2 = &u, v
	add	#40,r4		! r4 = 32 past the next record
! 0c10c058: the lighting. The normal is in fr0-fr3 as (ny, nz, nx, 0).
.Lload_light:
	fldi0	fr11		! fr11 = 0: the half vector's fourth term
	fipr	fv12,fv0	! fr3 = N.L
	pref	@r4		! prefetch 32 bytes past the next record
	add	#-32,r4		! r4 = the next record
	flds	fr7,fpul	! fpul = minus the depth
	sts	fpul,r0		! r0 = its bits, for the near test
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1 / w
	fsts	fpul,fr4	! fr4 = minus the depth, in place of w
	fcmp/gt	fr11,fr3	! T = N.L is above 0
	fipr	fv0,fv8		! fr11 = N.H
	fmov	fr15,fr2	! fr2 = the ambient term
	bf	.Lload_dark	! N.L not above 0
	fadd	fr3,fr2		! base = ambient + N.L
	mov	r13,r1
	fmov	@r1+,fr0	! fr0 = k0
	tst	r8,r8		! T = r8 is 0: diffuse
	fmov	@r1+,fr1	! fr1 = k1
	fldi0	fr3		! fr3 = 0
	bt.s	.Lload_ret_spill	! diffuse: the spill alone
	fadd	fr2,fr1		! (delay slot) fr1 = base + k1
	mov	#1,r1
	tst	r1,r8		! T = r8 is even
	bf.s	.Lload_unlit	! odd: unlit
	ftrc	fr11,fpul	! (delay slot) fpul = ftrc(N.H), the row index
	mov	#127,r1		! r1 = 127 ... 254 ... 309
	fldi0	fr3
	add	#127,r1
	sts	fpul,r0		! r0 = the index
	add	#55,r1
	cmp/gt	r1,r0		! T = the index is above 309
	shll2	r0		! r0 = the index as a byte offset
	bf	.Lload_spill_only	! no highlight: the spill alone
	mov.l	@(r0,r8),r0	! r0 = row[index], as bits
	fcmp/gt	fr3,fr1		! T = base + k1 is above 0
	lds	r0,fpul
	bf.s	.Lload_ret_spec	! not above 0: the highlight alone
	fsts	fpul,fr3	! (delay slot) fr3 = the highlight
	fmac	fr0,fr1,fr3	! offset = highlight + k0 * (base + k1)
! 0c10c0a6: the way out of the highlight path: r0 held the index, so
! the bits for the near test are fetched again.
.Lload_ret_spec:
	flds	fr4,fpul	! fpul, then r0 = the bits of minus the depth again
	sts	fpul,r0
	rts
	cmp/hi	r0,r12		! (delay slot) T = cut away
! 0c10c0ae: unlit: base 1.0, offset 0 (fr3 is 0 on both ways in).
.Lload_unlit:
	fldi1	fr2		! base = 1.0
	flds	fr4,fpul	! fpul, then r0 = the bits of minus the depth
	sts	fpul,r0
	rts
	cmp/hi	r0,r12		! (delay slot) T = cut away
! 0c10c0b8: N.L is not above 0: base = ambient, no highlight.
.Lload_dark:
	mov	r13,r1
	cmp/pz	r8		! T = r8 is not negative
	fldi0	fr3		! fr3 = 0
	bf	.Lload_unlit	! negative: unlit
	fmov	@r1+,fr0	! fr0 = k0
	flds	fr4,fpul	! fpul, then r0 = the bits of minus the depth
	sts	fpul,r0
	cmp/hi	r0,r12		! T = cut away
	fmov	@r1+,fr1	! fr1 = k1
	fadd	fr2,fr1		! fr1 = base + k1
	rts
	fmac	fr0,fr1,fr3	! (delay slot) offset = k0 * (base + k1)
! 0c10c0d0: specular with an index of 309 or below: the spill alone.
.Lload_spill_only:
	flds	fr4,fpul	! fpul, then r0 = the bits of minus the depth
	sts	fpul,r0
! 0c10c0d4: the diffuse path arrives with r0 still set at 0c10c062.
.Lload_ret_spill:
	cmp/hi	r0,r12		! T = cut away
	rts
	fmac	fr0,fr1,fr3	! (delay slot) offset = k0 * (base + k1), whatever its sign
	nop			! padding to the next 16-byte boundary (never run)
	nop
	nop

! intensity_spill_vtx_emit
!
! Sends the vertex intensity_spill_vtx_load left in the registers as a
! 32-byte vertex, and counts it off r3. When the count reaches 0 the
! vertex gets the end-of-strip control word.
!
! In:    fr5, fr6 = X * w, Y * w, fr7 = 1/w, fr2, fr3 = base and offset
!        intensity, r2 = &u, v, r3 = vertices left (this one included),
!        r5 = list write pointer, r6 = its store-queue address.
! Out:   r3 one less, r5 and r6 moved on 32 bytes;
!        T = the count reached 0 (the strip is finished).
! Uses:  r2, fr0, fr1, fr5 and fr6 are changed. Pair moves inside,
!        single moves again on return.
	.global	_intensity_spill_vtx_emit
	.type	_intensity_spill_vtx_emit,@function
_intensity_spill_vtx_emit:
! 0c10c0e0: the entry (bsr from the two clippers).
.Lvtx_emit:
	fschg			! pair moves
	add	#32,r6		! r6 = the end of the slot
	fmov	@r2,fr0		! fr0, fr1 = u, v
	fmul	fr7,fr6		! Y
	fmov	fr2,@-r6	! slot +24 and +28: base, offset
	fmul	fr7,fr5		! X
	fmov	fr0,@-r6	! slot +16 and +20: u, v
	mov	r6,r2		! r2 = a store-queue address for the control word
	fmov	fr6,@-r6	! slot +8 and +12: Y, 1/w
	dt	r3		! count the vertex
	fmov	fr4,@-r6	! slot +0 and +4: (minus depth), then X
	bt.s	.Lemit_last	! the last one of the strip
	fschg			! (delay slot) single moves again
	mov.l	r6,@r6		! slot +0: the control word, the slot's own address
	add	#32,r5		! the write pointer moves on 32 bytes
	pref	@r6		! send the vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next slot
! 0c10c104: the strip's last vertex.
.Lemit_last:
	shar	r2		! the end-of-strip control word
	mov.l	r2,@r6		! slot +0: the control word
	add	#32,r5		! the write pointer moves on 32 bytes
	sett			! T = 1 for the caller (shar changed it)
	pref	@r6		! send the vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next slot
	nop			! padding to the next 16-byte boundary (never run)
	nop
	nop
	nop
	nop
	nop
	nop

! intensity_spill_vtx_keep
!
! Stores the vertex intensity_spill_vtx_load left in the registers in
! slot r11 & 3 of intensity_spill_clip_ring. A slot is 32 bytes:
!   +0 minus the depth, +4 X * w, +8 Y * w, +12 1/w, +16 u, +20 v,
!   +24 base intensity, +28 offset intensity.
!
! In:    r11 = vertex index (its low two bits pick the slot), fr4-fr7 =
!        minus depth, X * w, Y * w, 1/w, fr2, fr3 = the intensities,
!        r2 = &u, v.
! Out:   nothing in registers; the slot is filled.
! Uses:  r0, r10, fr0 and fr1 are changed (r10 without being saved: the
!        clippers save it). T is kept. Pair moves inside.
	.global	_intensity_spill_vtx_keep
	.type	_intensity_spill_vtx_keep,@function
_intensity_spill_vtx_keep:
! 0c10c120: the entry (bsr from the two clippers).
.Lvtx_keep:
	mov	#5,r10		! r10 = 5: the shift for 32-byte slots
	mov	r11,r0
	and	#3,r0		! r0 = the slot number
	fschg			! pair moves
	shld	r10,r0		! r0 = the slot's offset
	mov.l	.Lclip_ring_slot_end,r10	! r10 = the ring + 32: the end of slot 0
	fmov	@r2,fr0		! fr0, fr1 = u, v
	add	r0,r10		! r10 = the end of the slot
	fmov	fr2,@-r10	! slot +24 and +28: base, offset
	fmov	fr0,@-r10	! slot +16 and +20: u, v
	fmov	fr6,@-r10	! slot +8: Y * w, 1/w
	fmov	fr4,@-r10	! slot +0: minus depth, X * w
	rts
	fschg			! (delay slot) single moves again
	nop			! padding (never run)
	nop

! intensity_spill_flat_copy
!
! For flat shaded runs: copies the intensity pair of ring slot r11 & 3
! (the newest vertex) into the two slots before it, so that every piece
! cut from the triangle those three vertices make has one intensity,
! that of its last vertex.
!
! In:    r11 = the newest vertex's index.
! Out:   nothing in registers; slots (r11 - 1) & 3 and (r11 - 2) & 3 of
!        intensity_spill_clip_ring have the newest slot's +24 and +28.
! Uses:  r0, r1, r2, r10, fr2 and fr3 are changed. T is kept. Pair
!        moves inside.
	.global	_intensity_spill_flat_copy
	.type	_intensity_spill_flat_copy,@function
_intensity_spill_flat_copy:
! 0c10c140: the entry (bsr from the two clippers).
.Lflat_copy:
	mov	#5,r1		! r1 = 5: the shift for 32-byte slots
	mov.l	.Lclip_ring_slot_end,r10	! r10 = the ring + 32: the end of slot 0
	mov	r11,r0
	and	#3,r0		! r0 = the newest slot's number
	mov	r10,r2		! r2 = the ring + 32 as well
	shld	r1,r0
	fschg			! pair moves
	add	r0,r10		! r10 = the end of the newest slot
	add	#-8,r10		! r10 = its intensity pair
	mov	r11,r0
	fmov	@r10,fr2	! fr2, fr3 = its base and offset
	add	#-1,r0		! the slot before ...
	mov	r2,r10		! r10 = the ring + 32 again
	and	#3,r0
	shld	r1,r0
	add	r0,r2		! ... r2 = its end
	mov	r11,r0
	fmov	fr2,@-r2	! its +24: base, offset
	add	#-2,r0		! and the slot two before ...
	and	#3,r0
	shld	r1,r0
	add	r0,r10		! ... r10 = its end
	fmov	fr2,@-r10	! its +24: base, offset
	rts
	fschg			! (delay slot) single moves again
	nop			! padding to the next 16-byte boundary (never run)
	nop
	nop
	nop
	nop
	nop
	nop

! intensity_spill_kept_vtx_emit
!
! Sends the vertex kept in slot r0 & 3 of intensity_spill_clip_ring as
! a 32-byte vertex: X and Y are the kept values times the kept 1/w.
!
! In:    r0 = the slot (low two bits), T = this vertex ends the strip,
!        r5 = list write pointer, r6 = its store-queue address.
! Out:   r5 and r6 moved on 32 bytes; T as it came in.
! Uses:  r0, r2, r10 and fr0-fr7 are changed. Pair moves inside.
	.global	_intensity_spill_kept_vtx_emit
	.type	_intensity_spill_kept_vtx_emit,@function
_intensity_spill_kept_vtx_emit:
! 0c10c180: the entry (bsr from the two clippers).
.Lkept_vtx_emit:
	and	#3,r0		! r0 = the slot number
	mov	#5,r2		! r2 = 5: the shift for 32-byte slots
	mov.l	.Lclip_ring,r10	! r10 = the ring
	shld	r2,r0
	fschg			! pair moves
	add	r0,r10		! r10 = the slot
	fmov	@r10+,fr0	! fr0, fr1 = minus depth, X * w
	fmov	@r10+,fr2	! fr2, fr3 = Y * w, 1/w
	add	#32,r6		! r6 = the end of the queue slot
	fmov	@r10+,fr4	! fr4, fr5 = u, v
	fmul	fr3,fr2		! Y
	fmov	@r10+,fr6	! fr6, fr7 = base, offset
	fmul	fr3,fr1		! X
	fmov	fr6,@-r6	! slot +24 and +28: base, offset
	mov	r6,r2		! r2 = a store-queue address for the control word
	fmov	fr4,@-r6	! slot +16 and +20: u, v
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	fr2,@-r6	! slot +8 and +12: Y, 1/w
	bf.s	.Lkept_send	! T clear: not the end of the strip
	fmov	fr0,@-r6	! (delay slot) slot +0 and +4: (minus depth), then X
	shar	r2		! the end-of-strip control word
	sett			! T = 1 again (shar changed it)
! 0c10c1ac: write the control word and send.
.Lkept_send:
	mov.l	r2,@r6		! slot +0: the control word
	fschg			! single moves again
	pref	@r6		! send the vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next slot
	nop			! padding to the next 16-byte boundary (never run)
	nop
	nop
	nop
	nop

! intensity_spill_near_cut_emit
!
! Sends the point where the edge between two kept vertices meets the
! near limit. With a = slot r0 & 3 and b = slot r11 & 3 of
! intensity_spill_clip_ring,
!     t = (near_limit - a.depth) / (b.depth - a.depth)
! on the kept minus-depth values, and every other value is
! a + t * (b - a): the two intensities, u, v, and X * w, Y * w. The
! point lies on the near limit, so its 1/w is near_inv (r7), and X and
! Y are the interpolated values times that.
!
! In:    r0 = slot of a, r11 = slot of b (low two bits each),
!        r12 = near_limit bits (its flag bit is too small to matter),
!        r7 = near_inv bits, T = this vertex ends the strip,
!        r5 = list write pointer, r6 = its store-queue address.
! Out:   r5 and r6 moved on 32 bytes; T as it came in.
! Uses:  r0, r2, r10 and fr0-fr5 are changed. Pair moves for the
!        intensities and u, v, single moves for the rest.
! Notes: the control word is 0xf0000000 for the end of a strip, else
!        the queue slot's address + 4.
	.global	_intensity_spill_near_cut_emit
	.type	_intensity_spill_near_cut_emit,@function
_intensity_spill_near_cut_emit:
! 0c10c1c0: the entry (bsr from the two clippers).
.Lnear_cut_emit:
	and	#3,r0		! r0 = a's slot number ...
	shll2	r0
	mov.l	.Lclip_ring,r10	! r10 = the ring
	shll2	r0
	add	r0,r0		! ... times 32
	mov	r10,r2		! r2 = the ring
	add	r0,r10		! r10 = slot a
	mov	r11,r0
	and	#3,r0		! b's slot number ...
	fmov	@r10,fr2	! fr2 = a's minus depth
	shll2	r0
	shll2	r0
	add	r0,r0		! ... times 32
	add	r0,r2		! r2 = slot b
	fmov	@r2,fr1		! fr1 = b's minus depth
	lds	r12,fpul
	fsts	fpul,fr0	! fr0 = near_limit
	fsub	fr2,fr0		! fr0 = near_limit - a
	add	#24,r10		! r10 = a's intensity pair
	fsub	fr2,fr1		! fr1 = b - a
	add	#24,r2		! r2 = b's intensity pair
	fdiv	fr1,fr0		! fr0 = t
	lds	r7,fpul
	fsts	fpul,fr1	! fr1 = near_inv: the cut's 1/w
	fschg			! pair moves
	fmov	@r2,fr4		! fr4, fr5 = b's base, offset
	add	#-8,r2		! r2 = b's u, v
	fmov	@r10,fr2	! fr2, fr3 = a's base, offset
	add	#-8,r10		! r10 = a's u, v
	fsub	fr2,fr4		! b - a, base
	fsub	fr3,fr5		! b - a, offset
	add	#32,r6		! r6 = the end of the queue slot
	fmac	fr0,fr4,fr2	! base at the cut
	fmac	fr0,fr5,fr3	! offset at the cut
	fmov	fr2,@-r6	! slot +24 and +28: base, offset
	fmov	@r2,fr4		! fr4, fr5 = b's u, v
	add	#-8,r2		! r2 = b's Y * w
	fmov	@r10,fr2	! fr2, fr3 = a's u, v
	add	#-8,r10		! r10 = a's Y * w
	fsub	fr2,fr4
	fsub	fr3,fr5
	fmac	fr0,fr4,fr2	! u at the cut
	fmac	fr0,fr5,fr3	! v at the cut
	fmov	fr2,@-r6	! slot +16 and +20: u, v
	fschg			! single moves again
	fmov	fr1,@-r6	! slot +12: 1/w = near_inv
	fmov	@r2,fr5		! fr5 = b's Y * w
	add	#-4,r2		! r2 = b's X * w
	fmov	@r10,fr3	! fr3 = a's Y * w
	add	#-4,r10		! r10 = a's X * w
	fmov	@r2,fr4		! fr4 = b's X * w
	fmov	@r10,fr2	! fr2 = a's X * w
	fsub	fr3,fr5		! the difference along the edge, for Y * w and for X * w
	fsub	fr2,fr4
	mov	#-16,r2		! r2 = -16, to become 0xf0000000
	fmac	fr0,fr5,fr3	! Y * w at the cut
	shll16	r2
	fmac	fr0,fr4,fr2	! X * w at the cut
	shll8	r2		! r2 = 0xf0000000: the end-of-strip control word
	fmul	fr1,fr3		! Y
	add	#32,r5		! the write pointer moves on 32 bytes
	fmul	fr1,fr2		! X
	fmov	fr3,@-r6	! slot +8: Y
	fmov	fr2,@-r6	! slot +4: X
	bt	.Lcut_control	! T set: the end of the strip
	mov	r6,r2		! else the control word is a store-queue address
! 0c10c244: r2 = the control word.
.Lcut_control:
	mov.l	r2,@-r6		! slot +0: the control word
	pref	@r6		! send the vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next slot
! Pool of the ring helpers above.
.Lclip_ring:
	.long	_intensity_spill_clip_ring
! intensity_spill_clip_ring + 32: the end of slot 0, from where
! intensity_spill_vtx_keep and intensity_spill_flat_copy store downwards
.Lclip_ring_slot_end:
	.long	_intensity_spill_clip_ring+32
! Padding to the next 16-byte boundary (never run).
	nop
	nop
	nop
	nop
	nop
	nop

! intensity_spill_tri_near_clip
!
! Sends one run of independent triangles of a group that crosses the
! near limit. For each triangle intensity_spill_tri_classify gives three
! bits (first vertex in bit 2, second in bit 1, third in bit 0; set =
! cut away):
!   0      all three in: loaded and sent as they are, a 3-vertex strip;
!   7      all three out: their records are stepped over;
!   else   the three are loaded and kept in ring slots 0, 1, 2 (with
!          intensity_spill_flat_copy after them in a flat shaded run)
!          and the branch table at 0c10c29e picks the piece to send,
!          as a strip of kept vertices (v0, v1, v2) and cuts
!          ("cut 01" = the edge v0-v1 at the near limit):
!     1  v2 out       v0, v1, cut 02, cut 12
!     2  v1 out       v0, cut 01, v2, cut 12
!     3  v1, v2 out   v0, cut 01, cut 02
!     4  v0 out       cut 01, v1, cut 02, v2
!     5  v0, v2 out   cut 01, v1, cut 12
!     6  v0, v1 out   cut 02, cut 12, v2
!   The last vertex of each piece carries the end-of-strip control word.
!
! In:    r4 = the run's count word (triangles); r5, r6, r7, r8, r12,
!        r13 and the fr registers as for
!        intensity_spill_strip_near_clip.
! Out:   r4 = the word after the run; r5 and r6 moved past what was
!        sent; r12 bit 0 set (the group loop's crosses-near flag).
! Uses:  r10, r11 and pr are saved and restored. r0-r3, r9, fr0-fr7 and
!        fr11 are changed, r9 without being saved.
! Notes: T on entry (run bit 5 clear) is not read.
	.global	_intensity_spill_tri_near_clip
	.type	_intensity_spill_tri_near_clip,@function
_intensity_spill_tri_near_clip:
! 0c10c260: the entry (bsr from the group loop).
.Ltri_near_clip:
	mov.l	r10,@-r15	! save r10, r11 and pr
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3		! r3 = the number of triangles
! 0c10c268: one triangle; r4 is on its first record.
.Ltri_clip_next:
	bsr	.Ltri_classify	! the three near tests into r9; r4 is kept
	mov	#0,r9		! (delay slot) r9 = 0 to start from
	mov	r9,r0
	cmp/eq	#0,r0		! 0: none is cut away
	bt	.Ltri_clip_all_in	! ... send the triangle whole
	cmp/eq	#7,r0		! 7: all are cut away
	bt	.Ltri_clip_all_out	! ... skip the triangle
! A triangle across the limit: load and keep its three vertices.
	bsr	.Lvtx_load	! load the first vertex
	mov	#0,r11		! (delay slot) slot 0
	bsr	.Lvtx_keep	! keep it
	nop
	bsr	.Lvtx_load	! load the second
	mov	#1,r11		! (delay slot) slot 1
	bsr	.Lvtx_keep	! keep it
	nop
	bsr	.Lvtx_load	! load the third
	mov	#2,r11		! (delay slot) slot 2
	bsr	.Lvtx_keep	! keep it
	nop
	mov	r12,r0
	tst	#1,r0		! T = r12 bit 0 clear: not flat shaded
	bt.s	.Ltri_clip_dispatch	! not flat: to the table
	shll2	r9		! (delay slot) r9 = 4 * the case
	bsr	.Lflat_copy	! flat: the third vertex's intensities over the others
	nop
! 0c10c29a: branch into the table of two-instruction entries at
! 0c10c29e.
.Ltri_clip_dispatch:
	braf	r9		! to 0c10c29e + 4 * case
	nop			! (delay slot)
	nop			! case 0: handled above; would fall into case 1
	nop
	bra	.Ltri_case_in_in_out	! case 1: the third vertex out
	nop
	bra	.Ltri_case_in_out_in	! case 2: the second out
	nop
	bra	.Ltri_case_in_out_out	! case 3: the second and third out
	nop
	bra	.Ltri_case_out_in_in	! case 4: the first out
	nop
	bra	.Ltri_case_out_in_out	! case 5: the first and third out
	nop
	bra	.Ltri_case_out_out_in	! case 6: the first and second out
	nop
	nop			! case 7: handled above; would fall into the count below
	nop
! 0c10c2be: the triangle is done.
.Ltri_clip_count:
	dt	r3		! count it
	bf	.Ltri_clip_next	! more triangles
	mov	#1,r0
	lds.l	@r15+,pr	! restore pr
	or	r0,r12		! r12 bit 0 = 1 for the group loop
	mov.l	@r15+,r11	! restore r11
	rts
	mov.l	@r15+,r10	! (delay slot) restore r10
! 0c10c2ce: nothing is cut away. Load and send the three vertices;
! intensity_spill_vtx_emit counts r3 = 3 down, so the third one ends
! the strip. The triangle count waits in r9.
.Ltri_clip_all_in:
	mov	r3,r9		! r9 = the triangle count
	bsr	.Lvtx_load	! load the first vertex
	mov	#3,r3		! (delay slot) r3 = 3 vertices to send
	bsr	.Lvtx_emit	! send it
	nop
	bsr	.Lvtx_load	! load and send the second
	nop
	bsr	.Lvtx_emit
	nop
	bsr	.Lvtx_load	! load and send the third: end of strip
	nop
	bsr	.Lvtx_emit
	nop
	bra	.Ltri_clip_count	! the triangle is done
	mov	r9,r3		! (delay slot) r3 = the triangle count again
! 0c10c2ec: everything is cut away. Step r4 over the three records: 8
! bytes for a reference (bit 0 of the first word clear), 32 for a
! vertex.
.Ltri_clip_all_out:
	mov.l	@r4,r0		! the first record's first word
	tst	#1,r0
	add	#8,r4		! 8 bytes for a reference
	bt	.Ltri_skip_second	! bit 0 clear: a reference
	add	#24,r4		! a vertex: 24 bytes more
! 0c10c2f6: over the second record.
.Ltri_skip_second:
	mov.l	@r4,r0		! the second record
	tst	#1,r0
	add	#8,r4
	bt	.Ltri_skip_third	! bit 0 clear: a reference
	add	#24,r4		! a vertex: 24 bytes more
! 0c10c300: over the third record.
.Ltri_skip_third:
	mov.l	@r4,r0		! the third record
	tst	#1,r0
	add	#8,r4
	bt	.Ltri_skip_done	! bit 0 clear: a reference
	add	#24,r4		! a vertex: 24 bytes more
! 0c10c30a: r4 is on the next triangle.
.Ltri_skip_done:
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot)
! 0c10c30e: case 1: v0, v1, cut 02, cut 12. In all six cases T is
! cleared before each piece but the last, and set before the last; the
! cut's ends are r0 and r11.
.Ltri_case_in_in_out:
	clrt			! T clear: not the end of the strip
	bsr	.Lkept_vtx_emit	! send v0 from the ring
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	bsr	.Lkept_vtx_emit	! send v1
	mov	#1,r0		! (delay slot) r0 = slot 1
	clrt
	mov	#2,r11		! r11 = slot 2: the far end of both cuts
	bsr	.Lnear_cut_emit	! send cut 02
	mov	#0,r0		! (delay slot) r0 = slot 0
	sett			! T set: the end of the strip
	bsr	.Lnear_cut_emit	! send cut 12
	mov	#1,r0		! (delay slot) r0 = slot 1
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot)
! 0c10c32c: case 2: v0, cut 01, v2, cut 12.
.Ltri_case_in_out_in:
	clrt
	bsr	.Lkept_vtx_emit	! send v0 from the ring
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	mov	#1,r11		! r11 = slot 1
	bsr	.Lnear_cut_emit	! send cut 01
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	mov	#2,r11		! r11 = slot 2, for the last cut
	bsr	.Lkept_vtx_emit	! send v2
	mov	#2,r0		! (delay slot) r0 = slot 2
	sett			! T set: the end of the strip
	bsr	.Lnear_cut_emit	! send cut 12
	mov	#1,r0		! (delay slot) r0 = slot 1
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot)
! 0c10c34c: case 3: v0, cut 01, cut 02.
.Ltri_case_in_out_out:
	clrt
	bsr	.Lkept_vtx_emit	! send v0 from the ring
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	mov	#1,r11		! r11 = slot 1
	bsr	.Lnear_cut_emit	! send cut 01
	mov	#0,r0		! (delay slot) r0 = slot 0
	sett			! T set: the end of the strip
	mov	#2,r11		! r11 = slot 2
	bsr	.Lnear_cut_emit	! send cut 02
	mov	#0,r0		! (delay slot) r0 = slot 0
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot)
! 0c10c366: case 4: cut 01, v1, cut 02, v2.
.Ltri_case_out_in_in:
	clrt
	mov	#1,r11		! r11 = slot 1
	bsr	.Lnear_cut_emit	! send cut 01
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	bsr	.Lkept_vtx_emit	! send v1 from the ring
	mov	#1,r0		! (delay slot) r0 = slot 1
	clrt
	mov	#2,r11		! r11 = slot 2
	bsr	.Lnear_cut_emit	! send cut 02
	mov	#0,r0		! (delay slot) r0 = slot 0
	sett			! T set: the end of the strip
	bsr	.Lkept_vtx_emit	! send v2
	mov	#2,r0		! (delay slot) r0 = slot 2
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot)
! 0c10c386: case 5: cut 01, v1, cut 12.
.Ltri_case_out_in_out:
	clrt
	mov	#1,r11		! r11 = slot 1
	bsr	.Lnear_cut_emit	! send cut 01
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	bsr	.Lkept_vtx_emit	! send v1 from the ring
	mov	#1,r0		! (delay slot) r0 = slot 1
	sett			! T set: the end of the strip
	mov	#2,r11		! r11 = slot 2
	bsr	.Lnear_cut_emit	! send cut 12
	mov	#1,r0		! (delay slot) r0 = slot 1
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot)
! 0c10c3a0: case 6: cut 02, cut 12, v2.
.Ltri_case_out_out_in:
	clrt
	mov	#2,r11		! r11 = slot 2: the far end of both cuts
	bsr	.Lnear_cut_emit	! send cut 02
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	bsr	.Lnear_cut_emit	! send cut 12
	mov	#1,r0		! (delay slot) r0 = slot 1
	sett			! T set: the end of the strip
	bsr	.Lkept_vtx_emit	! send v2 from the ring
	mov	#2,r0		! (delay slot) r0 = slot 2
	bra	.Ltri_clip_count	! the triangle is done
	nop			! (delay slot, then padding)
	nop
	nop
	nop
	nop

! intensity_spill_tri_classify
!
! The near tests of a triangle, before anything is lit: transforms the
! three vertices whose records start at r4 (positions only) and shifts
! one bit per vertex into r9, set when the vertex is cut away (the
! test of intensity_spill_vtx_load). The first vertex ends up in bit 2,
! the third in bit 0: with r9 = 0 on entry, 0 = all in and 7 = all out.
! The first and third go through fr4-fr7, the second through fr0-fr3,
! so the three transforms overlap.
!
! In:    r4 = the triangle's first record, r9 = 0 (earlier bits are
!        shifted up), r12 = near_limit bits (bit 0 a flag).
! Out:   r9 = (r9 << 3) | the three bits; r4 unchanged;
!        T = the third vertex's bit.
! Uses:  r0, r1 and fr0-fr7 are changed. Single moves throughout.
	.global	_intensity_spill_tri_classify
	.type	_intensity_spill_tri_classify,@function
_intensity_spill_tri_classify:
! 0c10c3c0: the entry (bsr from intensity_spill_tri_near_clip).
.Ltri_classify:
	mov	r4,r1		! r1 = r4, to put back at the end
	mov.l	@r4,r0		! the first record's first word
	tst	#1,r0
	bf.s	.Lclassify_first_inline	! bit 0 set: the record is the vertex
	fmov	@r4+,fr4	! (delay slot) fr4 = that word: x, if it is the vertex
	mov.l	@r4+,r0		! a reference: its offset
	add	r4,r0		! r0 = the vertex it refers to
	fmov	@r0+,fr4	! fr4, fr5, fr6 = x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Lclassify_second
	fldi1	fr7		! (delay slot) w = 1.0
! 0c10c3d8: the first record is the vertex.
.Lclassify_first_inline:
	fmov	@r4+,fr5	! fr5, fr6 = y, z of the vertex in the record
	fmov	@r4,fr6
	fldi1	fr7		! w = 1.0
	add	#24,r4		! r4 = the second record
! 0c10c3e0: the second vertex, into fr0-fr3.
.Lclassify_second:
	pref	@r4		! prefetch the second record and 32 bytes on
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv4	! first vertex through the matrix: fr7 = minus its depth
	mov.l	@r4,r0		! the second record's first word
	tst	#1,r0
	bf.s	.Lclassify_second_inline	! bit 0 set: the record is the vertex
	fmov	@r4+,fr0	! (delay slot) fr0 = that word: x, if it is the vertex
	mov.l	@r4+,r0		! a reference: its offset
	add	r4,r0		! r0 = the vertex it refers to
	fmov	@r0+,fr0	! fr0, fr1, fr2 = x, y, z
	fmov	@r0+,fr1
	fmov	@r0+,fr2
	bra	.Lclassify_third
	fldi1	fr3		! (delay slot) w = 1.0
! 0c10c400: the second record is the vertex.
.Lclassify_second_inline:
	fmov	@r4+,fr1	! fr1, fr2 = y, z of the vertex in the record
	fmov	@r4,fr2
	fldi1	fr3		! w = 1.0
	add	#24,r4		! r4 = the third record
! 0c10c408: the third vertex, into fr4-fr7 again.
.Lclassify_third:
	add	#32,r4
	pref	@r4		! prefetch 32 bytes past the third record's start
	add	#-32,r4
	ftrv	xmtrx,fv0	! second vertex through the matrix: fr3 = minus its depth
	mov.l	@r4,r0		! the third record's first word
	tst	#1,r0
	flds	fr7,fpul	! fpul = minus the first vertex's depth, before fr7 is reused
	bf.s	.Lclassify_third_inline	! bit 0 set: the record is the vertex
	fmov	@r4+,fr4	! (delay slot) fr4 = that word: x, if it is the vertex
	mov.l	@r4+,r0		! a reference: its offset
	add	r4,r0		! r0 = the vertex it refers to
	fmov	@r0+,fr4	! fr4, fr5, fr6 = x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Lclassify_tests
	fldi1	fr7		! (delay slot) w = 1.0
! 0c10c428: the third record is the vertex.
.Lclassify_third_inline:
	fmov	@r4+,fr5	! fr5, fr6 = y, z of the vertex in the record
	fmov	@r4,fr6
	fldi1	fr7		! w = 1.0
! 0c10c42e: the three tests: a vertex is cut away when near_limit's
! bits are above the bits of minus its depth, as unsigned words.
.Lclassify_tests:
	mov	r1,r4		! r4 = the first record again
	sts	fpul,r0		! r0 = the first vertex's bits
	ftrv	xmtrx,fv4	! third vertex through the matrix: fr7 = minus its depth
	cmp/hi	r0,r12		! T = the first vertex is cut away
	flds	fr3,fpul	! fpul = minus the second vertex's depth
	rotcl	r9		! the first answer into r9
	sts	fpul,r0
	cmp/hi	r0,r12		! T = the second vertex is cut away
	flds	fr7,fpul	! fpul = minus the third vertex's depth
	rotcl	r9		! the second answer into r9
	sts	fpul,r0
	cmp/hi	r0,r12		! T = the third vertex is cut away
	rts
	rotcl	r9		! (delay slot) the third answer into r9
	nop			! padding to the next 16-byte boundary (never run)
	nop
	nop

! intensity_spill_tri_send
!
! Sends one run of independent triangles that needs no clipping: the
! three loops of intensity_spill_strip_send (unlit at 0c10c460, diffuse
! at 0c10c566, specular) with the same lighting and the same A/B
! turns, counted differently. r9 = the number of triangles and r3
! counts three vertices for each; every third vertex gets the
! end-of-strip control word, so each triangle is a strip of its own.
! The run is over when r9 runs out; there are no further strips to
! look for. As in the strip loops the next record's two words are read
! before the count is tested, and r4 is put back at the end.
!
! In:    r4 = the run's count word (triangles), r5 = list write
!        pointer, r6 = its store-queue address, r8 = lighting selector,
!        r13 = &intensity_spill_params, fr12-fr15 = light direction
!        (y, z, x) and the ambient term, fr8-fr10 = half vector
!        (y, z, x) when r8 is a row address.
! Out:   r4 = the word after the run; r5 and r6 moved past the vertices
!        sent (32 bytes each).
! Uses:  r0-r3, r9, r14 and fr0-fr11 are changed (r9, r14 and fr8-fr11
!        without being saved); r7 too on the specular path. No stack
!        use.
! Notes: SZ is flipped to pair moves on entry and back before each rts.
!        The specular loop is not in this file: the branch at 0c10c45c
!        goes to 0x0c10c6cc, the first byte after the file (the label
!        .Ltri_specular at its end), and the loop runs to 0x0c10c7a9.
!        ghidra/symbols/elan_asm.tsv has it as a function of its own,
!        intensity_spill_tri_send_plain.
	.global	_intensity_spill_tri_send
	.type	_intensity_spill_tri_send,@function
_intensity_spill_tri_send:
! 0c10c450: the entry (bsr from the group loop). Pick the loop by r8.
.Ltri_send:
	tst	r8,r8		! T = r8 is 0: diffuse
	mov	r8,r0
	bf	.Ltri_not_diffuse	! not 0: unlit or specular
	bra	.Ltri_diffuse	! 0: the diffuse loop (its delay slot is the tst below)
! 0c10c458: also the delay slot of the bra above, where it does no harm.
.Ltri_not_diffuse:
	tst	#1,r0		! T = r8 is even: a row address
	bf	.Ltri_unlit	! odd: the unlit loop
	bra	.Ltri_specular	! even: the specular loop, at 0x0c10c6cc, past the end of this file
	nop			! (delay slot)
! 0c10c460: the unlit loop, as 0c10ba30: (1.0, 0) once into words 6-7
! of both store queues, then 24 bytes per vertex with r6 = slot + 24.
.Ltri_unlit:
	mov.l	@r4+,r9		! r9 = the number of triangles
	fldi1	fr2
	fschg			! pair moves
	fldi0	fr3		! fr2, fr3 = 1.0, 0: base and offset intensity
	mov	#3,r3		! r3 = 3 vertices in the first triangle
	fmov	fr2,@-r6	! words 6-7 of the other queue
	add	#32,r6		! r6 = slot + 24
	fmov	fr2,@r6		! words 6-7 of this queue
	mov.l	@r4,r0		! r0 = the first record's first word
	mov	r4,r14
	tst	#1,r0
	add	#32,r4		! r4 = past a 32-byte vertex
	bf	.Ltri_unlit_first	! bit 0 set: the record is the vertex
	mov.l	@(4,r14),r14	! a reference: its offset word
	add	#-24,r4
	add	r4,r14		! r14 = the vertex it refers to
! 0c10c480: r14 is on the first vertex.
.Ltri_unlit_first:
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	fmov	@r14,fr6	! fr6 = z
	add	#16,r14		! r14 = &u
	fldi1	fr7
	fmov	@r14,fr0	! fr0, fr1 = u, v
	ftrv	xmtrx,fv4	! the first vertex, as A, through the matrix
! 0c10c48c: A is transformed; fetch the next record as B.
.Ltri_unlit_a:
	fldi1	fr7
