!          term every vertex's base intensity starts from
!     +44  face base color, four floats (alpha, red, green, blue)
!     +60  face offset color, four floats (alpha, red, green, blue)
!     +76  byte count of the runs that follow (used to skip the group)
!     +80  the runs
!   A run is a positive run word, a count, and the vertex records. Run
!   word bits: 0-1 cull mode; 3 independent triangles (the count is
!   triangles, else vertices of one strip); 4 strip (read only when the
!   group is clipped); 6 Gouraud (clear = flat); 7 a further strip of the
!   same run, with no polygon header of its own (read only where a strip
!   ends). After the last run comes 0 (end of the object) or the next
!   group's control word (negative).
!   A vertex record is the vertex itself, 32 bytes:
!     +0 x, +4 y, +8 z, +12 nx, +16 ny, +20 nz, +24 u, +28 v
!   with bit 0 of the x word set, or an 8-byte reference: +0 a word with
!   bit 0 clear, +4 the offset from the end of the reference to a vertex.
!   (The clippers step backwards over records by testing bit 0 of the
!   word before r4, so a vertex's last word, v, has bit 0 set too.)
!
! The transform
!   XMTRX (the back bank) is loaded by the caller so that ftrv of
!   (x, y, z, 1) gives fr4 = w (the depth), fr5 = X * w, fr6 = Y * w and
!   fr7 = minus the depth, the value the near tests read. A point is cut
!   away when fr7 is above near_limit (header +0xc); the tests on single
