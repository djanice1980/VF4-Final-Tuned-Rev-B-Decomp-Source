	mov.l	@r4+,r1
	bra	.Lnext_group	! and loop
	fmov	@r4+,fr3	! (delay slot) fr3 = its texture word
! 0c10b910: a run. Build and send its polygon header from
! elan_group_header_words: the control word with the Gouraud bit (1)
! from run bit 6, the ISP word with the cull mode (bits 27-28) from run
! bits 0-1, the TSP and texture words as kept. The first header of a
! group with face colors is 64 bytes (the colors are already in the
! queue); the kept control word then gets bit 4 set, which makes the
! later headers of the group 32 bytes reusing those colors.
.Lrun_header:
	mov	r0,r1		! r1 = the run word
	mov	#-5,r2
	mov.l	@r9+,r3		! r3 = the kept control word; r9 = &header word 1
	and	#64,r0		! run bit 6 ...
	shld	r2,r0		! ... moved down to bit 1, the Gouraud bit
	mov	#-3,r2
	and	r2,r3		! the control word without its bit 1
	or	r3,r0		! r0 = this run's control word
	tst	#16,r0		! T = bit 4 clear: this header brings the face colors
	add	#32,r4		! r4 +32 for the prefetch below
	bf.s	.Lheader_cull	! bit 4 set: a 32-byte header
	lds	r0,fpul		! (delay slot) fpul = this run's control word
	or	#16,r0		! later headers of the group: bit 4 set
	mov	r9,r2
	mov.l	r0,@-r2		! written back to header word 0
! 0c10b92e: the cull mode. A negative control_or word (frame +40)
! flips its low bit (the facing).
.Lheader_cull:
	mov.l	@(40,r15),r2	! r2 = control_or
	movt	r3		! r3 = 1 when this header is the 64-byte one
	mov	r1,r0		! r0 = the run word
	cmp/pz	r2		! T = control_or is not negative
	mov	#27,r2
	bt.s	.Lheader_send
	and	#3,r0		! (delay slot) r0 = run bits 0-1: the cull mode
	xor	#1,r0		! negative: the other facing
! 0c10b93e: write the four words and send them.
.Lheader_send:
	shld	r2,r0		! the cull mode at bits 27-28
	cmp/pl	r3		! T = the 64-byte header (kept until the bf.s below)
	mov	#3,r3
	fschg			! pair moves
	shld	r2,r3		! r3 = 3 << 27: the cull field
	pref	@r4		! prefetch the run's first vertex data
	not	r3,r3
	mov.l	@r9+,r2		! r2 = the kept ISP word; r9 = &header word 2
	and	r3,r2		! without its cull field
	fsts	fpul,fr0	! fr0 = the control word
	or	r0,r2		! the ISP word with this run's cull mode
	lds	r2,fpul
	add	#-32,r4		! r4 back on the run's count word
	fsts	fpul,fr1	! fr1 = the ISP word
	add	#16,r6
	fmov	@r9+,fr2	! fr2, fr3 = the TSP and texture words
	fmov	fr2,@-r6	! header +8: TSP, texture
	add	#32,r5		! the write pointer moves on 32 bytes
	fmov	fr0,@-r6	! header +0: control, ISP
	fschg			! single moves again
	pref	@r6		! send the 32 bytes
	bf.s	.Lrun_body	! a 32-byte header: done
	add	#32,r6		! (delay slot) r6 = the next slot
	pref	@r6		! the 64-byte header: send the face colors too
	add	#32,r6
	add	#32,r5		! and count their 32 bytes
! 0c10b972: send the run's vertices. r12 bit 0 (the group crosses the
! near limit) picks the clipping senders; the bit is cleared here either
! way, and the clippers set it again before they return.
.Lrun_body:
	rotcr	r12		! T = r12 bit 0
	mov	r1,r0		! r0 = the run word
	bt.s	.Lrun_clipped	! the group crosses the near limit
