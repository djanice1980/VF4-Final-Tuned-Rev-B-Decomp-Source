! bump_tri_classify
!
! Tests the three vertices of a triangle against the near plane without
! loading the rest of them: only the three positions (at r4, r4 + 56,
! r4 + 112) are read and put through XMTRX, and each minus depth is
! compared with r12 as bump_vtx_load does. The three results are
! rotated into r9, vertex 0 first. Called (bsr) by bump_tri_near_clip.
!
! In:    r4 = the triangle's first record.
!        r9 = 0 (the caller clears it in the delay slot of the call).
!        r12 = the near value as raw float bits.
!        XMTRX = the transform; its fourth result is minus depth.
! Out:   r9 = the code: bit 2 = vertex 0 is behind the near plane,
!        bit 1 = vertex 1, bit 0 = vertex 2 (0 = all in front, 7 = all
!        behind). r4 as on entry. T = 0 (the bit rotated out of r9).
! Uses:  r0 and fr0-fr7 are changed; nothing else. No stack use.
! Notes: 32-bit fmov (FPSCR SZ = 0, PR = 0). Tests the near plane
!        only. The second transform runs in fr0-fr3 so that the first
!        result is still in fr7 when the third is started.
	.global	_bump_tri_classify
	.type	_bump_tri_classify,@function
_bump_tri_classify:
.Ltri_classify:				! 0c10d170
	fmov	@r4+,fr4		! fr4, fr5, fr6 = x, y, z of vertex 0
	fmov	@r4+,fr5
	fmov	@r4,fr6
	fldi1	fr7			! fr7 = 1: the point (x, y, z, 1)
	add	#48,r4			! r4 = vertex 1's record
	pref	@r4			! fetch its two cache lines
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv4		! fr7 = vertex 0's minus depth
	fmov	@r4+,fr0		! fr0, fr1, fr2 = x, y, z of vertex 1
	fmov	@r4+,fr1
	fmov	@r4,fr2
	fldi1	fr3
	add	#48,r4			! r4 = vertex 2's record
	pref	@r4			! fetch its two cache lines
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv0		! fr3 = vertex 1's minus depth
	flds	fr7,fpul
	sts	fpul,r0			! r0 = vertex 0's minus depth as raw bits
	fmov	@r4+,fr4		! fr4, fr5, fr6 = x, y, z of vertex 2
	fmov	@r4+,fr5
	fmov	@r4,fr6
	cmp/hi	r0,r12			! T = vertex 0 is behind the plane (r12 above the bits)
	fldi1	fr7
	add	#-120,r4		! r4 = the first record again (8 + 112 back)
	ftrv	xmtrx,fv4		! fr7 = vertex 2's minus depth
	rotcl	r9			! vertex 0's test into r9
	flds	fr3,fpul
	sts	fpul,r0			! r0 = vertex 1's minus depth as raw bits
	cmp/hi	r0,r12			! T = vertex 1 is behind the plane
	flds	fr7,fpul
	rotcl	r9			! vertex 1's test into r9
	sts	fpul,r0			! r0 = vertex 2's minus depth as raw bits
	cmp/hi	r0,r12			! T = vertex 2 is behind the plane
	rts
	rotcl	r9			! (delay slot) vertex 2's test into r9
