	shll16	r0
	fldi0	fr11			! fr11 = 0
	fcmp/gt	fr11,fr3		! T = N.L is above 0
	fmov	@r4+,fr1
	add	#32,r4			! r4 = record +80 ...
	fipr	fv12,fv8		! fr11 = L.T = t
	pref	@r4			! ... to fetch ahead in the records
	bt	.Lstrip_nl_ok		! lit from the front
	fldi0	fr3			! facing away: N.L counts as 0
! 0c10ca1e: fr3 = max(0, N.L), fr11 = t. Next b = L.B, the two absolute
! values, and the octant: r0 bit 0 = t negative, r0 bit 1 = |b| above
! |t|, r1 = 4 when b is negative.
.Lstrip_nl_ok:
	fmov	fr3,fr8
	fmul	fr8,fr8			! fr8 = N.L squared
	fldi1	fr9
	fipr	fv0,fv12		! fr15 = L.B = b (fr3's term is times fr15 = 0)
	fldi0	fr10
	fcmp/gt	fr11,fr10		! T = t is negative
	mov	r13,r2
	fsub	fr8,fr9			! fr9 = 1 - N.L squared
	extu.b	r2,r2			! r2 = the k byte of r13
	bf	.Lstrip_abs_t		! t is 0 or more
	fneg	fr11			! fr11 = |t|
.Lstrip_abs_t:				! 0c10ca34
	movt	r0			! r0 = 1 when t was negative
	fcmp/gt	fr15,fr10		! T = b is negative
	lds	r2,fpul			! the k byte waits in fpul
	fsqrt	fr9			! fr9 = sqrt(1 - N.L squared)
	bf	.Lstrip_abs_b		! b is 0 or more
	fneg	fr15			! fr15 = |b|
.Lstrip_abs_b:				! 0c10ca40
	movt	r1			! r1 = 1 when b was negative
	fcmp/gt	fr11,fr15		! T = |b| is above |t|
	fmov	fr15,fr10
	shll2	r1			! r1 = 4 when b was negative
	bf	.Lstrip_octant		! |t| is the larger: fr15 / fr11 is the ratio as they stand
	fmov	fr11,fr15		! |b| is the larger: swap, so fr11 = the larger, fr15 = the smaller
	or	#2,r0			! ... and note it in r0 bit 1
	fmov	fr10,fr11
! 0c10ca50: r1 = the octant, 0 to 7. Its halfword in the table at
! 0c10cb30 is twice the angle to start from, with bit 0 set when the
! table's arctangent is to be subtracted.
.Lstrip_octant:
	or	r0,r1			! r1 = the octant
	float	fpul,fr10		! fr10 = k * 255 as a float
	shll	r1			! r1 = the octant's offset in the halfword table
	mova	.Lstrip_octants,r0
	mov.w	@(r0,r1),r1		! r1 = the octant's halfword
	mova	.Lstrip_consts,r0	! r0 = &the constants at 0c10cb20
	fmov	@r0+,fr0		! fr0 = 128.0
	fdiv	fr11,fr15		! fr15 = smaller / larger: the tangent, 0 to 1
	shlr	r1			! T = subtract; r1 = the starting angle (0x00, 0x40, 0x80, 0xc0 or 0xff)
	fmov	@r0+,fr11		! fr11 = 0.5
	fmul	fr10,fr3		! fr3 = k * 255 * max(0, N.L)
	mov.l	@r0,r2			! r2 = the arctangent table (129 bytes at 0c12c86c)
! Put the four bytes together in r1, the K1 byte first.
	mov	r13,r0
	shlr16	r0
	fmul	fr10,fr9		! fr9 = k * 255 * sqrt(1 - N.L squared)
	shll16	r0			! r0 = the K1 byte at bits 24-31 (r13 without its low half)
	ftrc	fr3,fpul
	or	r0,r1			! r1 = K1 byte | the starting angle
	sts	fpul,r0			! r0 = k * 255 * N.L as an integer
	add	#32,r4			! r4 = record +112 ...
	ftrc	fr9,fpul
	pref	@r4			! ... to fetch further ahead
	shll16	r0
	add	r0,r1			! r1 += the N.L byte at bits 16-23
	sts	fpul,r0			! r0 = k * 255 * sqrt(...) as an integer
	add	#-64,r4			! r4 = record +48: u, v
	fmac	fr0,fr15,fr11		! fr11 = tangent * 128 + 0.5: the table index, rounded
	shll8	r0
	ftrc	fr11,fpul
	fldi0	fr15			! fr15 = 0 again, for the next vertex's dot products
	add	r0,r1			! r1 += the sqrt byte at bits 8-15
	sts	fpul,r0			! r0 = the index, 0 to 128
	and	#255,r0
	mov.b	@(r0,r2),r0		! r0 = the arctangent: 0 to 32, in 1/256ths of a turn
	bf	.Lstrip_angle		! T clear (from the shlr at 0c10ca60): add it
	neg	r0,r0			! T set: subtract it
! 0c10ca98: r0 = the offset word. Write the vertex downward from +28;
! r6 = the vertex's address + 32.
.Lstrip_angle:
	add	r1,r0			! r0 = the offset word: the angle now in bits 0-7
	mov.l	r0,@-r6			! vertex +28 = the offset word
	fschg				! pair moves (SZ = 1) for the two fmov stores below
	mov.l	@r4+,r1			! r1 = u (raw bits)
	fmul	fr7,fr6			! fr6 = Y = y / depth
	mov.l	@r4+,r2			! r2 = v (raw bits); r4 = the next record
	fmul	fr7,fr5			! fr5 = X = x / depth
	mov.l	r8,@-r6			! vertex +24 = the base color word
	mov	r0,r14			! r14 = the offset word (only the unreached code at 0c10cae2 reads r14)
	mov.l	r2,@-r6			! vertex +20 = v
	mov	r6,r0			! r0 = vertex +20 ...
	mov.l	r1,@-r6			! vertex +16 = u
	shar	r0			! ... >> 1: the end-of-strip control word
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	dt	r3			! T = this is the strip's last vertex
	fmov	fr4,@-r6		! vertex +0, +4 = depth, X
	bt.s	.Lstrip_last		! the last vertex
	fschg				! (delay slot) back to single moves (SZ = 0)
	mov.l	r6,@r6			! vertex +0 = the store-queue address: the plain control word
	add	#32,r5			! the vertex takes 32 bytes of the list
	pref	@r6			! send the 32 bytes to the list
	bra	.Lstrip_vertex		! on to the next vertex
	add	#64,r6			! (delay slot) r6 = the next vertex +32

! 0c10cac6: the strip's last vertex, then the word after the strip.
.Lstrip_last:
	mov.l	r0,@r6			! vertex +0 = the end-of-strip control word
	add	#32,r5			! the vertex takes 32 bytes of the list
	mov.l	@r4+,r0			! r0 = the word after the strip; r4 just past it
	pref	@r6			! send the 32 bytes to the list
	add	#64,r6			! r6 = the next vertex +32
	cmp/pl	r0
	bf.s	.Lstrip_done		! 0 or less: no more runs here
	tst	#128,r0			! (delay slot) T = bit 7 clear
	bf.s	.Lstrip_vertex		! bit 7 set: another strip under the same header
	mov.l	@r4+,r3			! (delay slot) r3 = its count, r4 = its first record
	add	#-4,r4			! a run with a header of its own: undo the count read
! 0c10cadc: leave r4 on the word just read, for the group sender.
.Lstrip_done:
	add	#-4,r4			! r4 = the next run word
	rts
	add	#-32,r6			! (delay slot) r6 = the store-queue address of what comes next

! 0c10cae2: not reached. Nothing in this file branches here and the code
! above ends in rts. It is a shorter end for a vertex: 1 / depth, r4
! moved on to u, v, and the vertex written with the offset word of the
! vertex before (r14) in place of a new one; then the same two exits
! as above. Whether anything was meant to use it is not established.
	fldi1	fr7			! fr7 = 1 / depth (with the fdiv below)
	add	#56,r4			! r4 = 56 bytes on, to fetch ahead
	fschg				! pair moves (SZ = 1)
	pref	@r4
	fdiv	fr4,fr7
	mov.l	r14,@-r6		! vertex +28 = the last vertex's offset word
	add	#32,r4			! r4 = 32 further on, for a second prefetch
	mov.l	r8,@-r6			! vertex +24 = the base color word
	fmul	fr7,fr6			! fr6 = Y = y / depth
	pref	@r4
	add	#-64,r4			! r4 = 24 on from where it began: u, v if that was record +24
	fmul	fr7,fr5			! fr5 = X = x / depth
	fmov	@r4+,fr0		! fr0, fr1 = u, v (one pair move)
	mov	r6,r0
	fmov	fr0,@-r6		! vertex +16, +20 = u, v
	shar	r0			! r0 = the end-of-strip control word
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	dt	r3			! T = the strip's last vertex
	fmov	fr4,@-r6		! vertex +0, +4 = depth, X
	bt.s	.Lstrip_last		! last: to the last-vertex exit above
	fschg				! (delay slot) back to single moves
	mov.l	r6,@r6			! vertex +0 = the plain control word
	add	#32,r5
	pref	@r6			! send the 32 bytes to the list
	bra	.Lstrip_vertex		! on to the next vertex
	add	#64,r6			! (delay slot) r6 = the next vertex +32
! Five nops of padding before the constants.
	nop
	nop
	nop
	nop
	nop
! 0c10cb20: constants of bump_strip_send, read in order through r0.
.Lstrip_consts:
	.long	0x43000000		! the float 128.0: tangent to table index
	.long	0x3f000000		! the float 0.5: rounds the index
	.long	_arctan_ang8_table		! the arctangent table: 129 bytes, atan(i / 128) in 1/256ths of a turn (0 to 32)
	.long	0x3f000000		! the float 0.5 again; not read
! 0c10cb30: the eight octant halfwords, indexed by (b negative) * 4 +
! (|b| above |t|) * 2 + (t negative). Each is twice the angle to start
! from, plus 1 when the arctangent is subtracted from it:
!   0  0x0000  0x00 + a      4  0x01ff  0xff - a
!   1  0x0101  0x80 - a      5  0x0100  0x80 + a
!   2  0x0081  0x40 - a      6  0x0180  0xc0 + a
!   3  0x0080  0x40 + a      7  0x0181  0xc0 - a
! (0x40 is a quarter turn; octant 4 starts from 0xff, not 0x100, so the
! byte cannot carry into the one above it.)
.Lstrip_octants:
	.long	0x01010000		! octants 0 and 1: the halfwords 0x0000 and 0x0101, written as one long
	.word	0x0081			! octant 2: from 0x40, subtract
	.word	0x0080			! octant 3: from 0x40, add
	.word	0x01ff			! octant 4: from 0xff, subtract
	.word	0x0100			! octant 5: from 0x80, add
	.word	0x0180			! octant 6: from 0xc0, add
	.word	0x0181			! octant 7: from 0xc0, subtract

! bump_tri_send
!
! Sends one run of independent triangles of a bump-mapped group that
! does not cross the near plane. Called (bsr) by bump_group_send only,
! after the polygon header has gone out. It is bump_strip_send with
! the count in triangles: the per-vertex code from 0c10cb46 is that
! routine's from 0c10c9e4, instruction for instruction (with its own
! copy of the constants), and every third vertex gets the end-of-strip
! control word, so each triangle goes out as a strip of three. See
! bump_strip_send for the 56-byte record, the 32-byte vertex written
! and how the offset word is made.
!
! In:    r4 = the run's count word (triangles); three records a
!        triangle follow it.
!        r5 = the list's write address; r6 = the store-queue address
!        of the first vertex.
!        r8 = the base color word; r13 = the K1 and k bytes; fr12-fr14
!        = the light direction; XMTRX = the transform (all as for
!        bump_strip_send).
! Out:   r4 = just past the last triangle: the next run word (this
!        routine does not look at it).
!        r5 and r6 moved on 32 bytes for each vertex.
! Uses:  not the compiled code's convention: r9 (the triangle count),
!        r14, fr8-fr11 and fr15 (left 0) are changed without being
!        saved here, as are r0-r3 and fr0-fr7. r7, r8, r10-r13 and
!        fr12-fr14 are not changed. No stack use.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0, PR = 0); pair
!        moves only between the two fschg of the vertex write. A
!        count of 0 is not expected. As in bump_strip_send, a second
!        vertex tail that nothing branches to follows the return
!        (0c10cc3a).
	.global	_bump_tri_send
	.type	_bump_tri_send,@function
_bump_tri_send:
.Ltri_send:				! 0c10cb40
	mov.l	@r4+,r9			! r9 = the number of triangles; r4 = the first record
	add	#32,r6			! r6 = the vertex's address + 32, kept so through the loop
	mov	#3,r3			! r3 = the vertices left in the triangle

! 0c10cb46: per vertex, as bump_strip_send at 0c10c9e4. r4 = its record.
.Ltri_vertex:
	fmov	@r4+,fr4		! fr4, fr5, fr6 = x, y, z
	fmov	@r4+,fr5
	fmov	@r4+,fr6
	fldi1	fr7			! fr7 = 1: the point (x, y, z, 1)
	fmov	@r4+,fr2		! fr2, fr0, fr1 = N: first, second, third component
	fmov	@r4+,fr0
	fmov	@r4+,fr1
	ftrv	xmtrx,fv4		! fr4 = depth, fr5 = x, fr6 = y after the transform
	fldi0	fr3			! fr3 = 0: no fourth term in N.L
	fmov	@r4+,fr10		! fr10, fr8, fr9 = T: first, second, third component
	mov	r13,r0			! r0 = r13 without its low half (here and at 0c10cb6e); made again at 0c10cbca
	fmov	@r4+,fr8
	shlr16	r0
	fmov	@r4+,fr9
	fipr	fv12,fv0		! fr3 = N.L (fr15's term is times fr3 = 0)
	fmov	@r4+,fr2		! fr2, fr0, fr1 = B: first, second, third component (N is done with)
	fsub	fr15,fr15		! fr15 = 0: no fourth term in the next two dot products
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth
	fmov	@r4+,fr0
	shll16	r0
	fldi0	fr11			! fr11 = 0
	fcmp/gt	fr11,fr3		! T = N.L is above 0
	fmov	@r4+,fr1
	add	#32,r4			! r4 = record +80 ...
	fipr	fv12,fv8		! fr11 = L.T = t
	pref	@r4			! ... to fetch ahead in the records
	bt	.Ltri_nl_ok		! lit from the front
	fldi0	fr3			! facing away: N.L counts as 0
! 0c10cb80: fr3 = max(0, N.L), fr11 = t = L.T. Next b = L.B, the absolute
! values and the octant.
.Ltri_nl_ok:
	fmov	fr3,fr8
	fmul	fr8,fr8			! fr8 = N.L squared
	fldi1	fr9
	fipr	fv0,fv12		! fr15 = L.B = b (fr3's term is times fr15 = 0)
	fldi0	fr10
	fcmp/gt	fr11,fr10		! T = t is negative
	mov	r13,r2
	fsub	fr8,fr9			! fr9 = 1 - N.L squared
	extu.b	r2,r2			! r2 = the k byte of r13
	bf	.Ltri_abs_t		! t is 0 or more
	fneg	fr11			! fr11 = |t|
.Ltri_abs_t:				! 0c10cb96
	movt	r0			! r0 = 1 when t was negative
	fcmp/gt	fr15,fr10		! T = b is negative
	lds	r2,fpul			! the k byte waits in fpul
	fsqrt	fr9			! fr9 = sqrt(1 - N.L squared)
	bf	.Ltri_abs_b		! b is 0 or more
	fneg	fr15			! fr15 = |b|
.Ltri_abs_b:				! 0c10cba2
	movt	r1			! r1 = 1 when b was negative
	fcmp/gt	fr11,fr15		! T = |b| is above |t|
	fmov	fr15,fr10
	shll2	r1			! r1 = 4 when b was negative
	bf	.Ltri_octant		! |t| is the larger: fr15 / fr11 is the ratio as they stand
	fmov	fr11,fr15		! |b| is the larger: swap, so fr11 = the larger, fr15 = the smaller
	or	#2,r0			! ... and note it in r0 bit 1
	fmov	fr10,fr11
! 0c10cbb2: r1 = the octant; its halfword (0c10cc80) gives the starting
! angle and whether the arctangent is added or subtracted.
.Ltri_octant:
	or	r0,r1			! r1 = the octant
	float	fpul,fr10		! fr10 = k * 255 as a float
	shll	r1			! r1 = the octant's offset in the halfword table
	mova	.Ltri_octants,r0
	mov.w	@(r0,r1),r1		! r1 = the octant's halfword
	mova	.Ltri_consts,r0		! r0 = &the constants at 0c10cc70
	fmov	@r0+,fr0		! fr0 = 128.0
	fdiv	fr11,fr15		! fr15 = smaller / larger: the tangent, 0 to 1
	shlr	r1			! T = subtract; r1 = the starting angle (0x00, 0x40, 0x80, 0xc0 or 0xff)
	fmov	@r0+,fr11		! fr11 = 0.5
	fmul	fr10,fr3		! fr3 = k * 255 * max(0, N.L)
	mov.l	@r0,r2			! r2 = the arctangent table (129 bytes at 0c12c86c)
! Put the four bytes of the offset word together in r1.
	mov	r13,r0
	shlr16	r0
	fmul	fr10,fr9		! fr9 = k * 255 * sqrt(1 - N.L squared)
	shll16	r0			! r0 = the K1 byte at bits 24-31 (r13 without its low half)
	ftrc	fr3,fpul
	or	r0,r1			! r1 = K1 byte | the starting angle
	sts	fpul,r0			! r0 = k * 255 * N.L as an integer
	add	#32,r4			! r4 = record +112 ...
	ftrc	fr9,fpul
	pref	@r4			! ... to fetch further ahead
	shll16	r0
	add	r0,r1			! r1 += the N.L byte at bits 16-23
	sts	fpul,r0			! r0 = k * 255 * sqrt(...) as an integer
	add	#-64,r4			! r4 = record +48: u, v
	fmac	fr0,fr15,fr11		! fr11 = tangent * 128 + 0.5: the table index, rounded
	shll8	r0
	ftrc	fr11,fpul
	fldi0	fr15			! fr15 = 0 again, for the next vertex's dot products
	add	r0,r1			! r1 += the sqrt byte at bits 8-15
	sts	fpul,r0			! r0 = the index, 0 to 128
	and	#255,r0
	mov.b	@(r0,r2),r0		! r0 = the arctangent: 0 to 32, in 1/256ths of a turn
	bf	.Ltri_angle		! T clear (from the shlr at 0c10cbc2): add it
	neg	r0,r0			! T set: subtract it
! 0c10cbfa: r0 = the offset word. Write the vertex downward from +28.
.Ltri_angle:
	add	r1,r0			! r0 = the offset word: the angle now in bits 0-7
	mov.l	r0,@-r6			! vertex +28 = the offset word
	fschg				! pair moves (SZ = 1) for the two fmov stores below
	mov.l	@r4+,r1			! r1 = u (raw bits)
	fmul	fr7,fr6			! fr6 = Y = y / depth
	mov.l	@r4+,r2			! r2 = v (raw bits); r4 = the next record
	fmul	fr7,fr5			! fr5 = X = x / depth
	mov.l	r8,@-r6			! vertex +24 = the base color word
	mov	r0,r14			! r14 = the offset word (only the unreached code at 0c10cc3a reads r14)
	mov.l	r2,@-r6			! vertex +20 = v
	mov	r6,r0			! r0 = vertex +20 ...
	mov.l	r1,@-r6			! vertex +16 = u
	shar	r0			! ... >> 1: the end-of-strip control word
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	dt	r3			! T = this is the triangle's third vertex
	fmov	fr4,@-r6		! vertex +0, +4 = depth, X
	bt.s	.Ltri_third		! the third vertex
	fschg				! (delay slot) back to single moves (SZ = 0)
	mov.l	r6,@r6			! vertex +0 = the store-queue address: the plain control word
	add	#32,r5			! the vertex takes 32 bytes of the list
	pref	@r6			! send the 32 bytes to the list
	bra	.Ltri_vertex		! on to the next vertex
	add	#64,r6			! (delay slot) r6 = the next vertex +32

! 0c10cc28: a triangle's third vertex: it ends the strip of three.
.Ltri_third:
	add	#32,r5			! the vertex takes 32 bytes of the list
	mov.l	r0,@r6			! vertex +0 = the end-of-strip control word
	dt	r9			! T = that was the run's last triangle
	pref	@r6			! send the 32 bytes to the list
	add	#64,r6			! r6 = the next vertex +32
	bf.s	.Ltri_vertex		! more triangles
	mov	#3,r3			! (delay slot) r3 = three vertices again
	rts
	add	#-32,r6			! (delay slot) r6 = the store-queue address of what comes next

! 0c10cc3a: not reached, as its twin at 0c10cae2 in bump_strip_send: a
! vertex end that reuses the offset word of the vertex before (r14).
! Nothing in this file branches here.
	fldi1	fr7			! fr7 = 1 / depth (with the fdiv below)
	add	#56,r4			! r4 = 56 bytes on, to fetch ahead
	fschg				! pair moves (SZ = 1)
	pref	@r4
	fdiv	fr4,fr7
	mov.l	r14,@-r6		! vertex +28 = the last vertex's offset word
	add	#32,r4			! r4 = 32 further on, for a second prefetch
	mov.l	r8,@-r6			! vertex +24 = the base color word
	fmul	fr7,fr6			! fr6 = Y = y / depth
	pref	@r4
	add	#-64,r4			! r4 = 24 on from where it began: u, v if that was record +24
	fmul	fr7,fr5			! fr5 = X = x / depth
	fmov	@r4+,fr0		! fr0, fr1 = u, v (one pair move)
	mov	r6,r0
	fmov	fr0,@-r6		! vertex +16, +20 = u, v
	shar	r0			! r0 = the end-of-strip control word
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	dt	r3			! T = the triangle's third vertex
	fmov	fr4,@-r6		! vertex +0, +4 = depth, X
	bt.s	.Ltri_third		! third: to the third-vertex exit above
	fschg				! (delay slot) back to single moves
	mov.l	r6,@r6			! vertex +0 = the plain control word
	add	#32,r5
	pref	@r6			! send the 32 bytes to the list
	bra	.Ltri_vertex		! on to the next vertex
	add	#64,r6			! (delay slot) r6 = the next vertex +32
	nop				! padding before the constants
! 0c10cc70: constants of bump_tri_send, a copy of those at 0c10cb20.
.Ltri_consts:
	.long	0x43000000		! the float 128.0: tangent to table index
	.long	0x3f000000		! the float 0.5: rounds the index
	.long	_arctan_ang8_table		! the arctangent table: 129 bytes, atan(i / 128) in 1/256ths of a turn (0 to 32)
	.long	0x3f000000		! the float 0.5 again; not read
! 0c10cc80: the eight octant halfwords, a copy of those at 0c10cb30
! (explained there).
.Ltri_octants:
	.long	0x01010000		! octants 0 and 1: the halfwords 0x0000 and 0x0101, written as one long
	.word	0x0081			! octant 2: from 0x40, subtract
	.word	0x0080			! octant 3: from 0x40, add
	.word	0x01ff			! octant 4: from 0xff, subtract
	.word	0x0100			! octant 5: from 0x80, add
	.word	0x0180			! octant 6: from 0xc0, add
	.word	0x0181			! octant 7: from 0xc0, subtract

! bump_strip_near_clip
!
! Sends one strip run of a bump-mapped group that crosses the near plane
! (and any strips that follow it under the same polygon header),
! cutting it at the plane: only the part in front goes to the list.
! Called (bsr) by bump_group_send only. The run is a count and then
! 56-byte records, as for bump_strip_send.
!
! How the walk works. bump_vtx_load loads each vertex and tests it
! against the near plane (T = behind it); the result is rotated into
! r9, so that r9 bits 2, 1, 0 are the tests of the vertex two back, the
! one before and the current one. r11 counts the vertices of the
! strip; r11 & 3 is the current vertex's slot in the clip ring at
! 0c10c8d0 (four slots that hold the last vertices loaded).
!   - While every vertex is in front (0c10ccb2) each is sent as loaded.
!   - While every vertex is behind (0c10ccd0) each is loaded and
!     tested, and nothing is sent.
!   - When the side changes, the walk steps back in the records, loads
!     the last three vertices into their ring slots (0c10cd2e) and from
!     then on keeps every vertex it loads (0c10cd4c). After each one a
!     jump table on r9 & 7 (0c10cd5e, cases 1-6) sends what the newest
!     triangle adds: kept vertices and points where its edges cross the
!     plane. Cases 3 and 4 hand back to the two simple loops.
! r3 counts the vertices left; the vertex that brings it to 0 goes out
! with the end-of-strip control word. The next word is then looked at
! as in bump_strip_send: positive with bit 7 set, another strip
! follows; otherwise the routine returns with r4 on that word.
!
! In:    r4 = the run's count word; the records follow it.
!        r5 = the list's write address; r6 = the store-queue address of
!        the next vertex.
!        r12 = the near value as raw float bits (in the terms of minus
!        depth; its bit 0 is not read here).
!        r7 = the 1/w for points on the near plane (raw float bits).
!        r8, r13, fr12-fr14 = the base color word, the K1 and k bytes
!        and the light direction, as for bump_strip_send.
!        XMTRX = the transform; its fourth result is minus depth.
! Out:   r4 = the word after the last strip walked (the next run word).
!        r5 and r6 moved on 32 bytes for each vertex sent.
!        r12 bit 0 set (for the group sender: the group crosses the
!        near plane).
! Uses:  r10, r11 and pr are saved and restored. Not the compiled
!        code's convention otherwise: r9, fr8-fr11 and fr15 are
!        changed and not saved here, as are r0-r3 and fr0-fr7; r7, r8,
!        r13 and fr12-fr14 are not changed.
! Notes: runs with 32-bit fmov (FPSCR SZ = 0, PR = 0); the helpers
!        that write vertices switch to pair moves and back. Strips are
!        taken to have at least three vertices (the first two are not
!        checked against the count). Cases 0 and 7 of the jump table
!        (three in front, three behind) do not arise where the table
!        is used; their entries are two nops that run on into the next
!        entry or into case 1.
	.global	_bump_strip_near_clip
	.type	_bump_strip_near_clip,@function
_bump_strip_near_clip:
.Lstrip_near_clip:			! 0c10cc90
	mov.l	r10,@-r15
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3			! r3 = the number of vertices; r4 = the first record

! 0c10cc98: start of a strip. The first two vertices decide how it opens.
.Lclip_strip_start:
	mov	#0,r11			! r11 = 0: vertex 0, ring slot 0
	bsr	.Lvtx_load		! load vertex 0; T = it is behind the near plane
	mov	#0,r9			! (delay slot) r9 = 0: no tests yet
	bt.s	.Lclip_first_behind	! vertex 0 behind
	rotcl	r9			! (delay slot) its test into r9
	bsr	.Lvtx_emit		! vertex 0 in front: send it
	add	#1,r11			! (delay slot) r11 = 1
	bsr	.Lvtx_load		! load vertex 1
	nop
	bt.s	.Lclip_second_behind	! in front, then behind
	rotcl	r9			! (delay slot) its test into r9
	bsr	.Lvtx_emit		! both in front: send vertex 1
	add	#1,r11			! (delay slot) r11 = 2
! 0c10ccb2: the run of vertices in front. Each is sent as it is loaded.
.Lclip_front_loop:
	bsr	.Lvtx_load		! load the next vertex
	nop
	bt.s	.Lclip_crossing		! behind: the strip crosses the plane here
	rotcl	r9			! (delay slot) its test into r9
	bsr	.Lvtx_emit		! in front: send it; T = it was the strip's last
	add	#1,r11			! (delay slot) r11 = the next vertex
	bf	.Lclip_front_loop	! more vertices
	bra	.Lclip_run_end		! the strip is done
	nop

! 0c10ccc4: vertex 0 is behind the plane.
.Lclip_first_behind:
	dt	r3			! count vertex 0
	add	#1,r11			! r11 = 1
	bsr	.Lvtx_load		! load vertex 1
	dt	r3			! (delay slot) count vertex 1
	bf.s	.Lclip_second_front	! behind, then in front
	rotcl	r9			! (delay slot) its test into r9
! 0c10ccd0: the run of vertices behind the plane: loaded and tested, not
! sent or kept.
.Lclip_behind_loop:
	bsr	.Lvtx_load		! load the next vertex
	add	#1,r11			! (delay slot) r11 = this vertex
	bf.s	.Lclip_crossing		! in front: the strip comes out from behind
	rotcl	r9			! (delay slot) its test into r9
	dt	r3			! still behind: count it; T = it was the last
	bf	.Lclip_behind_loop	! more vertices

! 0c10ccdc: the strip is finished. Look at the word after it.
.Lclip_run_end:
	mov.l	@r4+,r0			! r0 = that word; r4 just past it
	cmp/pl	r0
	bf.s	.Lclip_done		! 0 or less: no more runs here
	tst	#128,r0			! (delay slot) T = bit 7 clear
	bf.s	.Lclip_strip_start	! bit 7 set: another strip under the same header
	mov.l	@r4+,r3			! (delay slot) r3 = its count, r4 = its first record
	add	#-4,r4			! a run with a header of its own: undo the count read
! 0c10ccea: return with r4 on the word just read and r12 bit 0 set.
.Lclip_done:
	lds.l	@r15+,pr
	mov.l	@r15+,r11
	mov	#1,r0
	mov.l	@r15+,r10
	add	#-4,r4			! r4 = the next run word
	rts
	or	r0,r12			! (delay slot) r12 bit 0 = 1: the group crosses the near plane

! 0c10ccf8: vertex 0 in front (already sent), vertex 1 behind. Keep both
! and send the point where the edge between them crosses the plane.
.Lclip_second_behind:
	bsr	.Lvtx_keep		! keep vertex 1 in slot 1
	dt	r3			! (delay slot) count vertex 1
	bsr	.Lvtx_load		! load vertex 0 again ...
	add	#-112,r4		! (delay slot) ... r4 = two records (112 bytes) back
	bsr	.Lvtx_keep		! keep it in slot 0
	mov	#0,r11			! (delay slot) r11 = 0
	mov	#1,r11			! r11 = 1: the current vertex
	clrt				! T = 0: not the end of the strip
	bsr	.Lnear_cut_emit		! send the cut of the edge from slot 0 to slot 1
	mov	#0,r0			! (delay slot) r0 = 0, the edge's other slot
	bra	.Lclip_next_kept	! on with vertex 2, kept
	add	#56,r4			! (delay slot) r4 = past vertex 1's record

! 0c10cd10: vertex 0 behind, vertex 1 in front. Keep both, send the cut
! of the edge between them and then vertex 1.
.Lclip_second_front:
	bsr	.Lvtx_keep		! keep vertex 1 in slot 1
	mov	#1,r11			! (delay slot) r11 = 1
	bsr	.Lvtx_load		! load vertex 0 again ...
	add	#-112,r4		! (delay slot) ... r4 = two records back
	bsr	.Lvtx_keep		! keep it in slot 0
	mov	#0,r11			! (delay slot) r11 = 0
	mov	#1,r11			! r11 = 1: the current vertex
	clrt
	bsr	.Lnear_cut_emit		! send the cut of the edge from slot 0 to slot 1
	mov	#0,r0			! (delay slot) r0 = 0
	clrt				! T = 0: not the end of the strip
	bsr	.Lkept_vtx_emit		! send the kept vertex 1
	mov	#1,r0			! (delay slot) r0 = 1, its slot
	bra	.Lclip_next_kept	! on with vertex 2, kept
	add	#56,r4			! (delay slot) r4 = past vertex 1's record

! 0c10cd2e: the strip changes side at the current vertex N (from the
! front loop, N behind; from the behind loop, N in front). Fill the
! ring with N-2, N-1 and N.
.Lclip_crossing:
	bsr	.Lvtx_keep		! keep vertex N in slot r11 & 3
	nop
	add	#-56,r4			! r4 = vertex N's record ...
	bsr	.Lvtx_load		! load vertex N-2 again
	add	#-112,r4		! (delay slot) ... and two more back: vertex N-2
	bsr	.Lvtx_keep		! keep it
	add	#-2,r11			! (delay slot) r11 = N-2
	bsr	.Lvtx_load		! load vertex N-1 again
	nop
	bsr	.Lvtx_keep		! keep it
	add	#1,r11			! (delay slot) r11 = N-1
	add	#56,r4			! r4 = past vertex N's record
	add	#1,r11			! r11 = N again
	bra	.Lclip_dispatch		! to the jump table
	mov	r9,r0			! (delay slot) r0 = the tests

! 0c10cd4c: load the next vertex and keep it (the ring already holds the
! two before it).
.Lclip_next_kept:
	bsr	.Lvtx_load		! load it; T = behind the plane
	add	#1,r11			! (delay slot) r11 = this vertex
	bsr	.Lvtx_keep		! keep it in slot r11 & 3
	rotcl	r9			! (delay slot) its test into r9
	mov	r9,r0			! r0 = the tests
! 0c10cd56: jump on the last three tests. r0 & 7: bit 2 = vertex N-2,
! bit 1 = N-1, bit 0 = N (the current one); 1 = behind the plane. braf
! lands at 0c10cd5e + 4 * case: a table of 4-byte entries.
.Lclip_dispatch:
	and	#7,r0
	shll2	r0			! r0 = 4 * case
	braf	r0			! jump into the table
	nop
	nop				! case 0 (all in front, not used): two nops, runs on into case 1
	nop
	bra	.Lclip_case_1		! case 1: front, front, behind
	nop
	bra	.Lclip_case_2		! case 2: front, behind, front
	nop
	bra	.Lclip_case_3		! case 3: front, behind, behind
	nop
	bra	.Lclip_case_4		! case 4: behind, front, front
	nop
	bra	.Lclip_case_5		! case 5: behind, front, behind
	nop
	bra	.Lclip_case_6		! case 6: behind, behind, front
	nop
	nop				! case 7 (all behind, not used): two nops, runs on into case 1's code
	nop

! In the cases, "cut a-b" is the point where the edge between the kept
! vertices a and b crosses the plane (bump_near_cut_emit, r0 = a's
! slot, r11 = b's), and "kept a" is a kept vertex sent whole
! (bump_kept_vtx_emit, r0 = its slot). T on entry to either gives the
! control word: clear = plain, set = end of strip. Each case counts
! the current vertex with dt r3, so T is set at its last send when the
! strip ends there; neither helper changes T.
!
! 0c10cd7e: case 1, N-2 and N-1 in front, N behind. Sends cut (N-2)-N,
! kept N-1, cut (N-1)-N.
.Lclip_case_1:
	mov	r11,r0
	clrt				! T = 0: plain control word
	bsr	.Lnear_cut_emit		! cut (N-2)-N
	add	#-2,r0			! (delay slot) r0 = N-2
	mov	r11,r0
	clrt
	bsr	.Lkept_vtx_emit		! kept N-1
	add	#-1,r0			! (delay slot) r0 = N-1
	mov	r11,r0
	dt	r3			! count vertex N; T = the strip ends here
	bsr	.Lnear_cut_emit		! cut (N-1)-N, end of strip if T
	add	#-1,r0			! (delay slot) r0 = N-1
	bf	.Lclip_next_kept	! more vertices: load and keep the next
	bra	.Lclip_run_end		! the strip is done
	nop

! 0c10cd9c: case 2, N-2 in front, N-1 behind, N in front. Sends kept N,
! cut (N-1)-N, kept N again.
.Lclip_case_2:
	clrt
	bsr	.Lkept_vtx_emit		! kept N
	mov	r11,r0			! (delay slot) r0 = N
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut (N-1)-N
	add	#-1,r0			! (delay slot) r0 = N-1
	dt	r3			! count vertex N; T = the strip ends here
	bsr	.Lkept_vtx_emit		! kept N, end of strip if T
	mov	r11,r0			! (delay slot) r0 = N
	bf	.Lclip_next_kept	! more vertices: load and keep the next
	bra	.Lclip_run_end		! the strip is done
	nop

! 0c10cdb6: case 3, N-2 in front, N-1 and N behind. Sends cut (N-2)-N as
! the end of a strip; the vertices that follow are behind until one
! comes in front, so the walk goes back to the behind loop.
.Lclip_case_3:
	mov	r11,r0
	sett				! T = 1: end-of-strip control word
	bsr	.Lnear_cut_emit		! cut (N-2)-N
	add	#-2,r0			! (delay slot) r0 = N-2
	dt	r3			! count vertex N
	bt	.Lclip_to_run_end	! it was the last: the strip is done
	bra	.Lclip_behind_loop	! on in the behind loop
	nop

! 0c10cdc6: case 4, N-2 behind, N-1 and N in front. Sends cut (N-2)-N,
! kept N-1, kept N; the strip is in front again, so the walk goes back
! to the front loop.
.Lclip_case_4:
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut (N-2)-N
	add	#-2,r0			! (delay slot) r0 = N-2
	mov	r11,r0
	clrt
	bsr	.Lkept_vtx_emit		! kept N-1
	add	#-1,r0			! (delay slot) r0 = N-1
	dt	r3			! count vertex N; T = the strip ends here
	bsr	.Lkept_vtx_emit		! kept N, end of strip if T
	mov	r11,r0			! (delay slot) r0 = N
	bt	.Lclip_to_run_end	! it was the last: the strip is done
	bra	.Lclip_front_loop	! on in the front loop
	add	#1,r11			! (delay slot) r11 = the next vertex
.Lclip_to_run_end:			! 0c10cde2
	bra	.Lclip_run_end		! cases 3 and 4: the strip is done
	nop

! 0c10cde6: case 5, N-2 behind, N-1 in front, N behind. Sends cut (N-1)-N.
.Lclip_case_5:
	mov	r11,r0
	dt	r3			! count vertex N; T = the strip ends here
	bsr	.Lnear_cut_emit		! cut (N-1)-N, end of strip if T
	add	#-1,r0			! (delay slot) r0 = N-1
	bf	.Lclip_next_kept	! more vertices: load and keep the next
	bra	.Lclip_run_end		! the strip is done
	nop

! 0c10cdf4: case 6, N-2 and N-1 behind, N in front: a new strip starts.
! Sends cut (N-2)-N, cut (N-1)-N, kept N; when N is odd, cut (N-1)-N
! goes out once more ahead of them (one more vertex, which turns the
! facing of the triangles that follow; that this is the purpose is
! inferred from the test on N's parity).
.Lclip_case_6:
	mov	r11,r0
	tst	#1,r0			! T = N is even
	bt	.Lclip_case_6_even	! even: no extra vertex
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! odd: cut (N-1)-N first
	add	#-1,r0			! (delay slot) r0 = N-1
.Lclip_case_6_even:			! 0c10ce02
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut (N-2)-N
	add	#-2,r0			! (delay slot) r0 = N-2
	mov	r11,r0
	clrt
	bsr	.Lnear_cut_emit		! cut (N-1)-N
	add	#-1,r0			! (delay slot) r0 = N-1
	dt	r3			! count vertex N; T = the strip ends here
	bsr	.Lkept_vtx_emit		! kept N, end of strip if T
	mov	r11,r0			! (delay slot) r0 = N
	bf	.Lclip_next_kept	! more vertices: load and keep the next
	bra	.Lclip_run_end		! the strip is done
	nop
	nop				! padding to the next routine

! bump_vtx_load
!
! Loads the 56-byte vertex record at r4 for the near-plane clippers:
! transforms the position, works out the vertex's offset word exactly
! as bump_strip_send does (same steps, with its own copy of the
! constants) and tests the vertex against the near plane. Nothing is
! written. Called (bsr) by bump_strip_near_clip and
! bump_tri_near_clip.
!
! In:    r4 = the record (x, y, z, N, T, B, u, v).
!        r12 = the near value as raw float bits (bit 0 is a flag of
!        the callers and takes part in the compare as the lowest bit).
!        r13 = the K1 and k bytes; fr12-fr14 = the light direction
!        (as for bump_strip_send).
!        XMTRX = the transform; its fourth result is minus depth.
! Out:   T = 1 when the vertex is behind the near plane: r12 is above
!        the raw bits of minus depth, compared as unsigned numbers.
!        fr4 = minus depth, fr5 = x, fr6 = y (not yet divided by
!        depth), fr7 = 1 / depth, fr2 = u, fr3 = v, r1 = the offset
!        word. r4 = the next record.
! Uses:  r0, r2, fr0, fr1 and fr8-fr11 are changed as well, and fr15
!        is left 0 (fr8-fr11 and fr15 without being saved, unlike
!        compiled code). r3, r5-r8, r13 and fr12-fr14 are not changed.
! Notes: 32-bit fmov throughout (FPSCR SZ = 0, PR = 0).
	.global	_bump_vtx_load
	.type	_bump_vtx_load,@function
_bump_vtx_load:
.Lvtx_load:				! 0c10ce20
	fmov	@r4+,fr4		! fr4, fr5, fr6 = x, y, z
	fmov	@r4+,fr5
	fmov	@r4+,fr6
	fldi1	fr7			! fr7 = 1: the point (x, y, z, 1)
	fmov	@r4+,fr2		! fr2, fr0, fr1 = N: first, second, third component
	fmov	@r4+,fr0
	fmov	@r4+,fr1
	ftrv	xmtrx,fv4		! fr4 = depth, fr5 = x, fr6 = y, fr7 = minus depth
	fldi0	fr3			! fr3 = 0: no fourth term in N.L
	fmov	@r4+,fr10		! fr10, fr8, fr9 = T: first, second, third component
	mov	r13,r0			! r0 = r13 without its low half (here and at 0c10ce44); made again at 0c10cea4
	fmov	@r4+,fr8
	shlr16	r0
	fmov	@r4+,fr9
	fipr	fv12,fv0		! fr3 = N.L (fr15's term is times fr3 = 0)
	fmov	@r4+,fr2		! fr2, fr0 = B: first and second component
	fsub	fr15,fr15		! fr15 = 0: no fourth term in the next two dot products
	fmov	@r4+,fr0
	shll16	r0
	flds	fr7,fpul		! fpul = minus depth, kept while fr7 is reused
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1 / depth
	fldi0	fr11			! fr11 = 0
	fcmp/gt	fr11,fr3		! T = N.L is above 0
	fsts	fpul,fr4		! fr4 = minus depth (in place of the depth)
	fipr	fv12,fv8		! fr11 = L.T = t
	fmov	@r4+,fr1		! fr1 = B's third component; r4 = record +48
	bt	.Lload_nl_ok		! lit from the front
	fldi0	fr3			! facing away: N.L counts as 0
! 0c10ce5a: from here to 0c10ceda the offset word is made as in
! bump_strip_send from 0c10ca1e (b = L.B, the octant, the arctangent
! table, the four bytes put together in r1).
.Lload_nl_ok:
	fmov	fr3,fr8
	fmul	fr8,fr8			! fr8 = N.L squared
	fldi1	fr9
	fipr	fv0,fv12		! fr15 = L.B = b (fr3's term is times fr15 = 0)
	fldi0	fr10
	fcmp/gt	fr11,fr10		! T = t is negative
	mov	r13,r2
	fsub	fr8,fr9			! fr9 = 1 - N.L squared
	extu.b	r2,r2			! r2 = the k byte of r13
	bf	.Lload_abs_t		! t is 0 or more
	fneg	fr11			! fr11 = |t|
.Lload_abs_t:				! 0c10ce70
	movt	r0			! r0 = 1 when t was negative
	fcmp/gt	fr15,fr10		! T = b is negative
	lds	r2,fpul			! the k byte waits in fpul
	fsqrt	fr9			! fr9 = sqrt(1 - N.L squared)
	bf	.Lload_abs_b		! b is 0 or more
	fneg	fr15			! fr15 = |b|
.Lload_abs_b:				! 0c10ce7c
	movt	r1			! r1 = 1 when b was negative
	fcmp/gt	fr11,fr15		! T = |b| is above |t|
	fmov	fr15,fr10
	shll2	r1			! r1 = 4 when b was negative
	bf	.Lload_octant		! |t| is the larger: fr15 / fr11 is the ratio as they stand
	fmov	fr11,fr15		! |b| is the larger: swap, so fr11 = the larger, fr15 = the smaller
	or	#2,r0			! ... and note it in r0 bit 1
	fmov	fr10,fr11
.Lload_octant:				! 0c10ce8c
	or	r0,r1			! r1 = the octant
	float	fpul,fr10		! fr10 = k * 255 as a float
	shll	r1			! r1 = the octant's offset in the halfword table
	mova	.Lload_octants,r0
	mov.w	@(r0,r1),r1		! r1 = the octant's halfword
	mova	.Lload_consts,r0	! r0 = &the constants at 0c10cef0
	fmov	@r0+,fr0		! fr0 = 128.0
	fdiv	fr11,fr15		! fr15 = smaller / larger: the tangent, 0 to 1
	shlr	r1			! T = subtract; r1 = the starting angle (0x00, 0x40, 0x80, 0xc0 or 0xff)
	fmov	@r0+,fr11		! fr11 = 0.5
	fmul	fr10,fr3		! fr3 = k * 255 * max(0, N.L)
	mov.l	@r0,r2			! r2 = the arctangent table (129 bytes at 0c12c86c)
	mov	r13,r0
	shlr16	r0
	fmul	fr10,fr9		! fr9 = k * 255 * sqrt(1 - N.L squared)
	shll16	r0			! r0 = the K1 byte at bits 24-31 (r13 without its low half)
	ftrc	fr3,fpul
	or	r0,r1			! r1 = K1 byte | the starting angle
	sts	fpul,r0			! r0 = k * 255 * N.L as an integer
	add	#32,r4			! r4 = record +80 ...
	ftrc	fr9,fpul		! fpul = k * 255 * sqrt(...) as an integer
	pref	@r4			! ... to fetch ahead in the records
	shll16	r0
	add	r0,r1			! r1 += the N.L byte at bits 16-23
	sts	fpul,r0			! r0 = k * 255 * sqrt(...) as an integer
	add	#32,r4			! r4 = record +112 ...
	fmac	fr0,fr15,fr11		! fr11 = tangent * 128 + 0.5: the table index, rounded
	pref	@r4			! ... to fetch further ahead
	ftrc	fr11,fpul
	add	#-64,r4			! r4 = record +48: u, v
	shll8	r0
	fldi0	fr15			! fr15 = 0 again, for the next vertex's dot products
	add	r0,r1			! r1 += the sqrt byte at bits 8-15
	sts	fpul,r0			! r0 = the index, 0 to 128
	and	#255,r0
	flds	fr4,fpul		! fpul = minus depth, for the near test
	mov.b	@(r0,r2),r0		! r0 = the arctangent: 0 to 32, in 1/256ths of a turn
	bf	.Lload_angle		! T clear (from the shlr at 0c10ce9c): add it
	neg	r0,r0			! T set: subtract it
! 0c10ceda: the offset word, then u, v and the near test.
.Lload_angle:
	add	r1,r0			! r0 = the offset word: the angle now in bits 0-7
	sts	fpul,r2			! r2 = minus depth as raw bits
	mov	r0,r1			! r1 = the offset word
	fmov	@r4+,fr2		! fr2 = u
	fmov	@r4+,fr3		! fr3 = v; r4 = the next record
	rts
	cmp/hi	r2,r12			! (delay slot) T = r12 above minus depth's bits: behind the near plane
! Four nops of padding before the constants.
	nop
	nop
	nop
	nop
! 0c10cef0: constants of bump_vtx_load, a copy of those at 0c10cb20 but
! for the last word.
.Lload_consts:
	.long	0x43000000		! the float 128.0: tangent to table index
	.long	0x3f000000		! the float 0.5: rounds the index
	.long	_arctan_ang8_table		! the arctangent table: 129 bytes, atan(i / 128) in 1/256ths of a turn (0 to 32)
	.long	0x00000000		! a zero word; not read (0.5 in the other two copies)
! 0c10cf00: the eight octant halfwords, a copy of those at 0c10cb30
! (explained there).
.Lload_octants:
	.long	0x01010000		! octants 0 and 1: the halfwords 0x0000 and 0x0101, written as one long
	.word	0x0081			! octant 2: from 0x40, subtract
	.word	0x0080			! octant 3: from 0x40, add
	.word	0x01ff			! octant 4: from 0xff, subtract
	.word	0x0100			! octant 5: from 0x80, add
	.word	0x0180			! octant 6: from 0xc0, add
	.word	0x0181			! octant 7: from 0xc0, subtract

! bump_vtx_emit
!
! Sends the vertex bump_vtx_load has just loaded as a 32-byte vertex of
! the kind bump_strip_send writes: control word, X = x / depth,
! Y = y / depth, 1 / depth, u, v, the base color word, the offset
! word. It counts the vertex (dt r3): the one that brings r3 to 0 gets
! the end-of-strip control word. Called (bsr) by bump_strip_near_clip
! and bump_tri_near_clip.
!
! In:    fr5, fr6 = x, y; fr7 = 1 / depth; fr2, fr3 = u, v; r1 = the
!        offset word (all as bump_vtx_load leaves them); r8 = the base
!        color word.
!        r3 = the vertices left in the strip, this one included.
!        r5 = the list's write address; r6 = the store-queue address
!        of the vertex.
! Out:   r3 one less; T = 1 when it reached 0 (the strip's last
!        vertex). r5 and r6 moved on 32 bytes.
! Uses:  r0, fr5, fr6 are changed; nothing else.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg.
	.global	_bump_vtx_emit
	.type	_bump_vtx_emit,@function
_bump_vtx_emit:
.Lvtx_emit:				! 0c10cf10
	fschg				! pair moves (SZ = 1)
	add	#32,r6			! r6 = vertex +32
	mov.l	r1,@-r6			! vertex +28 = the offset word
	fmul	fr7,fr6			! fr6 = Y = y / depth
	fmul	fr7,fr5			! fr5 = X = x / depth
	mov.l	r8,@-r6			! vertex +24 = the base color word
	mov	r6,r0			! r0 = vertex +24 ...
	fmov	fr2,@-r6		! vertex +16, +20 = u, v
	shar	r0			! ... >> 1: the end-of-strip control word
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	dt	r3			! count the vertex; T = it is the strip's last
	fmov	fr4,@-r6		! vertex +0, +4 = minus depth, X
	bt	.Lemit_control		! last: keep the end-of-strip word
	mov	r6,r0			! r0 = the store-queue address: the plain control word
.Lemit_control:				! 0c10cf2c
	mov.l	r0,@r6			! vertex +0 = the control word (over minus depth)
	fschg				! back to single moves (SZ = 0)
	add	#32,r5			! the vertex takes 32 bytes of the list
	pref	@r6			! send the 32 bytes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the next vertex
! Four nops of padding to the next routine.
	nop
	nop
	nop
	nop

! bump_vtx_keep
!
! Stores the vertex bump_vtx_load has just loaded in slot r11 & 3 of the
! clip ring at 0c10c8d0. A slot is 32 bytes:
!   +0 minus depth   +4 x   +8 y   +12 1 / depth   +16 u   +20 v
!   +24 the base color word   +28 the offset word
! Called (bsr) by bump_strip_near_clip and bump_tri_near_clip.
!
! In:    r11 = the vertex's number (its low two bits pick the slot).
!        fr4 = minus depth, fr5 = x, fr6 = y, fr7 = 1 / depth, fr2,
!        fr3 = u, v, r1 = the offset word, r8 = the base color word.
! Out:   the slot filled. No register result; T is not changed.
! Uses:  r0 and r10 are changed (r10 without being saved; the clippers
!        save it for all the ring helpers).
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg.
	.global	_bump_vtx_keep
	.type	_bump_vtx_keep,@function
_bump_vtx_keep:
.Lvtx_keep:				! 0c10cf40
	mov	r11,r0
	mov	#5,r10			! r10 = 5: a slot is 32 bytes
	and	#3,r0
	shld	r10,r0			! r0 = the slot's offset in the ring
	mov.l	.Lclip_ring_slot_end,r10	! r10 = the ring +32: the end of slot 0
	fschg				! pair moves (SZ = 1)
	add	r0,r10			! r10 = the end of this slot
	mov.l	r1,@-r10		! slot +28 = the offset word
	mov.l	r8,@-r10		! slot +24 = the base color word
	fmov	fr2,@-r10		! slot +16, +20 = u, v
	fmov	fr6,@-r10		! slot +8, +12 = y, 1 / depth
	fmov	fr4,@-r10		! slot +0, +4 = minus depth, x
	rts
	fschg				! (delay slot) back to single moves (SZ = 0)
! Two nops of padding to the next routine.
	nop
	nop

! bump_kept_vtx_emit
!
! Sends a vertex kept in the clip ring (0c10c8d0) as a 32-byte vertex,
! the layout bump_strip_send writes. Called (bsr) by
! bump_strip_near_clip and bump_tri_near_clip.
!
! In:    r0 = the vertex's number (its low two bits pick the slot).
!        T = 1 to send it as the end of a strip (control word
!        0xf0000000), 0 for the plain control word (the store-queue
!        address).
!        r5 = the list's write address; r6 = the store-queue address
!        of the vertex.
! Out:   r5 and r6 moved on 32 bytes. T is not changed.
! Uses:  r0, r1, r2, r10 and fr0-fr7 are changed (r10 without being
!        saved). r3, r4, r7 and fr8-fr11 are not touched.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg. The two packed words travel through
!        fr6, fr7 as raw bits.
	.global	_bump_kept_vtx_emit
	.type	_bump_kept_vtx_emit,@function
_bump_kept_vtx_emit:
.Lkept_vtx_emit:			! 0c10cf60
	mov	#5,r1			! r1 = 5: a slot is 32 bytes
	mov.l	.Lclip_ring,r10
	and	#3,r0
	fschg				! pair moves (SZ = 1)
	shld	r1,r0			! r0 = the slot's offset in the ring
	add	r0,r10			! r10 = the slot
	mov	#-16,r2
	fmov	@r10+,fr0		! fr0, fr1 = minus depth, x
	shll16	r2
	fmov	@r10+,fr2		! fr2, fr3 = y, 1 / depth
	add	#32,r6			! r6 = vertex +32
	fmov	@r10+,fr4		! fr4, fr5 = u, v
	fmul	fr3,fr2			! fr2 = Y = y / depth
	fmov	@r10+,fr6		! fr6, fr7 = the base color word, the offset word
	fmul	fr3,fr1			! fr1 = X = x / depth
	shll8	r2			! r2 = 0xf0000000: the end-of-strip control word
	fmov	fr6,@-r6		! vertex +24, +28 = the two packed words
	add	#32,r5			! the vertex takes 32 bytes of the list
	fmov	fr4,@-r6		! vertex +16, +20 = u, v
	fmov	fr2,@-r6		! vertex +8, +12 = Y, 1 / depth
	fmov	fr0,@-r6		! vertex +0, +4 = minus depth, X
	bt	.Lkept_control		! T set on entry: end of strip
	mov	r6,r2			! r2 = the store-queue address: the plain control word
.Lkept_control:				! 0c10cf8e
	mov.l	r2,@r6			! vertex +0 = the control word (over minus depth)
	fschg				! back to single moves (SZ = 0)
	pref	@r6			! send the 32 bytes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the next vertex
! Four nops of padding to the next routine.
	nop
	nop
	nop
	nop

! bump_near_cut_emit
!
! Sends the point where the edge between two kept vertices a and b
! crosses the near plane, as a 32-byte vertex (the layout
! bump_strip_send writes). With the minus depths of the two taken from
! their ring slots,
!   t = (near - a) / (b - a)
! and x, y, u, v are each a + t * (b - a). The vertex's 1/w is the
! value in r7, and X, Y are x, y times it. The base color word and the
! offset word are vertex b's, copied as they are (packed bytes are not
! interpolated). Called (bsr) by bump_strip_near_clip and
! bump_tri_near_clip.
!
! In:    r0 = vertex a's number, r11 = vertex b's (low two bits =
!        their slots in the clip ring at 0c10c8d0).
!        r12 = the near value as raw float bits (its bit 0, a flag of
!        the callers, is taken along as the lowest bit of the float).
!        r7 = the 1/w of points on the near plane, raw float bits.
!        T = 1 to send it as the end of a strip (control word
!        0xf0000000), 0 for the plain control word (the store-queue
!        address).
!        r5 = the list's write address; r6 = the store-queue address
!        of the vertex.
! Out:   r5 and r6 moved on 32 bytes. T is not changed.
! Uses:  r0, r1, r2, r10 and fr0-fr5 are changed (r10 without being
!        saved). r3, r4, r7, r11 and fr6-fr11 are not touched.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg (the packed words and u, v), single
!        moves for the rest. The pool after it serves bump_vtx_keep
!        and bump_kept_vtx_emit as well.
	.global	_bump_near_cut_emit
	.type	_bump_near_cut_emit,@function
_bump_near_cut_emit:
.Lnear_cut_emit:			! 0c10cfa0
	mov	#5,r1			! r1 = 5: a slot is 32 bytes
	mov.l	.Lclip_ring,r10
	and	#3,r0
	shld	r1,r0			! r0 = slot a's offset in the ring
	mov	r10,r2
	add	r0,r10			! r10 = slot a
	mov	r11,r0
	and	#3,r0
	fmov	@r10,fr2		! fr2 = a's minus depth
	shld	r1,r0			! r0 = slot b's offset
	lds	r12,fpul
	add	r0,r2			! r2 = slot b
	fsts	fpul,fr0		! fr0 = the near value (r12's bits)
	fmov	@r2,fr1			! fr1 = b's minus depth
	fsub	fr2,fr0			! fr0 = near - a
	add	#24,r2			! r2 = &b's base color word
	fschg				! pair moves (SZ = 1)
	add	#32,r6			! r6 = vertex +32
	fsub	fr2,fr1			! fr1 = b - a
	fmov	@r2,fr4			! fr4, fr5 = b's base color word and offset word (raw bits)
	add	#-8,r2			! r2 = &u of vertex b
	lds	r7,fpul			! fpul = the near 1/w, for later
	add	#16,r10			! r10 = &u of vertex a
	fdiv	fr1,fr0			! fr0 = t = (near - a) / (b - a)
	fmov	fr4,@-r6		! vertex +24, +28 = b's two packed words
	fmov	@r2,fr4			! fr4, fr5 = u, v of vertex b
	add	#-8,r2			! r2 = &y of vertex b
	fmov	@r10,fr2		! fr2, fr3 = u, v of vertex a
	add	#-8,r10			! r10 = &y of vertex a
	fsts	fpul,fr1		! fr1 = the near 1/w (from r7)
	fsub	fr2,fr4			! fr4, fr5 = b - a for u and v
	fsub	fr3,fr5
	fmac	fr0,fr4,fr2		! fr2, fr3 = a + t * (b - a): u, v at the cut
	fmac	fr0,fr5,fr3
	fmov	fr2,@-r6		! vertex +16, +20 = u, v
	fschg				! back to single moves (SZ = 0)
	fmov	fr1,@-r6		! vertex +12 = the near 1/w
	fmov	@r2,fr5			! fr5 = y of vertex b
	add	#-4,r2			! r2 = &x of vertex b
	fmov	@r10,fr3		! fr3 = y of vertex a
	add	#-4,r10			! r10 = &x of vertex a
	fmov	@r2,fr4			! fr4 = x of vertex b
	fmov	@r10,fr2		! fr2 = x of vertex a
	fsub	fr3,fr5			! fr5, fr4 = b - a for y and x
	fsub	fr2,fr4
	mov	#-16,r2
	fmac	fr0,fr5,fr3		! fr3 = y at the cut
	shll16	r2
	fmac	fr0,fr4,fr2		! fr2 = x at the cut
	shll8	r2			! r2 = 0xf0000000: the end-of-strip control word
	fmul	fr1,fr3			! fr3 = Y = y * the near 1/w
	add	#32,r5			! the vertex takes 32 bytes of the list
	fmul	fr1,fr2			! fr2 = X = x * the near 1/w
	fmov	fr3,@-r6		! vertex +8 = Y
	fmov	fr2,@-r6		! vertex +4 = X
	bt	.Lcut_control		! T set on entry: end of strip
	mov	r6,r2			! r2 = the store-queue address: the plain control word
.Lcut_control:				! 0c10d012
	mov.l	r2,@-r6			! vertex +0 = the control word
	pref	@r6			! send the 32 bytes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the next vertex
	nop				! padding before the pool
! Pool of the three ring helpers. The ring is the block at 0c10c8d0 in
! this file, bump_clip_ring (the second word is the same symbol
! + 32, the address 0c10c8f0).
.Lclip_ring:
	.long	_bump_clip_ring		! the clip ring (slot 0), the block at 0c10c8d0
.Lclip_ring_slot_end:
	.long	_bump_clip_ring+32	! the end of slot 0: bump_vtx_keep stores downward from here
! Six nops of padding to the next routine.
	nop
	nop
	nop
	nop
	nop
	nop

! bump_tri_near_clip
!
! Sends one run of independent triangles of a bump-mapped group that
! crosses the near plane, cutting each triangle at the plane. Called
! (bsr) by bump_group_send only. The run is a triangle count and then
! three 56-byte records a triangle.
!
! For each triangle bump_tri_classify gives a 3-bit code: bit 2 =
! vertex 0 is behind the plane, bit 1 = vertex 1, bit 0 = vertex 2.
!   0 (all in front): the three are loaded and sent as they are.
!   7 (all behind):   the triangle's 168 bytes are skipped.
!   1 to 6: the three are loaded and kept in ring slots 0, 1, 2 and a
!     jump table (0c10d064) picks the code that sends the part in
!     front as one strip of three or four vertices: kept vertices
!     (bump_kept_vtx_emit) and points where an edge crosses the plane
!     (bump_near_cut_emit), the last one as the end of the strip.
!
! In:    r4 = the run's count word (triangles); the records follow.
!        r5 = the list's write address; r6 = the store-queue address of
!        the next vertex.
!        r12 = the near value as raw float bits; r7 = the 1/w for
!        points on the near plane.
!        r8, r13, fr12-fr14 = the base color word, the K1 and k bytes
!        and the light direction, as for bump_strip_send.
!        XMTRX = the transform; its fourth result is minus depth.
! Out:   r4 = just past the last triangle (the next run word).
!        r5 and r6 moved on 32 bytes for each vertex sent.
!        r12 bit 0 set (for the group sender: the group crosses the
!        near plane).
! Uses:  r10, r11 and pr are saved and restored. Not the compiled
!        code's convention otherwise: r9, fr8-fr11 and fr15 are
!        changed and not saved here, as are r0-r3 and fr0-fr7; r7, r8,
!        r13 and fr12-fr14 are not changed.
! Notes: runs with 32-bit fmov (FPSCR SZ = 0, PR = 0); the helpers
!        that write vertices switch to pair moves and back. A count
!        of 0 is not expected. The table's entries for codes 0 and 7
!        are two nops each and are not used: those codes are dealt
!        with before the jump.
	.global	_bump_tri_near_clip
	.type	_bump_tri_near_clip,@function
_bump_tri_near_clip:
.Ltri_near_clip:			! 0c10d030
	mov.l	r10,@-r15
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3			! r3 = the number of triangles; r4 = the first record

! 0c10d038: per triangle. r4 = its first record.
.Ltri_clip_next:
	bsr	.Ltri_classify		! r9 = the code of the three near tests (r4 is left where it is)
	mov	#0,r9			! (delay slot) r9 = 0 for the tests to be rotated into
	mov	r9,r0
	cmp/eq	#0,r0			! code 0 ...
	bt	.Ltri_clip_all_front	! ... all in front: send the triangle whole
	cmp/eq	#7,r0			! code 7 ...
	bt	.Ltri_clip_all_behind	! ... all behind: skip it
! Codes 1 to 6: the plane cuts the triangle. Keep its three vertices in
! slots 0, 1 and 2 of the ring.
	bsr	.Lvtx_load		! load vertex 0
	mov	#0,r11			! (delay slot) r11 = 0
	bsr	.Lvtx_keep		! keep it in slot 0
	nop
	bsr	.Lvtx_load		! load vertex 1
	mov	#1,r11			! (delay slot) r11 = 1
	bsr	.Lvtx_keep		! keep it in slot 1
	nop
	bsr	.Lvtx_load		! load vertex 2
	mov	#2,r11			! (delay slot) r11 = 2
	bsr	.Lvtx_keep		! keep it in slot 2; r4 = past the triangle
	nop
! Jump on the code: braf lands at 0c10d064 + 4 * code, a table of
! 4-byte entries.
	shll2	r9			! r9 = 4 * code
	braf	r9			! jump into the table
	nop
	nop				! code 0 (dealt with above, not used): two nops, runs on into code 1
	nop
	bra	.Ltri_case_1		! code 1: vertex 2 behind
	nop
	bra	.Ltri_case_2		! code 2: vertex 1 behind
	nop
	bra	.Ltri_case_3		! code 3: vertices 1 and 2 behind
	nop
	bra	.Ltri_case_4		! code 4: vertex 0 behind
	nop
	bra	.Ltri_case_5		! code 5: vertices 0 and 2 behind
	nop
	bra	.Ltri_case_6		! code 6: vertices 0 and 1 behind
	nop
	nop				! code 7 (dealt with above, not used): two nops, runs on into the count below
	nop

! 0c10d084: a triangle is done. Count it; after the last one return
! with r12 bit 0 set.
.Ltri_clip_counted:
	dt	r3			! T = that was the run's last triangle
	bf	.Ltri_clip_next		! more triangles
	mov	#1,r0
	lds.l	@r15+,pr
	or	r0,r12			! r12 bit 0 = 1: the group crosses the near plane
	mov.l	@r15+,r11
	rts
	mov.l	@r15+,r10		! (delay slot) the last pop

! 0c10d094: code 0, the triangle is wholly in front. Load and send its
! three vertices; r3 is borrowed as bump_vtx_emit's vertex count so the
! third goes out as the end of the strip, and the triangle count
! waits in r9.
.Ltri_clip_all_front:
	mov	r3,r9			! r9 = the triangles left
	bsr	.Lvtx_load		! load vertex 0 of the triangle
	mov	#3,r3			! (delay slot) r3 = 3 vertices to send
	bsr	.Lvtx_emit		! send it (r3 goes to 2)
	nop
	bsr	.Lvtx_load		! load vertex 1 the same way
	nop
	bsr	.Lvtx_emit		! send it (r3 goes to 1)
	nop
	bsr	.Lvtx_load		! load vertex 2 the same way
	nop
	bsr	.Lvtx_emit		! send it, as the end of the strip
	nop
	bra	.Ltri_clip_counted	! count the triangle
	mov	r9,r3			! (delay slot) r3 = the triangles left again
! 0c10d0b2: code 7, the triangle is wholly behind: step over its three
! records (56 + 112 = 168 bytes).
.Ltri_clip_all_behind:
	add	#56,r4
	bra	.Ltri_clip_counted	! count the triangle
	add	#112,r4			! (delay slot) r4 = the next triangle

! In the cases, "kept a" sends the kept vertex of slot a
! (bump_kept_vtx_emit, r0 = a) and "cut a-b" the point where the edge
! from slot a to slot b crosses the plane (bump_near_cut_emit, r0 = a,
! r11 = b; it carries b's packed words). clrt before a call gives the
! plain control word, sett the end of the strip.
!
! 0c10d0b8: code 1, vertex 2 behind. Sends kept 0, kept 1, cut 0-2,
