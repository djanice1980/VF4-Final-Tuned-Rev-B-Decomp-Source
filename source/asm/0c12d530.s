! Rotates the current matrix about its own X axis by a 16-bit angle
! (0x10000 to a turn): current = current x R, where R has the columns
! (1, 0, 0), (0, c, s) and (0, -s, c). fsca gives the sine and cosine;
! the rest is mtx_rot_x_sincos with its instructions in another order.
! The current matrix is XMTRX, the back bank of FPU registers (xf0-xf3
! X axis, xf4-xf7 Y axis, xf8-xf11 Z axis, xf12-xf15 translation).
!   new Y axis = c x Y axis + s x Z axis   (XMTRX into (0, c, s, 0))
!   new Z axis = -s x Y axis + c x Z axis  (XMTRX into (0, -s, c, 0))
!
! The two results are computed in the front bank from the old matrix
! (ftrv reads XMTRX and writes only the front bank) and then copied
! into XMTRX with four pair moves. Between the two fschg the FPU moves
! register pairs (FPSCR.SZ = 1), and in that mode an odd register
! number in fmov names a pair of the back bank: "fmov fr0,fr5" copies
! front pair fr0, fr1 to back pair xf4, xf5.
!
! In:    r4 = the angle; only its low 16 bits count, so callers may
!        pass a short either sign- or zero-extended.
