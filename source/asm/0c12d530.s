! Out:   nothing in registers. XMTRX with its Y and Z axes replaced.
! Uses:  fr0-fr7 (left holding the new Y axis and the new Z axis) and
!        fpul; no general register.
! Notes: FPSCR: entered with SZ = 0 and single precision (fsca needs
