!
! Inverts the current matrix in place, treating it as a rotation plus a
! translation. The current matrix is XMTRX, the back bank of FPU
! registers; between the two frchg it is addressed as fr0-fr15:
!   a = fr0-fr2 the X axis, b = fr4-fr6 the Y axis, c = fr8-fr10 the
!   Z axis, t = fr12-fr14 the translation; fr3, fr7, fr11 and fr15 are
!   the fourth floats (0, 0, 0, 1 in an ordinary matrix).
! The result has
!   translation = (-t.a / |a|, -t.b / |b|, -t.c / |c|),
!   3x3 part = the old one with every axis divided by its length
!   (fsrra) and then transposed,
!   fr3 = fr7 = fr11 = 0, fr15 as it was.
! That is the exact inverse when the axes are unit length and at right
! angles. When the axes carry a scale the result has unit axes instead
! of axes shortened by the scale: the scale is dropped, not inverted.
!
