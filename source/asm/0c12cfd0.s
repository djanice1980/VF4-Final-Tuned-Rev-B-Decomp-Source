!        are four-term (fipr), so they count fr15 x fr3, fr15 x fr7
!        and fr15 x fr11 as well: the fourth floats of the axes are
!        taken to be 0.
! Out:   XMTRX = the inverse as described. Nothing in registers.
! Uses:  fpul; no general register and none of the front-bank fr0-fr15.
! Notes: FPSCR: single precision as it comes; FR is flipped by frchg on
!        entry and flipped back in the delay slot of the rts.
