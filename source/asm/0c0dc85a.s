!        register is touched. XMTRX is used as work space and put
!        back as it was.
! Notes: FPSCR is taken as in compiled code and handed back that way.
!        In between the routine switches SZ with fschg and the
!        register banks with frchg. With SZ = 1 an fmov between
!        registers moves a pair, and an odd register number names a
!        pair of the back bank: "fmov fr13,fr0" copies XMTRX
!        elements 12 and 13 to fr0 and fr1; "fmov fr4,fr13" copies
!        fr4 and fr5 to elements 12 and 13. After frchg the names
!        fr0-fr15 mean the matrix and "the back bank" means the
!        caller's fr0-fr15, until the second frchg.
!        Each dot product is done by fipr with d as (d, 0) in fv12 of
!        the matrix's bank, so the fourth element of each column
!        does not count.
	.global	_point_to_xmtrx_local
	.type	_point_to_xmtrx_local,@function
_point_to_xmtrx_local:
.Lto_local:				! 0c0dca00
