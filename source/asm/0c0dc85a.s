	fmov	fr13,fr0		! fr0, fr1 = T's x and y (elements 12, 13)
	fmov	fr15,fr2		! fr2, fr3 = T's z and fourth (elements 14, 15)
	fsub	fr0,fr4			! fr4, fr5, fr6 = d = point - T
	fsub	fr1,fr5
	fsub	fr2,fr6
.Lno_subtract:				! 0c0dca0c: where the unreached entry joins
