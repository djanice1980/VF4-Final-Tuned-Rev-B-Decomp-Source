	shll2	r0		! four bytes a table entry
	braf	r0		! into the table
	nop			! (delay slot)
	nop			! 0c1076d4, case 0: no entry (two words of padding)
	nop
	bra	.Lnc_case1	! case 1: k on the near side
	nop			! (delay slot)
	bra	.Lnc_case2	! case 2: k-1 on the near side
	nop			! (delay slot)
	bra	.Lnc_case3	! case 3: k-1 and k on the near side
	nop			! (delay slot)
	bra	.Lnc_case4	! case 4: k-2 on the near side
	nop			! (delay slot)
	bra	.Lnc_case5	! case 5: k-2 and k on the near side
	nop			! (delay slot)
	bra	.Lnc_case6	! case 6: k-2 and k-1 on the near side
	nop			! (delay slot)
	nop			! case 7: no entry (two words of padding, then case 1's code)
	nop
! 0c1076f4, case 1: k-2 and k-1 are in view and already sent, k is
! not. Send cut (k-2, k), vertex k-1 again, cut (k-1, k).
.Lnc_case1:
