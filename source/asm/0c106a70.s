	clrt			! not the last vertex of a strip
	bsr	.Lnear_emit	! send cut (k-2, k)
	add	#-2,r0		! (delay slot) r0 = slot k-2
	mov	r11,r0
	clrt			! not the last vertex of a strip
	bsr	.Lnear_emit	! send cut (k-1, k)
	add	#-1,r0		! (delay slot) r0 = slot k-1
	dt	r3		! count vertex k; T = it was the last
	bsr	.Lkept_emit	! send the kept vertex k, ending the strip if T
	mov	r11,r0		! (delay slot) r0 = slot k
	bf	.Lnc_cut_loop	! more vertices: the cutting loop
	bra	.Lnc_strip_end	! the strip is done
	nop			! (delay slot)

! lit_offset_vertex_load (0c107794)
!
! Loads one vertex for the near-clip senders. It follows the back
! reference if the entry is one, works out the light sum when the
! group is lit (r8 >= 0: the code of 0c106f1e in
! lit_offset_strip_send once more) or takes 1.0 for it, puts the
! position through ftrv, and compares the depth with the near limit.
!
! In:    r4 = the entry. r8 = material type. r12 = the near limit.
! XMTRX = the transform. lit_offset_ambient_scaled,
! lit_offset_group_light_mask, lit_offset_group_colours,
! light_table.
! Out:   T = the vertex is on the near side of the limit.
! fr4 = depth, fr5 = x, fr6 = y (not divided yet), fr7 = 1 / w.
! fr8-fr11 = base color A, R, G, B (R, G, B x the light sum).
! fr13-fr15 = the light sum, for the offset color.
! r1, r2 = u, v as bits. r4 = the entry after.
! Uses:  changes r0, r13, r14 and fr0-fr3, fr12 besides its results.
! r3, r5-r7 and r9-r12 are left alone; the callers keep
! counts and flags in r3, r9, r11 across the call.
! Notes: callers lit_offset_strip_send_near_clip and
! lit_offset_tris_send_near_clip. SZ = 0 on entry and exit.
	.global	_lit_offset_vertex_load
	.type	_lit_offset_vertex_load,@function
_lit_offset_vertex_load:
.Lvertex_load:
	mov.l	@r4,r0		! r0 = the first word of the entry
	fschg			! SZ = 1: pairs
	mov.l	.Lvl_light_mask,r13	! r13 = &lit_offset_group_light_mask
	tst	#1,r0		! bit 0 set marks a vertex stored here
	mov.l	.Lvl_ambient_scaled,r0	! r0 = &lit_offset_ambient_scaled
	mov	r4,r14		! r14 = the entry, taken as a vertex
	bf.s	.Lvl_load	! a vertex: r14 is right
	add	#32,r4		! (delay slot) r4 = past a 32-byte vertex
	add	#-24,r4		! a back reference: r4 = past the 8-byte entry
	mov.l	@(4,r14),r14	! r14 = its offset
	add	r4,r14		! r14 = the earlier vertex it refers to
! 0c1077aa: start the light sum and load the vertex.
.Lvl_load:
	mov.l	@r13,r13	! r13 = the mask of lights reaching the group
	fmov	@r0+,fr12	! fr12, fr13 = ambient [0] (not used), red
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	fmov	@r14+,fr6	! fr6, fr7 = z, normal x
	fschg			! SZ = 0 again
	cmp/pz	r8		! T = the group is lit per vertex
	fmov	fr7,fr8		! fr8 = normal x
	bf.s	.Lvl_not_lit	! not lit: the sum is 1.0
	tst	r13,r13		! (delay slot) T = no light reaches the group
	fmov	@r14+,fr9	! fr9 = normal y
	bt.s	.Lvl_no_lights	! none: only the transform is left to do
	fmov	@r14+,fr10	! (delay slot) fr10 = normal z; r14 = the vertex's u
	shlr	r13		! T = light 0 is in the mask
	mov.l	.Lvl_light_table,r2	! r2 = light_table, record 0
	bf	.Lvl_no_gain	! not light 0: look for the first one that is
	mov.w	@(2,r2),r0	! r0 = the light's type (+2)
! 0c1077cc: one light, as at 0c106f30. r2 = its record, r0 = its type.
.Lvl_light:
	fldi0	fr3		! fr3 = 0, so that fipr adds up x, y, z only
	cmp/eq	#2,r0		! type 2 is a directional light
	mov	#116,r1
	bf.s	.Lvl_point_or_spot	! another type: a point or a spot light
	add	r2,r1		! (delay slot) r1 = &record.model_pos (+0x74)
	fldi1	fr7		! w = 1 for the vertex position
	tst	r13,r13		! T = this is the last light
	add	#12,r1		! r1 = &record.model_dir (+0x80)
	bf.s	.Lvl_directional	! not the last: the transform waits
	fmov	@r1+,fr0	! (delay slot) fr0 = direction x
	ftrv	xmtrx,fv4	! last light: fv4 = w, x, y, depth of the vertex
! 0c1077e2: directional. Strength = model_dir . normal.
.Lvl_directional:
	fmov	@r1+,fr1	! fr1 = direction y
	mov	r2,r0
	fmov	@r1+,fr2	! fr2 = direction z
	add	#24,r0		! r0 = &record.color.red (+0x18)
	fipr	fv0,fv8		! fr11 = direction . normal
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	fmov	@r0+,fr3
	fldi0	fr0		! fr0 = 0 to compare with
	fcmp/gt	fr11,fr0	! T = the normal faces away from the light
	fmov	fr11,fr0	! fr0 = the strength
	bf.s	.Lvl_add_light	! facing the light: add it to the sum
	tst	r13,r13		! (delay slot) T = that was the last light
! 0c1077fc: nothing to add for this light. T = it was the last one.
.Lvl_no_gain:
	mov	#-80,r0		! r0 = 0xb0 once zero-extended: the size of a light record
	bt	.Lvl_results	! the last light: finish the vertex
	shlr	r13		! T = the next light is in the mask
	extu.b	r0,r0
	bf.s	.Lvl_find_light	! not in the mask: go on looking
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lvl_light	! work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
! 0c10780c: a group that is not lit: transform, and a sum of 1.0.
.Lvl_not_lit:
	fldi1	fr7		! w = 1 for the vertex position
	add	#8,r14		! r14 = the vertex's u, past normal y and z
	bra	.Lvl_sum_one
	ftrv	xmtrx,fv4	! (delay slot) fv4 = w, x, y, depth of the vertex
! 0c107814: no light reaches the group: transform and finish.
.Lvl_no_lights:
	fldi1	fr7		! w = 1 for the vertex position
	bra	.Lvl_results
	ftrv	xmtrx,fv4	! (delay slot) fv4 = w, x, y, depth of the vertex
	nop			! never reached: padding
! 0c10781c: a point or a spot light. fv0 = L, from the vertex to
! the light.
.Lvl_point_or_spot:
	fmov	@r1+,fr0	! fr0 = light x
	tst	r13,r13		! T = this is the last light
	fmov	@r1+,fr1	! fr1 = light y
	fsub	fr4,fr0		! fr0 = L x
	fmov	@r1+,fr2	! fr2 = light z; r1 = record +0x80
	fsub	fr5,fr1		! fr1 = L y
	fldi1	fr7		! w = 1 for the vertex position
	add	#24,r1		! r1 = record +0x98
	fldi0	fr11		! fr11 = 0: the normal's fourth component
	bf.s	.Lvl_range_test	! not the last light: the transform waits
	fsub	fr6,fr2		! (delay slot) fr2 = L z
	ftrv	xmtrx,fv4	! last light: fv4 = w, x, y, depth (L is already taken)
! 0c107834: facing and range tests.
.Lvl_range_test:
	fipr	fv0,fv8		! fr11 = L . normal
	fldi0	fr12		! fr12 = 0 to compare with (fr12 is free: not part of the sum)
	fipr	fv0,fv0		! fr3 = L . L, the distance squared
	fcmp/gt	fr11,fr12	! T = the normal faces away from the light
	fmov	@r1,fr12	! fr12 = the float at record +0x98
	bt	.Lvl_skip_light	! facing away: nothing from this light
	fcmp/gt	fr3,fr12	! T = the distance squared is below that float
	bf	.Lvl_skip_light	! too far: nothing from this light
	cmp/eq	#3,r0		! type 3 is a point light
	flds	fr3,fpul	! fpul = the distance squared, kept for later
	bt.s	.Lvl_attenuate	! a point light has no cone
	fsrra	fr3		! (delay slot) fr3 = 1 / distance
! Spot light: the cone factor from -(L . model_dir) / distance.
	add	#-24,r1		! r1 = &record.model_dir (+0x80)
	fmov	@r1+,fr12	! fr12 = direction x
	fmul	fr0,fr12	! fr12 = direction x times L x
	fmov	@r1+,fr0	! fr0 = direction y
	fmac	fr0,fr1,fr12	! plus direction y times L y
	fmov	@r1,fr0		! fr0 = direction z; r1 = record +0x88
	add	#-48,r1		! r1 = &record.cone_cos (+0x58)
	fmac	fr0,fr2,fr12	! fr12 = L . model_dir
	fmov	@r1,fr2		! fr2 = cone_cos
	fneg	fr12		! toward the vertex, not toward the light
	fmul	fr3,fr12	! fr12 = c
	add	#68,r1		! r1 = &record.cone_scale (+0x9c)
	fcmp/gt	fr12,fr2	! T = c is below cone_cos: outside the cone
	fsub	fr2,fr12	! fr12 = c - cone_cos
	fmov	@r1,fr2		! fr2 = cone_scale
	bt	.Lvl_skip_light	! outside the cone: nothing from this light
	fmul	fr2,fr12	! fr12 = (c - cone_cos) x cone_scale: 0 at the edge
	add	#-4,r1		! r1 = record +0x98, as on the point light path
	fmul	fr12,fr11	! fr11 = L . normal x the cone factor
! 0c107872: attenuation, as at 0c106fce.
.Lvl_attenuate:
	add	#-68,r1		! r1 = record +0x54
	fmov	@r1,fr2		! fr2 = the float at +0x54
	add	#-8,r1		! r1 = record +0x4c
	fsts	fpul,fr0	! fr0 = distance squared
	fmul	fr3,fr11	! fr11 = (L . normal) / distance [x the cone factor]
	fmov	@r1,fr12	! fr12 = the float at +0x4c
	fmul	fr0,fr3		! fr3 = the distance
	add	#4,r1		! r1 = record +0x50
	fmac	fr0,fr2,fr12	! fr12 = [+0x4c] + distance squared x [+0x54]
	fmov	@r1,fr2		! fr2 = the float at +0x50
	mov	r2,r0
	fmov	fr3,fr0		! fr0 = the distance
	fmac	fr0,fr2,fr12	! fr12 = a, with distance x [+0x50] added
	fmov	fr11,fr0	! fr0 = the strength, not divided
	add	#24,r0		! r0 = &record.color.red (+0x18)
	fdiv	fr12,fr11	! fr11 = the strength divided by a
	fldi1	fr2
	fcmp/gt	fr2,fr12	! T = a is above 1
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	bf.s	.Lvl_strength_set	! a is 1 or less: keep the strength as it is
	fmov	@r0+,fr3	! (delay slot) fr3 = the light's blue
	fmov	fr11,fr0	! a above 1: take the divided strength
! 0c1078a0: T = that was the last light.
.Lvl_strength_set:
	tst	r13,r13
! 0c1078a2: add the light. fr0 = strength, fr1-fr3 = its color.
.Lvl_add_light:
	fmac	fr0,fr1,fr13	! red sum += strength x red
	mov	#-80,r0		! r0 = 0xb0 once zero-extended: the size of a light record
	fmac	fr0,fr2,fr14	! green sum += strength x green
	bt.s	.Lvl_results	! the last light: finish the vertex
	fmac	fr0,fr3,fr15	! (delay slot) blue sum += strength x blue
	bra	.Lvl_step_light	! on to the next light
	shlr	r13		! (delay slot) T = the next light is in the mask
! 0c1078b0: this light gives nothing: step on, unless it was the last.
.Lvl_skip_light:
	tst	r13,r13		! T = that was the last light
	mov	#-80,r0		! r0 = 0xb0 once zero-extended: the size of a light record
	bt.s	.Lvl_results	! the last light: finish (the shift below runs as its delay slot)
! 0c1078b6: find the next light of the mask, a record a step.
.Lvl_find_light:
	shlr	r13		! T = this light is in the mask
! 0c1078b8: T = the next light is in the mask; r2 steps to its record.
.Lvl_step_light:
	extu.b	r0,r0		! r0 = 0xb0
	bf.s	.Lvl_find_light	! not in the mask: try the one after
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lvl_light	! work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
	nop			! never reached: padding
! 0c1078c4: not lit: the light sum is 1.0, so the base color is the
! group's own.
.Lvl_sum_one:
	fldi1	fr13		! red, blue and green sums = 1.0
	fldi1	fr15
	fldi1	fr14
! 0c1078ca: results. fv4 = w, x, y, depth; fr13-fr15 = the light sum;
! r14 = the vertex's u; r4 = the entry after.
.Lvl_results:
	flds	fr7,fpul	! fpul = the depth, as bits
	add	#32,r4		! look 32 bytes past the entry after
	pref	@r4		! fetch that cache line
	fschg			! SZ = 1: pairs
	fldi1	fr7		! fr7 = 1.0, about to become 1 / w
	fdiv	fr4,fr7		! fr7 = 1 / w
	mov.l	.Lvl_group_colours,r2	! r2 = &lit_offset_group_colours
	add	#-32,r4		! r4 = the entry after again
	sts	fpul,r0		! r0 = the depth's bits
	fmov	@r2+,fr8	! fr8, fr9 = the group's base A, R
	fmov	@r2+,fr10	! fr10, fr11 = the group's base G, B
	cmp/hi	r0,r12		! T = the vertex is on the near side of the limit
	fmul	fr13,fr9	! base R x red sum
	mov.l	@r14+,r1	! r1 = u, as bits
	fmul	fr14,fr10	! base G x green sum
	mov.l	@r14+,r2	! r2 = v, as bits
	fmul	fr15,fr11	! base B x blue sum
	fsts	fpul,fr4	! fr4 = the depth, in place of w (1 / w is in fr7)
	rts
	fschg			! (delay slot) SZ = 0 again

! lit_offset_vertex_emit (0c1078f2)
!
! Sends the vertex lit_offset_vertex_load has just produced as a
! 64-byte vertex, counting it off the strip: when r3 reaches 0 the
! vertex gets the end-of-strip control word.
!
! In:    the results of lit_offset_vertex_load: fr5, fr6 = x, y,
! fr7 = 1 / w, r1, r2 = u, v, fr8-fr11 = base color,
! fr13-fr15 = the light sum (read only when r8 >= 0).
! r3 = vertices left in the strip, this one included.
! r5, r6 = write address and store-queue address; r8 =
! material type; lit_offset_group_colours[4..7] = the group's
! offset color.
! Out:   r3 one less; T = r3 is 0 (that was the last vertex).
! r5 and r6 moved on 64 bytes.
! Uses:  changes r0, fr0, fr1, fr4-fr6 and fr12-fr15; r1, r2, r4, r7
! and fr7-fr11 are left alone.
! Notes: SZ = 0 on entry and exit.
	.global	_lit_offset_vertex_emit
	.type	_lit_offset_vertex_emit,@function
_lit_offset_vertex_emit:
.Lvertex_emit:
	dt	r3		! count the vertex; T = it is the strip's last
	lds	r6,fpul		! fpul = the queue address: the control word of a vertex
	bf	.Lve_first_block	! not the last: that is the control word
	mov	r6,r0		! the last: the address shifted right, sign kept,
	shar	r0		! is the end-of-strip control word (top bits 1111)
	sett			! T back to 1 (the shift cleared it); not read again
	lds	r0,fpul		! fpul = the end-of-strip control word
! 0c107900: the first block. V = r6 as it came in.
.Lve_first_block:
	fschg			! SZ = 1: pairs
	add	#24,r6		! r6 = V +24
	fsts	fpul,fr4	! fr4 = the control word
	fmul	fr7,fr6		! fr6 = Y = y / w
	mov.l	r2,@-r6		! V +20: v
	fmul	fr7,fr5		! fr5 = X = x / w
	mov.l	r1,@-r6		! V +16: u
	fmov	fr6,@-r6	! V +8: Y, 1 / w
	fmov	fr4,@-r6	! V +0: control word, X
	pref	@r6		! send the first block
	add	#64,r6		! r6 = V +64, the end of the vertex
	cmp/pz	r8		! T = the group is lit per vertex
	fldi0	fr12		! fr12 = 0: the offset color's alpha
	bf	.Lve_not_lit	! not lit: an offset color of zeros
	fldi1	fr0		! lit: offset color = group offset color x (sum - 1)
	fsub	fr0,fr13	! red sum - 1
	fsub	fr0,fr14	! green sum - 1
	fsub	fr0,fr15	! blue sum - 1
	mov.l	.Lvl_group_colours,r0	! r0 = &lit_offset_group_colours
	add	#16,r0		! r0 = &lit_offset_group_colours[4], the offset color
	fmov	@r0+,fr0	! fr0, fr1 = the group's offset A, R
	fmul	fr1,fr13	! fr13 = offset R x (red sum - 1)
	fmov	@r0+,fr0	! fr0, fr1 = the group's offset G, B
	fmul	fr0,fr14	! fr14 = offset G x (green sum - 1)
	fmul	fr1,fr15	! fr15 = offset B x (blue sum - 1)
	fmov	fr14,@-r6	! V +56: offset color G, B
	bra	.Lve_base_color	! on to the base color
	fmov	fr12,@-r6	! (delay slot) V +48: offset color A = 0, R
! 0c107938: a group that is not lit: offset color 0, 0, 0, 0.
.Lve_not_lit:
	fldi0	fr13		! fr12, fr13 = 0, 0
	fmov	fr12,@-r6	! V +56: offset color G, B = 0
	fmov	fr12,@-r6	! V +48: offset color A, R = 0
! 0c10793e: the base color, and the result in T.
.Lve_base_color:
	tst	r3,r3		! T = that was the strip's last vertex
	fmov	fr10,@-r6	! V +40: base color G, B
	add	#64,r5		! the list has 64 bytes more
	fmov	fr8,@-r6	! V +32: base color A, R
	fschg			! SZ = 0 again
	pref	@r6		! send the second block
	rts
	add	#32,r6		! (delay slot) r6 = the next free block

! lit_offset_vertex_keep (0c10794e)
