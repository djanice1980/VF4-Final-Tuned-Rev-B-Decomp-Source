	mov.l	.Lobj_light_colour2,r0	! r0 = &obj_light_colour2
	fmov	@r0+,fr11	! fr11 = obj_light_colour2[0] (fr11 is reloaded per group)
	fmul	fr5,fr1		! R x light color r
	fmov	@r2+,fr4	! fr4 = offset A
	fmov	@r2+,fr5	! fr5 = offset R
	fmul	fr11,fr5	! offset R x obj_light_colour2[0]
	fmov	@r0+,fr11	! fr11 = obj_light_colour2[1], for the green
	fmul	fr6,fr2		! G x light color g
	fmov	@r2+,fr6	! fr6 = offset G
	fmul	fr11,fr6	! offset G x obj_light_colour2[1]
	fmov	@r0+,fr11	! fr11 = obj_light_colour2[2], for the blue
	fmul	fr7,fr3		! B x light color b
	fmov	@r2+,fr7	! fr7 = offset B
	fmul	fr11,fr7	! offset B x obj_light_colour2[2]
	bt	.Lbump_group	! bump mapped: the colors go to bump_group_send in fr0-fr3
	mov.l	.Lgroup_colours_end,r0	! r0 = the end of lit_offset_group_colours
	fschg			! SZ = 1 for the four pair stores
	fmov	fr6,@-r0	! [6], [7] = offset G, B
	fmov	fr4,@-r0	! [4], [5] = offset A, R
	fmov	fr2,@-r0	! [2], [3] = base G, B
	fmov	fr0,@-r0	! [0], [1] = base A, R
	fschg			! SZ = 0 again
! 0c106ca2: branch on the material type.
.Lby_material:
	cmp/pz	r8		! 0 and up: lit per vertex
	bt	.Llit_group
	mov	r8,r0
	cmp/eq	#-1,r0		! -1: unlit
	bt.s	.Lunlit_group
	cmp/eq	#-2,r0		! (delay slot) -2: bump mapped
	bf	.Lnot_bump	! neither: see if it is -3
! 0c106cb0: bump mapped group. bump_group_send takes the light
! direction in fv12: fr14, fr12, fr13 = the header block's floats at
! +0x10, +0x14, +0x18 (light_dir), and fr15 = the group's factor. It
! sends the whole group and comes back with r8 = the word that ended
! it and T set when that word is 0.
.Lbump_group:
	mov.l	.Lheader_light_dir,r0	! r0 = &obj_send_header.light_dir
	fmov	@r0+,fr14
	fmov	@r0+,fr12
	fmov	@r0+,fr13
	mov.l	.Lbump_group_send,r0
	jsr	@r0		! bump_group_send
	nop			! (delay slot)
	bf	.Lafter_bump	! T clear: another group follows
	bra	.Lexit		! T set: the end of the object
	nop			! (delay slot)
! 0c106cc4: after a bump group, load the next group's words 1-3.
.Lafter_bump:
	fmov	@r4+,fr2	! fr2 = header word 1
	mov.l	@r4+,r1		! r1 = header word 2
	bra	.Lnext_group
	fmov	@r4+,fr3	! (delay slot) fr3 = header word 3
! 0c106ccc: -3 = colors carried by the vertices, any other negative
! type is treated as unlit.
.Lnot_bump:
