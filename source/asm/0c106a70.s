! 4-5) set to 1, floating colors; r0 keeps the word as it came.
	mov	r8,r0
	or	r1,r8		! set bit 4
	mov	#-33,r1
	and	r1,r8		! clear bit 5
	mov.l	r8,@-r9		! elan_group_header_words[0] = word 0, color type 1
	mov	#8,r1		! r1 = 8: not read before r1 is loaded again
	tst	#16,r0		! T = bit 4 of the word as it came is clear
	mov.b	@(4,r2),r0	! r0 = the material type byte (group +0x24)
	add	#8,r2		! r2 = group +0x28
	fmov	@r3+,fr7	! fr7 = light color b
	mov	r0,r8		! r8 = the material type from here on
	fmov	@r2+,fr15	! fr15 = the group's ambient factor (+0x28); r2 = +0x2c
	bf.s	.Lby_material	! bit 4 was set: the colors of the group before stay
	add	#48,r4		! (delay slot) r4 = the group's strips (+0x50)
! 0c106c68: the group's colors. fr0-fr3 = base A, R, G, B with A x
! the alpha scale and R, G, B x the light color; fr4-fr7 = offset A,
! R, G, B with R, G, B x obj_light_colour2.
	fmov	@r2+,fr0	! fr0 = base A
	mov	#-2,r0
	fmov	@r2+,fr1	! fr1, fr2 = base R, G
	fmov	@r2+,fr2
	cmp/eq	r0,r8		! T = the material type is -2 (bump mapped)
	fmov	@r2+,fr3	! fr3 = base B
