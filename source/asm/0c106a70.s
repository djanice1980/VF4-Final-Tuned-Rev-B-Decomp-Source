	bf.s	.Lts_first_vertex	! a vertex: r14 is right
	add	#32,r4		! (delay slot) r4 = past a 32-byte vertex
	mov.l	@(4,r14),r14	! a back reference: r14 = its offset
	add	#-24,r4		! r4 = past the 8-byte entry
	add	r4,r14		! r14 = the earlier vertex it refers to
! 0c107250: start the light sum and load the vertex.
.Lts_first_vertex:
