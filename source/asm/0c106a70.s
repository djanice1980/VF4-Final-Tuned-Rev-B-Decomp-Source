	sett			! the last vertex of a strip
	bsr	.Lnear_emit	! send cut (k-2, k) with the end-of-strip mark
	add	#-2,r0		! (delay slot) r0 = slot k-2
	dt	r3		! count vertex k; T = it was the last
	bt	.Lnc_strip_done	! the strip is done
	bra	.Lnc_scan	! look for the next vertex in view (0c107580)
	nop			! (delay slot)
