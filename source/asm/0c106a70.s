	bf	.Lunlit_group
	mov.l	.Lvertex_colour_send,r0	! r0 = vertex_colour_group_send, same contract as the bump one
	jsr	@r0		! send the whole group with its vertex colors
	nop			! (delay slot)
	bf	.Lafter_vertex_colors	! T clear: another group follows
	bra	.Lexit		! T set: the end of the object
	nop			! (delay slot)
! 0c106cdc: after a vertex-color group, the next group's words 1-3.
.Lafter_vertex_colors:
	fmov	@r4+,fr2	! fr2 = header word 1
	mov.l	@r4+,r1		! r1 = header word 2
	bra	.Lnext_group
	fmov	@r4+,fr3	! (delay slot) fr3 = header word 3
! 0c106ce4: unlit group. The ambient is 1.0, so the face color sent
! with the header below is the group's base color as it is.
.Lunlit_group:
	mov.l	.Lambient_scaled,r1	! r1 = &lit_offset_ambient_scaled
	fldi0	fr0
	add	#16,r1		! r1 = its end
	fldi1	fr1
	mov	#-1,r8		! r8 = -1 whatever negative type it was
	fmov	fr1,@-r1	! lit_offset_ambient_scaled[3], [2], [1] = 1.0
	fmov	fr1,@-r1
	fmov	fr1,@-r1
	bra	.Lgroup_ready	! no light mask is worked out for an unlit group
	fldi1	fr15		! (delay slot) fr15 = 1.0
! 0c106cf8: lit group. lit_offset_ambient_scaled[1..3] =
! light_ambient_color red, green, blue x the group's factor.
.Llit_group:
	mov.l	.Lambient_color,r0
	mov.l	.Lambient_scaled,r1
	add	#4,r0		! r0 = &light_ambient_color.red
	fmov	@r0+,fr1	! fr1 = ambient red
	add	#4,r1
	fmov	@r0+,fr2	! fr2 = ambient green
	fmul	fr15,fr1	! red x the group's factor
	fmul	fr15,fr2
	fmov	@r0+,fr0	! fr0 = ambient blue
	fmov	fr1,@r1		! lit_offset_ambient_scaled[1] = red
	add	#4,r1
	fmul	fr15,fr0	! blue x the group's factor
	fmov	fr2,@r1		! lit_offset_ambient_scaled[2] = green
	add	#4,r1
	fmov	fr0,@r1		! lit_offset_ambient_scaled[3] = blue
! 0c106d16: for a lit group find which lights reach its sphere.
.Lgroup_ready:
	cmp/pz	r8
	mov.l	.Llights_reaching,r0	! r0 = lit_offset_group_lights_reaching
	bf	.Lfirst_strip	! unlit: no call (the mask of the group before stays)
	jsr	@r0		! r4 = the strips = sphere +0x40; sets lit_offset_group_light_mask
	nop			! (delay slot)
! 0c106d20: the strips. r0 = each strip's flags word in turn.
.Lfirst_strip:
	mov.l	@r4+,r0		! r0 = the first strip's flags
! 0c106d22: a positive word is a strip. Anything else ends the group:
! the write address goes back into the list's pointer, then 0 ends
! the object and a negative word is the next group's word 0.
.Lstrip_loop:
	cmp/pl	r0		! T = a strip
	mov.l	.Lheader_words,r9
	bt.s	.Lstrip_header	! a strip: build its header
	cmp/pz	r0		! (delay slot) T = zero, the end of the object
	mov	r0,r8		! r8 = the word: the next group's word 0, or 0
	mov	r11,r0
	mov.l	r5,@(r0,r10)	! the list's write pointer = r5
	bf	.Lgroup_done
	bra	.Lexit		! zero: restore and return
	nop			! (delay slot)
! 0c106d36: load the next group's words 1-3 and go round.
.Lgroup_done:
	fmov	@r4+,fr2	! fr2 = header word 1
	mov.l	@r4+,r1		! r1 = header word 2
	bra	.Lnext_group
	fmov	@r4+,fr3	! (delay slot) fr3 = header word 3
	nop			! never reached: padding

! 0c106d40: the polygon header of one strip. r0 = its flags.
.Lstrip_header:
	mov	r0,r1		! r1 = the strip's flags, kept to the calls below
	mov	#-5,r2
	mov.l	@r9+,r3		! r3 = header word 0 as kept for the group
	and	#64,r0		! flags bit 6, Gouraud shading
	shld	r2,r0		! moved down to bit 1, its place in word 0
	mov	#-3,r2
	and	r2,r3		! word 0 without bit 1
	or	r3,r0		! r0 = word 0 with the strip's Gouraud bit
	add	#32,r4		! look 32 bytes ahead in the strip
	pref	@r4		! fetch that cache line
	fschg			! SZ = 1: the header goes out as pairs
	lds	r0,fpul		! fpul = word 0, on its way to fr0
	mov.l	@(40,r15),r2	! r2 = control_or (frame +40)
	mov	r1,r0
	cmp/pz	r2		! T = bit 31 of control_or is clear
	mov	#27,r2
	bt.s	.Lcull_set	! clear: cull mode as the flags give it
	and	#3,r0		! (delay slot) r0 = flags bits 0-1, the cull mode
	xor	#1,r0		! bit 31 set: the other winding
! 0c106d66: put the cull mode into bits 27-28 of word 1.
.Lcull_set:
	shld	r2,r0		! r0 = cull mode << 27
	mov	#3,r3
	shld	r2,r3
	not	r3,r3		! r3 = all but bits 27-28
	mov.l	@r9+,r2		! r2 = header word 1 as kept for the group
	and	r3,r2		! without its cull bits
	fsts	fpul,fr0	! fr0 = word 0 for the strip
	or	r0,r2		! r2 = word 1 with the strip's cull mode
	lds	r2,fpul
	add	#-32,r4		! r4 back on the strip's count word
	fsts	fpul,fr1	! fr1 = word 1 for the strip: fr0, fr1 is the first pair
	mov.l	.Llight_mask,r0
	add	#16,r6		! r6 = the header's block +16
	fmov	@r9+,fr2	! fr2, fr3 = header words 2 and 3
	rotcr	r12		! T = r12 bit 0: the group crosses the near limit
	mov.l	@r0,r0		! r0 = lit_offset_group_light_mask
	bt.s	.Lplain_header	! crossing: always a plain header and 64-byte vertices
	rotcl	r12		! (delay slot) r12 as it was
	tst	r0,r0		! T = no light reaches the group
	mov	#-2,r0		! r0 = -2 for the test at 0c106da2
	bt	.Lface_header	! no light: the face color header
	cmp/pz	r8
	bf	.Lface_header	! unlit: the face color header
! 0c106d94: plain header, one block. Only words 0-3 are written; the
! block's other four words are whatever the queue held.
.Lplain_header:
	fmov	fr2,@-r6	! words 2, 3 at block +8
! 0c106d96: send words 0, 1 and the block.
.Lsend_header:
	add	#32,r5		! 32 bytes more in the list
	fmov	fr0,@-r6	! words 0, 1 at block +0
	fschg			! SZ = 0 again
	pref	@r6		! send the header block
	bra	.Lsend_strip
	add	#32,r6		! (delay slot) r6 = the next block

! 0c106da2: the group is unlit or no light reaches it, so every vertex
! would get the same color. Once per group (r8 becomes -2 as the mark)
! a 64-byte header goes out with color type 2 and the face colors:
! base = group base color x ambient, offset = group offset color x
! (ambient - 1), or 0 for an unlit group. Word 0 is kept with color
! type 3 (same face colors as before) for the group's later strips,
! which take the plain header at 0c106d96.
.Lface_header:
	cmp/eq	r0,r8		! T = r8 is -2: the face colors are already out
	fmov	fr2,@-r6	! words 2, 3 at block +8
	bt	.Lsend_header	! already out: a plain header with color type 3
	add	#64,r5		! 64 bytes more in the list
	flds	fr0,fpul	! r0 = word 0 (through fpul)
	sts	fpul,r0
	or	#48,r0		! set bits 4-5
	fschg			! SZ = 0 for the single stores
	xor	#16,r0		! clear bit 4: color type 2
	fmov	fr1,@-r6	! word 1 at block +4
	add	#-16,r9		! r9 = &elan_group_header_words[0]
	mov.l	r0,@-r6		! word 0 at block +0
	or	#48,r0		! color type 3 for the strips after this one
	pref	@r6		! send the first block
	fschg			! SZ = 1: pairs
	mov.l	r0,@r9		! elan_group_header_words[0] = word 0 with color type 3
	add	#48,r6		! r6 = the second block +16
	mov.l	.Lgroup_colours_end,r0
	add	#-32,r0		! r0 = &lit_offset_group_colours[0]
	fmov	@r0+,fr0	! fr0, fr1 = base A, R
	fmov	@r0+,fr2	! fr2, fr3 = base G, B
	mov.l	.Lambient_scaled,r0	! r0 = &lit_offset_ambient_scaled
	fmov	@r0+,fr4	! fr4, fr5 = ambient [0] (not used), red
	fmul	fr5,fr1		! R x ambient red
	fmov	@r0+,fr6	! fr6, fr7 = ambient green, blue
	fmul	fr6,fr2		! G x ambient green
	mov	#-1,r0
	fmul	fr7,fr3		! B x ambient blue
	fmov	fr2,@-r6	! face base G, B at second block +8
	cmp/eq	r0,r8		! T = the group is unlit (-1)
	fmov	fr0,@-r6	! face base A, R at second block +0
	bt.s	.Lface_unlit	! unlit: the offset color is 0
	add	#32,r6		! (delay slot) r6 = the end of the second block
! Lit, but out of every light's reach: offset color x (ambient - 1).
	mov.l	.Lgroup_colours_end,r0
	add	#-16,r0		! r0 = &lit_offset_group_colours[4], the offset color
	fldi1	fr4
	fsub	fr4,fr5		! fr5, fr6, fr7 = ambient red, green, blue - 1
	fsub	fr4,fr6
	fsub	fr4,fr7
