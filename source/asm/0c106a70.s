! lit_offset_strip_send_near_clip (0c107540)
!
! Sends one strip of a group whose sphere crosses the near limit,
! cutting the strip at the limit. Every vertex is loaded and lit by
! lit_offset_vertex_load, which also tells whether it lies on the
! near side. r9 collects that, one bit a vertex with the newest in
! bit 0 (1 = near side, not to be drawn); r11 is the vertex's number
! in the strip.
! - While all vertices are on the far side they go straight out
! (lit_offset_vertex_emit), as in lit_offset_strip_send.
! - After two near-side vertices in a row the following ones are
! only transformed and tested, without lighting, until one is on
! the far side again (0c107580).
! - In between, the last three vertices are kept in
! lit_offset_clip_ring (slot = number & 3; a vertex sent or
! passed over earlier is loaded again by stepping r4 back), and a
! table on the last three bits (0c1076cc) sends the mix of kept
! vertices (lit_offset_kept_vertex_emit) and of points on the
! near limit (lit_offset_near_vertex_emit) that the case needs.
! When r12 bit 0 is set (a flat shaded strip) the newest vertex's
! colors are first copied to the two before it
! (lit_offset_flat_colour_spread). A strip that follows with flags
! bit 7 set is sent too, under the same header.
! Below, "cut (a, b)" is the point where the edge from the vertex in
! slot a to the one in slot b meets the near limit, and k is the
! number of the newest vertex.
!
! In:    r4 = the strip's count word, followed by its entries.
! r5, r6, r7, r8, XMTRX as at the top of the file.
! r12 = the near limit; bit 0 set = the strip is flat shaded.
! Out:   r0 = 1 and r12 bit 0 set (the caller's "crosses the near
! limit" flag again). r4 = the word that ended the strip; r5
! and r6 moved past what was sent.
