	fmov	@r0+,fr2	! fr2, fr3 = offset G, B
	fmul	fr5,fr1		! offset R x (ambient red - 1)
	fmul	fr6,fr2
	fmul	fr7,fr3		! and G, B likewise
	fmov	fr2,@-r6	! face offset G, B at second block +24
	fmov	fr0,@-r6	! face offset A, R at second block +16 (A as the group has it)
	add	#-16,r6		! r6 = the second block
	fschg			! SZ = 0 again
	pref	@r6		! send the second block
	mov	#-2,r8		! r8 = -2: face colors out, vertices go as intensity ones
	bra	.Lsend_strip
	add	#32,r6		! (delay slot) r6 = the next block
! 0c106e0a: unlit group: a face offset color of four zeros.
.Lface_unlit:
	fldi0	fr0
	fldi0	fr1
	fmov	fr0,@-r6	! face offset G, B = 0 at second block +24
	fmov	fr0,@-r6	! face offset A, R = 0 at second block +16
	add	#-16,r6		! r6 = the second block
	fschg			! SZ = 0 again
	pref	@r6		! send the second block
	mov	#-2,r8		! r8 = -2: face colors out, vertices go as intensity ones
	add	#32,r6		! r6 = the next block

! 0c106e1c: send the strip's vertices. r1 = its flags, r4 = its count.
