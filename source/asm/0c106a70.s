	dt	r3		! count vertex k; T = it was the last
	bsr	.Lnear_emit	! send cut (k-1, k), ending the strip if T
	add	#-1,r0		! (delay slot) r0 = slot k-1
	bf	.Lnc_cut_loop	! more vertices: the cutting loop
	bra	.Lnc_strip_end	! the strip is done
	nop			! (delay slot)
! 0c10776a, case 6: only k is in view: a new run starts. Send
! cut (k-2, k), cut (k-1, k), vertex k. When k is odd, cut (k-1, k)
! is sent once more in front (the reason is not established; an
