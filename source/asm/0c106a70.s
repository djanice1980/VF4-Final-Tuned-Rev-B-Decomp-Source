! vertex k-1, vertex k, and go back to the plain loop.
.Lnc_case4:
	mov	r11,r0
	clrt			! not the last vertex of a strip
	bsr	.Lnear_emit	! send cut (k-2, k)
	add	#-2,r0		! (delay slot) r0 = slot k-2
	mov	r11,r0
	clrt			! not the last vertex of a strip
	bsr	.Lkept_emit	! send the kept vertex k-1
	add	#-1,r0		! (delay slot) r0 = slot k-1
	dt	r3		! count vertex k; T = it was the last
	bsr	.Lkept_emit	! send the kept vertex k, ending the strip if T
	mov	r11,r0		! (delay slot) r0 = slot k
	bt	.Lnc_strip_done	! the strip is done
	bra	.Lnc_plain_loop	! two in view in a row: the plain loop again
	add	#1,r11		! (delay slot) r11 = the next vertex number
! 0c107758: the way out of cases 3 and 4 when the strip is done.
.Lnc_strip_done:
	bra	.Lnc_strip_end	! the strip is done
	nop			! (delay slot)
! 0c10775c, case 5: only k-1 is in view. Send cut (k-1, k).
.Lnc_case5:
