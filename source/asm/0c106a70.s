	tst	#1,r0		! T = k is even
	bt	.Lnc_case6_even	! even: no extra vertex
	mov	r11,r0
	clrt			! not the last vertex of a strip
	bsr	.Lnear_emit	! k odd: send cut (k-1, k) first
	add	#-1,r0		! (delay slot) r0 = slot k-1
