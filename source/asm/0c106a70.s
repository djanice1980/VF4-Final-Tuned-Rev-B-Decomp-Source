	bsr	.Lkept_emit	! send the kept vertex k
	mov	r11,r0		! (delay slot) r0 = slot k
	mov	r11,r0
	clrt			! not the last vertex of a strip
	bsr	.Lnear_emit	! send cut (k-1, k)
	add	#-1,r0		! (delay slot) r0 = slot k-1
	dt	r3		! count vertex k; T = it was the last
	bsr	.Lkept_emit	! send the kept vertex k, ending the strip if T
	mov	r11,r0		! (delay slot) r0 = slot k
	bf	.Lnc_cut_loop	! more vertices: the cutting loop
	bra	.Lnc_strip_end	! the strip is done
	nop			! (delay slot)
! 0c10772c, case 3: only k-2 is in view. Send cut (k-2, k) as the end
! of a strip; with two near-side vertices in a row, scan on.
.Lnc_case3:
