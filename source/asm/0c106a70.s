! lit_offset_strip_send (0c106ed0)
!
! Sends one strip that needs no clipping. For a lit group (r8 >= 0)
! each vertex goes out as a 64-byte floating-color vertex:
! light sum (red, green, blue) = lit_offset_ambient_scaled[1..3]
! plus, for every light of lit_offset_group_light_mask, its color
! (light record +0x18) times a strength:
! type 2 (directional): model_dir . normal, when not negative.
! type 3 (point): with L = model_pos - vertex and d = |L|, the
! light is skipped when L . normal is negative or d squared is
! not below the float at record +0x98; else the strength is
! (L . normal) / d, divided by the attenuation
! a = [+0x4c] + d x [+0x50] + d squared x [+0x54] when a is
! above 1.
! any other type (spot): as a point light, times
! (c - cone_cos) x cone_scale, where c is the cosine of the
! angle between model_dir and the direction from the light to
! the vertex; skipped when c is below cone_cos.
! base color = lit_offset_group_colours[0..3], its R, G, B x the sum;
! offset color = 0 for A and lit_offset_group_colours[5..7] x
! (sum - 1) for R, G, B.
! The position goes through ftrv; X = x / w, Y = y / w and 1 / w are
! sent with u and v. The last vertex carries the end-of-strip control
! word. When the word after the strip is positive with bit 7 set, the
! strip it starts is sent as well, under the same header.
! For a group with r8 < 0 (the caller has sent the face colors with
! the header) the path at 0c107100 sends 32-byte vertices instead:
! control word, X, Y, 1/w, u, v, base intensity 1.0, offset
! intensity 1.0.
!
! In:    r4 = the strip's count word, followed by its entries.
! r5, r6 = the list's write address and store-queue address.
! r8 = material type; XMTRX = the transform.
! lit_offset_ambient_scaled, lit_offset_group_light_mask,
! lit_offset_group_colours, light_table (model_pos, model_dir,
! color and the cone and range fields).
! Out:   r4 = the word that ended the strip (the next flags word, or
! the end of the group); r5 and r6 moved past what was sent.
! Uses:  changes r0-r3, r13, r14 and fr0-fr15 and saves none of them
! (lit_offset_groups_send_alpha has saved r13, r14 and
! fr12-fr15 for its own caller). r7-r12 are left alone.
! Notes: only caller lit_offset_groups_send_alpha; SZ = 0 on entry
! and exit. The light record fields at +0x4c, +0x50 and +0x54 are
! atten[0..2] and the one at +0x98 is range_sq.
	.global	_lit_offset_strip_send
	.type	_lit_offset_strip_send,@function
_lit_offset_strip_send:
.Lstrip_send:
	cmp/pz	r8		! lit per vertex when r8 is 0 or more
	bt	.Lss_lit
	bra	.Lss_unlit	! r8 below 0: the 32-byte intensity vertices
	nop			! (delay slot)
! 0c106ed8: the lit path. V below is the queue address of the vertex
! being built; r6 runs ahead of it because the stores count down.
.Lss_lit:
	mov.l	@r4+,r3		! r3 = the number of vertices
	add	#48,r6		! r6 = V +48
	mov.l	@r4,r0		! r0 = the first word of the first entry
	mov	r4,r14		! r14 = the entry, taken as a vertex
	tst	#1,r0		! bit 0 set marks a vertex stored here
	mov.l	.Lss_light_mask,r13	! r13 = &lit_offset_group_light_mask
	bf.s	.Lss_first_vertex	! a vertex: r14 is right
	add	#32,r4		! (delay slot) r4 = past a 32-byte vertex
	mov.l	@(4,r14),r14	! a back reference: r14 = its offset
	add	#-24,r4		! r4 = past the 8-byte entry
	add	r4,r14		! r14 = the earlier vertex it refers to
! 0c106eee: start the light sum and load the first vertex.
.Lss_first_vertex:
	mov.l	.Lss_ambient_scaled,r0
	fschg			! SZ = 1: pairs
	mov.l	@r13,r13	! r13 = the mask of lights reaching the group
	fmov	@r0+,fr12	! fr12, fr13 = ambient [0] (not used), red
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue: the sum starts here
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#32,r4		! r4 = 32 bytes past the next entry, for the fetch ahead
	fmov	@r14+,fr6	! fr6, fr7 = z, normal x
	bra	.Lss_light_sum
	fschg			! (delay slot) SZ = 0 again
	nop			! never reached: padding
! 0c106f04: the next vertex is stored here (r14 = it). r6 = V of the
! vertex just written, whose second block has still to be sent.
.Lss_next_vertex:
	mov.l	.Lss_ambient_scaled,r0	! r0 = &lit_offset_ambient_scaled
	add	#32,r6		! r6 = that vertex's second block
	mov.l	@r13,r13	! r13 = the light mask again (r13 held its address)
	mov	r6,r1		! r1 = the block to send
	fmov	@r0+,fr12	! fr12, fr13 = ambient [0], red
	add	#64,r5		! the list has 64 bytes more
! 0c106f10: also entered from 0c1070c4 for the first vertex of a
! strip that carries on.
.Lss_next_load:
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	add	#64,r4		! r4 = 32 bytes past the entry after this vertex
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#80,r6		! r6 = the new V +48
	fmov	@r14+,fr6	! fr6, fr7 = z, normal x
	fschg			! SZ = 0 again
	pref	@r1		! send the second block of the vertex before

! 0c106f1e: the light sum for one vertex. fr4-fr6 = position, fr7 =
! normal x, r14 = the vertex's normal y; fr13-fr15 = the sum so far.
! r13 = the lights still to do, r2 = the record of the light in hand.
! The position is put through ftrv while the last light is worked
! out (r13 has become 0), not before: the lights need it untouched.
.Lss_light_sum:
	fmov	fr7,fr8		! fr8 = normal x
	tst	r13,r13		! T = no light reaches the group
	fmov	@r14+,fr9	! fr9 = normal y
	bt.s	.Lss_no_lights	! none: only the transform is left to do
	fmov	@r14+,fr10	! (delay slot) fr10 = normal z; r14 = the vertex's u
	shlr	r13		! T = light 0 is in the mask
	mov.l	.Lss_light_table,r2	! r2 = light_table, record 0
	bf	.Lss_no_gain	! not light 0: look for the first one that is
	mov.w	@(2,r2),r0	! r0 = the light's type (+2)
! 0c106f30: one light. r2 = its record, r0 = its type.
.Lss_light:
	fldi0	fr3		! fr3 = 0, so that fipr adds up x, y, z only
	cmp/eq	#2,r0		! type 2 is a directional light
	mov	#116,r1
	bf.s	.Lss_point_or_spot	! another type: a point or a spot light
	add	r2,r1		! (delay slot) r1 = &record.model_pos (+0x74)
	fldi1	fr7		! w = 1 for the vertex position
	tst	r13,r13		! T = this is the last light
	add	#12,r1		! r1 = &record.model_dir (+0x80)
	bf.s	.Lss_directional	! not the last: the transform waits
	fmov	@r1+,fr0	! (delay slot) fr0 = direction x
	ftrv	xmtrx,fv4	! last light: fv4 = w, x, y, depth of the vertex
! 0c106f46: directional. Strength = model_dir . normal.
.Lss_directional:
	fmov	@r1+,fr1	! fr1 = direction y
	mov	r2,r0
	fmov	@r1+,fr2	! fr2 = direction z
	add	#24,r0		! r0 = &record.color.red (+0x18)
	fipr	fv0,fv8		! fr11 = direction . normal
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	fmov	@r0+,fr3
	fldi0	fr0		! fr0 = 0 to compare with
	fcmp/gt	fr11,fr0	! T = the normal faces away from the light
	fmov	fr11,fr0	! fr0 = the strength
	bf.s	.Lss_add_light	! facing the light: add it to the sum
	tst	r13,r13		! (delay slot) T = that was the last light
! 0c106f60: nothing to add for this light. T = it was the last one.
.Lss_no_gain:
	mov	#-80,r0		! r0 = 0xb0 once zero-extended: the size of a light record
	bt	.Lss_finish_vertex	! the last light: finish the vertex
	shlr	r13		! T = the next light is in the mask
	extu.b	r0,r0
	bf.s	.Lss_find_light	! not in the mask: go on looking
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lss_light	! work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
! 0c106f70: no light reaches the group: transform and finish.
.Lss_no_lights:
	fldi1	fr7		! w = 1 for the vertex position
	bra	.Lss_finish_vertex
	ftrv	xmtrx,fv4	! (delay slot) fv4 = w, x, y, depth of the vertex
	nop			! never reached: padding
! 0c106f78: a point or a spot light. r1 = &record.model_pos, r0 = the
! type. fv0 = L, the vector from the vertex to the light.
.Lss_point_or_spot:
	fmov	@r1+,fr0	! fr0 = light x
	tst	r13,r13		! T = this is the last light
	fmov	@r1+,fr1	! fr1 = light y
	fsub	fr4,fr0		! fr0 = L x
	fmov	@r1+,fr2	! fr2 = light z; r1 = record +0x80
	fsub	fr5,fr1		! fr1 = L y
	fldi1	fr7		! w = 1 for the vertex position
	add	#24,r1		! r1 = record +0x98
	fldi0	fr11		! fr11 = 0: the normal's fourth component
	bf.s	.Lss_range_test	! not the last light: the transform waits
	fsub	fr6,fr2		! (delay slot) fr2 = L z
	ftrv	xmtrx,fv4	! last light: fv4 = w, x, y, depth (L is already taken)
! 0c106f90: facing and range tests.
.Lss_range_test:
	fipr	fv0,fv8		! fr11 = L . normal
	fldi0	fr12		! fr12 = 0 to compare with (fr12 is free: not part of the sum)
	fipr	fv0,fv0		! fr3 = L . L, the distance squared
	fcmp/gt	fr11,fr12	! T = the normal faces away from the light
	fmov	@r1,fr12	! fr12 = the float at record +0x98
	bt	.Lss_skip_light	! facing away: nothing from this light
	fcmp/gt	fr3,fr12	! T = the distance squared is below that float
	bf	.Lss_skip_light	! too far: nothing from this light
	cmp/eq	#3,r0		! type 3 is a point light
	flds	fr3,fpul	! fpul = the distance squared, kept for later
	bt.s	.Lss_attenuate	! a point light has no cone
	fsrra	fr3		! (delay slot) fr3 = 1 / distance
! Spot light: c = cosine of the angle between model_dir and the
! direction from the light to the vertex = -(L . model_dir) / distance.
	add	#-24,r1		! r1 = &record.model_dir (+0x80)
	fmov	@r1+,fr12	! fr12 = direction x
	fmul	fr0,fr12	! fr12 = direction x times L x
	fmov	@r1+,fr0	! fr0 = direction y
	fmac	fr0,fr1,fr12	! plus direction y times L y
	fmov	@r1,fr0		! fr0 = direction z; r1 = record +0x88
	add	#-48,r1		! r1 = &record.cone_cos (+0x58)
	fmac	fr0,fr2,fr12	! fr12 = L . model_dir
	fmov	@r1,fr2		! fr2 = cone_cos
	fneg	fr12		! toward the vertex, not toward the light
	fmul	fr3,fr12	! fr12 = c
	add	#68,r1		! r1 = &record.cone_scale (+0x9c)
	fcmp/gt	fr12,fr2	! T = c is below cone_cos: outside the cone
	fsub	fr2,fr12	! fr12 = c - cone_cos
	fmov	@r1,fr2		! fr2 = cone_scale
	bt	.Lss_skip_light	! outside the cone: nothing from this light
	fmul	fr2,fr12	! fr12 = (c - cone_cos) x cone_scale: 0 at the edge
	add	#-4,r1		! r1 = record +0x98, as on the point light path
	fmul	fr12,fr11	! fr11 = L . normal x the cone factor
! 0c106fce: attenuation. r1 = record +0x98, fr3 = 1 / distance, fpul =
! distance squared. a = [+0x4c] + distance x [+0x50] + distance
! squared x [+0x54]; the strength is divided by a only when a > 1.
.Lss_attenuate:
	add	#-68,r1		! r1 = record +0x54
	fmov	@r1,fr2		! fr2 = the float at +0x54
	add	#-8,r1		! r1 = record +0x4c
	fsts	fpul,fr0	! fr0 = distance squared
	fmul	fr3,fr11	! fr11 = (L . normal) / distance [x the cone factor]
	fmov	@r1,fr12	! fr12 = the float at +0x4c
	fmul	fr0,fr3		! fr3 = the distance
	add	#4,r1		! r1 = record +0x50
	fmac	fr0,fr2,fr12	! fr12 = [+0x4c] + distance squared x [+0x54]
	fmov	@r1,fr2		! fr2 = the float at +0x50
	mov	r2,r0
	fmov	fr3,fr0		! fr0 = the distance
	fmac	fr0,fr2,fr12	! fr12 = a, with distance x [+0x50] added
	fmov	fr11,fr0	! fr0 = the strength, not divided
	add	#24,r0		! r0 = &record.color.red (+0x18)
	fdiv	fr12,fr11	! fr11 = the strength divided by a
	fldi1	fr2
	fcmp/gt	fr2,fr12	! T = a is above 1
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	bf.s	.Lss_strength_set	! a is 1 or less: keep the strength as it is
	fmov	@r0+,fr3	! (delay slot) fr3 = the light's blue
	fmov	fr11,fr0	! a above 1: take the divided strength
! 0c106ffc: T = that was the last light.
.Lss_strength_set:
	tst	r13,r13
! 0c106ffe: add the light. fr0 = strength, fr1-fr3 = its color.
.Lss_add_light:
	fmac	fr0,fr1,fr13	! red sum += strength x red
	mov	#-80,r0		! r0 = 0xb0 once zero-extended: the size of a light record
	fmac	fr0,fr2,fr14	! green sum += strength x green
	bt.s	.Lss_finish_vertex	! the last light: finish the vertex
	fmac	fr0,fr3,fr15	! (delay slot) blue sum += strength x blue
	bra	.Lss_step_light	! on to the next light
	shlr	r13		! (delay slot) T = the next light is in the mask
! 0c10700c: this light gives nothing: step on, unless it was the last.
.Lss_skip_light:
	tst	r13,r13		! T = that was the last light
	mov	#-80,r0		! r0 = 0xb0 once zero-extended: the size of a light record
	bt.s	.Lss_finish_vertex	! the last light: finish (the shift below runs as its delay slot)
! 0c107012: find the next light of the mask, a record a step.
.Lss_find_light:
	shlr	r13		! T = this light is in the mask
! 0c107014: T = the next light is in the mask; r2 steps to its record.
.Lss_step_light:
	extu.b	r0,r0		! r0 = 0xb0
	bf.s	.Lss_find_light	! not in the mask: try the one after
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lss_light	! work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type

! 0c10701e: finish the vertex. fv4 = w, x, y, depth; fr13-fr15 = the
! light sum; r14 = the vertex's u; r4 = 32 past the next entry;
! r6 = V +48.
.Lss_finish_vertex:
	mov.l	.Lss_group_colours,r2	! r2 = &lit_offset_group_colours
	fschg			! SZ = 1: pairs
	fldi1	fr7		! fr7 = 1.0, about to become 1 / w
	fdiv	fr4,fr7		! fr7 = 1 / w (ready by the time it is used below)
	pref	@r4		! fetch the stream 32 bytes past the next entry
	add	#-32,r4		! r4 = the next entry
	fmov	@r2+,fr8	! fr8, fr9 = the group's base A, R
	mov	r6,r1		! r1 = V +48, to be the last vertex's control word
	shar	r1		! top bits 1111: the end-of-strip control word
	fmov	@r2+,fr10	! fr10, fr11 = the group's base G, B
	fmul	fr13,fr9	! base R x red sum
	mov.l	@r4,r0		! r0 = the next entry's first word
	fmul	fr14,fr10	! base G x green sum
	add	#16,r6		! r6 = V +64, the end of the vertex
	fmul	fr15,fr11	! base B x blue sum
	fmov	@r14+,fr2	! fr2, fr3 = u, v
	fldi0	fr12		! fr12 = 0: the offset color's alpha
	fldi1	fr0
	fsub	fr0,fr13	! red sum - 1
	mov.l	.Lss_group_colours,r2	! r2 = &lit_offset_group_colours again
	fsub	fr0,fr14	! green sum - 1
	add	#16,r2		! r2 = &lit_offset_group_colours[4], the offset color
	fsub	fr0,fr15	! blue sum - 1
	fmov	@r2+,fr0	! fr0, fr1 = the group's offset A, R
	fmul	fr1,fr13	! fr13 = offset R x (red sum - 1)
	fmov	@r2+,fr0	! fr0, fr1 = the group's offset G, B
	fmul	fr0,fr14	! fr14 = offset G x (green sum - 1)
	fmul	fr1,fr15	! fr15 = offset B x (blue sum - 1)
	fmov	fr14,@-r6	! V +56: offset color G, B
	fmov	fr12,@-r6	! V +48: offset color A = 0, R
	mov.l	.Lss_light_mask,r13	! r13 = &lit_offset_group_light_mask for the next vertex
	dt	r3		! count the vertex; T = it was the strip's last
	fmov	fr10,@-r6	! V +40: base color G, B
	mov	r4,r14		! r14 = the next entry
	fmov	fr8,@-r6	! V +32: base color A, R
	add	#-8,r6		! pass the two words at V +24 that are not written
	fmul	fr7,fr6		! fr6 = Y = y / w
	fmov	fr2,@-r6	! V +16: u, v
	fmul	fr7,fr5		! fr5 = X = x / w
	fmov	fr6,@-r6	! V +8: Y, 1 / w
	bt.s	.Lss_last_vertex	! the last vertex: its control word differs
	fmov	fr4,@-r6	! (delay slot) V +0: w and X; w is overwritten below
	tst	#1,r0		! T = the next entry is a back reference
	mov.l	r6,@r6		! V +0: the control word, the queue address itself
	bt	.Lss_next_backref	! a back reference: load through it below
	bra	.Lss_next_vertex	! a vertex stored here: 0c106f04
! 0c10707a: this pref is the delay slot of the bra above and also
! where the bt lands: both ways the first block of the vertex goes.
.Lss_next_backref:
	pref	@r6		! send the first block of the vertex
	add	#8,r4		! the next entry is a back reference: r4 = past it
	mov.l	@(4,r14),r14	! r14 = its offset
	add	#32,r6		! r6 = the second block of the vertex just written
	mov.l	.Lss_ambient_scaled,r0	! r0 = &lit_offset_ambient_scaled
	add	r4,r14		! r14 = the earlier vertex it refers to
	mov.l	@r13,r13	! r13 = the light mask
	add	#64,r5		! the list has 64 bytes more
	fmov	@r0+,fr12	! fr12, fr13 = ambient [0], red
	mov	r6,r1		! r1 = the block to send
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	add	#32,r4		! r4 = 32 bytes past the entry after this one
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#80,r6		! r6 = the new V +48
	fmov	@r14+,fr6	! fr6, fr7 = z, normal x
	fschg			! SZ = 0 again
	bra	.Lss_light_sum	! the light sum for this vertex
	pref	@r1		! (delay slot) send the second block of the vertex before
	nop			! never reached: padding

! 0c1070a0: the strip's last vertex is built; r1 = its control word.
.Lss_last_vertex:
	mov.l	@r4+,r0		! r0 = the word after the strip
	mov.l	r1,@r6		! V +0: the end-of-strip control word
	cmp/pl	r0		! T = another strip follows
	pref	@r6		! send the first block of the vertex
	add	#32,r6		! r6 = its second block
	bf	.Lss_return	! the group ends here: return
	tst	#128,r0		! flags bit 7: the strip carries on under this header
	mov.l	.Lss_light_mask,r13	! r13 = &lit_offset_group_light_mask
	bt	.Lss_return	! bit 7 clear: return, the caller writes a new header
	mov.l	@r4+,r3		! r3 = the number of vertices of the strip that carries on
	mov	r6,r1		! r1 = the block still to send
	mov.l	@r4,r0		! r0 = the first word of its first entry
	mov	r4,r14		! r14 = that entry, taken as a vertex
	mov.l	@r13,r13	! r13 = the light mask
	tst	#1,r0		! T = the entry is a back reference
	mov.l	.Lss_ambient_scaled,r0	! r0 = &lit_offset_ambient_scaled
	add	#64,r5		! the list has 64 bytes more
	bt	.Lss_carry_on_backref	! a back reference: load through it below
	bra	.Lss_next_load	! a vertex stored here: 0c106f10
! 0c1070c6: delay slot of the bra above and where the bt lands. SZ is
! still 1 here.
.Lss_carry_on_backref:
	fmov	@r0+,fr12	! fr12, fr13 = ambient [0], red
	add	#8,r4		! a back reference: r4 = past the 8-byte entry
	mov.l	@(4,r14),r14	! r14 = its offset
	add	#80,r6		! r6 = the new V +48
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	add	r4,r14		! r14 = the earlier vertex it refers to
	pref	@r1		! send the second block of the vertex before
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#32,r4		! r4 = 32 bytes past the entry after this one
	fmov	@r14+,fr6	! fr6, fr7 = z, normal x
	bra	.Lss_light_sum	! the light sum for this vertex
	fschg			! (delay slot) SZ = 0 again
! 0c1070de: return. r6 = the second block of the last vertex.
.Lss_return:
	add	#-4,r4		! r4 = back on the word that ended the strip
	fschg			! SZ = 0 for the caller
	add	#64,r5		! the list has 64 bytes more
	pref	@r6		! send the second block of the last vertex
	rts
	add	#32,r6		! (delay slot) r6 = the next free block
	nop			! never reached: padding up to the pool
	nop
	nop
! Pool of the lit path of lit_offset_strip_send.
.Lss_group_colours:
	.long	_lit_offset_group_colours
.Lss_ambient_scaled:
	.long	_lit_offset_ambient_scaled
.Lss_light_table:
	.long	_light_table
.Lss_light_mask:
	.long	_lit_offset_group_light_mask

! 0c107100: the path for r8 < 0: 32-byte intensity vertices, both
! intensities 1.0. The two store queues take the blocks in turn, so
! the pair of 1.0s is written once into the last two words of each
! queue and stays there; a vertex then writes only its first 24
! bytes. The loop does two vertices a turn: vertex A in fv4 and
! vertex B in fv8, each one transformed while the other is stored.
! V below is the queue address of the vertex being stored.
.Lss_unlit:
	mov.l	@r4+,r3		! r3 = the number of vertices
	fldi1	fr2
	fschg			! SZ = 1: pairs
	fldi1	fr3		! fr2, fr3 = 1.0, 1.0: base and offset intensity
	fmov	fr2,@-r6	! the last two words of the block before, in the other queue
	add	#32,r6		! r6 = V +24
	fmov	fr2,@r6		! V +24: the last two words of this queue's block
	mov.l	@r4,r0		! r0 = the first word of the first entry
	mov	r4,r14		! r14 = the entry, taken as a vertex
	tst	#1,r0		! bit 0 set marks a vertex stored here
	add	#32,r4		! r4 = past a 32-byte vertex
	bf	.Lss_unlit_first	! a vertex: r14 is right
	mov.l	@(4,r14),r14	! a back reference: r14 = its offset
	add	#-24,r4		! r4 = past the 8-byte entry
	add	r4,r14		! r14 = the earlier vertex it refers to
! 0c10711e: load and transform the first vertex (the normal is not
! used on this path).
.Lss_unlit_first:
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	fmov	@r14,fr6	! fr6 = z (fr7 takes normal x and is set to 1 below)
	add	#16,r14		! r14 = the vertex's u (+24)
	fldi1	fr7
	fmov	@r14,fr0	! fr0, fr1 = u, v
	ftrv	xmtrx,fv4	! fv4 = w, x, y, depth
! 0c10712a: vertex A is in fv4 with u, v in fr0, fr1; r6 = V +24.
.Lss_unlit_a:
	fldi1	fr7		! fr7 = 1.0, about to become 1 / w
	fdiv	fr4,fr7		! fr7 = 1 / w of A
	dt	r3		! count A; T = it is the strip's last
