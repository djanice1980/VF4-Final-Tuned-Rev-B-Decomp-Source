! 0c1076b6: the cutting loop: load the next vertex, keep it, and pick
! the case by its bit and those of the two before it.
.Lnc_cut_loop:
	bsr	.Lvertex_load	! load and light the next vertex; T = near side
	add	#1,r11		! (delay slot) r11 = its number
	bsr	.Lvertex_keep	! keep it in slot r11 & 3
	rotcl	r9		! (delay slot) its bit into r9
	mov	r12,r0		! r0 = r12, for its bit 0
	tst	#1,r0		! T = bit 0 clear: Gouraud shaded
	bt.s	.Lnc_dispatch	! Gouraud: the kept colors stay
	mov	r9,r0		! (delay slot) r0 = the near bits
	bsr	.Lflat_spread	! flat: vertex k's colors into slots k-1 and k-2
	nop			! (delay slot)
	mov	r9,r0		! r0 = the near bits
! 0c1076cc: the table. r0 & 7 = the bits of vertices k-2, k-1, k (bit
! 0 = k; 1 = near side). braf jumps r0 x 4 bytes past 0c1076d4. Cases
! 0 and 7 have no entry and would fall into case 1; the paths into
! the table do not produce them (two far-side vertices in a row
! leave by case 4, two near-side ones by case 3). Each case counts
! vertex k itself (dt r3).
.Lnc_dispatch:
