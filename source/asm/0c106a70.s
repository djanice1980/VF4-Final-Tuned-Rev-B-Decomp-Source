! lit_offset_tris_send (0c107230)
!
! Sends a triangle list that needs no clipping. It is
! lit_offset_strip_send over again, with the third vertex of every
! triangle given the end-of-strip control word, so that each triangle
! is a strip of its own. The light sum and the 64-byte vertex are
! the same, instruction for instruction (see lit_offset_strip_send
! for both), and so is the 32-byte intensity path for r8 < 0, here
! at 0c107430. Nothing carries on after the list: bit 7 of the word
! that follows is not looked at.
!
! In:    r4 = the list's count word (triangles), followed by three
! entries a triangle.
! r5, r6, r8, XMTRX and the globals as lit_offset_strip_send.
! Out:   r4 = the word after the last triangle; r5 and r6 moved past
! what was sent.
! Uses:  as lit_offset_strip_send (r0-r3, r13, r14, fr0-fr15), and
! r9 = the triangles left, changed and not saved either.
! Notes: only caller lit_offset_groups_send_alpha; SZ = 0 on entry
! and exit.
	.global	_lit_offset_tris_send
	.type	_lit_offset_tris_send,@function
_lit_offset_tris_send:
.Ltris_send:
	cmp/pz	r8		! lit per vertex when r8 is 0 or more
	bt	.Lts_lit
	bra	.Lts_unlit	! r8 below 0: the 32-byte intensity vertices
	nop			! (delay slot)
! 0c107238: the lit path. r9 = triangles left, r3 = vertices left in
! the triangle, V = the queue address of the vertex being built.
.Lts_lit:
	mov.l	@r4+,r9		! r9 = the number of triangles
	mov	#3,r3
	add	#48,r6		! r6 = V +48
! 0c10723e: the first vertex of a triangle, as at 0c106edc.
.Lts_triangle:
	mov.l	@r4,r0		! r0 = the first word of the first entry
	mov	r4,r14		! r14 = the entry, taken as a vertex
	tst	#1,r0		! bit 0 set marks a vertex stored here
