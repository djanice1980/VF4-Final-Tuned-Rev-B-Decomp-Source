! plane. The entry and the vertex record are those of
! vertex_colour_strip_send (source/asm/0c10d2d0.s), and the color is
! worked out the same way: each color byte times its scale in
! fr12-fr15, and for a lit vertex red, green and blue times
! (group float + max(0, N.L) / 127). Nothing is written.
! Called (bsr) by vertex_colour_strip_near_clip and
! vertex_colour_tri_near_clip.
!
! In:    r4 = the entry (a 32-byte record, or an 8-byte reference).
!        r12 = the near value as raw float bits (bit 0 is a flag of
!        the callers and takes part in the compare as the lowest bit).
!        fr12-fr15 = the scales of the alpha, red, green, blue bytes.
!        sp +36, +40, +44 = the light direction's second, third and
!        first float, sp +48 = the group float: the group sender's
!        saved fr12-fr15, 12 bytes further up than in the unclipped
!        senders because the clipper has pushed r10, r11 and pr.
!        XMTRX = the transform; its fourth result is minus depth.
! Out:   T = 1 when the vertex is behind the near plane: r12 is above
!        the raw bits of minus depth, compared as unsigned numbers.
!        fr4 = minus depth, fr5 = x, fr6 = y (not yet divided by
!        depth), fr7 = 1 / depth; fr8-fr11 = the base color alpha,
!        red, green, blue; r1 = &u, v in the record.
!        r4 = the entry after this one.
! Uses:  r0, r2, r8, r14 and fr0-fr3 are changed as well (r8, r14
!        and fr8-fr11 without being saved, unlike compiled code). r3,
!        r5, r6, r7 are not touched.
! Notes: 32-bit fmov throughout (FPSCR SZ = 0, PR = 0).
	.global	_vertex_colour_vtx_load
	.type	_vertex_colour_vtx_load,@function
_vertex_colour_vtx_load:
.Lvtx_load:				! 0c10d740
	mov.l	@r4,r0			! r0 = the entry's first word
	tst	#1,r0			! T = bit 0 clear: a reference
	mov	r4,r14
	bf.s	.Lload_record		! bit 0 set: the record is here (r14)
	add	#32,r4			! (delay slot) r4 = past a 32-byte record
	mov.l	@(4,r14),r14		! reference: r14 = the offset in its second word
	add	#-24,r4			! r4 = past the 8-byte reference
	add	r4,r14			! r14 = the record: the end of the reference + the offset
! 0c10d750: r14 = the record.
.Lload_record:
	fmov	@r14+,fr4		! fr4 = x
	fmov	@r14+,fr5		! fr5 = y; r14 = record +8
	fmov	@r14,fr6		! fr6 = z
	mov	r14,r1
	fldi1	fr7			! fr7 = 1: the point (x, y, z, 1)
	mov.b	@(7,r14),r0		! r0 = the lit byte (record +15)
	add	#16,r1			! r1 = &u, v (record +24)
	mov.l	@(8,r14),r8		! r8 = the color word (record +16)
	cmp/pl	r0			! T = the vertex is lit
	extu.b	r8,r0			! r0 = the blue byte
	bf.s	.Lload_color		! not lit: straight to the color
	ftrv	xmtrx,fv4		! (delay slot) fr4 = depth, fr5 = x, fr6 = y, fr7 = minus depth
! Lit vertex: the normal's bytes as floats, in fr0-fr2 with fr3 = 0.
	mov.l	@(4,r14),r2		! r2 = the normal word (record +12)
	exts.b	r2,r0
	shlr8	r2
	lds	r0,fpul
	exts.b	r2,r0
	float	fpul,fr1		! fr1 = byte 0 (third component)
	shlr8	r2
	lds	r0,fpul
	exts.b	r2,r0
	float	fpul,fr0		! fr0 = byte 1 (second component)
	lds	r0,fpul
	float	fpul,fr2		! fr2 = byte 2 (first component)
	fldi0	fr3			! fr3 = 0: no fourth term in the dot product
! The light direction and the group float from the group sender's
! pushes; meanwhile r0 is built up to 0x3c010204, the float 1/127.
	mov	r15,r2
	add	#36,r2			! r2 = &the group sender's saved fr12 (sp +36)
	fmov	@r2+,fr8		! fr8 = light direction, second float
	mov	#60,r0
	fmov	@r2+,fr9		! fr9 = light direction, third float
	shll8	r0
	fmov	@r2+,fr10		! fr10 = light direction, first float
	or	#1,r0
	fipr	fv8,fv0			! fr3 = N.L (fr11's term is times fr3 = 0)
	shll8	r0
	fmov	@r2+,fr2		! fr2 = the group float (the saved fr15)
	or	#2,r0
	fldi0	fr0			! fr0 = 0 for the test below
	shll8	r0
	or	#4,r0			! r0 = 0x3c010204
	lds	r0,fpul
	extu.b	r8,r0			! r0 = the blue byte again
	fcmp/gt	fr0,fr3			! T = N.L is above 0
	fsts	fpul,fr11		! fr11 = 1/127
	bf	.Lload_sum_ready	! facing away: the light sum is the group float alone
	fmul	fr11,fr3		! fr3 = N.L / 127
	fadd	fr3,fr2			! fr2 = the light sum: group float + N.L / 127
.Lload_sum_ready:			! 0c10d7ae
	sett				! T = 1: remembered as "lit" for the bf.s at 0c10d7d8
! 0c10d7b0: the color bytes as floats (T = lit; nothing here changes T),
! 1 / depth, and minus depth for the near test. r0 = the blue byte.
.Lload_color:
	fldi1	fr1
	lds	r0,fpul
	shlr8	r8
	extu.b	r8,r0			! r0 = the green byte
	shlr8	r8
	fdiv	fr4,fr1			! fr1 = 1 / depth
	float	fpul,fr11		! fr11 = blue
	lds	r0,fpul
	float	fpul,fr10		! fr10 = green
	extu.b	r8,r0			! r0 = the red byte
	lds	r0,fpul
	shlr8	r8
	float	fpul,fr9		! fr9 = red
	lds	r8,fpul			! what is left of r8 is the alpha byte
	float	fpul,fr8		! fr8 = alpha
	flds	fr7,fpul		! fpul = minus depth (the transform's fourth result)
	fmul	fr15,fr11		! fr11 = blue * its scale
	sts	fpul,r0			! r0 = minus depth as raw bits
	fmul	fr14,fr10		! fr10 = green * its scale
	fsts	fpul,fr4		! fr4 = minus depth (in place of the depth)
	bf.s	.Lload_test		! not lit: no light sum
	fmul	fr13,fr9		! (delay slot) fr9 = red * its scale
	fmul	fr2,fr9			! lit: red, green and blue times the light sum
	fmul	fr2,fr10
	fmul	fr2,fr11
.Lload_test:				! 0c10d7e2
	cmp/hi	r0,r12			! T = r12 above minus depth's bits: behind the near plane
	fmul	fr12,fr8		! fr8 = alpha * its scale
	rts
	fmov	fr1,fr7			! (delay slot) fr7 = 1 / depth
! Three nops of padding to the next routine.
	nop
	nop
	nop

! vertex_colour_vtx_emit
!
! Sends the vertex vertex_colour_vtx_load has just loaded as a 64-byte
! vertex of the kind vertex_colour_strip_send writes: control word,
! X = x / depth, Y = y / depth, 1 / depth, u, v, two words not
! written, base color (alpha, red, green, blue), four zero floats of
! offset color. It counts the vertex (dt r3): the one that brings r3
! to 0 gets the end-of-strip control word. Called (bsr) by
! vertex_colour_strip_near_clip and vertex_colour_tri_near_clip.
!
! In:    fr5, fr6 = x, y; fr7 = 1 / depth; fr8-fr11 = the base color;
!        r1 = &u, v (all as vertex_colour_vtx_load leaves them).
!        r3 = the vertices left in the strip, this one included.
!        r5 = the list's write address; r6 = the store-queue address
!        of the vertex.
! Out:   r3 one less; T = 1 when it reached 0 (the strip's last
!        vertex). r5 and r6 moved on 64 bytes.
! Uses:  r0, fr2, fr3, fr5, fr6 are changed; nothing else.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg.
	.global	_vertex_colour_vtx_emit
	.type	_vertex_colour_vtx_emit,@function
_vertex_colour_vtx_emit:
.Lvtx_emit:				! 0c10d7f0
	fschg				! pair moves (SZ = 1)
	add	#24,r6			! r6 = vertex +24
	fmov	@r1,fr2			! fr2, fr3 = u, v
	fmul	fr7,fr6			! fr6 = Y = y / depth
	fmov	fr2,@-r6		! vertex +16, +20 = u, v
	fmul	fr7,fr5			! fr5 = X = x / depth
	fldi0	fr2			! fr2, fr3 = 0, 0: the offset color's pair
	mov	r6,r0			! r0 = vertex +16 ...
	fldi0	fr3
	shar	r0			! ... >> 1: the end-of-strip control word
	fmov	fr6,@-r6		! vertex +8, +12 = Y, 1 / depth
	dt	r3			! count the vertex; T = it is the strip's last
	fmov	fr4,@-r6		! vertex +0, +4 = minus depth, X
	bt	.Lemit_control		! last: keep the end-of-strip word
	mov	r6,r0			! r0 = the store-queue address: the plain control word
.Lemit_control:				! 0c10d80e
	mov.l	r0,@r6			! vertex +0 = the control word (over minus depth)
	pref	@r6			! send the first 32 bytes to the list
	add	#64,r6			! r6 = vertex +64
	fmov	fr2,@-r6		! vertex +56, +60 = 0, 0
	add	#64,r5			! the vertex takes 64 bytes of the list
	fmov	fr2,@-r6		! vertex +48, +52 = 0, 0: the offset color
	fmov	fr10,@-r6		! vertex +40, +44 = green, blue
	fmov	fr8,@-r6		! vertex +32, +36 = alpha, red
	fschg				! back to single moves (SZ = 0)
	pref	@r6			! send the second 32 bytes to the list
	rts
	add	#32,r6			! (delay slot) r6 = the next vertex
! Five nops of padding to the next routine.
	nop
	nop
	nop
	nop
	nop

! vertex_colour_vtx_keep
!
! Stores the vertex vertex_colour_vtx_load has just loaded in slot
! r11 & 3 of vertex_colour_clip_ring. A slot is 64 bytes:
!   +0x00 minus depth   +0x04 x        +0x08 y      +0x0c 1 / depth
!   +0x10 u             +0x14 v
!   +0x18 alpha         +0x1c red      +0x20 green  +0x24 blue
!   +0x28 to +0x3f not used
! Called (bsr) by vertex_colour_strip_near_clip and
! vertex_colour_tri_near_clip.
!
! In:    r11 = the vertex's number (its low two bits pick the slot).
!        fr4 = minus depth, fr5 = x, fr6 = y, fr7 = 1 / depth,
!        fr8-fr11 = the base color, r1 = &u, v.
! Out:   the slot filled. No register result; T is not changed.
! Uses:  r0, r10, fr2, fr3 are changed (r10 without being saved; the
!        clippers save it for all the ring helpers).
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg.
	.global	_vertex_colour_vtx_keep
	.type	_vertex_colour_vtx_keep,@function
_vertex_colour_vtx_keep:
.Lvtx_keep:				! 0c10d830
	mov	r11,r0
	mov	#6,r10			! r10 = 6: a slot is 64 bytes
	and	#3,r0
	shld	r10,r0			! r0 = the slot's offset in the ring
	mov.l	.Lring_keep_end,r10	! r10 = the ring +0x28: just past slot 0's blue
	fschg				! pair moves (SZ = 1)
	add	r0,r10			! r10 = just past this slot's blue
	fmov	@r1,fr2			! fr2, fr3 = u, v
	fmov	fr10,@-r10		! slot +0x20, +0x24 = green, blue
	fmov	fr8,@-r10		! slot +0x18, +0x1c = alpha, red
	fmov	fr2,@-r10		! slot +0x10, +0x14 = u, v
	fmov	fr6,@-r10		! slot +0x08, +0x0c = y, 1 / depth
	fmov	fr4,@-r10		! slot +0x00, +0x04 = minus depth, x
	rts
	fschg				! (delay slot) back to single moves (SZ = 0)
	nop				! padding to the next routine

! vertex_colour_flat_copy
!
! Copies the base color (alpha, red, green, blue) of ring slot r11 & 3
! into the two slots before it, wrapping round the four slots. The
! clippers call it for flat-shaded runs (r12 bit 0 set) after keeping
! a vertex, so the three vertices of the newest triangle, and the
! points made between them, carry that triangle's last color. Called
! (bsr) by vertex_colour_strip_near_clip and
! vertex_colour_tri_near_clip.
!
! In:    r11 = the newest vertex's number (low two bits = its slot).
!        vertex_colour_clip_ring = the kept vertices.
! Out:   the color of the two slots before it overwritten. No register
!        result; T is not changed.
! Uses:  r0, r1, r10 and fr8-fr11 are changed (r10 and fr8-fr11
!        without being saved).
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg.
	.global	_vertex_colour_flat_copy
	.type	_vertex_colour_flat_copy,@function
_vertex_colour_flat_copy:
.Lflat_copy:				! 0c10d850
	mov	#6,r1			! r1 = 6: a slot is 64 bytes
	mov.l	.Lring_color,r10	! r10 = the ring +0x18: slot 0's alpha
	mov	r11,r0
	and	#3,r0
	shld	r1,r0			! r0 = the slot's offset: 0, 64, 128 or 192
	fschg				! pair moves (SZ = 1)
	fmov	@(r0,r10),fr8		! fr8, fr9 = its alpha, red
	add	#8,r0
	fmov	@(r0,r10),fr10		! fr10, fr11 = its green, blue
	add	#-72,r0			! r0 = the alpha of the slot before (+8 - 72 = -64) ...
	extu.b	r0,r0			! ... modulo 256, the size of the ring
	fmov	fr8,@(r0,r10)		! slot before: alpha, red
	add	#8,r0
	fmov	fr10,@(r0,r10)		! slot before: green, blue
	add	#-72,r0			! one more slot back, the same way
	extu.b	r0,r0
	fmov	fr8,@(r0,r10)		! slot two before: alpha, red
	add	#8,r0
	fmov	fr10,@(r0,r10)		! slot two before: green, blue
	rts
	fschg				! (delay slot) back to single moves (SZ = 0)
! Three nops of padding to the next routine.
	nop
	nop
	nop

! vertex_colour_kept_vtx_emit
!
! Sends a vertex kept in vertex_colour_clip_ring as a 64-byte vertex
! (the layout vertex_colour_strip_send writes; offset color zero).
! Called (bsr) by vertex_colour_strip_near_clip and
! vertex_colour_tri_near_clip.
!
! In:    r0 = the vertex's number (its low two bits pick the slot).
!        T = 1 to send it as the end of a strip (control word
!        0xf0000000), 0 for the plain control word (the store-queue
!        address).
!        r5 = the list's write address; r6 = the store-queue address
!        of the vertex.
! Out:   r5 and r6 moved on 64 bytes. T is not changed.
! Uses:  r0, r1, r2, r10 and fr0-fr11 are changed (r10 and fr8-fr11
!        without being saved). r3, r4, r7 are not touched.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg.
	.global	_vertex_colour_kept_vtx_emit
	.type	_vertex_colour_kept_vtx_emit,@function
_vertex_colour_kept_vtx_emit:
.Lkept_vtx_emit:			! 0c10d880
	mov	#6,r1			! r1 = 6: a slot is 64 bytes
	mov.l	.Lclip_ring,r10
	and	#3,r0
	fschg				! pair moves (SZ = 1)
	shld	r1,r0			! r0 = the slot's offset in the ring
	fldi0	fr6
	add	r0,r10			! r10 = the slot
	fldi0	fr7			! fr6, fr7 = 0, 0: the offset color's pair
	mov	#-16,r2
	fmov	@r10+,fr0		! fr0, fr1 = minus depth, x
	shll16	r2
	fmov	@r10+,fr2		! fr2, fr3 = y, 1 / depth
	add	#24,r6			! r6 = vertex +24
	fmov	@r10+,fr4		! fr4, fr5 = u, v
	fmul	fr3,fr2			! fr2 = Y = y / depth
	fmov	@r10+,fr8		! fr8, fr9 = alpha, red
	fmul	fr3,fr1			! fr1 = X = x / depth
	fmov	@r10,fr10		! fr10, fr11 = green, blue
	shll8	r2			! r2 = 0xf0000000: the end-of-strip control word
	fmov	fr4,@-r6		! vertex +16, +20 = u, v
	add	#64,r5			! the vertex takes 64 bytes of the list
	fmov	fr2,@-r6		! vertex +8, +12 = Y, 1 / depth
	fmov	fr0,@-r6		! vertex +0, +4 = minus depth, X
	bt	.Lkept_control		! T set on entry: end of strip
	mov	r6,r2			! r2 = the store-queue address: the plain control word
.Lkept_control:				! 0c10d8b2
	mov.l	r2,@r6			! vertex +0 = the control word (over minus depth)
	mov	r6,r2			! r2 = the vertex's address (nothing in this file reads it)
	pref	@r6			! send the first 32 bytes to the list
	add	#64,r6			! r6 = vertex +64
	fmov	fr6,@-r6		! vertex +56, +60 = 0, 0
	fmov	fr6,@-r6		! vertex +48, +52 = 0, 0: the offset color
	fmov	fr10,@-r6		! vertex +40, +44 = green, blue
	fmov	fr8,@-r6		! vertex +32, +36 = alpha, red
	pref	@r6			! send the second 32 bytes to the list
	fschg				! back to single moves (SZ = 0)
	rts
	add	#32,r6			! (delay slot) r6 = the next vertex
! Three nops of padding to the next routine.
	nop
	nop
	nop

! vertex_colour_near_cut_emit
!
! Sends the point where the edge between two kept vertices a and b
! crosses the near plane, as a 64-byte vertex (the layout
! vertex_colour_strip_send writes; offset color zero). With the minus
! depths of the two taken from their ring slots,
!   t = (near - a) / (b - a)
! and x, y, u, v and the four color floats are each a + t * (b - a).
! The vertex's 1/w is the value in r7, and X, Y are x, y times it.
! Called (bsr) by vertex_colour_strip_near_clip and
! vertex_colour_tri_near_clip.
!
! In:    r0 = vertex a's number, r11 = vertex b's (low two bits =
!        their slots in vertex_colour_clip_ring).
!        r12 = the near value as raw float bits (its bit 0, a flag of
!        the callers, is taken along as the lowest bit of the float).
!        r7 = the 1/w of points on the near plane, raw float bits.
!        T = 1 to send it as the end of a strip (control word
!        0xf0000000), 0 for the plain control word (the store-queue
!        address).
!        r5 = the list's write address; r6 = the store-queue address
!        of the vertex.
! Out:   r5 and r6 moved on 64 bytes. T is not changed.
! Uses:  r0, r1, r2, r10 and fr0-fr5 are changed (r10 without being
!        saved). r3, r4, r7, r11 and fr6-fr11 are not touched.
! Notes: entered and left with 32-bit fmov (FPSCR SZ = 0); pair moves
!        between its two fschg (colors and u, v), single moves for
!        the rest. The pool after it serves the three ring helpers
!        above as well.
	.global	_vertex_colour_near_cut_emit
	.type	_vertex_colour_near_cut_emit,@function
_vertex_colour_near_cut_emit:
.Lnear_cut_emit:			! 0c10d8d0
	mov	#6,r1			! r1 = 6: a slot is 64 bytes
	mov.l	.Lclip_ring,r10
	and	#3,r0
	shld	r1,r0			! r0 = slot a's offset in the ring
	mov	r10,r2
	add	r0,r10			! r10 = slot a
	mov	r11,r0
	and	#3,r0
	fmov	@r10,fr2		! fr2 = a's minus depth
	shld	r1,r0			! r0 = slot b's offset
	lds	r12,fpul
	add	r0,r2			! r2 = slot b
	fsts	fpul,fr0		! fr0 = the near value (r12's bits)
	fmov	@r2,fr1			! fr1 = b's minus depth
	fsub	fr2,fr0			! fr0 = near - a
	add	#32,r2			! r2 = &b's green
	fschg				! pair moves (SZ = 1)
	add	#48,r6			! r6 = vertex +48
	fsub	fr2,fr1			! fr1 = b - a
	fmov	@r2,fr4			! fr4, fr5 = b's green, blue
	add	#-8,r2			! r2 = &b's alpha
	lds	r7,fpul			! fpul = the near 1/w, for later
	add	#32,r10			! r10 = &a's green
	fdiv	fr1,fr0			! fr0 = t = (near - a) / (b - a)
	fmov	@r10,fr2		! fr2, fr3 = a's green, blue
	add	#-8,r10			! r10 = &a's alpha
	fsub	fr2,fr4			! fr4, fr5 = b - a for the pair
	fsub	fr3,fr5
	fmac	fr0,fr4,fr2		! fr2 = a + t * (b - a): green at the cut
	fmac	fr0,fr5,fr3		! fr3 = blue at the cut
	fmov	fr2,@-r6		! vertex +40, +44 = green, blue
	fmov	@r2,fr4			! fr4, fr5 = b's alpha, red
	add	#-8,r2			! r2 = &b's u
	fmov	@r10,fr2		! fr2, fr3 = a's alpha, red
	add	#-8,r10			! r10 = &a's u
	fsub	fr2,fr4
	fsub	fr3,fr5
	fmac	fr0,fr4,fr2		! fr2, fr3 = alpha, red at the cut
	fmac	fr0,fr5,fr3
	fmov	fr2,@-r6		! vertex +32, +36 = alpha, red
	fmov	@r2,fr4			! fr4, fr5 = b's u, v
	add	#-8,r2			! r2 = &b's y
	fmov	@r10,fr2		! fr2, fr3 = a's u, v
	add	#-8,r10			! r10 = &a's y
	fsts	fpul,fr1		! fr1 = the near 1/w (from r7)
	fsub	fr2,fr4
	fsub	fr3,fr5
	add	#-8,r6			! r6 = vertex +24
	fmac	fr0,fr4,fr2		! fr2, fr3 = u, v at the cut
	fmac	fr0,fr5,fr3
	fmov	fr2,@-r6		! vertex +16, +20 = u, v
	fschg				! back to single moves (SZ = 0)
	fmov	fr1,@-r6		! vertex +12 = the near 1/w
	fmov	@r2,fr5			! fr5 = y of vertex b
	add	#-4,r2			! r2 = &x of vertex b
	fmov	@r10,fr3		! fr3 = y of vertex a
	add	#-4,r10			! r10 = &x of vertex a
	fmov	@r2,fr4			! fr4 = x of vertex b
	fmov	@r10,fr2		! fr2 = x of vertex a
	fsub	fr3,fr5			! fr5, fr4 = b - a for y and x
	fsub	fr2,fr4
	mov	#-16,r2
	fmac	fr0,fr5,fr3		! fr3 = y at the cut
	shll16	r2
	fmac	fr0,fr4,fr2		! fr2 = x at the cut
	shll8	r2			! r2 = 0xf0000000: the end-of-strip control word
	fmul	fr1,fr3			! fr3 = Y = y * the near 1/w
	add	#64,r5			! the vertex takes 64 bytes of the list
	fmul	fr1,fr2			! fr2 = X = x * the near 1/w
	fmov	fr3,@-r6		! vertex +8 = Y
	fmov	fr2,@-r6		! vertex +4 = X
	bt	.Lcut_control		! T set on entry: end of strip
	mov	r6,r2			! r2 = the store-queue address: the plain control word
.Lcut_control:				! 0c10d962
	mov.l	r2,@-r6			! vertex +0 = the control word
	pref	@r6			! send the first 32 bytes to the list
	add	#64,r6			! r6 = vertex +64
	fldi0	fr2			! fr2 = 0
	fmov	fr2,@-r6		! vertex +60 down to +48 = 0: the offset color
	fmov	fr2,@-r6
	fmov	fr2,@-r6
	fmov	fr2,@-r6
	pref	@r6			! send the second 32 bytes to the list
	rts
	add	#16,r6			! (delay slot) r6 = the next vertex
