	dt	r3		! count the vertex; T = it was the triangle's third
	fmov	fr10,@-r6	! block +40: green, blue
	mov	r4,r14
	fmov	fr8,@-r6	! block +32: alpha, red
	add	#-8,r6
	fmul	fr7,fr6
	fmov	fr2,@-r6	! block +16: u, v (X and Y are divided around it)
	fmul	fr7,fr5
	fmov	fr6,@-r6	! block +8: Y, 1/d
	bt.s	.Lt_last_of_triangle	! the triangle's third vertex
	fmov	fr4,@-r6	! (delay slot) block +0: (d,) X; r6 = the block
	tst	#1,r0		! T = the next entry is a back reference
	mov.l	r6,@r6		! block +0: the control word (the block's own address)
	bt	.Lt_next_back_ref	! back reference: the copy of the loop head below
	bra	.Lt_next_inline	! inline: round again; its delay slot is the pref below
! The next vertex is a back reference: .Lt_next_inline with the vertex
! found through the entry's offset. The pref (also the delay slot of
! the bra above) sends the first 32 bytes of the vertex just finished.
.Lt_next_back_ref:		! 0c1060d8
