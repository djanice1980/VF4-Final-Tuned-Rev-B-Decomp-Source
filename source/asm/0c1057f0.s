	mov	r6,r2
	bt.s	.Ltu_finish_a	! the last triangle: A ends it all
	shar	r2		! (delay slot) r2 = A's control word with end-of-strip
	tst	#1,r0
	mov	#3,r3		! r3 = 3 vertices again
	bt.s	.Ltu_load_b	! a back reference: the delay slot finds its vertex
	add	r4,r14
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	bra	.Ltu_load_b
	add	#-8,r14
.Ltu_finish_a:			! 0c106218
	add	#48,r4		! fetch ahead; r4 stays 8 past the word after the triangles
	pref	@r4
	add	#-48,r4
! Write and send the very last vertex (in fv4, u and v in fr0, fr1).
.Ltu_send_final:		! 0c10621e
	fmul	fr7,fr6		! Y and X divided, between the stores
	fmov	fr0,@-r6	! block +16: u, v
	fmul	fr7,fr5
	fmov	fr6,@-r6	! block +8: Y, 1/d
	add	#32,r5		! the write pointer moves over this vertex
	fmov	fr4,@-r6	! block +0: (d,) X
	add	#-8,r4		! r4 = the word after the triangles
	mov.l	r2,@r6		! block +0: the control word with end-of-strip
	fschg			! pairs off
	pref	@r6		! send it
	rts
	add	#32,r6		! (delay slot) r6 = the next block
	nop			! five nops of padding
	nop
	nop
	nop
	nop

! lit_strip_send_near_clip
!
! Sends one strip of a group that straddles the near limit, and any
! strips that carry on after it (flags bit 7), cutting the strip where it
! crosses the near limit. Every vertex is loaded, lit and transformed by
! lit_vertex_load, which also says whether it is on the near side (too
! close to draw). What goes out is always 64-byte lit vertices.
!
! r9 collects one bit per vertex, the newest in bit 0 (1 = near side),
! so its low three bits describe the triangle the newest vertex closes.
! r11 is the vertex's number in the strip; its low two bits are also the
! slot of lit_clip_ring (four slots) the vertex is kept in when it may
! be needed again (lit_vertex_keep).
!
! The routine moves between three ways of working:
!  - a run of visible vertices (.Lc_visible_run): each is sent as soon
!    as it is loaded and nothing is kept;
!  - a run of near vertices (.Lc_near_run): only the positions are
!    transformed, to find the vertex where the strip comes back;
!  - around a crossing (.Lc_ring_next and .Lc_dispatch): the last three
!    vertices are in the ring and a table indexed by the three bits
!    picks what to send for the triangle (n-2, n-1, n), where n is the
!    newest vertex (bits written oldest first):
!      001  cut(n-2,n), n-1, cut(n-1,n)
!      010  n, cut(n-1,n), n
!      011  cut(n-2,n) with end-of-strip; then the near run
!      100  cut(n-2,n), n-1, n; then the visible run
!      101  cut(n-1,n)
!      110  cut(n-2,n), cut(n-1,n), n, after one extra cut(n-1,n) when
!           n is odd
!    cut(a,b) is the point where the edge from a to b meets the near
!    limit (lit_near_vertex_emit); a vertex number alone is that kept
!    vertex sent again (lit_kept_vertex_emit). Added to what the case
!    before sent, each list completes the visible part of the triangle;
!    the repeated vertices make empty triangles that keep the strip's
!    alternation right. 000 and 111 never reach the table.
! When a crossing turns up in the middle of a run, the vertices before
! it were not kept: the read position is stepped back over their entries
! and they are loaded again. Stepping back works because an entry's last
! word tells its size the same way its first word does (bit 0 set = 32
! bytes inline, clear = an 8-byte back reference).
!
! In:    r4 = the strip's count word; the vertex entries follow.
!        r5, r6 = list write pointer and the store-queue address for it.
!        r7 = near_inv bits, r8 = material type, r12 = near_limit bits
!        with bit 0 = 1 when the strip is flat shaded (set by the
!        caller at .Lclipped).
!        XMTRX and the lit_* globals as for lit_vertex_load.
! Out:   r0 = 1, and bit 0 of r12 is set. r4 = the word after the last
!        strip handled. r5 and r6 are moved past everything sent.
! Uses:  r10, r11 and pr are saved and restored. r0-r3, r9, r13, r14 and
!        fr0-fr15 are changed, here or in the helpers.
! Notes: SZ = 0 on entry and on exit. Called only by
!        lit_groups_send_alpha (bsr, flags bit 4 on a straddling group).
!        Each vertex is counted in r3 once: by lit_vertex_emit in a
!        visible run, by a dt in this routine otherwise.
	.global	_lit_strip_send_near_clip
	.type	_lit_strip_send_near_clip,@function
_lit_strip_send_near_clip:
.Llit_strip_send_near_clip:	! 0c106240
	mov.l	r10,@-r15	! save r10, r11 (the helpers use them) and pr
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3		! r3 = the number of vertices; r4 = the first entry
! The start of a strip: the first two vertices decide where to begin.
.Lc_strip_start:		! 0c106248
	mov	#0,r11		! r11 = 0: vertex number and ring slot
	bsr	.Llit_vertex_load	! load vertex 0; T = it is on the near side
	mov	#0,r9		! (delay slot) r9 = 0: no near bits yet
	bt.s	.Lc_first_is_near	! vertex 0 is near: see what vertex 1 is
	rotcl	r9		! (delay slot) r9 takes the vertex's near bit (as after every load)
	bsr	.Llit_vertex_emit	! vertex 0 is visible: send it (lit_vertex_emit counts it)
	add	#1,r11		! (delay slot) r11 = 1
	bsr	.Llit_vertex_load	! load vertex 1
	nop
	bt.s	.Lc_second_is_near	! vertex 1 is near: the strip starts with a crossing
	rotcl	r9
	bsr	.Llit_vertex_emit	! vertex 1 is visible too: send it
	add	#1,r11		! (delay slot) r11 = 2
! A run of visible vertices: load, send, count; nothing is kept.
.Lc_visible_run:		! 0c106262
	bsr	.Llit_vertex_load	! load the next vertex
	nop
	bt.s	.Lc_side_changed	! it is near: the strip leaves the visible side
	rotcl	r9
	bsr	.Llit_vertex_emit	! visible: send it; T = it was the strip's last
	add	#1,r11		! (delay slot) the next vertex number
	bf	.Lc_visible_run	! not the last: round again
	bra	.Lc_strip_end	! the strip is finished
	nop
! Vertex 0 is on the near side. Count it and load vertex 1.
.Lc_first_is_near:		! 0c106274
	dt	r3		! count vertex 0 (it was loaded but is not sent)
	add	#1,r11
	bsr	.Llit_vertex_load	! load vertex 1; T = it is on the near side
	dt	r3		! (delay slot) count vertex 1 as well
	bf.s	.Lc_second_is_visible	! vertex 1 is visible: the strip comes in between 0 and 1
	rotcl	r9		! (delay slot) r9 takes its near bit
! A run of near vertices. Nothing can be drawn until a vertex is
! visible again, so only positions are transformed: fv4 = the vertex
! being tested, while r14 and r1 already describe the entry after it
! (its data and its size). From .Lc_near_next on, r4 = the entry after
! the one being tested.
! Also entered from case 011 of the table.
.Lc_near_run:			! 0c106280
	mov.l	@r4,r0		! r0 = the entry's first word
	mov	r4,r14
	tst	#1,r0		! T = bit 0 clear: a back reference
	add	#32,r4		! r4 = past a 32-byte inline vertex
	bf.s	.Lc_near_xy	! inline: r14 is the vertex
	fldi1	fr7		! (delay slot) w = 1
	add	#-24,r4		! back reference: r4 = past the 8-byte entry,
	mov.l	@(4,r14),r14
	add	r4,r14		! r14 = the vertex the entry refers to
.Lc_near_xy:			! 0c106292
	fmov	@r14+,fr4	! fr4, fr5 = x, y (single moves here)
	fmov	@r14+,fr5
.Lc_near_next:			! 0c106296
	fmov	@r14+,fr6	! fr6 = z of the vertex being tested
	mov	#32,r1		! r1 = 32: the size of the entry after it, if inline
	mov.l	@r4,r0		! r0 = that entry's first word
	add	#32,r4
	tst	#1,r0		! T = that entry is a back reference
	ftrv	xmtrx,fv4	! fv4 = (d, x', y', z') of the vertex being tested
	pref	@r4		! fetch the strip data 32 bytes ahead
	add	#-32,r4
	bf.s	.Lc_near_test	! the entry after is inline: r14 is right
	mov	r4,r14		! (delay slot) r14 = the entry after the tested one
	mov	#8,r1		! a back reference: its size is 8,
	mov.l	@(4,r14),r14
	add	#8,r14
	add	r4,r14		! and r14 = the vertex it refers to (offset + entry + 8)
.Lc_near_test:			! 0c1062b2
	flds	fr7,fpul
	sts	fpul,r0		! r0 = z' as raw bits
	cmp/hi	r0,r12		! T = near_limit bits above z' bits (unsigned): near side
	add	#1,r11		! the vertex's number
	bf.s	.Lc_back_in	! visible: the strip comes back in at this vertex
	rotcl	r9		! (delay slot) r9 takes its near bit
	dt	r3		! near: count it; T = it was the strip's last
	fldi1	fr7		! w = 1 for the next one
	bt	.Lc_strip_end	! the last: the strip ends on the near side
	add	r1,r4		! r4 = past the entry after
	fmov	@r14+,fr4	! fr4, fr5 = x, y of the next vertex to test
	bra	.Lc_near_next
	fmov	@r14+,fr5
! The strip is finished and r4 is on the word after it. A positive
! word with bit 7 set is a strip that carries on: start again with its
! count.
.Lc_strip_end:			! 0c1062cc
	mov.l	@r4+,r0		! r0 = the word after the strip
	cmp/pl	r0
	bf.s	.Lc_return	! not positive: no strip follows
	tst	#128,r0		! (delay slot) flags bit 7
	bf.s	.Lc_strip_start	! set: the strip carries on
	mov.l	@r4+,r3		! (delay slot) r3 = its count, read in either case
	add	#-4,r4		! not carrying on: undo the read of the count
.Lc_return:			! 0c1062da
	lds.l	@r15+,pr	! restore pr, r11 and r10
	mov	#1,r0		! r0 = 1, the value returned
	mov.l	@r15+,r11
	add	#-4,r4		! r4 = back on the word after the strip
	mov.l	@r15+,r10
	rts
	or	r0,r12		! (delay slot) bit 0 of r12 set: the caller's straddle flag again
! Vertex 0 was visible and has been sent; vertex 1 is near. Keep vertex
! 1 in slot 1, go back and load vertex 0 again to keep it in slot 0,
! send cut(0,1), and carry on in the ring with vertex 2.
.Lc_second_is_near:		! 0c1062e8
	bsr	.Llit_vertex_keep	! keep vertex 1 (r11 = 1)
	dt	r3		! (delay slot) count vertex 1
	add	#-8,r4		! step r4 back over vertex 1's entry: 8 bytes,
	mov.l	@(4,r4),r0
	tst	#1,r0		! or 32 when the entry's last word has bit 0 set
	bt	.Lc_sn_back_v0
	add	#-24,r4
.Lc_sn_back_v0:			! 0c1062f6
	add	#-8,r4		! step back over vertex 0's entry the same way
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sn_reload
	add	#-24,r4
.Lc_sn_reload:			! 0c106300
	bsr	.Llit_vertex_load	! load vertex 0 again
	nop
	bsr	.Llit_vertex_keep	! keep it in slot 0
	mov	#0,r11		! (delay slot) r11 = 0 for the keep
	mov	#1,r11		! r11 = 1, the near end of the edge
	clrt			! T clear: not the strip's last vertex
	bsr	.Llit_near_vertex_emit	! send cut(0,1)
	mov	#0,r0		! (delay slot) r0 = slot 0, the other end
	mov.l	@r4,r0		! step r4 forward over vertex 1's entry again
	tst	#1,r0
	add	#8,r4
	bt	.Lc_sn_ring
	add	#24,r4
.Lc_sn_ring:			! 0c10631a
	bra	.Lc_ring_next	! on to vertex 2, in the ring
	nop
! Vertex 0 is near and vertex 1 is visible. Keep both the same way,
! send cut(0,1) and vertex 1, and carry on in the ring with vertex 2.
.Lc_second_is_visible:		! 0c10631e
	bsr	.Llit_vertex_keep	! keep vertex 1 in slot 1
	mov	#1,r11
	add	#-8,r4		! step r4 back over vertex 1's entry
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sv_back_v0
	add	#-24,r4
.Lc_sv_back_v0:			! 0c10632c
	add	#-8,r4		! step back over vertex 0's entry
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sv_reload
	add	#-24,r4
.Lc_sv_reload:			! 0c106336
	bsr	.Llit_vertex_load	! load vertex 0 again
	nop
	bsr	.Llit_vertex_keep	! keep it in slot 0
	mov	#0,r11
	mov	#1,r11		! r11 = 1, the visible end of the edge
	clrt
	bsr	.Llit_near_vertex_emit	! send cut(0,1), not the last
	mov	#0,r0		! (delay slot) r0 = slot 0
	clrt
	bsr	.Llit_kept_vertex_emit	! send vertex 1 from the ring, not the last
	mov	#1,r0		! (delay slot) r0 = slot 1
	mov.l	@r4,r0		! step r4 forward over vertex 1's entry again
	tst	#1,r0
	add	#8,r4
	bt	.Lc_sv_ring
	add	#24,r4
.Lc_sv_ring:			! 0c106356
	bra	.Lc_ring_next	! on to vertex 2, in the ring
	nop
! From the near run: the vertex just tested is visible. r4 is past its
! entry; step back and load it in full.
.Lc_back_in:			! 0c10635a
	add	#-8,r4		! step r4 back over the visible vertex's entry
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_back_in_load
	add	#-24,r4
.Lc_back_in_load:		! 0c106364
	bsr	.Llit_vertex_load	! load it in full (lighting and all)
	nop
! The newest vertex n (loaded, slot r11) is on the other side from the
! two before it, which were not kept. Keep n, step back three entries,
! load n-2 and n-1 again into the two slots before, and step forward
! over n's entry. Entered from the visible run with n near, and from
! above with n visible.
.Lc_side_changed:		! 0c106368
	bsr	.Llit_vertex_keep	! keep vertex n in slot r11
	nop
	add	#-8,r4		! step r4 back over n's entry
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sc_back_2
	add	#-24,r4
.Lc_sc_back_2:			! 0c106376
	add	#-8,r4		! step back over the entry of n-1
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sc_back_3
	add	#-24,r4
.Lc_sc_back_3:			! 0c106380
	add	#-8,r4		! step back over the entry of n-2
	mov.l	@(4,r4),r0
	tst	#1,r0
	bt	.Lc_sc_reload
	add	#-24,r4
.Lc_sc_reload:			! 0c10638a
	bsr	.Llit_vertex_load	! load vertex n-2 again
	nop
	bsr	.Llit_vertex_keep	! keep it two slots back
	add	#-2,r11		! (delay slot) r11 = n-2 for the keep
	bsr	.Llit_vertex_load	! load vertex n-1 again
	nop
	bsr	.Llit_vertex_keep	! keep it one slot back
	add	#1,r11		! (delay slot) r11 = n-1 for the keep
	mov.l	@r4,r0		! step r4 forward over n's entry
	tst	#1,r0
	add	#8,r4
	bt	.Lc_sc_spread
	add	#24,r4
.Lc_sc_spread:			! 0c1063a4
	mov	r12,r0		! r0 = r12, for its bit 0
	add	#1,r11		! r11 = n again
	tst	#1,r0		! T = bit 0 clear: Gouraud shaded
	bt.s	.Lc_dispatch	! Gouraud: every vertex keeps its own color
	mov	r9,r0		! (delay slot) r0 = the near bits
	bsr	.Llit_flat_colour_spread	! flat: slot n's color into the two slots before
	nop
	bra	.Lc_dispatch
	mov	r9,r0		! (delay slot) r0 = the near bits
! In the ring: load the next vertex, keep it, and let the table decide.
.Lc_ring_next:			! 0c1063b6
	bsr	.Llit_vertex_load	! load the next vertex; T = near side
	add	#1,r11		! (delay slot) its number and slot
	bsr	.Llit_vertex_keep	! keep it in the ring
	rotcl	r9		! (delay slot) r9 takes its near bit
	mov	r12,r0
	tst	#1,r0		! T = bit 0 of r12 clear: Gouraud shaded
	bt.s	.Lc_dispatch	! Gouraud: no color to spread
	mov	r9,r0		! (delay slot) r0 = the near bits
	bsr	.Llit_flat_colour_spread	! flat: slot n's color into the two slots before
	nop
	mov	r9,r0		! r0 = the near bits
! Jump through the table on the last three near bits. braf adds r0 to
! the address 4 past itself, so entry k is at 0c1063d4 + 4 x k; each
! entry is a bra and a nop. Entries 0 and 7 are nops (never reached;
! they would run on into the entry or the code after them).
.Lc_dispatch:			! 0c1063cc
	and	#7,r0		! the near bits of n-2, n-1 and n
	shll2	r0		! times 4, the size of a table entry
	braf	r0
	nop			! (delay slot) nothing to do
	nop			! entry 000: two nops, not reached
	nop
	bra	.Lc_case_001	! entry 001: n is near, the two before are visible
	nop
	bra	.Lc_case_010	! entry 010: n-1 is near
	nop
	bra	.Lc_case_011	! entry 011: n-1 and n are near
	nop
	bra	.Lc_case_100	! entry 100: n-2 is near
	nop
	bra	.Lc_case_101	! entry 101: only n-1 is visible
	nop
	bra	.Lc_case_110	! entry 110: only n is visible
	nop
	nop			! entry 111: two nops, not reached
	nop
! 001: the strip goes out of view at n. n-2 and n-1 have been sent.
! Send cut(n-2,n), n-1 again and cut(n-1,n). In each call below T says
! whether the vertex is the strip's last (end-of-strip), r0 is one ring
! slot (the bsr's delay slot sets it from r11) and, for a cut, r11 is
! the other end of the edge. The emitters return T as they got it.
.Lc_case_001:			! 0c1063f4
	mov	r11,r0
	clrt			! T clear: not the last
	bsr	.Llit_near_vertex_emit	! send cut(n-2,n)
	add	#-2,r0		! (delay slot) r0 = the slot of n-2
	mov	r11,r0
	clrt
	bsr	.Llit_kept_vertex_emit	! send n-1 from the ring
	add	#-1,r0		! (delay slot) r0 = the slot of n-1
	mov	r11,r0
	dt	r3		! count vertex n; T = it is the strip's last
	bsr	.Llit_near_vertex_emit	! send cut(n-1,n), with end-of-strip if n is the last
	add	#-1,r0
	bf	.Lc_ring_next	! more vertices: the next one, in the ring
	bra	.Lc_strip_end	! the strip is finished
	nop
! 010: n-1 is near, n-2 and n are visible. Send n, cut(n-1,n) and n
! again.
.Lc_case_010:			! 0c106412
	clrt
	bsr	.Llit_kept_vertex_emit	! send n from the ring
	mov	r11,r0		! (delay slot) r0 = the slot of n
	mov	r11,r0
	clrt
	bsr	.Llit_near_vertex_emit	! send cut(n-1,n)
	add	#-1,r0
	dt	r3		! count vertex n; T = it is the strip's last
	bsr	.Llit_kept_vertex_emit	! send n again, with end-of-strip if it is the last
	mov	r11,r0
	bf	.Lc_ring_next	! more vertices: the next one, in the ring
	bra	.Lc_strip_end	! the strip is finished
	nop
! 011: n-1 and n are near, n-2 is visible. Send cut(n-2,n) with
! end-of-strip: what is out so far is complete. Then skip near vertices.
.Lc_case_011:			! 0c10642c
	mov	r11,r0
	sett			! T set: the last vertex of this piece
	bsr	.Llit_near_vertex_emit	! send cut(n-2,n) with end-of-strip
	add	#-2,r0
	dt	r3		! count vertex n; T = it is the strip's last
	bt	.Lc_case_100_end	! the last: the strip is finished
	bra	.Lc_near_run	! more vertices: the near run
	nop
! 100: n-2 is near, n-1 and n are visible. Send cut(n-2,n), n-1 and n,
! then go back to the visible run.
.Lc_case_100:			! 0c10643c
	mov	r11,r0
	clrt
	bsr	.Llit_near_vertex_emit	! send cut(n-2,n)
	add	#-2,r0
	mov	r11,r0
	clrt
	bsr	.Llit_kept_vertex_emit	! send n-1 from the ring
	add	#-1,r0
	dt	r3		! count vertex n; T = it is the strip's last
	bsr	.Llit_kept_vertex_emit	! send n, with end-of-strip if it is the last
	mov	r11,r0
	bt	.Lc_case_100_end	! the last: the strip is finished
	bra	.Lc_visible_run	! more vertices: the visible run
	add	#1,r11		! (delay slot) the next vertex number
.Lc_case_100_end:		! 0c106458
	bra	.Lc_strip_end	! the strip is finished (also from case 011)
	nop
! 101: n-1 is the only visible one of the three. Send cut(n-1,n), which
! closes the corner at n-1.
.Lc_case_101:			! 0c10645c
	mov	r11,r0
	dt	r3		! count vertex n; T = it is the strip's last
	bsr	.Llit_near_vertex_emit	! send cut(n-1,n), with end-of-strip if n is the last
	add	#-1,r0
	bf	.Lc_ring_next	! more vertices: the next one, in the ring
	bra	.Lc_strip_end	! the strip is finished
	nop
! 110: the strip comes back into view at n and a new piece starts:
! cut(n-2,n), cut(n-1,n), n. When n is odd one more cut(n-1,n) goes
! first, so that the triangles face the way they did in the uncut strip.
.Lc_case_110:			! 0c10646a
	mov	r11,r0
	tst	#1,r0		! T = the vertex number n is even
	bt	.Lc_case_110_even	! even: no extra vertex
	mov	r11,r0
	clrt
	bsr	.Llit_near_vertex_emit	! odd: send cut(n-1,n) once more first
	add	#-1,r0
.Lc_case_110_even:		! 0c106478
	mov	r11,r0
	clrt
	bsr	.Llit_near_vertex_emit	! send the new piece: cut(n-2,n),
	add	#-2,r0
	mov	r11,r0
	clrt
	bsr	.Llit_near_vertex_emit	! then the point cut(n-1,n),
	add	#-1,r0
	dt	r3		! count vertex n; T = it is the strip's last
	bsr	.Llit_kept_vertex_emit	! then n itself, with end-of-strip if it is the last
	mov	r11,r0
	bf	.Lc_ring_next	! more vertices: the next one, in the ring
	bra	.Lc_strip_end	! the strip is finished
	nop

! lit_vertex_load
!
! Loads one vertex entry for the clipping senders: finds its data
! (inline or through a back reference), works out its color, transforms
! its position and reports which side of the near limit it is on. For a
! lit group (r8 >= 0) the color is lit_group_colour times the light sum,
! by the same instructions as at .Ls_light_sum in lit_strip_send; for an
! unlit group the sum is 1.0, so the color is lit_group_colour itself.
!
! In:    r4 = the vertex entry. r8 = material type. r12 = near_limit
!        bits (its bit 0 may be set; that moves the limit by the float's
!        last bit only). XMTRX, lit_group_colour, lit_ambient_scaled,
!        lit_group_light_mask and light_table as for lit_strip_send.
! Out:   T = the vertex is on the near side: near_limit's bits are above
!        the bits of z', compared as unsigned numbers. near_limit is
!        negative, so that holds for a negative z' of smaller size
!        (nearer than the limit) and for every positive z' (behind the
!        eye).
!        fr4 = z', fr5 = x', fr6 = y' (not divided), fr7 = 1/d.
!        fr8-fr11 = color: alpha, red, green, blue.
!        r1, r2 = u, v as raw bits. r4 = past the entry.
! Uses:  r0, r13, r14, fr0-fr3 and fr12-fr15 are changed too. Nothing is
!        saved.
! Notes: SZ = 0 on entry and on exit. Called (bsr) by
!        lit_strip_send_near_clip and lit_tris_send_near_clip.
	.global	_lit_vertex_load
	.type	_lit_vertex_load,@function
_lit_vertex_load:
.Llit_vertex_load:		! 0c106494
	mov.l	@r4,r0		! r0 = the entry's first word
	fschg			! pairs on
	mov.l	.Lv_light_mask,r13	! r13 = &lit_group_light_mask
	tst	#1,r0		! T = bit 0 clear: a back reference
	mov.l	.Lv_ambient_scaled,r0	! r0 = lit_ambient_scaled
	mov	r4,r14		! r14 = the vertex data, if it is inline
	bf.s	.Lv_found	! inline: r14 is right
	add	#32,r4		! (delay slot) r4 = past a 32-byte inline vertex
	add	#-24,r4		! back reference: r4 = past the 8-byte entry,
	mov.l	@(4,r14),r14
	add	r4,r14		! r14 = the vertex the entry refers to
.Lv_found:			! 0c1064aa
	mov.l	@r13,r13	! r13 = the mask of lights that reach the group
	fmov	@r0+,fr12	! fr13 = ambient red (fr12 is only scratch)
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue: the light sum starts here
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	fschg			! pairs off
	cmp/pz	r8		! T = a lit group (material type 0 or more)
	fmov	fr7,fr8
	bf.s	.Lv_unlit	! unlit: no light sum at all
	tst	r13,r13		! (delay slot) T = no light reaches the group
	fmov	@r14+,fr9	! fr9 = normal y
	bt.s	.Lv_no_lights	! no light: the ambient color alone
	fmov	@r14+,fr10	! (delay slot) fr10 = normal z; r14 = &u
	shlr	r13		! T = light 0 is in the mask
	mov.l	.Lv_light_table,r2	! r2 = light_table record 0
	bf	.Lv_skip_light	! not in the mask: step to the first one that is
	mov.w	@(2,r2),r0	! r0 = light 0's type
! The light sum: the same instructions as at .Ls_light in
! lit_strip_send (0c105c5c-0c105d49), where each step is explained.
.Lv_light:			! 0c1064cc
	fldi0	fr3
	cmp/eq	#2,r0		! T = directional
	mov	#116,r1
	bf.s	.Lv_point_or_spot	! not directional: point or spot
	add	r2,r1		! (delay slot) r1 = &record.model_pos (+0x74)
	fldi1	fr7
	tst	r13,r13
	add	#12,r1		! r1 = &record.model_dir (+0x80)
	bf.s	.Lv_dir_dot
	fmov	@r1+,fr0
	ftrv	xmtrx,fv4	! last light: fv4 = (d, x', y', z') of the position
.Lv_dir_dot:			! 0c1064e2
	fmov	@r1+,fr1
	mov	r2,r0
	fmov	@r1+,fr2
	add	#24,r0
	fipr	fv0,fv8		! fr11 = N . direction
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	fmov	@r0+,fr3
	fldi0	fr0
	fcmp/gt	fr11,fr0	! T = the term is negative
	fmov	fr11,fr0
	bf.s	.Lv_add_light	! not negative: add this light
	tst	r13,r13
.Lv_skip_light:			! 0c1064fc
	mov	#-80,r0
	bt	.Lv_finish	! no light left: finish the vertex
	shlr	r13
	extu.b	r0,r0
	bf.s	.Lv_step_bit	! bit clear: keep stepping
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lv_light
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
! Unlit group: skip the normal, transform, and use a sum of 1.0.
.Lv_unlit:			! 0c10650c
	fldi1	fr7		! w = 1 for the position
	add	#8,r14		! r14 = &u (normal y and z are not needed)
	bra	.Lv_unlit_sum
	ftrv	xmtrx,fv4	! (delay slot) fv4 = (d, x', y', z')
.Lv_no_lights:			! 0c106514
	fldi1	fr7		! w = 1 for the position
	bra	.Lv_finish
	ftrv	xmtrx,fv4	! (delay slot) fv4 = (d, x', y', z')
	nop			! padding, never run
.Lv_point_or_spot:		! 0c10651c
	fmov	@r1+,fr0
	tst	r13,r13
	fmov	@r1+,fr1
	fsub	fr4,fr0
	fmov	@r1+,fr2
	fsub	fr5,fr1
	fldi1	fr7
	add	#24,r1		! r1 = record +0x98, the range squared
	fldi0	fr11
	bf.s	.Lv_point_dot
	fsub	fr6,fr2		! (delay slot) fr2 = L z; fv0 = L (fr3 = 0)
	ftrv	xmtrx,fv4	! last light: fv4 = (d, x', y', z') of the position
.Lv_point_dot:			! 0c106534
	fipr	fv0,fv8		! fr11 = N . L
	fldi0	fr12
	fipr	fv0,fv0		! fr3 = |L| squared
	fcmp/gt	fr11,fr12
	fmov	@r1,fr12
	bt	.Lv_light_adds_nothing	! facing away: nothing from this light
	fcmp/gt	fr3,fr12
	bf	.Lv_light_adds_nothing	! out of range: nothing from this light
	cmp/eq	#3,r0
	flds	fr3,fpul
	bt.s	.Lv_attenuate	! point light: no cone
	fsrra	fr3		! (delay slot) fr3 = 1 / |L|
	add	#-24,r1
	fmov	@r1+,fr12
	fmul	fr0,fr12	! fr12 = L x times direction x
	fmov	@r1+,fr0
	fmac	fr0,fr1,fr12
	fmov	@r1,fr0
	add	#-48,r1
	fmac	fr0,fr2,fr12	! fr12 = L . direction
	fmov	@r1,fr2
	fneg	fr12
	fmul	fr3,fr12	! fr12 = cosine of the angle off the light's axis
	add	#68,r1
	fcmp/gt	fr12,fr2
	fsub	fr2,fr12
	fmov	@r1,fr2
	bt	.Lv_light_adds_nothing	! outside the cone: nothing from this light
	fmul	fr2,fr12	! fr12 = the cone factor, 0 at the edge to 1 on the axis
	add	#-4,r1
	fmul	fr12,fr11	! fr11 = N . L times the cone factor
.Lv_attenuate:			! 0c106572
	add	#-68,r1
	fmov	@r1,fr2
	add	#-8,r1
	fsts	fpul,fr0
	fmul	fr3,fr11	! fr11 = N . L / |L| (times the cone factor)
	fmov	@r1,fr12
	fmul	fr0,fr3		! fr3 = |L|
	add	#4,r1
	fmac	fr0,fr2,fr12
	fmov	@r1,fr2
	mov	r2,r0
	fmov	fr3,fr0
	fmac	fr0,fr2,fr12	! fr12 = the attenuation
	fmov	fr11,fr0
	add	#24,r0
	fdiv	fr12,fr11	! fr11 = the term over the attenuation
	fldi1	fr2
	fcmp/gt	fr2,fr12
	fmov	@r0+,fr1
	fmov	@r0+,fr2
	bf.s	.Lv_term_ready	! not above 1: the term as it is
	fmov	@r0+,fr3
	fmov	fr11,fr0	! above 1: the divided term
.Lv_term_ready:			! 0c1065a0
	tst	r13,r13
.Lv_add_light:			! 0c1065a2
	fmac	fr0,fr1,fr13	! red sum
	mov	#-80,r0
	fmac	fr0,fr2,fr14	! green sum
	bt.s	.Lv_finish	! that was the last light: finish the vertex
	fmac	fr0,fr3,fr15	! (delay slot) blue sum
	bra	.Lv_step_record
	shlr	r13
.Lv_light_adds_nothing:		! 0c1065b0
	tst	r13,r13
	mov	#-80,r0
	bt.s	.Lv_finish	! none: finish the vertex (the shlr below is its delay slot)
.Lv_step_bit:			! 0c1065b6
	shlr	r13
.Lv_step_record:		! 0c1065b8
	extu.b	r0,r0
	bf.s	.Lv_step_bit	! bit clear: step again
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lv_light	! bit set: work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
	nop			! padding, never run
.Lv_unlit_sum:			! 0c1065c4
	fldi1	fr13		! the red, blue and green sums = 1.0
	fldi1	fr15
	fldi1	fr14
! Finish: the near test, 1/d and the color. Here fv4 = (d, x', y', z')
! and r14 = &u.
.Lv_finish:			! 0c1065ca
	flds	fr7,fpul	! fpul keeps z' (raw bits)
	add	#32,r4
	pref	@r4		! fetch the strip data 32 bytes on
	fschg			! pairs on
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1 / d
	mov.l	.Lv_group_colour,r2	! r2 = lit_group_colour
	add	#-32,r4
	sts	fpul,r0		! r0 = z' bits
	fmov	@r2+,fr8	! fr8, fr9 = group alpha, red
	fmov	@r2+,fr10	! fr10, fr11 = group green, blue
	cmp/hi	r0,r12		! T = near_limit bits above z' bits: the near side
	fmul	fr13,fr9	! red times the red sum
	mov.l	@r14+,r1	! r1 = u bits
	fmul	fr14,fr10	! green times the green sum
	mov.l	@r14+,r2	! r2 = v bits
	fmul	fr15,fr11	! blue times the blue sum
	fsts	fpul,fr4	! fr4 = z' (d is not needed any more)
	rts
	fschg			! (delay slot) pairs off

! lit_vertex_emit
!
! Sends the vertex lit_vertex_load has just produced as a 64-byte lit
! vertex (the layout is at lit_strip_send), counts it in r3 and marks it
! end-of-strip when the count reaches 0.
!
! In:    fr5, fr6 = x', y'; fr7 = 1/d; fr8-fr11 = color; r1, r2 = u, v
!        bits. r3 = vertices left, this one included.
!        r5, r6 = list write pointer and the store-queue address for it.
! Out:   T = this was the last vertex (r3 reached 0). r3 one less. r5
!        and r6 moved on by 64.
! Uses:  r0, fr0, fr1, fr4-fr6 are changed. Nothing is saved.
! Notes: SZ = 0 on entry and on exit. Called (bsr) by the two clipping
!        senders.
	.global	_lit_vertex_emit
	.type	_lit_vertex_emit,@function
_lit_vertex_emit:
.Llit_vertex_emit:		! 0c1065f2
	dt	r3		! count the vertex; T = it is the last
	lds	r6,fpul		! fpul = the control word: the block's own address
	bf	.Lve_write	! not the last: that word will do
	mov	r6,r0		! the last: the address shifted right once sets end-of-strip
	shar	r0
	sett			! T set again (the shift changed it)
	lds	r0,fpul
.Lve_write:			! 0c106600
	fschg			! pairs on
	add	#24,r6		! r6 = block +24
	fsts	fpul,fr4	! fr4 = the control word
	fmul	fr7,fr6		! fr6 = Y of the vertex
	mov.l	r2,@-r6		! block +20: v
	fmul	fr7,fr5		! fr5 = X of the vertex
	mov.l	r1,@-r6		! block +16: u
	fmov	fr6,@-r6	! block +8: Y, 1/d
	fmov	fr4,@-r6	! block +0: control word, X
	pref	@r6		! send the first 32 bytes
	add	#64,r6		! r6 = the end of the block
	fldi0	fr0
	fldi0	fr1
	fmov	fr0,@-r6	! block +56 and +48: offset color = 0
	fmov	fr0,@-r6
	fmov	fr10,@-r6	! block +40: green, blue
	add	#64,r5		! the write pointer moves over the vertex
	fmov	fr8,@-r6	! block +32: alpha, red
	fschg			! pairs off
	pref	@r6		! send the second 32 bytes
	rts
	add	#32,r6		! (delay slot) r6 = the next block

! lit_vertex_keep
!
! Stores the vertex lit_vertex_load has just produced in a slot of
! lit_clip_ring, so that it can be sent or cut against later. A slot is
! 64 bytes: +0 z', +4 x', +8 y', +12 1/d, +16 u, +20 v, (+24 and +28 not
! written), +32 alpha, red, green, blue, +48 four zeros.
!
! In:    r11 = the slot (only its low two bits count).
!        fr4-fr7 = z', x', y', 1/d; fr8-fr11 = color; r1, r2 = u, v bits.
! Out:   the slot is filled. Nothing in registers.
! Uses:  r0, r10, fr0 and fr1 are changed (r10 is why the clipping
!        senders save it). Nothing is saved.
! Notes: SZ = 0 on entry and on exit. Called (bsr) by the two clipping
!        senders.
	.global	_lit_vertex_keep
	.type	_lit_vertex_keep,@function
_lit_vertex_keep:
.Llit_vertex_keep:		! 0c10662c
	mov	#6,r10
	mov	r11,r0
	and	#3,r0		! r0 = the slot number, 0-3
	fldi0	fr0
	shld	r10,r0		! r0 = 64 x slot
	fldi0	fr1
	fschg			! pairs on
	mov.l	.Lv_ring_slot0_end,r10	! r10 = the end of slot 0 (lit_clip_ring +64)
	add	r0,r10		! r10 = the end of the slot
	fmov	fr0,@-r10	! slot +56 and +48: zeros
	fmov	fr0,@-r10
	fmov	fr10,@-r10	! slot +40: green, blue
	fmov	fr8,@-r10	! slot +32: alpha, red
	add	#-8,r10		! skip +24 and +28
	mov.l	r2,@-r10	! slot +20: v, then +16: u
	mov.l	r1,@-r10
	fmov	fr6,@-r10	! slot +8: y', 1/d
	fmov	fr4,@-r10	! slot +0: z', x'
	rts
	fschg			! (delay slot) pairs off

! lit_flat_colour_spread
!
! For a flat-shaded strip: copies the color of ring slot r11 into the
! two slots before it (the ring wraps), so that all three kept vertices
! of the triangle have the color of its last vertex and the pieces left
! after cutting keep that color.
!
! In:    r11 = the slot of the triangle's last vertex (low two bits).
! Out:   the colors (+32 to +47) of the two slots before it. Nothing in
!        registers.
! Uses:  r0, r1, r10 and fr12-fr15 are changed. Nothing is saved.
! Notes: SZ = 0 on entry and on exit. The clipping senders call it (bsr)
!        only when bit 0 of r12 is set, which lit_groups_send_alpha sets
!        at .Lclipped for a strip whose flags have bit 6 clear.
	.global	_lit_flat_colour_spread
	.type	_lit_flat_colour_spread,@function
_lit_flat_colour_spread:
.Llit_flat_colour_spread:	! 0c106654
	mov	#6,r1
	mov	r11,r0
	and	#3,r0		! r0 = the slot number, 0-3
	mov.l	.Lv_ring_colour_f,r10	! r10 = slot 0's color (lit_clip_ring +32)
	shld	r1,r0		! r0 = 64 x slot
	fschg			! pairs on
	mov	r10,r1
	add	r0,r1		! r1 = this slot's color
	fmov	@r1+,fr12	! fr12, fr13 = alpha, red
	add	#-64,r0		! back one slot,
	fmov	@r1+,fr14	! fr14, fr15 = green, blue
	and	#255,r0		! wrapping within the four slots
	add	#16,r10		! r10 = the end of slot 0's color
	mov	r10,r1
	add	r0,r1		! r1 = the end of the color of the slot before
	fmov	fr14,@-r1	! its green, blue
	add	#-64,r0
	fmov	fr12,@-r1	! its alpha, red
	and	#255,r0		! back one more slot, wrapping
	mov	r10,r1
	add	r0,r1		! r1 = the end of the color of the slot two before
	fmov	fr14,@-r1	! its green, blue
	fmov	fr12,@-r1	! its alpha, red
	rts
	fschg			! (delay slot) pairs off

! lit_kept_vertex_emit
!
! Sends a vertex kept in lit_clip_ring as a 64-byte lit vertex: X and Y
! are divided here with the kept 1/d.
!
! In:    r0 = the slot (low two bits). T = it is the last vertex of the
!        strip being sent (end-of-strip).
!        r5, r6 = list write pointer and the store-queue address for it.
! Out:   T as it came in. r5 and r6 moved on by 64.
! Uses:  r0, r1, r2, r10 and fr0-fr7 are changed. Nothing is saved.
! Notes: SZ = 0 on entry and on exit. Called (bsr) by the two clipping
!        senders. Block words +24 and +28 are copied from the slot's two
!        unwritten words.
	.global	_lit_kept_vertex_emit
	.type	_lit_kept_vertex_emit,@function
_lit_kept_vertex_emit:
.Llit_kept_vertex_emit:		! 0c106686
	mov	#6,r1
	mov.l	.Lv_ring_colour_k,r10	! r10 = slot 0's color (lit_clip_ring +32)
	and	#3,r0		! r0 = the slot number, 0-3
	fschg			! pairs on
	shld	r1,r0		! r0 = 64 x slot
	fldi0	fr6
	add	r0,r10		! r10 = the slot's color
	fldi0	fr7
	mov	#-16,r2
	fmov	@r10+,fr0	! fr0, fr1 = alpha, red
	add	#64,r6		! r6 = the end of the block
	fmov	@r10+,fr2	! fr2, fr3 = green, blue
	add	#-48,r10	! r10 = the start of the slot
	fmov	fr6,@-r6	! block +56 and +48: offset color = 0
	fmov	fr6,@-r6
	fmov	fr2,@-r6	! block +40: green, blue
	fmov	fr0,@-r6	! block +32: alpha, red
	fmov	@r10+,fr0	! fr0, fr1 = z', x'
	shll16	r2
	fmov	@r10+,fr2	! fr2, fr3 = y', 1/d
	fmov	@r10+,fr4	! fr4, fr5 = u, v
	fmul	fr3,fr2		! fr2 = Y of the vertex
	fmov	@r10+,fr6	! fr6, fr7 = the slot's two unwritten words
	fmul	fr3,fr1		! fr1 = X of the vertex
	shll8	r2		! r2 = 0xf0000000: a control word with end-of-strip
	fmov	fr6,@-r6	! block +24: those two words
	add	#64,r5		! the write pointer moves over the vertex
	fmov	fr4,@-r6	! block +16: u, v
	fmov	fr2,@-r6	! block +8: Y, 1/d
	bt.s	.Lvk_control	! the last vertex: keep the end-of-strip word
	fmov	fr0,@-r6	! (delay slot) block +0: (z',) X; r6 = the block
	mov	r6,r2		! not the last: the block's own address is the control word
.Lvk_control:			! 0c1066c6
	mov.l	r2,@r6		! block +0: the control word
	pref	@r6		! send the first 32 bytes
	add	#32,r6
	pref	@r6		! send the second 32 bytes
	fschg			! pairs off
	rts
	add	#32,r6		! (delay slot) r6 = the next block

! lit_near_vertex_emit
!
! Sends the point where the edge between two kept vertices meets the
! near limit, as a 64-byte lit vertex. With A the slot in r0 and B the
! slot in r11:
!   t = (near_limit - z'A) / (z'B - z'A)
! and x', y', u, v and the four color floats are each A + t x (B - A).
! X and Y are x' and y' times near_inv, which is also sent as the
! vertex's 1/d.
!
! In:    r0, r11 = the two slots (low two bits each); one vertex is on
!        each side of the near limit, in either order.
!        T = it is the last vertex of the strip being sent.
!        r12 = near_limit bits, r7 = near_inv bits.
!        r5, r6 = list write pointer and the store-queue address for it.
! Out:   T as it came in. r5 and r6 moved on by 64.
! Uses:  r0, r1, r2, r10 and fr0-fr7 are changed. Nothing is saved.
! Notes: SZ = 0 on entry and on exit. Called (bsr) by the two clipping
!        senders. Block words +24 and +28 are not written.
	.global	_lit_near_vertex_emit
	.type	_lit_near_vertex_emit,@function
_lit_near_vertex_emit:
.Llit_near_vertex_emit:		! 0c1066d4
	mov	#6,r1
	mov.l	.Lv_ring,r10	! r10 = lit_clip_ring
	and	#3,r0		! r0 = slot A's number, 0-3
	mov	r10,r2
	shld	r1,r0
	lds	r12,fpul	! fpul = near_limit bits
	add	r0,r10		! r10 = slot A
	fsts	fpul,fr0	! fr0 = near_limit
	mov	r11,r0
	fmov	@r10,fr2	! fr2 = z' of A
	and	#3,r0
	shld	r1,r0		! r0 = 64 x slot B
	fsub	fr2,fr0		! fr0 = near_limit - z'A
	add	r0,r2		! r2 = slot B
	fmov	@r2,fr1		! fr1 = z' of B
	fschg			! pairs on
	add	#16,r2
	fsub	fr2,fr1		! fr1 = z'B - z'A
	add	#16,r10
	lds	r7,fpul		! fpul = near_inv bits
	fdiv	fr1,fr0		! fr0 = t, how far along the edge from A the cut is
	fmov	@r2,fr4		! fr4, fr5 = u, v of B (slot +16)
	add	#-8,r2
	fmov	@r10,fr2	! fr2, fr3 = u, v of A
	fsub	fr2,fr4		! the u and v differences, B - A
	add	#-8,r10
	fsub	fr3,fr5
	fsts	fpul,fr1	! fr1 = near_inv
	fmac	fr0,fr4,fr2	! fr2 = u at the cut
	add	#24,r6		! r6 = block +24
	fmac	fr0,fr5,fr3	! fr3 = v at the cut
	fmov	fr2,@-r6	! block +16: u, v
	fschg			! pairs off
	fmov	fr1,@-r6	! block +12: 1/d = near_inv
	fmov	@r2,fr5		! fr5 = y' of B (slot +8)
	add	#-4,r2
	fmov	@r10,fr3	! fr3 = y' of A
	add	#-4,r10
	fmov	@r2,fr4		! fr4 = x' of B (slot +4)
	fmov	@r10,fr2	! fr2 = x' of A
	fsub	fr3,fr5		! the y' and x' differences
	fsub	fr2,fr4
	fmac	fr0,fr5,fr3	! fr3 = y' at the cut
	add	#52,r10		! r10 = slot A +56
	fmac	fr0,fr4,fr2	! fr2 = x' at the cut
	mov	r6,r0		! r0 = the control word: an address in the block
	fmul	fr1,fr3		! fr3 = Y, with near_inv as 1/d
	add	#64,r5		! the write pointer moves over the vertex
	fmul	fr1,fr2		! fr2 = X of the cut
	fmov	fr3,@-r6	! block +8: Y of the cut
	bf.s	.Lvn_control	! not the last: the address as it is
	fmov	fr2,@-r6	! (delay slot) block +4: X
	shar	r0		! the last: shifted right once for end-of-strip,
	sett			! and T set again (the shift changed it)
.Lvn_control:			! 0c106740
	mov.l	r0,@-r6		! block +0: the control word
	add	#52,r2		! r2 = slot B +56
	pref	@r6		! send the first 32 bytes
	add	#64,r6		! r6 = the end of the block
	fschg			! pairs on
	fldi0	fr2
	add	#-16,r2		! r2 = slot B +40: green, blue
	fldi0	fr3
	add	#-16,r10	! r10 = slot A +40
	fmov	fr2,@-r6	! block +56 and +48: offset color = 0
	fmov	fr2,@-r6
	fmov	@r2,fr4		! fr4, fr5 = green, blue of B
	add	#-8,r2
	fmov	@r10,fr2	! fr2, fr3 = green, blue of A
	add	#-8,r10
	fsub	fr2,fr4		! the green and blue differences
	fsub	fr3,fr5
	fmov	@r2,fr6		! fr6, fr7 = alpha, red of B (slot +32)
	fmac	fr0,fr4,fr2	! fr2, fr3 = green, blue at the cut
	fmac	fr0,fr5,fr3
	fmov	@r10,fr4	! fr4, fr5 = alpha, red of A
	fmov	fr2,@-r6	! block +40: green, blue
	fsub	fr4,fr6		! the alpha and red differences
	fsub	fr5,fr7
	fmac	fr0,fr6,fr4	! fr4, fr5 = alpha, red at the cut
	fmac	fr0,fr7,fr5
	fmov	fr4,@-r6	! block +32: alpha, red
	fschg			! pairs off
	pref	@r6		! send the second 32 bytes
	rts
	add	#32,r6		! (delay slot) r6 = the next block
	nop			! one nop of padding before the pool
