	fschg			! pairs on
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1 / d
	pref	@r4
	add	#-32,r4		! r4 = the next entry
	fmov	@r2+,fr8	! fr8, fr9 = group alpha, red
	mov	r6,r1
	shar	r1		! r1 = the control word with end-of-strip, for a third vertex
	fmov	@r2+,fr10	! fr10, fr11 = group green, blue
	fmul	fr13,fr9	! red, green and blue times their sums (three fmul)
	mov.l	@r4,r0		! r0 = the next entry's first word
	fmul	fr14,fr10
	fmov	@r14+,fr2	! fr2, fr3 = u, v
	fmul	fr15,fr11
