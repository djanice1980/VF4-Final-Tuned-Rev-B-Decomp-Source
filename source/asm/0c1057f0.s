	mov.l	.Lg_ambient_scaled,r1
	add	#4,r0		! r0 = &light_ambient_color.red
	fmov	@r0+,fr1
	add	#4,r1		! r1 = &lit_ambient_scaled[1]
	fmov	@r0+,fr2
	fmul	fr15,fr1	! red times the ambient factor
	fmul	fr15,fr2	! green times the ambient factor
	fmov	@r0+,fr0
	fmov	fr1,@r1		! lit_ambient_scaled[1] = red
	add	#4,r1
	fmul	fr15,fr0	! blue times the ambient factor
	fmov	fr2,@r1		! lit_ambient_scaled[2] = green
	add	#4,r1
	fmov	fr0,@r1		! lit_ambient_scaled[3] = blue
