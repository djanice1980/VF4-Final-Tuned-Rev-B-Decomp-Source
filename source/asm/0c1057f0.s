	nop
.Lfirst_strip:			! 0c105a6e
	mov.l	@r4+,r0		! r0 = the first strip's flags word
! Per strip. r0 = the word at the head of the next strip: positive = a
! strip's flags, negative = the next group's control word, 0 = the end
! of the object.
.Lstrip_or_end:			! 0c105a70
