.Ltu_load_b:			! 0c106176
	fmov	@r14+,fr8	! B: fr8, fr9 = x, y; then z, and w = 1
	add	#32,r4
	pref	@r4		! fetch the strip data ahead
	fmov	@r14,fr10
	add	#16,r14
	fldi1	fr11
	fmul	fr7,fr6		! A: Y and X divided, between the stores
	fmov	fr0,@-r6	! A block +16: u, v
	fmul	fr7,fr5
	fmov	fr6,@-r6	! A block +8: Y, 1/d
	ftrv	xmtrx,fv8	! B = (d, x', y', z')
	fmov	fr4,@-r6	! A block +0: (d,) X, then the control word over d
	add	#-32,r4
	mov.l	r2,@r6
	fmov	@r14,fr0	! fr0, fr1 = u, v of B
	dt	r3		! count B; T = B is the triangle's third vertex
	pref	@r6		! send A
	add	#56,r6		! r6 = B's block +24
	mov	r6,r2
	fldi1	fr11
	fdiv	fr8,fr11	! fr11 = 1/d of B
	mov.l	@r4+,r0
	bt.s	.Ltu_b_is_third	! B ends the triangle
	mov.l	@r4+,r14	! (delay slot) the next entry's first two words are in r0, r14
	tst	#1,r0
	bt.s	.Ltu_load_a	! a back reference: the delay slot finds its vertex
	add	r4,r14
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	add	#-8,r14
! Load the next A, write and send B.
.Ltu_load_a:			! 0c1061b2
	add	#32,r4
	fmov	@r14+,fr4	! A: fr4, fr5 = x, y; then z, and w = 1
	pref	@r4		! fetch the strip data ahead
	fmov	@r14,fr6
	add	#16,r14
	fldi1	fr7
	fmul	fr11,fr10	! B: Y and X are divided here
	add	#-32,r4
	fmul	fr11,fr9
	fmov	fr0,@-r6	! B block +16: u, v
	fmov	fr10,@-r6	! B block +8: Y, 1/d
	ftrv	xmtrx,fv4	! A = (d, x', y', z')
	fmov	fr8,@-r6	! B block +0: (d,) X, then the control word over d
	add	#64,r5		! the write pointer moves over A and B
	mov.l	r2,@r6
	fmov	@r14,fr0	! fr0, fr1 = u, v of A
	pref	@r6		! send B
	bra	.Ltu_pair
	add	#56,r6		! (delay slot) r6 = A's block +24
! B is a triangle's third vertex. With a triangle left, its first vertex
! (already in r0, r14) becomes the next A and B goes out with
! end-of-strip.
.Ltu_b_is_third:		! 0c1061d8
	dt	r9		! count the triangle; T = it was the last
	mov	r6,r2
	bt.s	.Ltu_finish_b	! the last triangle: B ends it all
	shar	r2		! (delay slot) r2 = B's control word with end-of-strip
	tst	#1,r0
	mov	#3,r3		! r3 = 3 vertices again
	bt.s	.Ltu_load_a	! a back reference: the delay slot finds its vertex
	add	r4,r14
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	bra	.Ltu_load_a
	add	#-8,r14
.Ltu_finish_b:			! 0c1061f0
	add	#48,r4		! fetch ahead; r4 stays 8 past the word after the triangles
	pref	@r4
	add	#-48,r4
	fmov	fr8,fr4		! B moves into A's registers: fr4, fr5 = d, x'
	add	#32,r5		! the write pointer moves over A
	bra	.Ltu_send_final
	fmov	fr10,fr6	! (delay slot) fr6, fr7 = y', 1/d of B
	nop			! padding, never run
! A is a triangle's third vertex: the same, with the next triangle's
! first vertex loaded as B.
.Ltu_a_is_third:		! 0c106200
