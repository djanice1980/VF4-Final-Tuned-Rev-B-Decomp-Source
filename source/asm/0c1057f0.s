	cmp/eq	#-1,r0
	bt.s	.Lunlit_group	! -1: unlit
	cmp/eq	#-2,r0		! (delay slot) T = it is -2
	bf	.Lnot_bump	! not -2: see whether it is -3
! Material type -2, bump mapped: bump_group_send sends all the group's
! strips. It is given the three floats of the header block's light_dir
! in fr14, fr12, fr13 (in that order) and the face color in fr0-fr3
! (which holds it only when the color set-up above ran). It comes back
! with T set at the end of the object; otherwise r8 = the next group's
! control word and r4 is just past it.
.Lbump_group:			! 0c1059fe
