	fmov	fr2,@-r0	! lit_group_colour[2], [3] = green, blue
	fmov	fr0,@-r0	! lit_group_colour[0], [1] = alpha, red
	fschg			! pairs off
! Branch on the material type in r8.
.Lby_material:			! 0c1059f0
