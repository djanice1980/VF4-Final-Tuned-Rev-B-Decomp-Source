	fmov	@r0+,fr14
	fmov	@r0+,fr12	! fr14, fr12, fr13 = the words at +0x10, +0x14, +0x18
	fmov	@r0+,fr13
	mov.l	.Lbump_group_send,r0
	jsr	@r0		! bump_group_send
	nop
	bf	.Lafter_bump	! T clear: another group follows
	bra	.Lobject_done	! T set: the object is done
	nop
.Lafter_bump:			! 0c105a12
