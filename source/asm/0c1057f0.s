	mov.l	@r4+,r1
	bra	.Lnext_group
	fmov	@r4+,fr3
! Build the strip's polygon header from elan_group_header_words:
! word 0 with bit 1 (Gouraud) taken from flags bit 6, word 1 with bits
! 27-28 (cull mode) taken from flags bits 0-1, words 2 and 3 as they
! are. fr0-fr3 carry the four words to the store queue.
.Lstrip_header:			! 0c105a8c
	mov	r0,r1		! r1 = the strip's flags, kept for the choice of sender
	mov	#-5,r2
	mov.l	@r9+,r3		! r3 = header word 0
	and	#64,r0
	shld	r2,r0		! r0 = flags bit 6 moved down to bit 1
	mov	#-3,r2
	and	r2,r3		! word 0 without its Gouraud bit
	or	r3,r0		! word 0 with the strip's Gouraud bit
	add	#32,r4
	pref	@r4		! fetch the strip data 32 bytes on
	fschg			! pairs on
	lds	r0,fpul		! fpul = word 0
	mov.l	@(40,r15),r2	! r2 = control_or (frame +40)
	mov	r1,r0
	cmp/pz	r2		! T = its bit 31 is clear
	mov	#27,r2
	bt.s	.Lcull_bits	! clear: the cull mode as the strip gives it
	and	#3,r0		! (delay slot) r0 = flags bits 0-1, the cull mode
	xor	#1,r0		! bit 31 of control_or set: the other facing (bit 0 flipped)
.Lcull_bits:			! 0c105ab2
	shld	r2,r0		! r0 = the cull mode at bits 27-28
	mov	#3,r3
	shld	r2,r3
	not	r3,r3		! r3 = every bit but 27-28
	mov.l	@r9+,r2		! r2 = header word 1
	and	r3,r2
	fsts	fpul,fr0	! fr0 = word 0
	or	r0,r2		! word 1 with the strip's cull mode
	lds	r2,fpul
	add	#-32,r4		! r4 back on the strip's count
	fsts	fpul,fr1	! fr1 = word 1
	mov.l	.Lg_light_mask,r0
	add	#16,r6		! r6 = 16 bytes into the store-queue block
	fmov	@r9+,fr2	! fr2, fr3 = header words 2 and 3
! Which header: a group that straddles the near limit always gets the
! plain 32-byte one (its vertices go out with floating colors even when
! unlit). Otherwise a lit group with at least one light gets the plain
! one, and a group with no light or an unlit one gets the header with
! the face color.
	rotcr	r12		! T = r12 bit 0, the straddle flag
	mov.l	@r0,r0		! r0 = lit_group_light_mask
	bt.s	.Lplain_header	! straddles: plain header
	rotcl	r12		! (delay slot) r12 as it was
	tst	r0,r0		! T = no light reaches the group
	mov	#-2,r0		! r0 = -2, the mark tested at .Lintensity_header
	bt	.Lintensity_header	! no light: face color header
	cmp/pz	r8
	bf	.Lintensity_header	! unlit (r8 negative): face color header
.Lplain_header:			! 0c105ae0
	fmov	fr2,@-r6	! block +8: header words 2 and 3
.Lsend_header_32:		! 0c105ae2
	add	#32,r5		! the write pointer moves over the 32-byte header
	fmov	fr0,@-r6	! block +0: header words 0 and 1
	fschg			! pairs off
	pref	@r6		! send the block (its last 16 bytes are whatever the queue held)
	bra	.Lsend_strip
	add	#32,r6		! (delay slot) r6 = the next block
! Header for a group whose vertices carry no color of their own. The
! first strip of the group sends 64 bytes: the header with color type 2
! (intensity mode 1), then the face color = lit_group_colour with its
! red, green and blue times lit_ambient_scaled, and a zero offset color.
! elan_group_header_words[0] is then left with color type 3 (intensity
! mode 2, "the face color sent before") and r8 is set to -2, so that the
! group's later strips come here, find the mark and send that word in a
! plain 32-byte header. r8 = -2 also sends a lit group with no light
! down the unlit vertex paths of the senders.
.Lintensity_header:		! 0c105aee
	cmp/eq	r0,r8		! T = the mark: this group's face color is already sent
	fmov	fr2,@-r6	! block +8: header words 2 and 3
	bt	.Lsend_header_32	! marked: a 32-byte header (word 0 now has color type 3)
	add	#64,r5		! the write pointer moves over the 64-byte header
	flds	fr0,fpul
	sts	fpul,r0		! r0 = header word 0 (color type 1)
	or	#48,r0		! bits 4-5 = 11
	fschg			! pairs off
	xor	#16,r0		! bits 4-5 = 10: color type 2
	fmov	fr1,@-r6	! block +4: header word 1
	add	#-16,r9		! r9 = &elan_group_header_words
	mov.l	r0,@-r6		! block +0: header word 0 with color type 2
	or	#48,r0		! r0 = the same word with color type 3
	pref	@r6		! send the first 32 bytes
	fschg			! pairs on
	mov.l	r0,@r9		! elan_group_header_words[0] = color type 3, for the later strips
	add	#64,r6		! r6 = the end of the second 32 bytes
	mov.l	.Lgroup_colour_end,r0
	fldi0	fr4
	add	#-16,r0		! r0 = lit_group_colour
	fldi0	fr5		! fr4, fr5 = 0
	fmov	@r0+,fr0	! fr0, fr1 = face alpha, red
	fmov	@r0+,fr2	! fr2, fr3 = face green, blue
	fmov	fr4,@-r6	! block +56: offset color green, blue = 0
	fmov	fr4,@-r6	! block +48: offset color alpha, red = 0
	mov.l	.Lg_ambient_scaled,r0
	fmov	@r0+,fr4	! fr5 = lit_ambient_scaled[1], red (fr4 = word 0, not used)
	fmul	fr5,fr1		! face red x ambient red
	fmov	@r0+,fr4	! fr4, fr5 = lit_ambient_scaled[2], [3]: green, blue
	fmul	fr4,fr2		! face green x ambient green
	fmul	fr5,fr3		! face blue x ambient blue
	fmov	fr2,@-r6	! block +40: face green, blue
	fmov	fr0,@-r6	! block +32: face alpha, red
	fschg			! pairs off
	pref	@r6		! send the second 32 bytes
	mov	#-2,r8		! r8 = -2: the mark
	add	#32,r6		! r6 = the next block
! Pick the sender. Without clipping: flags bit 3 set = triangles, clear
! = a strip. Each sender is entered with r4 on the strip's count and
! leaves r4 on the word after the strip.
.Lsend_strip:			! 0c105b38
