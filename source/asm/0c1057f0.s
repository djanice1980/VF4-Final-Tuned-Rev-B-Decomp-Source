! lit_strip_send
!
! Sends one strip of a group that does not straddle the near limit, and
! any strips after it that carry on under the same header (flags bit 7),
! with no clipping.
!
! Lit group (r8 >= 0): each vertex goes out as 64 bytes with a
! floating-point color:
!   +0   control word: a store-queue address inside the block, whose
!        top three bits are set as a vertex's are; for the last vertex
!        the address is shifted right once, which sets bit 28
!        (end-of-strip)
!   +4   X = x'/d       +8   Y = y'/d       +12  1/d
!   +16  u              +20  v              (+24 and +28 are not written)
!   +32  base color: alpha, red, green, blue
!   +48  offset color, all 0 (written once on entry; that half of the
!        store queue keeps it for every later vertex)
! The base color is lit_group_colour times the vertex's light sum; the
! alpha is lit_group_colour[0] as it stands. The light sum starts at
! lit_ambient_scaled (red, green, blue) and adds, for every light in
! lit_group_light_mask, the light's color (record +0x18) times a term
! worked out from its light_table record by type (+2), with N the
! vertex's normal:
!   2 (directional): term = N . model_dir (+0x80). Nothing is added when
!     it is negative.
!   3 (point): L = model_pos (+0x74) - vertex. Nothing is added when
!     N . L is negative, or when |L| squared is not below the float at
!     +0x98 (the range squared: 65536 squared in the default record,
!     whose range is 65536). term = N . L / |L|, divided by the
!     attenuation (+0x4c) + (+0x50) x |L| + (+0x54) x |L| squared when
!     that is above 1.
!   any other type (spot): as a point light, but first the cosine of
!     the angle between model_dir and the direction from the light to
!     the vertex must reach cone_cos (+0x58), or nothing is added; and
!     the term is multiplied by (cosine - cone_cos) x cone_scale
!     (+0x9c), which runs from 0 at the cone's edge to 1 on its axis.
! The code is laid out so that slow instructions overlap: the position's
! ftrv is issued while the last light of the mask is being worked out,
! and the second 32 bytes of each vertex are sent while the next vertex
! is being loaded.
!
! Unlit group (r8 < 0; that includes a lit group that no light reaches,
! see .Lintensity_header): the code from .Ls_unlit sends 32-byte
! vertices (control word, X, Y, 1/d, u, v, base intensity 1.0, offset
! intensity 1.0), two per turn of its loop. Their color is the face
! color in the group's header.
!
! In:    r4 = the strip's count word (the word after its flags); the
!        vertex entries follow it.
!        r5 = list write pointer, r6 = the store-queue address for it.
!        r8 = material type (negative = unlit).
!        XMTRX = the current matrix (see lit_groups_send_alpha).
!        lit_group_colour, lit_ambient_scaled, lit_group_light_mask and
!        light_table as described above.
! Out:   r4 = the word after the last strip sent (the caller reads it
!        next). r5 and r6 are moved past everything sent.
! Uses:  r0-r3, r13, r14 and fr0-fr15 are changed and none is saved (the
!        caller saved r13, r14 and fr12-fr15 for the whole object).
!        r7-r12 are not touched.
! Notes: entered and left with SZ = 0; pairs are on for stretches.
!        Called only by lit_groups_send_alpha (bsr).
	.global	_lit_strip_send
	.type	_lit_strip_send,@function
_lit_strip_send:
.Llit_strip_send:		! 0c105bf0
	cmp/pz	r8
	bt	.Ls_lit		! material type 0 or more: the lit path
	bra	.Ls_unlit	! negative: 32-byte vertices without lighting
	nop
! Lit path. Write the zero offset color into the second half of the
! vertex block once, then find the first vertex's data.
.Ls_lit:			! 0c105bf8
	mov.l	@r4+,r3		! r3 = the number of vertices; r4 = the first vertex entry
	fldi0	fr0
	add	#64,r6		! r6 = the end of the 64-byte block
	fldi0	fr1
	fschg			! pairs on
	fmov	fr0,@-r6	! block +56: offset green, blue = 0
	fmov	fr0,@-r6	! block +48: offset alpha, red = 0; r6 = block +48
	fschg			! pairs off
	mov.l	@r4,r0		! r0 = the entry's first word
	mov	r4,r14		! r14 = the vertex data, if it is inline
	tst	#1,r0		! T = bit 0 clear: a back reference
	mov.l	.Ls_light_mask,r13	! r13 = &lit_group_light_mask
	bf.s	.Ls_first_vertex	! inline: r14 is right
	add	#32,r4		! (delay slot) r4 = past a 32-byte inline vertex
	mov.l	@(4,r14),r14	! back reference: r14 = the offset
	add	#-24,r4		! r4 = past the 8-byte entry
	add	r4,r14		! r14 = the vertex the entry refers to
.Ls_first_vertex:		! 0c105c1a
	mov.l	.Ls_ambient_scaled,r0	! r0 = lit_ambient_scaled
	fschg			! pairs on
	mov.l	@r13,r13	! r13 = the mask of lights that reach the group
	fmov	@r0+,fr12	! fr13 = ambient red (fr12 = word 0, only scratch below)
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue: the light sum starts here
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#32,r4		! r4 = 32 bytes past the next entry, for the pref at .Ls_finish_vertex
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	bra	.Ls_light_sum
	fschg			! (delay slot) pairs off
	nop			! padding, never run
! The next vertex is inline (r14 = its entry, set at 0c105d6e). The
! first 32 bytes of the vertex before it have just been sent; its second
! 32 bytes (r1) go out at the pref below, after this vertex's loads.
.Ls_next_inline:		! 0c105c30
	mov.l	.Ls_ambient_scaled,r0
	add	#32,r6		! r6 = the second half of the block just filled
	mov.l	@r13,r13	! r13 = the light mask again
	mov	r6,r1		! r1 = that second half, for the pref below
	fmov	@r0+,fr12	! fr13 = ambient red (pairs are still on from .Ls_finish_vertex)
	add	#64,r5		! the write pointer moves over the vertex before
! Also the way in for the first inline vertex of a strip that carries on
! (from 0c105dd0, with r0, r1, r13 and r5 already set).
.Ls_join_inline:		! 0c105c3c
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	add	#64,r4		! r4 = 32 bytes past the entry after this one
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#80,r6		! r6 = this vertex's block +48
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	fschg			! pairs off
	pref	@r1		! send the second 32 bytes of the vertex before
! The light sum for one vertex. Here fv4 = x, y, z and normal x (which
! moves to fr8), r14 = &normal y, r13 = the mask, fr13-fr15 = the sum so
! far. In the loop r2 = the light's record and r13 holds the mask bits
! of the lights after it, so r13 = 0 means "this is the last light".
.Ls_light_sum:			! 0c105c4a
	fmov	fr7,fr8		! fr8 = normal x
	tst	r13,r13		! T = no light reaches the group
	fmov	@r14+,fr9	! fr9 = normal y
	bt.s	.Ls_no_lights	! no light: only the position is left to do
	fmov	@r14+,fr10	! (delay slot) fr10 = normal z; r14 = &u
	shlr	r13		! T = light 0 is in the mask
	mov.l	.Ls_light_table,r2	! r2 = light_table record 0
	bf	.Ls_skip_light	! not in the mask: step to the first one that is
	mov.w	@(2,r2),r0	! r0 = light 0's type
! One light: r2 = its record, r0 = its type.
.Ls_light:			! 0c105c5c
	fldi0	fr3		! fr3 = 0: the fourth term of the dot products with fv0
	cmp/eq	#2,r0		! T = directional
	mov	#116,r1
	bf.s	.Ls_point_or_spot	! not directional: point or spot
	add	r2,r1		! (delay slot) r1 = &record.model_pos (+0x74)
! Directional light: term = N . model_dir.
	fldi1	fr7		! w = 1 for the position
	tst	r13,r13		! T = no light follows
	add	#12,r1		! r1 = &record.model_dir (+0x80)
	bf.s	.Ls_dir_dot	! more follow: leave the position for later
	fmov	@r1+,fr0	! (delay slot) fr0 = direction x
	ftrv	xmtrx,fv4	! last light: fv4 = (d, x', y', z') of the position
.Ls_dir_dot:			! 0c105c72
	fmov	@r1+,fr1	! fr1 = direction y
	mov	r2,r0
	fmov	@r1+,fr2	! fr2 = direction z
	add	#24,r0		! r0 = &record.color.red (+0x18)
	fipr	fv0,fv8		! fr11 = N . direction
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	fmov	@r0+,fr3
	fldi0	fr0
	fcmp/gt	fr11,fr0	! T = the term is negative
	fmov	fr11,fr0	! fr0 = the term
	bf.s	.Ls_add_light	! not negative: add this light
	tst	r13,r13		! (delay slot) T = no light follows
! This light adds nothing, or light 0 is not in the mask. With T set
! there is no light left; otherwise step r2 on to the next light whose
! bit is set.
.Ls_skip_light:			! 0c105c8c
	mov	#-80,r0
	bt	.Ls_finish_vertex	! no light left: finish the vertex
	shlr	r13		! T = the next light's bit
	extu.b	r0,r0		! r0 = 0xb0, the size of a light record
	bf.s	.Ls_step_bit	! bit clear: keep stepping
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Ls_light
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
.Ls_no_lights:			! 0c105c9c
	fldi1	fr7		! w = 1 for the position
	bra	.Ls_finish_vertex
	ftrv	xmtrx,fv4	! (delay slot) fv4 = (d, x', y', z')
	nop			! padding, never run
! Point or spot light. L = model_pos - vertex is taken before the
! position is transformed in place.
.Ls_point_or_spot:		! 0c105ca4
	fmov	@r1+,fr0	! fr0 = light x
	tst	r13,r13		! T = no light follows
	fmov	@r1+,fr1
	fsub	fr4,fr0		! fr0 = L x
	fmov	@r1+,fr2
	fsub	fr5,fr1		! fr1 = L y
	fldi1	fr7		! w = 1 for the position
	add	#24,r1		! r1 = record +0x98, the range squared
	fldi0	fr11		! fr11 = 0: the fourth term of the dot product with fv8
	bf.s	.Ls_point_dot	! more lights follow: leave the position for later
	fsub	fr6,fr2		! (delay slot) fr2 = L z; fv0 = L (fr3 = 0)
	ftrv	xmtrx,fv4	! last light: fv4 = (d, x', y', z') of the position
.Ls_point_dot:			! 0c105cbc
	fipr	fv0,fv8		! fr11 = N . L
	fldi0	fr12
	fipr	fv0,fv0		! fr3 = |L| squared
	fcmp/gt	fr11,fr12	! T = N . L is negative
	fmov	@r1,fr12	! fr12 = the range squared (+0x98)
	bt	.Ls_light_adds_nothing	! facing away: nothing from this light
	fcmp/gt	fr3,fr12	! T = the vertex is nearer than the range
	bf	.Ls_light_adds_nothing	! out of range: nothing from this light
	cmp/eq	#3,r0		! T = a point light (type 3)
	flds	fr3,fpul	! fpul keeps |L| squared
	bt.s	.Ls_attenuate	! point light: no cone
	fsrra	fr3		! (delay slot) fr3 = 1 / |L|
! Spot light only: the cone. fr0-fr2 are reused as each part of L has
! been multiplied.
	add	#-24,r1		! r1 = &record.model_dir (+0x80)
	fmov	@r1+,fr12
	fmul	fr0,fr12	! fr12 = L x times direction x
	fmov	@r1+,fr0
	fmac	fr0,fr1,fr12	! plus L y times direction y
	fmov	@r1,fr0
	add	#-48,r1		! r1 = &record.cone_cos (+0x58)
	fmac	fr0,fr2,fr12	! fr12 = L . direction
	fmov	@r1,fr2		! fr2 = cone_cos
	fneg	fr12		! fr12 = (vertex - light) . direction
	fmul	fr3,fr12	! fr12 = cosine of the angle off the light's axis
	add	#68,r1		! r1 = &record.cone_scale (+0x9c)
	fcmp/gt	fr12,fr2	! T = outside the cone
	fsub	fr2,fr12	! fr12 = cosine - cone_cos
	fmov	@r1,fr2		! fr2 = cone_scale
	bt	.Ls_light_adds_nothing	! outside the cone: nothing from this light
	fmul	fr2,fr12	! fr12 = the cone factor, 0 at the edge to 1 on the axis
	add	#-4,r1		! r1 = record +0x98 again, as a point light has it
	fmul	fr12,fr11	! fr11 = N . L times the cone factor
! Point and spot: divide by the distance and by the attenuation
! a0 + a1 x |L| + a2 x |L| squared (a0, a1, a2 = the floats at +0x4c,
! +0x50, +0x54), the latter only when it is above 1.
.Ls_attenuate:			! 0c105cfa
	add	#-68,r1		! r1 = record +0x54
	fmov	@r1,fr2		! fr2 = a2
	add	#-8,r1		! r1 = record +0x4c
	fsts	fpul,fr0	! fr0 = |L| squared
	fmul	fr3,fr11	! fr11 = N . L / |L| (times the cone factor)
	fmov	@r1,fr12	! fr12 = a0
	fmul	fr0,fr3		! fr3 = |L|
	add	#4,r1
	fmac	fr0,fr2,fr12	! fr12 = a0 + a2 x |L| squared
	fmov	@r1,fr2		! fr2 = a1 (+0x50)
	mov	r2,r0
	fmov	fr3,fr0
	fmac	fr0,fr2,fr12	! fr12 = the attenuation
	fmov	fr11,fr0	! fr0 = the term as it is
	add	#24,r0		! r0 = &record.color.red (+0x18)
	fdiv	fr12,fr11	! fr11 = the term over the attenuation
	fldi1	fr2
	fcmp/gt	fr2,fr12	! T = the attenuation is above 1
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	bf.s	.Ls_term_ready	! not above 1: the term as it is
	fmov	@r0+,fr3	! (delay slot) the light's blue
	fmov	fr11,fr0	! above 1: the divided term
.Ls_term_ready:			! 0c105d28
	tst	r13,r13		! T = no light follows
! Add the light: sum += term (fr0) x the light's color (fr1-fr3).
.Ls_add_light:			! 0c105d2a
	fmac	fr0,fr1,fr13	! red sum
	mov	#-80,r0
	fmac	fr0,fr2,fr14	! green sum
	bt.s	.Ls_finish_vertex	! that was the last light: finish the vertex
	fmac	fr0,fr3,fr15	! (delay slot) blue sum
	bra	.Ls_step_record
	shlr	r13		! (delay slot) T = the next light's bit
.Ls_light_adds_nothing:		! 0c105d38
	tst	r13,r13		! T = no light follows
	mov	#-80,r0
	bt.s	.Ls_finish_vertex	! none: finish the vertex (the shlr below is its delay slot)
.Ls_step_bit:			! 0c105d3e
	shlr	r13		! T = the next light's bit
.Ls_step_record:		! 0c105d40
	extu.b	r0,r0		! r0 = 0xb0, the size of a light record
	bf.s	.Ls_step_bit	! bit clear: step again
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Ls_light	! bit set: work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
! Finish the vertex: divide, scale the group color by the light sum and
! fill the block from +44 down. Here fv4 = (d, x', y', z'), r14 = &u,
! r6 = block +48, r4 = 32 bytes past the next entry.
.Ls_finish_vertex:		! 0c105d4a
	mov.l	.Ls_group_colour,r2	! r2 = lit_group_colour
	fschg			! pairs on
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1 / d
	pref	@r4		! fetch the strip data ahead
	add	#-32,r4		! r4 = the next entry
	fmov	@r2+,fr8	! fr8, fr9 = group alpha, red
	mov	r6,r1
	shar	r1		! r1 = the control word with end-of-strip, if this is the last
	fmov	@r2+,fr10	! fr10, fr11 = group green, blue
	fmul	fr13,fr9	! red x red sum
	mov.l	@r4,r0		! r0 = the next entry's first word
	fmul	fr14,fr10	! green x green sum
	fmov	@r14+,fr2	! fr2, fr3 = u, v
	fmul	fr15,fr11	! blue x blue sum
	mov.l	.Ls_light_mask,r13	! r13 = &lit_group_light_mask, for the next vertex
	dt	r3		! count the vertex; T = it was the strip's last
	fmov	fr10,@-r6	! block +40: green, blue
	mov	r4,r14		! r14 = the next entry (its data, if it is inline)
	fmov	fr8,@-r6	! block +32: alpha, red
	add	#-8,r6		! leave +24 and +28 alone
	fmul	fr7,fr6		! fr6 = Y
	fmov	fr2,@-r6	! block +16: u, v
	fmul	fr7,fr5		! fr5 = X
	fmov	fr6,@-r6	! block +8: Y, 1/d
	bt.s	.Ls_last_vertex	! the strip's last vertex
	fmov	fr4,@-r6	! (delay slot) block +0: (d,) X; r6 = the block
	tst	#1,r0		! T = the next entry is a back reference
	mov.l	r6,@r6		! block +0: the control word, the block's own address
	bt	.Ls_next_back_ref	! back reference: the copy of the loop head below
	bra	.Ls_next_inline	! inline: round again; its delay slot is the pref below
! The next vertex is a back reference: the same steps as .Ls_next_inline
! and .Ls_join_inline with the vertex found through the entry's offset.
! The pref is also the delay slot of the bra above: either way it sends
! the first 32 bytes of the vertex just finished.
.Ls_next_back_ref:		! 0c105d88
	pref	@r6		! send the first 32 bytes
	add	#8,r4		! r4 = past the 8-byte entry
	mov.l	@(4,r14),r14	! r14 = the offset
	add	#32,r6		! r6 = the second half of the block
	mov.l	.Ls_ambient_scaled,r0
	add	r4,r14		! r14 = the vertex the entry refers to
	mov.l	@r13,r13	! r13 = the light mask
	add	#64,r5		! the write pointer moves over the vertex before
	fmov	@r0+,fr12	! fr13 = ambient red
	mov	r6,r1
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	add	#32,r4		! r4 = 32 bytes past the next entry
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#80,r6		! r6 = this vertex's block +48
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	fschg			! pairs off
	bra	.Ls_light_sum
	pref	@r1		! (delay slot) send the second 32 bytes of the vertex before
! The strip's last vertex is in the block. r1 = its control word with
! end-of-strip. See whether a strip that carries on follows.
.Ls_last_vertex:		! 0c105dac
	mov.l	@r4+,r0		! r0 = the word after the strip
	mov.l	r1,@r6		! block +0: the control word with end-of-strip
	cmp/pl	r0
	pref	@r6		! send the first 32 bytes
	add	#32,r6		! r6 = the second half
	bf	.Ls_done	! not positive: not a strip
	tst	#128,r0		! flags bit 7
	mov.l	.Ls_light_mask,r13
	bt	.Ls_done	! clear: a strip with a header of its own
	mov.l	@r4+,r3		! it carries on: r3 = its number of vertices
	mov	r6,r1		! r1 = the second half, sent once the next vertex is loaded
	mov.l	@r4,r0		! r0 = the first entry's first word
	mov	r4,r14
	mov.l	@r13,r13	! r13 = the light mask
	tst	#1,r0		! T = the entry is a back reference
	mov.l	.Ls_ambient_scaled,r0	! r0 = lit_ambient_scaled
	add	#64,r5		! the write pointer moves over the vertex before
	bt	.Ls_cont_back_ref	! back reference: below
	bra	.Ls_join_inline	! inline: join the loop; its delay slot is the fmov below
! First vertex of a strip that carries on, as a back reference. The
! fmov is also the delay slot of the bra above.
.Ls_cont_back_ref:		! 0c105dd2
	fmov	@r0+,fr12	! fr13 = ambient red (pairs are on)
	add	#8,r4		! r4 = past the 8-byte entry
	mov.l	@(4,r14),r14
	add	#80,r6		! r6 = this vertex's block +48
	fmov	@r0+,fr14	! fr14, fr15 = ambient green, blue
	add	r4,r14		! r14 = the vertex the entry refers to
	pref	@r1		! send the second 32 bytes of the vertex before
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#32,r4		! r4 = 32 bytes past the next entry
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	bra	.Ls_light_sum
	fschg			! (delay slot) pairs off
! Done. r4 goes back onto the word after the strip.
.Ls_done:			! 0c105dea
	add	#-4,r4		! undo the read of that word
	fschg			! pairs off
	add	#64,r5		! the write pointer moves over the last vertex
	pref	@r6		! send its second 32 bytes
	rts
	add	#32,r6		! (delay slot) r6 = the next block
	nop			! five nops of padding before the pool
	nop
	nop
	nop
	nop
.Ls_group_colour:
	.long	_lit_group_colour
.Ls_ambient_scaled:
	.long	_lit_ambient_scaled
.Ls_light_table:
	.long	_light_table
.Ls_light_mask:
	.long	_lit_group_light_mask
! 0c105e10: the unlit path. A 32-byte vertex ends with the base and
! offset intensities, both 1.0 here. They are written once, into the
! last two words of both store queues (the 32-byte block before r6 and
! the one at r6), and stay there for every vertex.
! The loop handles two vertices a turn, A in fv4 and B in fv8, so that
! one's divide runs while the other is loaded and transformed. fr0, fr1
! hold u, v of the vertex about to be written. r2 = the control word.
.Ls_unlit:			! 0c105e10
	mov.l	@r4+,r3		! r3 = the number of vertices
	fldi1	fr2
	fschg			! pairs on, until the routine returns
	fldi1	fr3		! fr2, fr3 = 1.0, 1.0
	fmov	fr2,@-r6	! the block before, +24: intensities 1.0, 1.0
	add	#32,r6		! r6 = block +24
	fmov	fr2,@r6		! this block +24: the same
	mov.l	@r4,r0		! r0 = the first entry's first word
	mov	r4,r14
	tst	#1,r0		! T = a back reference
	add	#32,r4		! r4 = past a 32-byte inline vertex
	bf	.Lsu_first	! inline: r14 is the vertex
	mov.l	@(4,r14),r14	! back reference: r14 = the offset
	add	#-24,r4		! r4 = past the 8-byte entry
	add	r4,r14		! r14 = the vertex referred to
.Lsu_first:			! 0c105e2e
	fmov	@r14+,fr4	! A: fr4, fr5 = x, y
	fmov	@r14,fr6	! fr6 = z (fr7 = normal x, replaced next)
	add	#16,r14		! r14 = &u
	fldi1	fr7		! w = 1
	fmov	@r14,fr0	! fr0, fr1 = u, v of A
	ftrv	xmtrx,fv4	! A = (d, x', y', z')
! One turn: A is transformed and waits to be written.
.Lsu_pair:			! 0c105e3a
	fldi1	fr7
	fdiv	fr4,fr7		! fr7 = 1/d of A
	dt	r3		! count A; T = A is the strip's last
	mov.l	@r4+,r0		! r0 = the next entry's first word
	bt.s	.Lsu_a_is_last	! A is the last vertex
	mov.l	@r4+,r14	! (delay slot) r14 = the entry's second word; r4 = entry +8
	tst	#1,r0		! T = the entry is a back reference
	mov	r6,r2		! r2 = A's control word (an address in its block)
	bt.s	.Lsu_load_b	! a back reference: the delay slot finds its vertex
	add	r4,r14		! (delay slot) r14 = offset + end of entry, for a back reference
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	add	#-8,r14
! Load B, write and send A.
.Lsu_load_b:			! 0c105e54
	fmov	@r14+,fr8	! B: fr8, fr9 = x, y
	add	#32,r4
	pref	@r4		! fetch the strip data ahead
	fmov	@r14,fr10	! fr10 = z
	add	#16,r14		! r14 = &u of B
	fldi1	fr11		! w = 1
	fmul	fr7,fr6		! A: fr6 = Y of the vertex
	fmov	fr0,@-r6	! A block +16: u, v
	fmul	fr7,fr5		! A: fr5 = X of the vertex
	fmov	fr6,@-r6	! A block +8: Y, 1/d
	ftrv	xmtrx,fv8	! B = (d, x', y', z')
	fmov	fr4,@-r6	! A block +0: (d,) X
	add	#-32,r4
	mov.l	r2,@r6		! A block +0: the control word
	fmov	@r14,fr0	! fr0, fr1 = u, v of B
	dt	r3		! count B; T = B is the strip's last
	pref	@r6		! send A
	add	#56,r6		! r6 = B's block +24
	mov	r6,r2		! r2 = B's control word
	fldi1	fr11
	fdiv	fr8,fr11	! fr11 = 1/d of B
	mov.l	@r4+,r0		! r0 = the next entry's first word
	bt.s	.Lsu_b_is_last	! B is the last vertex
	mov.l	@r4+,r14	! (delay slot) r14 = the entry's second word; r4 = entry +8
	tst	#1,r0		! T = a back reference
	bt.s	.Lsu_load_a	! back reference: r14 = offset + end of entry
	add	r4,r14
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	add	#-8,r14
! Load the next A, write and send B.
.Lsu_load_a:			! 0c105e90
	add	#32,r4
	fmov	@r14+,fr4	! A: fr4, fr5 = x, y
	pref	@r4		! fetch the strip data ahead
	fmov	@r14,fr6	! fr6 = z
	add	#16,r14
	fldi1	fr7		! w = 1
	fmul	fr11,fr10	! B: fr10 = Y of the vertex
	add	#-32,r4
	fmul	fr11,fr9	! B: fr9 = X of the vertex
	fmov	fr0,@-r6	! B block +16: u, v
	fmov	fr10,@-r6	! B block +8: Y, 1/d
	ftrv	xmtrx,fv4	! A = (d, x', y', z')
	fmov	fr8,@-r6	! B block +0: (d,) X
	add	#64,r5		! the write pointer moves over A and B
	mov.l	r2,@r6		! B block +0: the control word
	fmov	@r14,fr0	! fr0, fr1 = u, v of A
	pref	@r6		! send B
	bra	.Lsu_pair
	add	#56,r6		! (delay slot) r6 = A's block +24
	nop			! padding, never run
! B is the strip's last vertex. r0 = the word after the strip, r14 = the
! word after that. If r0 is positive with bit 7 set the strip carries
! on: r14 is its count and the first vertex of it becomes the next A,
! while B goes out with end-of-strip.
.Lsu_b_is_last:			! 0c105eb8
	cmp/pl	r0
	mov.l	@r4+,r2		! r2 = the third word; r4 = past it
	bf	.Lsu_finish_b	! not a strip: B ends it all
	tst	#128,r0
	mov	r14,r3		! r3 = the count, if it carries on
	bt	.Lsu_finish_b	! bit 7 clear: B ends it all
	mov	r2,r0		! r0 = the first entry's first word
	mov	r6,r2
	shar	r2		! r2 = B's control word with end-of-strip
	mov.l	@r4+,r14	! r14 = the entry's second word; r4 = entry +8
	tst	#1,r0		! T = a back reference
	bt.s	.Lsu_load_a	! back reference: r14 = offset + end of entry
	add	r4,r14
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	bra	.Lsu_load_a
	add	#-8,r14
	nop			! padding, never run
.Lsu_finish_b:			! 0c105edc
	add	#44,r4		! three words were read past the strip: fetch ahead, and
	pref	@r4
	add	#-48,r4		! r4 = 8 past the word after the strip
	fmov	fr8,fr4		! B moves into A's registers: fr4, fr5 = d, x'
	add	#32,r5		! the write pointer moves over A
	bra	.Lsu_send_final
	fmov	fr10,fr6	! (delay slot) fr6, fr7 = y', 1/d of B
	nop			! padding, never run
! A is the strip's last vertex: the same test. When the strip carries
! on, its first vertex is loaded as B and A goes out with end-of-strip.
.Lsu_a_is_last:			! 0c105eec
	cmp/pl	r0
	mov.l	@r4+,r2		! r2 = the third word; r4 = past it
	bf	.Lsu_finish_a	! not a strip: A ends it all
	tst	#128,r0
	mov	r14,r3		! r3 = the count, if it carries on
	bt	.Lsu_finish_a	! bit 7 clear: A ends it all
	mov	r2,r0		! r0 = the first entry's first word
	mov	r6,r2
	shar	r2		! r2 = A's control word with end-of-strip
	mov.l	@r4+,r14	! r14 = the entry's second word; r4 = entry +8
	tst	#1,r0
	bt.s	.Lsu_load_b	! back reference: r14 = offset + end of entry
	add	r4,r14
	mov	r4,r14		! inline: r14 = the vertex, r4 = past its 32 bytes
	add	#24,r4
	bra	.Lsu_load_b
	add	#-8,r14
	nop			! padding, never run
.Lsu_finish_a:			! 0c105f10
	add	#44,r4
	pref	@r4
	add	#-48,r4		! r4 = 8 past the word after the strip
! Write and send the very last vertex (in fv4, u and v in fr0, fr1).
.Lsu_send_final:		! 0c105f16
	fmul	fr7,fr6		! fr6 = Y
	mov	r6,r2
	shar	r2		! r2 = the control word with end-of-strip
	fmul	fr7,fr5		! fr5 = X
	fmov	fr0,@-r6	! block +16: u, v
	add	#-8,r4		! r4 = the word after the strip
	fmov	fr6,@-r6	! block +8: Y, 1/d
	add	#32,r5		! the write pointer moves over this vertex
	fmov	fr4,@-r6	! block +0: (d,) X
	mov.l	r2,@r6		! block +0: the control word
	fschg			! pairs off
	pref	@r6		! send it
	rts
	add	#32,r6		! (delay slot) r6 = the next block
	nop			! seven nops of padding
	nop
	nop
	nop
	nop
	nop
	nop

! lit_tris_send
!
! lit_strip_send for a list of separate triangles: the strip's count
! word is the number of triangles, and each triangle is sent as a
! three-vertex strip (end-of-strip on its third vertex). Vertex entries,
! the 64-byte lit vertex, the light sum and the 32-byte unlit vertex are
! exactly as described at lit_strip_send; the code is the same macro
! expanded again, with r3 counting the three vertices and r9 the
! triangles. There are no strips that carry on.
!
! In:    r4 = the count word (triangles); the vertex entries follow.
!        r5 = list write pointer, r6 = the store-queue address for it.
!        r8 = material type (negative = unlit: the code from .Lt_unlit).
!        XMTRX, lit_group_colour, lit_ambient_scaled,
!        lit_group_light_mask and light_table as for lit_strip_send.
! Out:   r4 = the word after the last triangle (the caller reads it
!        next). r5 and r6 are moved past everything sent.
! Uses:  r0-r3, r9, r13, r14 and fr0-fr15 are changed and none is saved
!        (the caller saved r9, r13, r14 and fr12-fr15 for the whole
!        object, and reloads r9 itself). r7, r8, r10-r12 are not touched.
! Notes: entered and left with SZ = 0; pairs are on for stretches.
!        Called only by lit_groups_send_alpha (bsr).
	.global	_lit_tris_send
	.type	_lit_tris_send,@function
_lit_tris_send:
.Llit_tris_send:		! 0c105f40
	cmp/pz	r8
	bt	.Lt_lit		! material type 0 or more: the lit path
	bra	.Lt_unlit	! negative: 32-byte vertices without lighting
	nop
! Lit path: the zero offset color once, as in lit_strip_send.
.Lt_lit:			! 0c105f48
	mov.l	@r4+,r9		! r9 = the number of triangles; r4 = the first vertex entry
	mov	#3,r3		! r3 = 3 vertices to the triangle
	fldi0	fr0
	add	#64,r6		! r6 = the end of the 64-byte block
	fldi0	fr1
	fschg
	fmov	fr0,@-r6	! block +56 and +48: offset color = 0 (pairs); r6 = block +48
	fmov	fr0,@-r6
	fschg
! The first vertex of a triangle (r6 = its block +48).
.Lt_triangle:			! 0c105f5a
	mov.l	@r4,r0		! r0 = the entry's first word
	mov	r4,r14
	tst	#1,r0		! T = bit 0 clear: a back reference
	mov.l	.Lt_light_mask,r13
	bf.s	.Lt_first_vertex	! inline: r14 is the vertex
	add	#32,r4		! (delay slot) r4 = past a 32-byte inline vertex
	mov.l	@(4,r14),r14	! back reference: r14 = the offset,
	add	#-24,r4
	add	r4,r14		! plus the end of the 8-byte entry
.Lt_first_vertex:		! 0c105f6c
	mov.l	.Lt_ambient_scaled,r0
	fschg			! pairs on
	mov.l	@r13,r13	! r13 = the mask of lights that reach the group
	fmov	@r0+,fr12	! fr13-fr15 = ambient red, green, blue: the light sum starts here
	fmov	@r0+,fr14
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#32,r4		! r4 = 32 bytes past the next entry
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	bra	.Lt_light_sum
	fschg			! (delay slot) pairs off
! The second or third vertex, inline: the second half of the vertex
! before (r1) is sent once this one is loaded.
.Lt_next_inline:		! 0c105f80
	mov.l	.Lt_ambient_scaled,r0
	add	#32,r6		! r6 = the second half of the block just filled
	mov.l	@r13,r13	! r13 = the light mask again
	mov	r6,r1
	fmov	@r0+,fr12	! fr13-fr15 = the ambient color (pairs are on)
	add	#64,r5		! the write pointer moves over the vertex before
	fmov	@r0+,fr14
	add	#64,r4		! r4 = 32 bytes past the entry after this one
	fmov	@r14+,fr4	! fr4, fr5 = x, y
	add	#80,r6		! r6 = this vertex's block +48
	fmov	@r14+,fr6	! fr6 = z, fr7 = normal x
	fschg
	pref	@r1		! send the second 32 bytes of the vertex before
! The light sum, the same instructions as at .Ls_light_sum in
! lit_strip_send (0c105c4a-0c105d49): r2 walks the light records, r13
! holds the mask bits still to come, fr13-fr15 collect the sum.
.Lt_light_sum:			! 0c105f9a
	fmov	fr7,fr8		! fr8 = normal x; fr9, fr10 = normal y, z below
	tst	r13,r13		! T = no light reaches the group
	fmov	@r14+,fr9
	bt.s	.Lt_no_lights	! no light: only the position is left to do
	fmov	@r14+,fr10
	shlr	r13		! T = light 0 is in the mask
	mov.l	.Lt_light_table,r2
	bf	.Lt_skip_light	! not in the mask: step to the first one that is
	mov.w	@(2,r2),r0
.Lt_light:			! 0c105fac
	fldi0	fr3
	cmp/eq	#2,r0		! T = directional
	mov	#116,r1
	bf.s	.Lt_point_or_spot	! not directional: point or spot
	add	r2,r1		! (delay slot) r1 = &record.model_pos (+0x74)
	fldi1	fr7
	tst	r13,r13
	add	#12,r1		! r1 = &record.model_dir (+0x80)
	bf.s	.Lt_dir_dot
	fmov	@r1+,fr0
	ftrv	xmtrx,fv4	! last light: fv4 = (d, x', y', z') of the position
.Lt_dir_dot:			! 0c105fc2
	fmov	@r1+,fr1
	mov	r2,r0
	fmov	@r1+,fr2
	add	#24,r0
	fipr	fv0,fv8		! fr11 = N . direction
	fmov	@r0+,fr1	! fr1, fr2, fr3 = the light's red, green, blue
	fmov	@r0+,fr2
	fmov	@r0+,fr3
	fldi0	fr0
	fcmp/gt	fr11,fr0	! T = the term is negative
	fmov	fr11,fr0
	bf.s	.Lt_add_light	! not negative: add this light
	tst	r13,r13
.Lt_skip_light:			! 0c105fdc
	mov	#-80,r0
	bt	.Lt_finish_vertex	! no light left: finish the vertex
	shlr	r13
	extu.b	r0,r0
	bf.s	.Lt_step_bit	! bit clear: keep stepping
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lt_light
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
.Lt_no_lights:			! 0c105fec
	fldi1	fr7
	bra	.Lt_finish_vertex
	ftrv	xmtrx,fv4	! (delay slot) fv4 = (d, x', y', z')
	nop
.Lt_point_or_spot:		! 0c105ff4
	fmov	@r1+,fr0
	tst	r13,r13
	fmov	@r1+,fr1
	fsub	fr4,fr0
	fmov	@r1+,fr2
	fsub	fr5,fr1
	fldi1	fr7
	add	#24,r1		! r1 = record +0x98, the range squared
	fldi0	fr11
	bf.s	.Lt_point_dot
	fsub	fr6,fr2		! (delay slot) fr2 = L z; fv0 = L (fr3 = 0)
	ftrv	xmtrx,fv4	! last light: fv4 = (d, x', y', z') of the position
.Lt_point_dot:			! 0c10600c
	fipr	fv0,fv8		! fr11 = N . L
	fldi0	fr12
	fipr	fv0,fv0		! fr3 = |L| squared
	fcmp/gt	fr11,fr12
	fmov	@r1,fr12
	bt	.Lt_light_adds_nothing	! facing away: nothing from this light
	fcmp/gt	fr3,fr12
	bf	.Lt_light_adds_nothing	! out of range: nothing from this light
	cmp/eq	#3,r0
	flds	fr3,fpul
	bt.s	.Lt_attenuate	! point light: no cone
	fsrra	fr3		! (delay slot) fr3 = 1 / |L|
	add	#-24,r1
	fmov	@r1+,fr12
	fmul	fr0,fr12	! fr12 = L x times direction x
	fmov	@r1+,fr0
	fmac	fr0,fr1,fr12
	fmov	@r1,fr0
	add	#-48,r1
	fmac	fr0,fr2,fr12	! fr12 = L . direction
	fmov	@r1,fr2
	fneg	fr12
	fmul	fr3,fr12	! fr12 = cosine of the angle off the light's axis
	add	#68,r1
	fcmp/gt	fr12,fr2
	fsub	fr2,fr12
	fmov	@r1,fr2
	bt	.Lt_light_adds_nothing	! outside the cone: nothing from this light
	fmul	fr2,fr12	! fr12 = the cone factor, 0 at the edge to 1 on the axis
	add	#-4,r1
	fmul	fr12,fr11	! fr11 = N . L times the cone factor
.Lt_attenuate:			! 0c10604a
	add	#-68,r1
	fmov	@r1,fr2
	add	#-8,r1
	fsts	fpul,fr0
	fmul	fr3,fr11	! fr11 = N . L / |L| (times the cone factor)
	fmov	@r1,fr12
	fmul	fr0,fr3		! fr3 = |L|
	add	#4,r1
	fmac	fr0,fr2,fr12
	fmov	@r1,fr2
	mov	r2,r0
	fmov	fr3,fr0
	fmac	fr0,fr2,fr12	! fr12 = the attenuation
	fmov	fr11,fr0
	add	#24,r0
	fdiv	fr12,fr11	! fr11 = the term over the attenuation
	fldi1	fr2
	fcmp/gt	fr2,fr12
	fmov	@r0+,fr1
	fmov	@r0+,fr2
	bf.s	.Lt_term_ready	! not above 1: the term as it is
	fmov	@r0+,fr3
	fmov	fr11,fr0	! above 1: the divided term
.Lt_term_ready:			! 0c106078
	tst	r13,r13
.Lt_add_light:			! 0c10607a
	fmac	fr0,fr1,fr13	! red sum
	mov	#-80,r0
	fmac	fr0,fr2,fr14	! green sum
	bt.s	.Lt_finish_vertex	! that was the last light: finish the vertex
	fmac	fr0,fr3,fr15	! (delay slot) blue sum
	bra	.Lt_step_record
	shlr	r13
.Lt_light_adds_nothing:		! 0c106088
	tst	r13,r13
	mov	#-80,r0
	bt.s	.Lt_finish_vertex	! none: finish the vertex (the shlr below is its delay slot)
.Lt_step_bit:			! 0c10608e
	shlr	r13
.Lt_step_record:		! 0c106090
	extu.b	r0,r0
	bf.s	.Lt_step_bit	! bit clear: step again
	add	r0,r2		! (delay slot) r2 = the next record
	bra	.Lt_light	! bit set: work that light out
	mov.w	@(2,r2),r0	! (delay slot) r0 = its type
