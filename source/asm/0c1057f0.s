! 0c106130: the unlit path, as .Ls_unlit in lit_strip_send: 32-byte
! vertices with both intensities 1.0 (written once into the last two
! words of both store queues), two vertices a turn (A in fv4, B in fv8).
! r3 counts down the three vertices of a triangle and r9 the triangles.
.Lt_unlit:			! 0c106130
	mov.l	@r4+,r9		! r9 = the number of triangles
	fldi1	fr2
	fschg			! pairs on, until the routine returns
	fldi1	fr3
	mov	#3,r3		! r3 = 3 vertices to the triangle
	fmov	fr2,@-r6	! the block before, +24: intensities 1.0, 1.0
	add	#32,r6
	fmov	fr2,@r6		! this block +24: the same; r6 = block +24
	mov.l	@r4,r0		! r0 = the first entry's first word
	mov	r4,r14
	tst	#1,r0
	add	#32,r4
	bf	.Ltu_first	! inline: r14 is the vertex
	mov.l	@(4,r14),r14	! back reference: r14 = the offset + the end of the entry
	add	#-24,r4
	add	r4,r14
.Ltu_first:			! 0c106150
	fmov	@r14+,fr4	! A: fr4, fr5 = x, y; then z, and w = 1
	fmov	@r14,fr6
	add	#16,r14
	fldi1	fr7
	fmov	@r14,fr0	! fr0, fr1 = u, v of A
	ftrv	xmtrx,fv4	! A = (d, x', y', z')
.Ltu_pair:			! 0c10615c
