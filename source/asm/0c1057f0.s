! lit_tris_send_near_clip
!
! Sends a list of separate triangles of a group that straddles the near
! limit, cutting each triangle at the near limit. lit_tri_near_test
! first gives three near bits for the triangle's vertices v1, v2, v3
! (bit 2 = v1, bit 1 = v2, bit 0 = v3; 1 = on the near side):
!   000  nothing to cut: the three vertices are loaded and sent as they
!        are (lit_vertex_load, lit_vertex_emit);
!   111  nothing to draw: the three entries are stepped over;
!   else the three are loaded and kept in ring slots 0, 1, 2 and a
!        table indexed by the bits sends the visible part as a strip of
!        three or four vertices, the last with end-of-strip:
!          001  v1, v2, cut(v1,v3), cut(v2,v3)
!          010  v1, cut(v1,v2), v3, cut(v2,v3)
!          011  v1, cut(v1,v2), cut(v1,v3)
!          100  cut(v1,v2), v2, cut(v1,v3), v3
!          101  cut(v1,v2), v2, cut(v2,v3)
!          110  cut(v1,v3), cut(v2,v3), v3
!        where cut(a,b) is the point on that edge at the near limit
!        (lit_near_vertex_emit) and a plain vertex is sent from the
!        ring (lit_kept_vertex_emit).
!
! In:    r4 = the count word (triangles); the vertex entries follow.
!        r5, r6 = list write pointer and the store-queue address for it.
!        r7 = near_inv bits, r8 = material type, r12 = near_limit bits
!        with bit 0 = 1 when the triangles are flat shaded (set by the
!        caller at .Lclipped).
!        XMTRX and the lit_* globals as for lit_vertex_load.
! Out:   r0 = 1, and bit 0 of r12 is set. r4 = the word after the last
!        triangle. r5 and r6 are moved past everything sent.
! Uses:  r10, r11 and pr are saved and restored. r0-r3, r9, r13, r14 and
!        fr0-fr15 are changed, here or in the helpers.
! Notes: SZ = 0 on entry and on exit. Called only by
!        lit_groups_send_alpha (bsr, flags bit 3 on a straddling group).
	.global	_lit_tris_send_near_clip
	.type	_lit_tris_send_near_clip,@function
_lit_tris_send_near_clip:
.Llit_tris_send_near_clip:	! 0c1067b0
	mov.l	r10,@-r15	! save r10, r11 (the helpers use them) and pr
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3		! r3 = the number of triangles; r4 = the first entry
! One triangle. r4 = its first vertex entry.
.Lk_triangle:			! 0c1067b8
	bsr	.Llit_tri_near_test	! r9 = the three near bits; r4 is not moved
	mov	#0,r9		! (delay slot) r9 = 0 before the bits are shifted in
	mov	r9,r0
	cmp/eq	#0,r0
	bt	.Lk_whole	! none is near: send the triangle as it is
	cmp/eq	#7,r0
	bt	.Lk_skip	! all three are near: skip the triangle
! Some but not all are near: load the three vertices into ring slots 0,
! 1 and 2 (r11 is set in each bsr's delay slot).
	bsr	.Llit_vertex_load	! load v1
	mov	#0,r11
	bsr	.Llit_vertex_keep	! keep it in slot 0
	nop
	bsr	.Llit_vertex_load	! load v2
	mov	#1,r11
	bsr	.Llit_vertex_keep	! keep it in slot 1
	nop
	bsr	.Llit_vertex_load	! load v3
	mov	#2,r11
	bsr	.Llit_vertex_keep	! keep it in slot 2
	nop
	mov	r12,r0
	tst	#1,r0		! T = bit 0 of r12 clear: Gouraud shaded
	bt.s	.Lk_dispatch	! Gouraud: every vertex keeps its own color
	shll2	r9		! (delay slot) r9 = 4 x the bits, the offset into the table
	bsr	.Llit_flat_colour_spread	! flat: v3's color into slots 1 and 0 (r11 = 2)
	nop
! Jump through the table: braf adds r9 to the address 4 past itself, so
! entry k is at 0c1067ee + 4 x k; each entry is a bra and a nop. Entries
! 0 and 7 are nops (those cases were dealt with above).
.Lk_dispatch:			! 0c1067ea
	braf	r9
	nop			! (delay slot) nothing to do
	nop			! entry 000: two nops, not reached
	nop
	bra	.Lk_case_001	! entry 001: v3 is near
	nop
	bra	.Lk_case_010	! entry 010: v2 is near
	nop
	bra	.Lk_case_011	! entry 011: v2 and v3 are near
	nop
	bra	.Lk_case_100	! entry 100: v1 is near
	nop
	bra	.Lk_case_101	! entry 101: v1 and v3 are near
	nop
	bra	.Lk_case_110	! entry 110: v1 and v2 are near
	nop
	nop			! entry 111: two nops, not reached
	nop
! The triangle is done: count it and go round, or return.
.Lk_next:			! 0c10680e
	dt	r3		! count the triangle; T = it was the last
	bf	.Lk_triangle	! more triangles to do
	mov	#1,r0		! r0 = 1, the value returned
	lds.l	@r15+,pr	! restore pr, r11 and r10
	or	r0,r12		! bit 0 of r12 set: the caller's straddle flag again
	mov.l	@r15+,r11
	rts
	mov.l	@r15+,r10
! No vertex is near: send the three with lit_vertex_emit. It counts
! vertices in r3, so r3 is lent to it (3) and the triangle count waits
! in r9.
.Lk_whole:			! 0c10681e
	mov	r3,r9		! r9 = the triangle count, put aside
	bsr	.Llit_vertex_load	! load v1 (lit and transformed)
	mov	#3,r3		! (delay slot) r3 = 3 vertices
	bsr	.Llit_vertex_emit	! send v1 as it is
	nop
	bsr	.Llit_vertex_load	! load v2 (lit and transformed)
	nop
	bsr	.Llit_vertex_emit	! send v2 as it is
	nop
	bsr	.Llit_vertex_load	! load v3 the same way
	nop
	bsr	.Llit_vertex_emit	! send v3, which gets end-of-strip (r3 reaches 0)
	nop
	bra	.Lk_next
	mov	r9,r3		! (delay slot) r3 = the triangle count again
! All three are near: step r4 over three entries, each 8 bytes for a
! back reference or 32 for an inline vertex (bit 0 of its first word).
.Lk_skip:			! 0c10683c
	mov.l	@r4,r0		! r0 = the first entry's first word
	tst	#1,r0
	add	#8,r4		! 8 bytes on
	bt	.Lk_skip_2	! a back reference: that is all
	add	#24,r4		! inline: 24 more
.Lk_skip_2:			! 0c106846
	mov.l	@r4,r0		! the second entry, the same way
	tst	#1,r0
	add	#8,r4
	bt	.Lk_skip_3
	add	#24,r4
.Lk_skip_3:			! 0c106850
	mov.l	@r4,r0		! the third entry, the same way
	tst	#1,r0
	add	#8,r4
	bt	.Lk_skipped
	add	#24,r4
.Lk_skipped:			! 0c10685a
	bra	.Lk_next	! on to the next triangle
	nop
! The six cases. In every call T says whether this is the last vertex
! of the piece (sett = end-of-strip), r0 = a ring slot (set in the bsr's
! delay slot) and, for a cut, r11 = the slot at the other end of the
! edge. Slot 0 = v1, slot 1 = v2, slot 2 = v3.
! 001, v3 is near: v1, v2, cut(v1,v3), cut(v2,v3).
.Lk_case_001:			! 0c10685e
	clrt
	bsr	.Llit_kept_vertex_emit	! send v1 from the ring
	mov	#0,r0
	clrt
	bsr	.Llit_kept_vertex_emit	! send v2 from the ring
	mov	#1,r0
	clrt
	mov	#2,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v3): slots 0 and 2
	mov	#0,r0
	sett
	bsr	.Llit_near_vertex_emit	! send cut(v2,v3) with end-of-strip: slots 1 and 2
	mov	#1,r0
	bra	.Lk_next	! the triangle is done
	nop
! 010, v2 is near: v1, cut(v1,v2), v3, cut(v2,v3).
.Lk_case_010:			! 0c10687c
	clrt
	bsr	.Llit_kept_vertex_emit	! send v1 from the ring
	mov	#0,r0
	clrt
	mov	#1,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v2): slots 0 and 1
	mov	#0,r0
	clrt
	mov	#2,r11
	bsr	.Llit_kept_vertex_emit	! send v3 from the ring (r11 = 2 is for the cut below)
	mov	#2,r0
	sett
	bsr	.Llit_near_vertex_emit	! send cut(v2,v3) with end-of-strip: slots 1 and 2
	mov	#1,r0
	bra	.Lk_next	! the triangle is done
	nop
! 011, only v1 is visible: v1, cut(v1,v2), cut(v1,v3).
.Lk_case_011:			! 0c10689c
	clrt
	bsr	.Llit_kept_vertex_emit	! send v1 from the ring
	mov	#0,r0
	clrt
	mov	#1,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v2): slots 0 and 1
	mov	#0,r0
	sett
	mov	#2,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v3) with end-of-strip: slots 0 and 2
	mov	#0,r0
	bra	.Lk_next	! the triangle is done
	nop
! 100, v1 is near: cut(v1,v2), v2, cut(v1,v3), v3.
.Lk_case_100:			! 0c1068b6
	clrt
	mov	#1,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v2): slots 0 and 1
	mov	#0,r0
	clrt
	bsr	.Llit_kept_vertex_emit	! send v2 from the ring
	mov	#1,r0
	clrt
	mov	#2,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v3): slots 0 and 2
	mov	#0,r0
	sett
	bsr	.Llit_kept_vertex_emit	! send v3 from the ring with end-of-strip
	mov	#2,r0
	bra	.Lk_next	! the triangle is done
	nop
! 101, only v2 is visible: cut(v1,v2), v2, cut(v2,v3).
.Lk_case_101:			! 0c1068d6
	clrt
	mov	#1,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v2): slots 0 and 1
	mov	#0,r0
	clrt
	bsr	.Llit_kept_vertex_emit	! send v2 from the ring
	mov	#1,r0
	sett
	mov	#2,r11
	bsr	.Llit_near_vertex_emit	! send cut(v2,v3) with end-of-strip: slots 1 and 2
	mov	#1,r0
	bra	.Lk_next	! the triangle is done
	nop
! 110, only v3 is visible: cut(v1,v3), cut(v2,v3), v3.
.Lk_case_110:			! 0c1068f0
	clrt
	mov	#2,r11
	bsr	.Llit_near_vertex_emit	! send cut(v1,v3): slots 0 and 2
	mov	#0,r0
	clrt
	bsr	.Llit_near_vertex_emit	! send cut(v2,v3): slots 1 and 2
	mov	#1,r0
	sett
	bsr	.Llit_kept_vertex_emit	! send v3 from the ring with end-of-strip
	mov	#2,r0
	bra	.Lk_next	! the triangle is done
	nop
	nop			! four nops of padding before the next routine
	nop
	nop
	nop

! lit_tri_near_test
!
! Looks ahead at the next three vertex entries (a triangle), transforms
! just their positions and shifts one bit per vertex into r9, first
! vertex first: 1 = the vertex is on the near side (near_limit's bits
! above the bits of its z', compared unsigned, as in lit_vertex_load).
! The read position is put back, so the caller can load the same three
! entries afterwards.
!
! In:    r4 = the first of three vertex entries. r9 = 0 (the caller
!        clears it). r12 = near_limit bits. XMTRX = the current matrix.
! Out:   r9 = (r9 << 3) + the three bits: bit 2 for the first vertex,
!        bit 1 the second, bit 0 the third. r4 unchanged.
! Uses:  r0, r1 and fr0-fr7 are changed. Nothing is saved.
! Notes: SZ = 0 throughout (single moves). Called only by
!        lit_tris_send_near_clip (bsr).
	.global	_lit_tri_near_test
	.type	_lit_tri_near_test,@function
_lit_tri_near_test:
.Llit_tri_near_test:		! 0c106910
	mov	r4,r1		! r1 = r4, to put it back at the end
	mov.l	@r4,r0		! r0 = the first entry's first word
	tst	#1,r0		! T = bit 0 clear: a back reference
	bf.s	.Ln_v1_inline	! inline: x, y, z are right here
	fmov	@r4+,fr4	! (delay slot) fr4 = x of an inline vertex; r4 = entry +4
	mov.l	@r4+,r0		! back reference: r0 = the offset; r4 = the end of the entry
	add	r4,r0		! r0 = the vertex the entry refers to
	fmov	@r0+,fr4	! fr4, fr5, fr6 = its x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Ln_v1_xform
	fldi1	fr7		! (delay slot) w = 1
.Ln_v1_inline:			! 0c106928
	fmov	@r4+,fr5	! fr5, fr6 = y, z of the inline vertex
	fmov	@r4,fr6
	fldi1	fr7
	add	#24,r4		! r4 = past the 32-byte entry
.Ln_v1_xform:			! 0c106930
	pref	@r4		! fetch this part of the strip data and the next
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv4	! fv4 = (d, x', y', z') of the first vertex
	mov.l	@r4,r0		! the second entry, the same way, into fv0
	tst	#1,r0
	bf.s	.Ln_v2_inline	! inline: x, y, z are right here
	fmov	@r4+,fr0	! (delay slot) fr0 = x of an inline vertex
	mov.l	@r4+,r0		! back reference: the vertex it refers to
	add	r4,r0
	fmov	@r0+,fr0	! fr0, fr1, fr2 = its x, y, z
	fmov	@r0+,fr1
	fmov	@r0+,fr2
	bra	.Ln_v2_xform
	fldi1	fr3		! (delay slot) w = 1
.Ln_v2_inline:			! 0c106950
	fmov	@r4+,fr1	! fr1, fr2 = y, z of the inline vertex
	fmov	@r4,fr2
	fldi1	fr3
	add	#24,r4		! r4 = past the 32-byte entry
.Ln_v2_xform:			! 0c106958
	pref	@r4		! fetch ahead as before
	add	#32,r4
	pref	@r4
	add	#-32,r4
	ftrv	xmtrx,fv0	! fv0 = (d, x', y', z') of the second vertex
	flds	fr7,fpul	! fpul = z' of the first vertex (fv4 is needed again)
	mov.l	@r4,r0		! the third entry, into fv4
	tst	#1,r0
	bf.s	.Ln_v3_inline	! inline: x, y, z are right here
	fmov	@r4+,fr4	! (delay slot) fr4 = x of an inline vertex
	mov.l	@r4+,r0		! back reference: the vertex it refers to
	add	r4,r0
	fmov	@r0+,fr4	! fr4, fr5, fr6 = its x, y, z
	fmov	@r0+,fr5
	fmov	@r0+,fr6
	bra	.Ln_v3_xform
	fldi1	fr7		! (delay slot) w = 1
.Ln_v3_inline:			! 0c10697a
	fmov	@r4+,fr5	! fr5, fr6 = y, z of the inline vertex
	fmov	@r4,fr6
