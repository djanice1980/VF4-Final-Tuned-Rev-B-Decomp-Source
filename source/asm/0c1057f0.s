	dt	r9		! count the triangle; T = it was the last
	pref	@r6		! send the first 32 bytes
	add	#32,r6
	fschg			! pairs off
	add	#64,r5		! the write pointer moves over the vertex
	pref	@r6		! send the second 32 bytes
	add	#-32,r6
	bt.s	.Lt_done	! the last triangle: return
	add	#112,r6		! (delay slot) r6 = the next block +48
	bra	.Lt_triangle
	mov	#3,r3		! (delay slot) r3 = 3 vertices again
.Lt_done:			! 0c106114
	rts
	add	#-48,r6		! (delay slot) r6 = the next block
	nop			! four nops of padding before the pool
	nop
	nop
	nop
