	add	#8,r4		! r4 = past the 8-byte entry
	mov.l	@(4,r14),r14
	add	#32,r6
	mov.l	.Lt_ambient_scaled,r0
	add	r4,r14		! r14 = the vertex the entry refers to
	mov.l	@r13,r13
	add	#64,r5		! the write pointer moves over the vertex before
	fmov	@r0+,fr12
	mov	r6,r1
	fmov	@r0+,fr14	! fr13-fr15 = the ambient color
	add	#32,r4
	fmov	@r14+,fr4
	add	#80,r6		! r6 = this vertex's block +48
	fmov	@r14+,fr6	! fv4 = x, y, z, normal x
	fschg
	bra	.Lt_light_sum
	pref	@r1		! (delay slot) send the second 32 bytes of the vertex before
! The triangle's third vertex is in the block: send both halves now and
! go on to the next triangle, if there is one.
.Lt_last_of_triangle:		! 0c1060fc
