! argb_offset_strip_send_near_clip (0c104fe0)
!
! Sends one strip of a group that straddles the near limit, and any
! strips that carry on from it (flags bit 7). Vertices on the far side
! go out as they are. Where the strip crosses the limit the points
! where its edges meet the limit go out instead
! (argb_offset_near_vertex_emit); where it stays on the near side the output
! strip is ended, and a new one is begun when it comes back.
!
! State while a strip is walked:
!     r3   vertices left in the strip
!     r11  number of the current vertex V in the strip, from 0; a kept
!          vertex is in slot r11 & 3 of argb_offset_clip_ring
!     r9   the cut history, a bit shifted in from the right per vertex:
!          bit 0 = V is cut, bit 1 = V-1, bit 2 = V-2
!     fr12-fr15  the matrix row that gives n (for the skipping loop)
! The strip is walked in one of three ways:
!   visible run (0c105016): V-2, V-1 and V all visible. The vertices go
!     straight out in argb_offset_strip_send's two-a-turn loop with the cut
!     test added; nothing is kept in the ring.
!   clipping (0c10525c): every vertex is loaded and kept in the ring
!     (argb_offset_vertex_load, argb_offset_vertex_keep), and the
!     triangle V-2, V-1, V is sent by the case for its three history
!     bits (0c105272).
!   skipping (0c105142): after two cut vertices in a row only n is
!     worked out for each vertex, until a visible one turns up.
! Going from the run or from skipping to clipping, the two vertices
! before V are not in the ring: the read position is stepped back three
! entries and they are loaded again (0c10520e).
!
! The cases, with c(a,b) for the point where the edge from a to b meets
! the limit. "After" is what the output strip already ends with.
!   001  V cut         c(V-2,V), V-1, c(V-1,V)     after V-2, V-1
!   010  V-1 cut       V, c(V-1,V), V              after c(V-2,V-1)
!   011  V-1, V cut    c(V-2,V) as end of strip; then skipping
!   100  V-2 cut       c(V-2,V), V-1, V; then the visible run
!   101  V-2, V cut    c(V-1,V)                    after c(V-2,V-1), V-1
!   110  V-2, V-1 cut  a new strip: c(V-2,V), c(V-1,V), V; when r11 is
!                      odd c(V-1,V) is sent once more in front, so that
!                      the triangle keeps its facing
! A vertex sent twice gives a triangle of no area; it keeps the strip's
! alternation in step with the stream's. 000 and 111 do not come up at
! the dispatch (the run and the skipping loop take those).
!
! In:    r4 = the strip's count word (the first two vertices are not
!        checked against the count: a strip has at least three).
!        r5, r6, r7, XMTRX as described at the top of the file.
!        r12 = the near limit; bit 0 set = the strip is flat shaded
!        (argb_offset_flat_colour_spread is then run for every triangle).
! Out:   r0 = 1. r12 bit 0 set (the group's straddling flag again).
!        r4 = the flags word after the last strip sent (not consumed).
!        r5 = 32 more per block sent; r6 = the next block.
! Uses:  r10, r11 and pr are saved and restored. r1-r3, r8, r9, r14,
!        fr0-fr15 and FPUL are changed with no saving (fr12-fr15 are
!        left holding the matrix row; the group routine restores them
!        when the group ends).
! Notes: SZ = 0 on entry and return.
	.global	_argb_offset_strip_send_near_clip
	.type	_argb_offset_strip_send_near_clip,@function
_argb_offset_strip_send_near_clip:
.Lstrip_near_clip:
	mov.l	r10,@-r15		! save r10, r11 (the group routine's) and pr
	mov.l	r11,@-r15
	sts.l	pr,@-r15
	mov.l	@r4+,r3			! r3 = vertices in this strip
! fr12-fr15 = the row of XMTRX that makes n: xf3, xf7, xf11, xf15. With
! SZ = 1 an odd source register in a register-to-register fmov names a
! pair of the back bank, so the four moves below copy xf2-xf3, xf6-xf7,
! xf10-xf11 and xf14-xf15.
	fschg				! SZ = 1
	fmov	fr3,fr0			! fr0, fr1 = xf2, xf3
	fmov	fr7,fr12		! fr12, fr13 = xf6, xf7
	fmov	fr11,fr2		! fr2, fr3 = xf10, xf11
	fmov	fr15,fr14		! fr14, fr15 = xf14, xf15
	fschg				! SZ = 0
	fmov	fr1,fr12		! fr12 = xf3
	fmov	fr3,fr14		! fr14 = xf11
! 0c104ff8: start of a strip (r3 = its count, r4 = its first entry).
.Lstrip_start:
	mov	#0,r11			! r11 = 0: the first vertex
	bsr	.Lvertex_load		! load v0; T = v0 is cut
	mov	#0,r9			! (delay slot) r9 = 0: an empty history
	bf	.Lv0_shift		! v0 visible: carry on at the rotcl below
	bra	.Lv0_cut		! v0 cut; the rotcl below is its delay slot
.Lv0_shift:
! 0c105002: reached both ways, as the bf's target and as the delay slot
! of the bra.
	rotcl	r9			! shift v0's bit into the history
	bsr	.Lvertex_emit		! v0 is visible: send it as it is
	add	#1,r11			! (delay slot) r11 = 1
	bsr	.Lvertex_load		! load v1; T = v1 is cut
	nop
	bf	.Lv1_shift		! v1 visible: carry on at the rotcl below
	bra	.Lv1_cut		! v1 cut; the rotcl below is its delay slot
.Lv1_shift:
! 0c105010: reached both ways, as at 0c105002.
	rotcl	r9			! shift v1's bit into the history
	bsr	.Lvertex_emit		! v1 is visible: send it as it is
	add	#1,r11			! (delay slot) r11 = 2
! 0c105016: the visible run. The last two vertices were visible and have
! been sent; r11 = the number of the vertex at r4. From here to 0c1050ca
! this is argb_offset_strip_send's loop (A in fr4-fr7, B in fr8-fr11) with a
! cut test on each vertex before it is counted.
.Lvisible_run:
	add	#32,r6			! r6 = the end of the block
	mov.l	@r4,r0			! r0 = first word of the entry
	fschg				! SZ = 1: paired moves in the run
	tst	#1,r0			! T = bit 0 clear: a reference
	mov	r4,r14			! r14 = the entry, taken to be a full vertex
	bf.s	.Lrun_first_ready	! a full vertex
	add	#32,r4			! (delay slot) r4 = past a full vertex
	mov.l	@(4,r14),r14		! a reference: r14 = its offset
	add	#-24,r4			! r4 = past the 8-byte entry
	add	r4,r14			! r14 = the vertex referred to
.Lrun_first_ready:
! 0c10502a: load the vertex as A and transform it.
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14+,fr6		! fr6 = z
	fldi1	fr7			! fr7 = 1
	fmov	@r14+,fr2		! fr2, fr3 = the base and offset colors
	fmov	@r14,fr0		! fr0, fr1 = u, v; r14 stays on them
	ftrv	xmtrx,fv4		! fr4-fr7 = w, xw, yw, n
! 0c105036: one turn of the run; A is transformed.
.Lrun_turn:
	fmov	fr2,@-r6		! A's block +24, +28 = base, offset color
	flds	fr7,fpul		! FPUL = the bits of A's n
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1/w of A
	sts	fpul,r0			! r0 = the bits of n
	cmp/hi	r0,r12			! T = A is cut
	bt	.Lrun_a_cut		! cut: leave the run
	dt	r3			! count A; T = A is the last of the strip
	mov.l	@r4+,r0			! r0 = the first of the two words after A's entry
	add	#1,r11			! r11 = the number of the next vertex
	bt.s	.Lrun_a_last		! A is the last
	mov.l	@r4+,r14		! (delay slot) r14 = the second word
	tst	#1,r0			! T = the next entry is a reference
	mov	r6,r2			! r2 = A's control word
	bt.s	.Lrun_load_b		! a reference
	add	r4,r14			! (delay slot) r14 = the vertex referred to
	mov	r4,r14			! a full vertex: r14 = its first word, r4 = past it
	add	#24,r4
	add	#-8,r14
! 0c10505c: fetch and transform B while A is finished and sent.
.Lrun_load_b:
	add	#64,r4			! r4 moved 64 on for the prefetch
	fmov	@r14+,fr8		! fr8, fr9 = B's x, y
	pref	@r4			! fetch the stream 64 bytes ahead
	fmov	@r14+,fr10		! fr10 = B's z
	add	#-64,r4			! r4 back where it was
	fldi1	fr11			! fr11 = 1
	fmul	fr7,fr6			! A: Y = yw / w
	fmov	@r14+,fr2		! fr2, fr3 = B's colors
	fmul	fr7,fr5			! A: X = xw / w
	fmov	fr0,@-r6		! A's block +16, +20 = u, v
	ftrv	xmtrx,fv8		! fr8-fr11 = B's w, xw, yw, n
	fmov	fr6,@-r6		! A's block +8, +12 = Y, 1/w
	fmov	fr4,@-r6		! A's block +0, +4 = (w, replaced next), X
	add	#32,r5			! count A's block
	mov.l	r2,@r6			! A's block +0 = the control word
	fmov	@r14,fr0		! fr0, fr1 = B's u, v
	pref	@r6			! send A's block
	add	#64,r6			! r6 = the end of B's block
	fmov	fr2,@-r6		! B's block +24, +28 = base, offset color
	flds	fr11,fpul		! FPUL = the bits of B's n
	fldi1	fr11
	fdiv	fr8,fr11		! fr11 = 1/w of B
	sts	fpul,r0			! r0 = the bits of n
	cmp/hi	r0,r12			! T = B is cut
	bt	.Lrun_b_cut		! cut: leave the run
	dt	r3			! count B; T = B is the last of the strip
	mov.l	@r4+,r0			! r0 = the first of the two words after B's entry
	add	#1,r11			! r11 = the number of the next vertex
	bt.s	.Lrun_b_last		! B is the last
	mov.l	@r4+,r14		! (delay slot) r14 = the second word
	tst	#1,r0			! T = the next entry is a reference
	mov	r6,r2			! r2 = B's control word
	bt.s	.Lrun_load_a		! a reference
	add	r4,r14			! (delay slot) r14 = the vertex referred to
	mov	r4,r14			! a full vertex: r14 = its first word, r4 = past it
	add	#24,r4
	add	#-8,r14
! 0c1050a6: fetch and transform the next A while B is finished and sent.
.Lrun_load_a:
	fmov	@r14+,fr4		! fr4, fr5 = A's x, y
	add	#64,r4			! r4 moved 64 on for the prefetch
	fmov	@r14+,fr6		! fr6 = A's z
	pref	@r4			! fetch the stream 64 bytes ahead
	fldi1	fr7			! fr7 = 1
	fmul	fr11,fr10		! B: Y = yw / w
	fmov	@r14+,fr2		! fr2, fr3 = A's colors
