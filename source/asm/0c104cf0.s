! argb_offset_tris_send (0c104ee0)
!
! Sends a list of separate triangles that needs no clipping. The loop
! is argb_offset_strip_send's (two vertices a turn, A in fr4-fr7 and B in
! fr8-fr11, the two words after each entry read ahead); what differs is
! the counting: r3 counts the three vertices of a triangle and r9 the
! triangles, every third vertex goes out with the end-of-strip mark,
! and nothing follows a strip that carries on (bit 7 is not looked at).
!
! In:    r4 = the count word (triangles; at least 1).
!        r5, r6, XMTRX as described at the top of the file.
! Out:   r4 = the word after the last triangle (not consumed).
!        r5 = 32 more per vertex; r6 = the next block.
! Uses:  r0, r2, r3, r9, r14, fr0-fr11 and FPUL are changed, with no
!        saving. Does not use the stack or call anything.
! Notes: SZ = 0 on entry and return, 1 inside.
	.global	_argb_offset_tris_send
	.type	_argb_offset_tris_send,@function
_argb_offset_tris_send:
.Ltris_send:
	mov.l	@r4+,r9			! r9 = triangles to send
	add	#32,r6			! r6 = the end of the block: it is filled downwards
	fschg				! SZ = 1: paired moves from here on
	mov	#3,r3			! r3 = vertices left in this triangle
! Find the first vertex: the entry itself, or the one it refers to.
	mov.l	@r4,r0			! r0 = first word of the entry
	mov	r4,r14			! r14 = the entry, taken to be a full vertex
	tst	#1,r0			! T = bit 0 clear: a reference
	add	#32,r4			! r4 = past a full vertex
	bf	.Lt_first_ready		! a full vertex: r14 and r4 are right
	mov.l	@(4,r14),r14		! r14 = the reference's offset
	add	#-24,r4			! r4 = past the 8-byte entry
	add	r4,r14			! r14 = the vertex referred to
.Lt_first_ready:
! 0c104ef8: load the first vertex as A and transform it.
	fmov	@r14+,fr4		! fr4, fr5 = x, y
	fmov	@r14+,fr6		! fr6 = z (fr7 takes the word after it)
	fldi1	fr7			! fr7 = 1
	fmov	@r14+,fr2		! fr2, fr3 = the base and offset colors
	fmov	@r14,fr0		! fr0, fr1 = u, v
	ftrv	xmtrx,fv4		! fr4-fr7 = w, xw, yw, n
! 0c104f04: one turn. A is transformed (fr4-fr7), its colors are in fr2, fr3
! and its u, v in fr0, fr1; r6 = the end of A's block.
.Lt_turn:
	fldi1	fr7
	fdiv	fr4,fr7			! fr7 = 1/w of A; the divide runs during what follows
	fmov	fr2,@-r6		! A's block +24, +28 = base, offset color
	dt	r3			! count A; T = A is the third of its triangle
	mov.l	@r4+,r0			! r0 = the first of the two words after A's entry
	bt.s	.Lt_a_third		! A closes a triangle
	mov.l	@r4+,r14		! (delay slot) r14 = the second of the two words
	tst	#1,r0			! T = the next entry is a reference
	mov	r6,r2			! r2 = A's control word (a store-queue address)
	bt.s	.Lt_load_b		! a reference
	add	r4,r14			! (delay slot) r14 = the vertex referred to
	mov	r4,r14			! a full vertex: r14 = its first word, r4 = past it
	add	#24,r4
	add	#-8,r14
! 0c104f20: fetch and transform B (at r14) while A is finished and sent.
.Lt_load_b:
	add	#32,r4			! r4 moved 32 on for the prefetch
	fmov	@r14+,fr8		! fr8, fr9 = B's x, y
	pref	@r4			! fetch the stream 32 bytes ahead
	fmov	@r14+,fr10		! fr10 = B's z
	fldi1	fr11			! fr11 = 1
	fmul	fr7,fr6			! A: Y = yw / w
	fmov	@r14+,fr2		! fr2, fr3 = B's colors; A's are in the block
	fmul	fr7,fr5			! A: X = xw / w
	fmov	fr0,@-r6		! A's block +16, +20 = u, v
	ftrv	xmtrx,fv8		! fr8-fr11 = B's w, xw, yw, n
	fmov	fr6,@-r6		! A's block +8, +12 = Y, 1/w
	add	#-32,r4			! r4 back where it was
	fmov	fr4,@-r6		! A's block +0, +4 = (w, replaced next), X
	mov.l	r2,@r6			! A's block +0 = the control word
	fmov	@r14,fr0		! fr0, fr1 = B's u, v
	dt	r3			! count B; T = B is the third of its triangle
	pref	@r6			! send A's block
	add	#64,r6			! r6 = the end of B's block
	fmov	fr2,@-r6		! B's block +24, +28 = base, offset color
	mov	r6,r2			! r2 = B's control word
	fldi1	fr11
	fdiv	fr8,fr11		! fr11 = 1/w of B
	mov.l	@r4+,r0			! r0 = the first of the two words after B's entry
	bt.s	.Lt_b_third		! B closes a triangle
	mov.l	@r4+,r14		! (delay slot) r14 = the second word
	tst	#1,r0			! T = the next entry is a reference
	bt.s	.Lt_load_a		! a reference
	add	r4,r14			! (delay slot) r14 = the vertex referred to
	mov	r4,r14			! a full vertex: r14 = its first word, r4 = past it
	add	#24,r4
	add	#-8,r14
! 0c104f5e: fetch and transform the next A (at r14) while B is finished
! and sent: the same steps as at 0c104f20 with the two swapped.
.Lt_load_a:
	add	#32,r4			! r4 moved 32 on for the prefetch
	fmov	@r14+,fr4		! fr4, fr5 = A's x, y
	pref	@r4			! fetch the stream 32 bytes ahead
	fmov	@r14+,fr6		! fr6 = A's z
	fldi1	fr7			! fr7 = 1
	fmul	fr11,fr10		! B: Y = yw / w
	fmov	@r14+,fr2		! fr2, fr3 = A's colors
	fmul	fr11,fr9		! B: X = xw / w
	fmov	fr0,@-r6		! B's block +16, +20 = u, v
	ftrv	xmtrx,fv4		! fr4-fr7 = A's w, xw, yw, n
	fmov	fr10,@-r6		! B's block +8, +12 = Y, 1/w
	add	#-32,r4			! r4 back where it was
	fmov	fr8,@-r6		! B's block +0, +4 = (w, replaced next), X
	add	#64,r5			! two blocks more in the display list: A's and B's
	mov.l	r2,@r6			! B's block +0 = the control word
	fmov	@r14,fr0		! fr0, fr1 = A's u, v
	pref	@r6			! send B's block
	bra	.Lt_turn		! the next turn
	add	#64,r6			! (delay slot) r6 = the end of A's block
! 0c104f84: B closes a triangle. r0 and r14 are the two words after it:
! the next triangle's first entry if there is one.
.Lt_b_third:
	dt	r9			! count the triangle; T = it was the last
	mov	r6,r2			! r2 = B's control word...
	bt.s	.Lt_b_ends		! the last triangle
	shar	r2			! (delay slot) ...with the end-of-strip bit
	tst	#1,r0			! T = the next entry is a reference
	mov	#3,r3			! r3 = three vertices again
	bt.s	.Lt_load_a		! a reference: go and load it as A
	add	r4,r14			! (delay slot) r14 = the vertex referred to
	mov	r4,r14			! a full vertex: r14 = its first word, r4 = past it
	add	#24,r4
	bra	.Lt_load_a		! go and load it as A
	add	#-8,r14			! (delay slot)
! 0c104f9c: B is the last vertex of all: move it to A's registers and
! let the common ending write it.
.Lt_b_ends:
	add	#32,r5			! count A's block, sent earlier in this turn
	fmov	fr8,fr4			! fr4, fr5 = B's w, xw
	bra	.Lt_last_vertex		! to the ending
	fmov	fr10,fr6		! (delay slot) fr6, fr7 = B's yw, 1/w
! 0c104fa4: A closes a triangle; as at 0c104f84, before A is written.
.Lt_a_third:
	dt	r9			! count the triangle; T = it was the last
	mov	r6,r2			! r2 = A's control word...
	bt.s	.Lt_last_vertex		! the last triangle
	shar	r2			! (delay slot) ...with the end-of-strip bit
	tst	#1,r0			! T = the next entry is a reference
	mov	#3,r3			! r3 = three vertices again
	bt.s	.Lt_load_b		! a reference: go and load it as B
	add	r4,r14			! (delay slot) r14 = the vertex referred to
	mov	r4,r14			! a full vertex: r14 = its first word, r4 = past it
	add	#24,r4
	bra	.Lt_load_b		! go and load it as B
	add	#-8,r14			! (delay slot)
! 0c104fbc: write the last vertex (in A's registers; r2 already has the
! end-of-strip bit) and return.
.Lt_last_vertex:
	fmul	fr7,fr6			! Y = yw / w
	fmov	fr0,@-r6		! block +16, +20 = u, v
	fmul	fr7,fr5			! X = xw / w
	fmov	fr6,@-r6		! block +8, +12 = Y, 1/w
	add	#32,r5			! count this block
	fmov	fr4,@-r6		! block +0, +4 = (w, replaced next), X
	add	#-8,r4			! r4 back on the word read ahead
	mov.l	r2,@r6			! block +0 = the control word
	fschg				! SZ = 0 again
	pref	@r6			! send the block
	rts				! back to the group routine
	add	#32,r6			! (delay slot) r6 = the next block
	nop				! padding before the next routine
